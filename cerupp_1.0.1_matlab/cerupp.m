        est_final_mem = NaN;
        if progress_mem_enabled
            last_memmon_phase_tag = 'STORE_STEP';
            [memmon_last_gb, memmon_peak_gb, memmon_time_vec, memmon_mem_vec, ...
                do_memmon_base, progress_mem_enabled, run_warn_state, ...
                memmon_warn_state, progress_mem_sample] = ...
                sample_memmon_or_latch_off( ...
                    'STORE_STEP', curr_z_step, z_post_step, prop_code_start, ...
                    memmon_time_vec, memmon_mem_vec, num_zsteps, ...
                    memmon_last_gb, memmon_peak_gb, warning_ledgers.memmon, ...
                    progress_mem_cfg, do_memmon_base, progress_mem_enabled, ...
                    run_warn_state, 'propagation');
            last_memmon_phase_tag = '';
            warning_ledgers.run = run_warn_state;
            warning_ledgers.memmon = memmon_warn_state;
            if isstruct(progress_mem_sample) && ~isempty(fieldnames(progress_mem_sample))
                curr_mem = progress_mem_sample.curr_mem_gb;
                est_final_mem = progress_mem_sample.est_final_mem_gb;
            end
        end
        fprintf('Storage %d / %d | Step %d / %d\n', ...
            save_idx, num_storage_steps, curr_z_step, num_zsteps);
        fprintf('Elapsed: %.1f min | ETA: %.1f min\n', elapsed_s/60, eta_s/60);

        if progress_mem_enabled
            if ~isnan(curr_mem)
                fprintf('Memory: %.2f GB | Est. final: %.2f GB\n\n', curr_mem, est_final_mem);
            else
                fprintf('Memory tracking not available on this OS\n\n');
            end
        else
            fprintf('\n');
        end
    end

    % 5E. Checkpoint-only restart/fullsave writes.
    % Driver-owned diagnostics added after cerupp_section4_setup(); can be
    % updated in Section 5D and plotted after cerupp_section6a_postprocess(...),
    % unless you deliberately add them to the checkpoint-owned diagnostic schema.
