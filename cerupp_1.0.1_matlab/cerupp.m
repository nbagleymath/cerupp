    % If the current dz matches the last built operator dz, the current
    % linear/guiding prefactors are reusable unless this step also triggers
    % a medium rebuild.
    dz_match_tol = dz_match_rel_tol * max(abs(double(dz)), abs(double(last_operator_dz))) + dz_match_abs_tol_m;
    reuse_last_operator_flag = perf_cfg.reuse_linear_guiding_operator_cache_flag && ...
        isfinite(double(dz)) && isfinite(double(last_operator_dz)) && ...
        isfinite(double(dz_match_tol)) && ...
        (abs(double(dz) - double(last_operator_dz)) <= double(dz_match_tol));

