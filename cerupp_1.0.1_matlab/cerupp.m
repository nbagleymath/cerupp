    % MEMMON tracks propagation-loop memory growth so a long run can warn early
    % or stop early instead of burning more wall time and then dying from an
    % out-of-memory failure. On selected steps it samples process RSS together
    % with timing, compares that sample against the configured or detected
    % memory budget, and either aborts on exceed or records a warning-only
    % over-budget event depending on the selected MEMMON policy.
    run_memmon_base_this_step = ...
        (curr_z_step <= perf_cfg.memmon_first_n_steps) || ...
        ((curr_z_step > perf_cfg.memmon_first_n_steps) && ...
         (mod(curr_z_step - perf_cfg.memmon_first_n_steps, ...
              perf_cfg.memmon_stride) == 0));
