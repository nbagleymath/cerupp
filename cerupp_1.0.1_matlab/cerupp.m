        (curr_z_step == 1);
    step_custom_args_this_step.advance_step_builtin = ...
        advance_step_builtin_this_step;

    % Perform CerUPP propagation step
    [A_S, A_F, rhs_plasma, rho, A_SSF, step_diag, step_warning_ledgers, step_runtime_meta] = advance_z_step( ...
            A_S, A_F, dz, ...
            mask, mask_f_runtime, mask_f_w_runtime, ...
            c, omega_fund, ...
            plasma_step_ctx, nla_step_ctx, ...
            warning_ledgers.plasma, warning_ledgers.nla, z_curr, ...
            core_idx, ...
            use_nlse_flag, fee_z_rk2_flag, ...
            step_diag_policy, ...
            lin_half_factor_pass, guiding_phase_pass, guiding_active_pass, ...
            sample_step_timing_this_step, ...
            kerr_n2_xy_in_step, nla_diag_scatter_ws, ...
            step_custom_args_this_step);

    % Scatter rho to full computational domain in case custom
    % diagnostics/logic/propagation need it.
    if plasma_flag
        nt_step = size(A_F, 3);
        if isempty(rho)
            error('CerUPP:Propagation:MissingStepRho', ...
                'advance_z_step(...) must return rho whenever plasma_flag=true.');
        elseif ismatrix(rho) && isequal(size(rho), [numel(core_idx), nt_step])
            rho = propagation_support.scatter_core_rows_to_full( ...
                real(rho), core_idx, num_x_pts, num_y_pts, nt_step, real(A_F(1)), []);
        elseif isequal(size(rho), [num_x_pts, num_y_pts, nt_step])
            rho = real(rho);
        else
            error('CerUPP:Propagation:InvalidStepRhoShape', ...
                ['advance_z_step(...) returned rho with size %s. Expected either ', ...
                 '[Nc,Nt]=[%d,%d] core rows or [%d,%d,%d] full-grid rho.'], ...
                mat2str(size(rho)), numel(core_idx), nt_step, ...
                num_x_pts, num_y_pts, nt_step);
