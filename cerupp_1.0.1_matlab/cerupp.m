for curr_z_step = 1:num_zsteps
    % curr_z_step is the 1-based propagation-step index.
    % z_domain(curr_z_step) is the pre-step z location [m].
    % z_domain(curr_z_step+1) is the post-step z location [m].
    z_pre_step = z_domain(curr_z_step); %[m]
    z_post_step = z_domain(curr_z_step + 1); %[m]
    z_curr = z_pre_step; %[m]
    pre_step_progress_span_m = double(z_pre_step - z_domain_start_m);
    pre_step_progress_frac = pre_step_progress_span_m / ...
        max(total_propagation_span_m, eps);
    completed_progress_span_m = double(z_post_step - z_domain_start_m);
    completed_progress_frac = completed_progress_span_m / ...
        max(total_propagation_span_m, eps);

    emit_progress_print_this_step = ...
        (curr_z_step == 1) || (curr_z_step == num_zsteps) || ...
        (mod(curr_z_step, perf_cfg.progress_print_stride) == 0);

