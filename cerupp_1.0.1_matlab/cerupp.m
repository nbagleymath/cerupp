                'final_fullsave_build_failed', ...
                'CerUPP:FinalFullsaveBuildFailed', ...
                ['Could not prepare or write the optional final full save after ', ...
                 'propagation completed. Continuing through the final status pass. ', ...
                 'Error: %s (%s)'], ...
                me_final_fullsave.message, me_final_fullsave.identifier);
            run_warn_state = output_io_warn_utils.record_output_io_failure( ...
                run_warn_state, 'final_fullsave_build_failed', runtime_setup.filename, ...
                me_final_fullsave, 'end');
        end
    else
        final_full_save_ok = false;
        final_full_save_error_id = 'CerUPP:FinalFullsaveBuildCfgUnavailable';
        final_full_save_error_message = ...
            'Final full output save was requested, but its build configuration was unavailable.';
    end
end

% 6C-III. Finalize run-status and run-pointer files.
% Write the final status and latest-run pointer files after the final
% warning summary so those saved results can include any warning-pass
% failures too.

% Capture the true final memory sample before the final status/pointer
% write helper runs so any last MEMMON warning lands in the saved end-of-run
% reporting contract too.
final_est_mem = pre_final_est_mem;
if progress_mem_enabled
    last_memmon_phase_tag = 'FINAL_SUMMARY';
    final_summary_memmon_cfg = progress_mem_cfg;
    final_summary_memmon_cfg.memmon_abort_on_exceed = false;
    [memmon_last_gb, memmon_peak_gb, memmon_time_vec, memmon_mem_vec, ...
        do_memmon_base, progress_mem_enabled, run_warn_state, ...
        memmon_warn_state, progress_mem_sample] = sample_memmon_or_latch_off( ...
            'FINAL_SUMMARY', terminal_event_step, terminal_event_z, prop_code_start, ...
            memmon_time_vec, memmon_mem_vec, terminal_event_step, ...
            memmon_last_gb, memmon_peak_gb, warning_ledgers.memmon, ...
            final_summary_memmon_cfg, do_memmon_base, progress_mem_enabled, ...
            run_warn_state, 'end');
    last_memmon_phase_tag = '';
    warning_ledgers.run = run_warn_state;
    warning_ledgers.memmon = memmon_warn_state;
    if isstruct(progress_mem_sample) && ~isempty(fieldnames(progress_mem_sample))
        final_est_mem = progress_mem_sample.est_final_mem_gb;
    end
end

if ~exist('final_rho_state_finite', 'var')
    final_rho_state_finite = true;
    if plasma_flag
        final_rho_state_finite = ~isempty(rho) && all(isfinite(rho(:)));
    end
end
if ~exist('final_rho_state_shape_ok', 'var')
    final_rho_state_shape_ok = true;
    if plasma_flag
        final_rho_state_shape_ok = ~isempty(rho) && isequal(size(rho), size(A_S));
    end
end

% Collapse the end-of-run output/status records, emit the final warning
% summary, and write the final status/pointer files after the last MEMMON
% sample has updated the run-warning state.
cerupp_section6c_finalize_reporting();

final_total_wall_s = toc(t_all);

% Report the final run result and elapsed time.
if completed_with_all_requested_outputs
    fprintf('\n--- Simulation Successfully Complete ---\n');
elseif ~(final_a_s_state_finite && final_a_f_state_finite && ...
        final_rho_state_finite && final_rho_state_shape_ok)
    fprintf('\n--- Run Reached the End, but Final A_S, A_F, and/or rho Failed the Terminal State Contract ---\n');
elseif ~propagation_completed_requested_distance
    fprintf('\n--- Run Stopped Before The Requested Propagation Distance ---\n');
    if output_plan.request.write_run_status_flag
        fprintf('See the warning summary and run-status files for details.\n');
    else
        fprintf('See the warning summary for details.\n');
    end
elseif ~artifact_status.final.finalization.ok
    fprintf('\n--- Propagation Complete, but Post-Propagation Finalization Failed ---\n');
    if output_plan.request.write_run_status_flag
        fprintf('See the warning summary and run-status files for details.\n');
    else
        fprintf('See the warning summary for details.\n');
    end
elseif ~postprocess_phase_ok
    fprintf('\n--- Propagation Complete, but Section 6A Postprocessing Failed ---\n');
    if output_plan.request.write_run_status_flag
        fprintf('See the warning summary and run-status files for details.\n');
    else
        fprintf('See the warning summary for details.\n');
    end
elseif physics_success
    fprintf('\n--- Propagation Complete, but One or More Requested Outputs Were Skipped or Failed ---\n');
    if output_plan.request.write_run_status_flag
        fprintf('See the warning summary and run-status files for details.\n');
    else
        fprintf('See the warning summary for details.\n');
    end
else
    fprintf('\n--- Simulation Did Not Reach a Successful Normal Exit ---\n');
end
fprintf('Total elapsed time: %.1f minutes (%.1f hours)\n', ...
    final_total_wall_s/60, final_total_wall_s/3600);
if progress_mem_enabled || ~isnan(final_est_mem)
    if ~isnan(final_est_mem)
        fprintf('Estimated final memory: %.2f GB\n', final_est_mem);
    else
        fprintf('Count of total memory used is unavailable on this platform\n');
    end
end
if (exist('console_output_log_ctx', 'var') == 1) && isstruct(console_output_log_ctx)
    console_log_utils.stop_console_output_log(console_output_log_ctx);
end

% Restore MATLAB's original path if requested.
if restore_matlab_path_after_cerupp
    path(matlab_path_before_cerupp);
end

% Final run-status cleanup before rethrowing any driver-level failure.
catch me_run
    if ~(exist('run_warn_state', 'var') == 1 && isstruct(run_warn_state))
        run_warn_state = struct_utils.ensure_warned_keys_map(struct());
    end
    warning_ledgers_fallback = struct( ...
        'run', run_warn_state, ...
        'plasma', struct(), ...
        'nla', struct(), ...
        'memmon', struct());
    if (exist('warning_ledgers', 'var') == 1) && isstruct(warning_ledgers)
        warning_ledgers_fallback = run_warn_state_utils.require_warning_ledger_bundle( ...
            warning_ledgers, run_warn_state, struct(), 'CerUPP:DriverRunFailWarnBundle');
        warning_ledgers_fallback.run = run_warn_state;
    end
    if isempty(warning_ledgers_fallback.plasma) && ...
            (exist('submodel_warn_state', 'var') == 1) && isstruct(submodel_warn_state) && ...
            isfield(submodel_warn_state, 'plasma') && isstruct(submodel_warn_state.plasma)
        warning_ledgers_fallback.plasma = submodel_warn_state.plasma;
    end
    if isempty(warning_ledgers_fallback.nla) && ...
            (exist('submodel_warn_state', 'var') == 1) && isstruct(submodel_warn_state) && ...
            isfield(submodel_warn_state, 'nla') && isstruct(submodel_warn_state.nla)
        warning_ledgers_fallback.nla = submodel_warn_state.nla;
    end
    [controlled_stop_salvage, checkpoint_policy_state, diag_state, ...
        run_warn_state] = ...
        restart_pipeline_utils.attempt_controlled_stop_salvage_from_caller( ...
            me_run, run_warn_state);
    caught_status_extra_fields = struct();
    if (exist('status_extra_fields', 'var') == 1) && ...
            isstruct(status_extra_fields) && isscalar(status_extra_fields)
        caught_status_extra_fields = status_extra_fields;
    else
        if (exist('run_end_state', 'var') == 1) && ...
                isstruct(run_end_state) && isscalar(run_end_state)
            caught_status_extra_fields.run_end_state = run_end_state;
        end
        if (exist('artifact_status', 'var') == 1) && ...
                isstruct(artifact_status) && isscalar(artifact_status)
            caught_status_extra_fields.artifact_status = artifact_status;
        end
    end
    if controlled_stop_salvage.attempted || ...
            ~isempty(controlled_stop_salvage.reason)
        caught_status_extra_fields.controlled_stop_salvage = ...
            controlled_stop_salvage;
    end
    if (exist('run_status_ctx', 'var') == 1) && isstruct(run_status_ctx) && ...
            ((isfield(run_status_ctx, 'enabled') && run_status_ctx.enabled) || ...
             (isfield(run_status_ctx, 'write_current_pointer') && run_status_ctx.write_current_pointer))
        [run_warn_state, run_status_ctx] = finalize_run_status_local( ...
            run_warn_state, run_status_ctx, 'failed', ...
            me_run.identifier, strrep(me_run.message, sprintf('\n'), ' '), ...
            'caught_error', caught_status_extra_fields);
    end
    warning_ledgers_fallback.run = run_warn_state;
    failure_warn_states = warning_ledgers_fallback;
    try
        failure_warn_states = warning_utils.emit_resetting_run_end_warnings( ...
            'CerUPP:DriverRunFail', failure_warn_states);
        run_warn_state = failure_warn_states.run;
    catch
    end
    if (exist('console_output_log_ctx', 'var') == 1) && isstruct(console_output_log_ctx)
        console_log_utils.stop_console_output_log(console_output_log_ctx);
    end
    if (exist('restore_matlab_path_after_cerupp', 'var') == 1) && ...
            restore_matlab_path_after_cerupp
        path(matlab_path_before_cerupp);
    end
    rethrow(me_run);
end
