        % 5E-I. Hand the current step state plus the latest stored
        % diagnostics directly to the checkpoint save helper.
        [checkpoint_write_state, run_warn_state] = ...
            restart_pipeline_utils.write_checkpoint_from_phase_runtime_local( ...
                grid_state, medium_state, output_state, ...
                step_phase_runtime_base, ...
                step_state_snapshot, step_reassembly_state, ...
                diag_state, checkpoint_restart_state_base, ...
