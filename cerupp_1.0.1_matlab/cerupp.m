% The OFI-based sink hard-fails unless an OFI/plasma source branch is on.
% Dynamic Keldysh and static matched OFI both use one Udep_matched scalar
% directly through dI/dz = -Udep_matched*rho_scale*W_ion(I). With one
% retained static order K, Udep_matched = K*hbar*omega_fund reproduces the
% usual single-K MPI loss. With multiple retained static orders this
% remains an OFI-based depletion closure, not the explicit perturbative
% MPA law sum_K(K*hbar*omega_fund*sigma_K*I^K).
% In the static beta_K branch, beta_K still follows
% K*hbar*omega_fund*rho_nt*sigma_K, so sigma_k_vec/k_power_vec must stay
% valid there. In the OFI-based branch, both dynamic Keldysh and static
% matched OFI use dI/dz = -Udep_matched*rho_scale*W_ion(I).
