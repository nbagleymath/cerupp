    % Pull back only the per-step outputs that the driver still reuses on
    % this z-step, then update the running plasma/stiffness/timing summaries.
    nla_diag_scatter_ws = step_diag.nla_diag_scatter_ws;
    warning_ledgers.plasma = step_warning_ledgers.plasma;
    warning_ledgers.nla = step_warning_ledgers.nla;
