%
% DESCRIPTION:
%   - Implements pulse propagation using the FEE (Forward Envelope Equation) in full (x,y,t,z).
%   - Propagation advances the field envelope A(x,y,t;z) through diffraction,
%     dispersion, Kerr, plasma, and nonlinear absorption.
%   - Includes support for Sellmeier dispersion, transverse refractive-index
%     structure, restart/checkpoint output, run-warning
%     summaries, and diagnostic reassembly around the main propagation
%     workflow.
%   - Main workflow: define the pulse and medium, build the operators,
%     propagate in z, then save diagnostics and checkpoints around that run.
%
%==========================================================================
% EQUATION WE ARE SOLVING (frequency-space representation)
%==========================================================================
%
% Numerical field symbols used below:
%   A0(x,y,t)                       : intensity-scaled envelope in the omega_fund carrier convention
%   A_S(x,y,t)                      : propagated time-domain envelope on the omega_ref FFT grid
%   E_hat(x,y,omega), A_SSF(x,y,omega) :
%       mixed (x,y,omega) space representation equal to the time FFT of
%       A_S; A_SSF is the name for that same field used within CerUPP
%   E_tilde(kx,ky,omega), A_F(kx,ky,omega) :
%       full spectral space representation equal to the full x-y-t FFT of
%       A_S (the propagated envelope A); A_F is the name for that same field used within CerUPP
%   J_eff_plasma                    : plasma-current effective source term
%
% Physical carrier convention:
%   E^(+)(x,y,t_lab,z) = A0(x,y,t,z)/sqrt(ep0*c*n_sell(omega_fund)/2) ...
%                    * exp(+1i * k(omega_fund) * z - 1i * omega_fund * t_lab)
%   where t is the solver pulse-frame time grid and
%   t_lab = t + z/v_g.
%   Here k(omega_fund)=n_sell(omega_fund)*omega_fund/c is the in-medium
%   carrier wavenumber. The later setup-side symbol k0_vac is the vacuum
%   wavenumber 2*pi/lambda_fund used by the mask/k-cut helpers and a few
%   scalar Kerr diagnostics.
% MATLAB's forward FFT in time uses exp(-1i*omega*t); that does not change
% the physical carrier written above.
%
% Stored A_S is not the direct physical omega_fund envelope unless
% omega_ref == omega_fund. The IC builder recenters onto the numerical FFT
% grid:
%   A_S(t) = A0(t) .* exp(-1i * (omega_fund - omega_ref) * t)
% so field reconstruction from stored A_S first demodulates back to
%   A0(t) = A_S(t) .* exp(+1i * (omega_fund - omega_ref) * t).
%
% Physical-field reconstruction from stored A_S:
%   A_S(x,y,t,z) is the propagated intensity-scaled envelope on the
%       pulse-frame t grid.
%   Recover the omega_fund-centered intensity-scaled envelope with
%       A0 = A_S .* exp(+1i * (omega_fund - omega_ref) * t).
%   Recover the physical complex envelope with
%       E_env0 = A0 ./ sqrt(ep0*c*n_sell(omega_fund)/2).
%   Rebuild laboratory time with t_lab = t + z/v_g for a static reference
%       medium; z-dependent reference media use the stored accumulated
%       scalar group delay.
%   Rebuild the analytic carrier field with
%       E^(+) = E_env0 .* exp(+1i*k(omega_fund)*z - 1i*omega_fund*t_lab).
%   The physical real field is real(E^(+)).
%   Magnitude-only diagnostics keep |A_S|^2 = |A0|^2, so intensity,
%       fluence, power, plasma density, NLA loss, energy, and beam-width
%       diagnostics do not need a separate recentering step.
%   A_SSF = fft(A_S,[],3) and A_F = fft2(A_SSF) under MATLAB's
%       unnormalized FFT convention; the manual gives the full
%       reference-frame table.
%
% Spectral form used by the solver when use_nlse_flag=true
% (NLSE Kerr form):
%   d/dz  A_F(kx,ky,omega)  =
%       +1i * [k(omega) - k(omega_fund) ...
%           - inv_vg_fund * (omega - omega_fund) ...
%           - k_perp^2/(2*k(omega)) ...
%             ] .* A_F ...
%       + 1i * F_xy[guiding_matrix(x,y,omega) .* F_t[A_S]] ...
%       + F_xyt[1i * (omega_fund/c) * n2(x,y) * |A_S|^2 .* A_S] ...
%       - F_xy[(1./(2*k(omega))) .* J_eff_plasma(x,y,omega)] ...
%       - F_xyt[S_NLA,time]
%
%     where A_S = F^(-1)_{xyt} [A_F]
%
% with
%
%   If use_nlse_flag=false, CerUPP uses the FEE Kerr term instead:
%       +1i * F_xy[Q(omega) .* ...
%           F_t[n2(x,y) * |A_S|^2 .* A_S]],
%       Q(omega) = (omega/c) * n_sell(omega_fund) ./ n_sell(omega)
%
%   k(omega) = n_sell(omega) * omega / c
%
%   guiding_matrix(x,y,omega) =
%       (omega/c) * ((n_lin(x,y,omega)^2 - n_sell(omega)^2) / ...
%       (2 * n_sell(omega)))
%
%   J_eff_plasma(x,y,omega)         : plasma-current effective source term
%       = (omega/c) * J_hat(x,y,omega) / (ep0*c)
%
%   Static beta_K sink:
%       S_NLA,time = 0.5 * (sum_K beta_K * I^(K-1)) .* A_S
%       With one active order this reduces to
%           0.5 * beta_K * I^(K-1) .* A_S
%
%   OFI-based matched sink:
%       dynamic Keldysh or static OFI:
%           S_NLA,time = 0.5 * Udep_matched * rho_scale * ...
%               (W_ion(I)./I) .* A_S
%           dI/dz = -Udep_matched * rho_scale * W_ion(I)
%       where rho_scale follows
%       nla_use_remaining_neutral_factor_flag:
%       max(rho_supply-rho,0) when that flag is true, or rho_ofi_scale
%       when that flag is false.
%
%   Intensity/source conventions:
%       I(x,y,t) = |A_S(x,y,t)|^2
%       S_ofi(I,rho) denotes the active OFI source law selected by the
%       plasma_ofi_use_remaining_neutral_factor_flag choice:
%       max(rho_supply-rho,0)*W_ion(I) when that flag is true, or
%       rho_ofi_scale*W_ion(I) when that flag is false
%
%   Here W_ion(I) is the active OFI law:
%       dynamic Keldysh W_ion(I) when keldysh_enabled=true
%       static sum_K sigma_K I^K otherwise
%   Udep_matched is the OFI-based optical depletion energy assigned to each
%       OFI-produced carrier counted through W_ion(I); see point 5 below
%       for the exact applied NLA forms.
%
% Split-step factors:
%   1. Diffraction + residual dispersion half-step in (kx,ky,omega):
%       A_F <- A_F .* exp(-1i * diffraction_dispersion_matrix * (dz/2))
%   2. Guiding half-step in (x,y,omega):
%       A_SSF <- A_SSF .* exp(+1i * guiding_matrix * (dz/2))
%   3. Kerr in (x,y,t):
%       NLSE mode: A_S <- A_S .* exp(+1i * phi),
%           phi = (omega_fund/c) * n2(x,y) * |A_S|^2 * dz
%       FEE mode:
%           dA_S/dz = +1i * F_t^{-1}[Q(omega) .* ...
%               F_t(n2(x,y) * |A_S|^2 .* A_S)],
%           Q(omega) = (omega/c) * n_sell(omega_fund) ./ n_sell(omega)
%   4. Plasma in time domain:
%       d(rho)/dt = S_ofi(I,rho) + W_aval(I) * rho ...
%                   - alpha_recombine * rho^2,
%       dA_S/dz = F_t^{-1}[ -(1/(2*k(omega))) * J_eff_plasma(x,y,omega) ],
%       then Euler/RK2 applies
%           A_S <- A_S + dz * F_t^{-1}[ -(1/(2*k(omega))) * J_eff_plasma(x,y,omega) ]
%   5. NLA in intensity form:
%       static beta_K closure:
%           dI/dz = -sum_K(beta_K * I^K),
%           beta_K = K*hbar*omega_fund*rho_nt*sigma_K
%       or OFI-based NLA closure:
%           dynamic Keldysh or static OFI:
%               dI/dz = -Udep_matched * rho_ofi_scale * W_ion(I)
%               or dI/dz = -Udep_matched * max(rho_supply-rho,0) * W_ion(I)
%               with rho_ofi_scale when
%               nla_use_remaining_neutral_factor_flag=false, or
%               max(rho_supply-rho,0) when
%               nla_use_remaining_neutral_factor_flag=true, independently of
%               plasma_ofi_use_remaining_neutral_factor_flag
%           and W_ion(I) is whichever OFI source law is active:
%           dynamic Keldysh W_ion(I) when keldysh_enabled=true, or
%           static sum_K sigma_K I^K when keldysh_enabled=false
%       then A_S <- A_S .* sqrt(I_new ./ I_old)
%
% Local updates in applied order:
%   1. Diffraction + residual dispersion half-step in (kx,ky,omega)
%   2. Guiding half-step in (x,y,omega)
%   3. Kerr applied in (x,y,t)
%   4. Plasma evolved and applied in time domain
%   5. NLA sink applied
%   6. Guiding half-step in (x,y,omega)
%   7. Diffraction + residual dispersion half-step in (kx,ky,omega)
%   8. Binary k and omega mask cleanup, transverse absorber, and final
%      binary k and omega cleanup
