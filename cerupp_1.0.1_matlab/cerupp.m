% The built-in solid-state Keldysh setup uses the effective gap E_gap and
% reduced carrier mass mu_red to form the adiabaticity parameter
% gamma_K = omega_fund*sqrt(mu_red*E_gap)/(qe*E), with
% E = sqrt(2*I/(n*ep0*c)).
% It first builds a volumetric interband rate w_vol(I), and the propagated
% runtime law later used by plasma and OFI-based NLA is the per-neutral
% rate W_ion(I) = w_vol(I) / rho_nt_keldysh_norm_m3.
% The original Keldysh (1965) Q-series branch uses
% w_vol(I) = prefactor_Q(gamma_K)*S_Q(gamma_K,nu)
% * exp(-pi*nu*(K_ell(gamma1) - E_ell(gamma1))/E_ell(gamma2)),
% where gamma1 = gamma_K^2/(1 + gamma_K^2), gamma2 = 1/(1 + gamma_K^2),
% prefactor_Q(gamma_K) =
% ((2*omega_fund)/(9*pi))*((mu_red*omega_fund)/(hbar*sqrt(gamma1)))^(3/2),
% and
% S_Q(gamma_K,nu) = sqrt(pi/(2*K_ell(gamma2))) * sum_{n>=0}
% exp(-pi*n*ratio)
% * D(sqrt(pi^2*(2*nu - 2*x + n)/(2*K_ell(gamma2)*E_ell(gamma2)))).
% CerUPP evaluates D(...) with the same three-region rational Dawson fit
% used by plasma_keldysh_setup.
