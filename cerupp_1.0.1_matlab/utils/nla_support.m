            [varargout{1:nargout}] = nla_support_build_keldysh_nla_context_local(varargin{:});
        end

        function [mode_name, mode_code, check_flag, applied_flag] = ...
                resolve_ofi_depletion_accounting_mode(varargin)
        % Resolve OFI event-energy accounting from the public booleans.

            if nargin == 1 && (ischar(varargin{1}) || ...
                    (isstring(varargin{1}) && isscalar(varargin{1})))
                mode_name = nla_support.normalize_ofi_energy_accounting_mode( ...
                    varargin{1});
            elseif nargin >= 3
                requested_mode = varargin{1};
                if isempty(requested_mode)
                    [mode_name, ~, ~, ~] = nla_support.resolve_ofi_depletion_accounting_mode( ...
                        varargin{2}, varargin{3});
                else
                    mode_name = nla_support.normalize_ofi_energy_accounting_mode( ...
                        requested_mode);
                end
            elseif nargin >= 2
                check_flag = struct_utils.normalize_bool_scalar( ...
                    varargin{1}, 'nla_check_ofi_event_energy_flag', ...
                    'CerUPP:InvalidOfiLedgerAccountingFlag');
                applied_flag = struct_utils.normalize_bool_scalar( ...
                    varargin{2}, 'nla_use_ofi_event_depletion_flag', ...
                    'CerUPP:InvalidOfiLedgerAccountingFlag');
                if logical(applied_flag)
                    mode_name = 'ofi_event_depletion';
                elseif logical(check_flag)
                    mode_name = 'ofi_event_check';
                else
                    mode_name = 'rate_matched';
                end
            else
                mode_name = 'rate_matched';
            end

            switch mode_name
                case 'rate_matched'
                    mode_code = uint8(0);
                    check_flag = false;
                    applied_flag = false;
                case 'ofi_event_check'
                    mode_code = uint8(1);
                    check_flag = true;
                    applied_flag = false;
                case 'ofi_event_depletion'
                    mode_code = uint8(2);
                    check_flag = false;
                    applied_flag = true;
                otherwise
                    error('CerUPP:InvalidOfiLedgerAccountingMode', ...
                        'Unsupported OFI accounting mode ''%s''.', mode_name);
            end
        end

        function mode_name = normalize_ofi_energy_accounting_mode(mode_in)
        % Normalize saved OFI event-energy accounting metadata.

            if isstring(mode_in)
                mode_in = char(mode_in);
            end
            if ~(ischar(mode_in) || isempty(mode_in))
                error('CerUPP:InvalidOfiLedgerAccountingMode', ...
                    'nla_ofi_energy_accounting_mode must be a char/string scalar.');
            end
            mode_name = lower(strtrim(char(mode_in)));
            if isempty(mode_name)
                mode_name = 'rate_matched';
            end
            mode_name = strrep(mode_name, '-', '_');
            switch mode_name
                case {'rate_matched'}
                    mode_name = 'rate_matched';
                case {'ofi_event_check'}
                    mode_name = 'ofi_event_check';
                case {'ofi_event_depletion'}
                    mode_name = 'ofi_event_depletion';
                otherwise
                    error('CerUPP:InvalidOfiLedgerAccountingMode', ...
                        ['nla_ofi_energy_accounting_mode must be rate_matched, ', ...
                         'ofi_event_check, or ofi_event_depletion; got ''%s''.'], ...
                        char(mode_in));
            end
        end

        function mode_payload = require_runtime_mode_payload(nla_runtime_cfg)
        % Return the prebuilt runtime NLA mode descriptor consumed by advance_z_step.

            if ~(isstruct(nla_runtime_cfg) && isfield(nla_runtime_cfg, 'mode_payload') && ...
                    isstruct(nla_runtime_cfg.mode_payload) && ~isempty(nla_runtime_cfg.mode_payload))
                error('CerUPP:AdvanceStepMissingNlaModePayload', ...
                    ['nla_runtime_cfg.mode_payload must be prebuilt during setup before the propagation-loop ', ...
