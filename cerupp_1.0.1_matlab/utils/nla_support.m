classdef nla_support
%NLA_SUPPORT Shared setup, mode-selection, and runtime helpers for NLA.
% cerupp.m still owns the visible NLA knobs and step ordering. This file
% keeps the deeper NLA setup validation, closure accounting, and runtime
% loss kernels in one place for setup helpers, advance_z_step.m, and
% postprocess/reporting code.
% Called mainly from cerupp.m, advance_z_step.m, and build_plasma_ofi_nla_step_inputs.m.

    methods (Static)
        function [k_active, beta_active] = canonicalize_static_term_pairs( ...
                k_terms_in, beta_terms_in, require_all_terms_active, pair_label, ...
                length_error_id, invalid_error_id)
        % Shared validator for static-NLA term vectors.

            if nargin < 3 || isempty(require_all_terms_active)
                require_all_terms_active = false;
            else
                require_all_terms_active = logical(require_all_terms_active);
            end
            if nargin < 4 || isempty(pair_label)
                pair_label = 'Static NLA term pairs';
            end
            if nargin < 5 || isempty(length_error_id)
                length_error_id = 'CerUPP:InvalidStaticNlaTermLengths';
            end
            if nargin < 6 || isempty(invalid_error_id)
                invalid_error_id = 'CerUPP:InvalidStaticNlaOrder';
            end

            k_terms = double(k_terms_in(:));
            beta_terms = double(beta_terms_in(:));
            if numel(k_terms) ~= numel(beta_terms)
                error(length_error_id, ...
                    '%s must have equal lengths; got %d and %d.', ...
                    pair_label, numel(k_terms), numel(beta_terms));
            end

            if require_all_terms_active
                bad_term = ~isfinite(k_terms) | (k_terms <= 0) | ...
                    ~isfinite(beta_terms) | (beta_terms <= 0);
                if any(bad_term)
                    bad_idx = find(bad_term, 1, 'first');
                    error(invalid_error_id, ...
                        ['%s require finite positive K and beta_K > 0. ' ...
                         'Got K=%g, beta=%g at linear index %d.'], ...
                        pair_label, double(k_terms(bad_idx)), double(beta_terms(bad_idx)), bad_idx);
                end
                k_active = k_terms;
                beta_active = beta_terms;
                return;
            end

            invalid_term_mask = ~isfinite(k_terms) | ~isfinite(beta_terms) | ...
                (k_terms <= 0) | (beta_terms <= 0);
            if any(invalid_term_mask)
                bad_idx = find(invalid_term_mask, 1, 'first');
                error(invalid_error_id, ...
                    ['%s require finite positive K and beta_K for every explicit term. ' ...
                     'Remove placeholder zero/NaN padding before calling this validator; ', ...
                     'got K=%g, beta=%g at linear index %d.'], ...
                    pair_label, double(k_terms(bad_idx)), double(beta_terms(bad_idx)), bad_idx);
            end
            k_active = k_terms;
            beta_active = beta_terms;
        end

        function desc = build_static_multiorder_descriptor(k_orders, beta_vals)
        % Canonical compact static-NLA descriptor builder.

            if nargin < 1 || isempty(k_orders)
                k_orders = zeros(0, 1);
            end
            if nargin < 2 || isempty(beta_vals)
                beta_vals = zeros(0, 1);
            end
            k_orders = double(k_orders(:));
            beta_vals = double(beta_vals(:));
            desc = struct( ...
                'kind_code', uint8(2), ...
                'k_orders', k_orders, ...
                'beta_vals', beta_vals, ...
                'max_exp', 0, ...
                'loss_coef', zeros(0, 1), ...
                'j_coef', zeros(0, 1), ...
                'active_exp', zeros(0, 1), ...
                'active_loss_coef', zeros(0, 1), ...
                'active_j_coef', zeros(0, 1));
            if numel(k_orders) <= 1
                return;
            end

            is_int_positive = all(isfinite(k_orders)) && ...
                all(k_orders >= 1) && all(k_orders == floor(k_orders));
            if ~is_int_positive
                return;
            end

            k_int = k_orders;
            max_exp = max([k_int; max(k_int - 1, 0)]);
            if isempty(max_exp) || ~isfinite(max_exp) || (max_exp < 0)
                return;
            end
            max_exp = double(max_exp);
            loss_coef = zeros(max_exp + 1, 1);
            j_coef = zeros(max_exp + 1, 1);
            for kk = 1:numel(k_int)
                b = beta_vals(kk);
                if b == 0
                    continue;
                end
                kk_2 = k_int(kk);
                loss_coef(kk_2 + 1) = loss_coef(kk_2 + 1) + b;
                j_coef(max(kk_2 - 1, 0) + 1) = j_coef(max(kk_2 - 1, 0) + 1) + b;
            end
            active_idx = find((loss_coef ~= 0) | (j_coef ~= 0));
            desc.kind_code = uint8(1);
            desc.max_exp = max_exp;
            desc.loss_coef = loss_coef;
            desc.j_coef = j_coef;
            desc.active_exp = double(active_idx(:) - 1);
            desc.active_loss_coef = loss_coef(active_idx);
            desc.active_j_coef = j_coef(active_idx);
        end

        function [nla_cfg, run_warn_state, setup_physics_rewrite_report] = build_runtime_cfg( ...
                k_power_vec_2, beta_k_vec, nl_absorption_flag, nla_setup_opts, ...
                nla_cfg_prev, run_warn_state, setup_physics_rewrite_report)
        % Build prevalidated NLA coefficients once per medium/operator build.

            if (nargin < 4) || isempty(nla_setup_opts) || ~isstruct(nla_setup_opts)
                nla_setup_opts = struct();
            end
            nla_setup_opts = nla_support_validate_setup_option_fields_local(nla_setup_opts);
            if (nargin < 5) || isempty(nla_cfg_prev) || ~isstruct(nla_cfg_prev)
                nla_cfg_prev = struct();
            end
            if nargin < 6 || isempty(run_warn_state) || ~isstruct(run_warn_state)
                run_warn_state = struct();
            end
            if nargin < 7 || isempty(setup_physics_rewrite_report) || ...
                    ~isstruct(setup_physics_rewrite_report)
                setup_physics_rewrite_report = struct();
            end
            if ~(islogical(nl_absorption_flag) && isscalar(nl_absorption_flag))
                error('CerUPP:InvalidNlaAbsorptionFlag', ...
                    'nl_absorption_flag must already be a logical scalar before nla_support.build_runtime_cfg.');
            end
            resolved_closure = nla_support.build_setup_resolved_closure(nla_setup_opts);
            ofi_event_accounting_requested = ...
                logical(resolved_closure.nla_check_ofi_event_energy_flag) || ...
                logical(resolved_closure.nla_use_ofi_event_depletion_flag);
            if ofi_event_accounting_requested && ~logical(nl_absorption_flag)
                error('CerUPP:InvalidOfiLedgerAccountingMode', ...
                    ['OFI event-energy accounting requires nl_absorption_flag=true. ', ...
                     'The check flag reports an event-based energy comparison, and ', ...
                     'the depletion flag consumes the NLA update path.']);
            end
            nla_cfg = struct( ...
                'k_orders', zeros(0, 1), ...
                'beta_vals', zeros(0, 1), ...
                'static_multiorder_desc', nla_support.build_static_multiorder_descriptor([], []), ...
                'closure_mode_requested', resolved_closure.requested_mode, ...
                'closure_mode', resolved_closure.effective_mode, ...
                'closure_code', resolved_closure.closure_code, ...
                'nla_ofi_energy_accounting_mode', ...
                    resolved_closure.ofi_depletion_accounting_mode, ...
                'ofi_depletion_accounting_mode', ...
                    resolved_closure.ofi_depletion_accounting_mode, ...
                'ofi_depletion_accounting_mode_code', ...
                    resolved_closure.ofi_depletion_accounting_mode_code, ...
                'nla_check_ofi_event_energy_flag', ...
                    logical(resolved_closure.nla_check_ofi_event_energy_flag), ...
                'nla_use_ofi_event_depletion_flag', ...
                    logical(resolved_closure.nla_use_ofi_event_depletion_flag), ...
                'keldysh_nla_enabled', logical(resolved_closure.keldysh_nla_enabled), ...
                'plasma_ofi_use_remaining_neutral_factor_flag', ...
                    logical(struct_utils.opt_struct_field( ...
                    resolved_closure, 'plasma_ofi_use_remaining_neutral_factor_flag', true)), ...
                'nla_use_remaining_neutral_factor_flag_requested', ...
                    logical(resolved_closure.nla_use_remaining_neutral_factor_flag_requested), ...
                'nla_use_remaining_neutral_factor_flag_effective', ...
                    logical(resolved_closure.nla_use_remaining_neutral_factor_flag_effective), ...
                'rk_order_mode', resolved_closure.rk_order_mode, ...
                'rk_order', resolved_closure.rk_order, ...
                'uses_neutral_fraction', resolved_closure.uses_neutral_fraction, ...
                'explicit_static_override_active', ...
                    logical(resolved_closure.explicit_static_override_active), ...
                'resolved_closure', resolved_closure, ...
                'keldysh_ctx_static', struct('enabled', false));
            nla_cfg.mode_payload = nla_support.build_mode_payload(nla_cfg);

            if logical(nl_absorption_flag) && logical(resolved_closure.keldysh_nla_enabled) && ...
                    logical(struct_utils.opt_struct_field( ...
                        resolved_closure, 'plasma_ofi_nla_weighting_mismatch_requested', false))
                run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                    run_warn_state, 'setup', ...
                    'plasma_ofi_nla_weighting_mismatch', ...
                    'CerUPP:Nla:PlasmaOfiWeightingMismatch', ...
                    ['nla_use_ofi_rate_law_flag=true keeps the optical sink on the active plasma OFI law, but ', ...
                     'plasma_ofi_use_remaining_neutral_factor_flag=%d and nla_use_remaining_neutral_factor_flag=%d differ. ', ...
                     'CerUPP now leaves them independent: the plasma OFI source uses the plasma flag, while the OFI-based optical sink uses the NLA flag. ', ...
                     'Set them equal if you want both branches to share the same neutral-weighting convention.'], ...
                    logical(struct_utils.opt_struct_field( ...
                        resolved_closure, 'plasma_ofi_use_remaining_neutral_factor_flag', true)), ...
                    logical(struct_utils.opt_struct_field( ...
                        resolved_closure, 'nla_use_remaining_neutral_factor_flag_effective', false)));
            end

            if ~nl_absorption_flag
                return;
            end
            if logical(resolved_closure.keldysh_nla_enabled)
                return;
            end

            k_orders = double(k_power_vec_2(:));
            beta_vals = double(beta_k_vec(:));
            if numel(k_orders) ~= numel(beta_vals)
                error('CerUPP:DriverVectorLengthMismatchNLA', ...
                    'K_power_vec and beta_K_vec must have equal lengths (got %d and %d).', ...
                    numel(k_orders), numel(beta_vals));
            end
            if isempty(k_orders)
                error('CerUPP:DriverEmptyNLAParams', ...
                    'nl_absorption_flag=true but K_power_vec/beta_K_vec are empty.');
            end
            if any(~isfinite(k_orders)) || any(~isfinite(beta_vals)) || ...
                    any(~isreal(beta_vals))
                error('CerUPP:DriverInvalidNLAParams', ...
                    'K_power_vec and beta_K_vec must be finite real values.');
            end
            if any(k_orders < 1) || any(beta_vals <= 0)
                error('CerUPP:DriverInvalidNLAParams', ...
                    'Require K_power_vec >= 1 and beta_K_vec > 0 for Practitioner''s Guide analytic NLA.');
            end

            nla_cfg.k_orders = k_orders;
            nla_cfg.beta_vals = beta_vals;
            nla_cfg.mode_payload = nla_support.build_mode_payload(nla_cfg);
            nla_cfg.static_multiorder_desc = nla_cfg.mode_payload.static_multiorder_desc;
        end

        function resolved_closure = build_setup_resolved_closure(nla_setup_opts)
        % Build the one canonical setup-owned NLA closure record.

            if nargin < 1 || isempty(nla_setup_opts) || ~isstruct(nla_setup_opts)
                nla_setup_opts = struct();
            end
            nla_setup_opts = nla_support_validate_setup_option_fields_local(nla_setup_opts);
            if isfield(nla_setup_opts, 'resolved_closure') && ...
                    isstruct(nla_setup_opts.resolved_closure) && ...
                    ~isempty(nla_setup_opts.resolved_closure)
                resolved_closure = nla_support.resolve_closure_record( ...
                    nla_setup_opts.resolved_closure);
                if isfield(nla_setup_opts, 'nla_ofi_energy_accounting_mode') || ...
                        isfield(nla_setup_opts, 'nla_check_ofi_event_energy_flag') || ...
                        isfield(nla_setup_opts, 'nla_use_ofi_event_depletion_flag')
                    ofi_event_energy_check_request = struct_utils.normalize_bool_scalar( ...
                        struct_utils.opt_struct_field( ...
                            nla_setup_opts, 'nla_check_ofi_event_energy_flag', ...
                            resolved_closure.nla_check_ofi_event_energy_flag), ...
                        'nla_setup_opts.nla_check_ofi_event_energy_flag', ...
                        'CerUPP:InvalidOfiLedgerAccountingFlag');
                    ofi_event_depletion_request = struct_utils.normalize_bool_scalar( ...
                        struct_utils.opt_struct_field( ...
                            nla_setup_opts, 'nla_use_ofi_event_depletion_flag', ...
                            resolved_closure.nla_use_ofi_event_depletion_flag), ...
                        'nla_setup_opts.nla_use_ofi_event_depletion_flag', ...
                        'CerUPP:InvalidOfiLedgerAccountingFlag');
                    [mode_name, mode_code, nla_check_ofi_event_energy_flag, ...
                        nla_use_ofi_event_depletion_flag] = ...
                        nla_support.resolve_ofi_depletion_accounting_mode( ...
                            struct_utils.opt_struct_field( ...
                                nla_setup_opts, 'nla_ofi_energy_accounting_mode', ...
                                resolved_closure.ofi_depletion_accounting_mode), ...
                            ofi_event_energy_check_request, ...
                            ofi_event_depletion_request);
                    resolved_closure.nla_check_ofi_event_energy_flag = ...
                        logical(nla_check_ofi_event_energy_flag);
                    resolved_closure.nla_use_ofi_event_depletion_flag = ...
                        logical(nla_use_ofi_event_depletion_flag);
                    resolved_closure.nla_ofi_energy_accounting_mode = mode_name;
                    resolved_closure.ofi_depletion_accounting_mode = mode_name;
                    resolved_closure.ofi_depletion_accounting_mode_code = mode_code;
                end
                ofi_event_accounting_requested = ...
                    logical(resolved_closure.nla_check_ofi_event_energy_flag) || ...
                    logical(resolved_closure.nla_use_ofi_event_depletion_flag);
                if ofi_event_accounting_requested
                    plasma_flag_for_ledger = struct_utils.normalize_bool_scalar( ...
                        struct_utils.opt_struct_field(nla_setup_opts, 'plasma_flag', false), ...
                        'nla_setup_opts.plasma_flag', ...
                        'CerUPP:InvalidOfiLedgerAccountingFlag');
                    ofi_branch_active_for_ledger = struct_utils.normalize_bool_scalar( ...
                        struct_utils.opt_struct_field(nla_setup_opts, 'ofi_branch_active', true), ...
                        'nla_setup_opts.ofi_branch_active', ...
                        'CerUPP:InvalidNlaOfiBranchActiveFlag');
                    if ~logical(resolved_closure.keldysh_nla_enabled)
                        error('CerUPP:InvalidOfiLedgerAccountingMode', ...
                            ['OFI event-energy accounting requires ', ...
                             'nla_use_ofi_rate_law_flag=true so the NLA path is OFI-based.']);
                    end
                    if ~logical(plasma_flag_for_ledger) || ...
                            ~logical(ofi_branch_active_for_ledger)
                        error('CerUPP:InvalidOfiLedgerAccountingMode', ...
                            ['OFI event-energy accounting requires plasma_flag=true ', ...
                             'and an active OFI source branch because the event ', ...
                             'increment is owned by the plasma substep.']);
                    end
                end
                if logical(resolved_closure.nla_use_ofi_event_depletion_flag)
                    if logical(struct_utils.opt_struct_field( ...
                            resolved_closure, ...
                            'plasma_ofi_nla_weighting_mismatch_requested', false))
                        error('CerUPP:InvalidOfiLedgerWeightingMismatch', ...
                            ['nla_use_ofi_event_depletion_flag=true requires the NLA ', ...
                             'remaining-neutral flag to match the plasma OFI source weighting.']);
                    end
                end
                return;
            end
            ofi_event_energy_check_request = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field( ...
                    nla_setup_opts, 'nla_check_ofi_event_energy_flag', false), ...
                'nla_setup_opts.nla_check_ofi_event_energy_flag', ...
                'CerUPP:InvalidOfiLedgerAccountingFlag');
            ofi_event_depletion_request = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field( ...
                    nla_setup_opts, 'nla_use_ofi_event_depletion_flag', false), ...
                'nla_setup_opts.nla_use_ofi_event_depletion_flag', ...
                'CerUPP:InvalidOfiLedgerAccountingFlag');
            [ofi_depletion_accounting_mode, ofi_depletion_accounting_mode_code, ...
                nla_check_ofi_event_energy_flag, nla_use_ofi_event_depletion_flag] = ...
                nla_support.resolve_ofi_depletion_accounting_mode( ...
                    struct_utils.opt_struct_field( ...
                        nla_setup_opts, 'nla_ofi_energy_accounting_mode', ''), ...
                    ofi_event_energy_check_request, ...
                    ofi_event_depletion_request);
            plasma_flag_for_ledger = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(nla_setup_opts, 'plasma_flag', false), ...
                'nla_setup_opts.plasma_flag', 'CerUPP:InvalidOfiLedgerAccountingFlag');
            plasma_ofi_use_remaining_neutral_factor_flag = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field( ...
                    nla_setup_opts, 'plasma_ofi_use_remaining_neutral_factor_flag', ...
                    ~struct_utils.opt_struct_field( ...
                        nla_setup_opts, 'keldysh_use_additive_volumetric_source_flag', false)), ...
                'nla_setup_opts.plasma_ofi_use_remaining_neutral_factor_flag', ...
                'CerUPP:InvalidNlaKeldyshSourceConvention');
            nla_use_remaining_neutral_factor_flag_requested = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field( ...
                    nla_setup_opts, 'nla_use_remaining_neutral_factor_flag', ...
                    plasma_ofi_use_remaining_neutral_factor_flag), ...
                'nla_use_remaining_neutral_factor_flag', ...
                'CerUPP:InvalidNlaDepletionAwareFlag');
            [rk_order_mode, rk_order] = nla_support_resolve_rk_order_local( ...
                struct_utils.opt_struct_field(nla_setup_opts, 'nla_z_rk2_flag', []));
            [requested_mode, explicit_static_override_active] = ...
                nla_support_resolve_requested_closure_mode_local(nla_setup_opts);
            keldysh_enabled_for_nla = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(nla_setup_opts, 'keldysh_enabled', false), ...
                'nla_setup_opts.keldysh_enabled', 'CerUPP:InvalidNlaKeldyshEnabledFlag');
            keldysh_use_additive_volumetric_source_flag = ...
                ~logical(plasma_ofi_use_remaining_neutral_factor_flag);
            ofi_branch_active_for_nla = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field( ...
                    nla_setup_opts, 'ofi_branch_active', keldysh_enabled_for_nla), ...
                'nla_setup_opts.ofi_branch_active', 'CerUPP:InvalidNlaOfiBranchActiveFlag');
            effective_mode = requested_mode;
            [closure_code, effective_mode] = nla_support.normalize_effective_closure_identifier( ...
                effective_mode, 'CerUPP:InvalidNlaClosureMode', 'NLA closure mode');
            keldysh_nla_enabled = (closure_code == uint8(2));
            if logical(keldysh_nla_enabled) && ~logical(ofi_branch_active_for_nla)
                error('CerUPP:InvalidNlaClosureMode', ...
                    ['OFI-based NLA requires an active OFI/plasma branch. ', ...
                     'Set nla_use_ofi_rate_law_flag=false to stay on the static beta_K sink, ', ...
                     'or enable an OFI/plasma branch first.']);
            end
            ofi_event_accounting_requested = ...
                logical(nla_check_ofi_event_energy_flag) || ...
                logical(nla_use_ofi_event_depletion_flag);
            if ofi_event_accounting_requested
                if ~logical(keldysh_nla_enabled)
                    error('CerUPP:InvalidOfiLedgerAccountingMode', ...
                        ['OFI event-energy accounting requires ', ...
                         'nla_use_ofi_rate_law_flag=true so the NLA path is OFI-based.']);
                end
                if ~logical(plasma_flag_for_ledger) || ~logical(ofi_branch_active_for_nla)
                    error('CerUPP:InvalidOfiLedgerAccountingMode', ...
                        ['OFI event-energy accounting requires plasma_flag=true ', ...
                         'and an active OFI source branch because the loss is driven by ', ...
                         'the plasma OFI event increment.']);
                end
            end
            nla_use_remaining_neutral_factor_flag_effective = ...
                logical(nla_use_remaining_neutral_factor_flag_requested);
            plasma_ofi_nla_replenishment_fallback_applied = false;
            plasma_ofi_nla_weighting_mismatch_requested = logical(keldysh_nla_enabled) && ...
                (logical(nla_use_remaining_neutral_factor_flag_requested) ~= ...
                 logical(plasma_ofi_use_remaining_neutral_factor_flag));
            if logical(nla_use_ofi_event_depletion_flag) && ...
                    logical(plasma_ofi_nla_weighting_mismatch_requested)
                error('CerUPP:InvalidOfiLedgerWeightingMismatch', ...
                    ['nla_use_ofi_event_depletion_flag=true requires ', ...
                     'nla_use_remaining_neutral_factor_flag to match ', ...
                     'plasma_ofi_use_remaining_neutral_factor_flag. The ledger already ', ...
                     'contains the plasma source-side reservoir weighting.']);
            end
            resolved_closure = struct( ...
                'requested_mode', requested_mode, ...
                'effective_mode', effective_mode, ...
                'closure_code', closure_code, ...
                'nla_ofi_energy_accounting_mode', ofi_depletion_accounting_mode, ...
                'ofi_depletion_accounting_mode', ofi_depletion_accounting_mode, ...
                'ofi_depletion_accounting_mode_code', ...
                    ofi_depletion_accounting_mode_code, ...
                'nla_check_ofi_event_energy_flag', ...
                    logical(nla_check_ofi_event_energy_flag), ...
                'nla_use_ofi_event_depletion_flag', ...
                    logical(nla_use_ofi_event_depletion_flag), ...
                'keldysh_nla_enabled', logical(keldysh_nla_enabled), ...
                'plasma_ofi_use_remaining_neutral_factor_flag', ...
                    logical(plasma_ofi_use_remaining_neutral_factor_flag), ...
                'nla_use_remaining_neutral_factor_flag_requested', ...
                    logical(nla_use_remaining_neutral_factor_flag_requested), ...
                'nla_use_remaining_neutral_factor_flag_effective', ...
                    logical(nla_use_remaining_neutral_factor_flag_effective), ...
                'plasma_ofi_nla_replenishment_fallback_applied', ...
                    logical(plasma_ofi_nla_replenishment_fallback_applied), ...
                'plasma_ofi_nla_weighting_mismatch_requested', ...
                    logical(plasma_ofi_nla_weighting_mismatch_requested), ...
                'uses_neutral_fraction', logical(nla_support.uses_neutral_fraction( ...
                    keldysh_nla_enabled, nla_use_remaining_neutral_factor_flag_effective, ...
                    keldysh_use_additive_volumetric_source_flag)), ...
                'explicit_static_override_active', logical(explicit_static_override_active), ...
                'rk_order_mode', rk_order_mode, ...
                'rk_order', double(rk_order));
        end

        function [closure_code, closure_mode] = normalize_effective_closure_identifier( ...
                closure_identifier, error_id, source_label)
        % Normalize an effective NLA closure identifier from either a label or a code.

            if nargin < 1 || isempty(closure_identifier)
                closure_identifier = 'static_mpi_beta';
            end
            if nargin < 2 || isempty(error_id)
                error_id = 'CerUPP:InvalidNlaClosureMode';
            end
            if nargin < 3 || isempty(source_label)
                source_label = 'nla closure';
            end
            if isstring(closure_identifier) && isscalar(closure_identifier)
                closure_identifier = char(closure_identifier);
            end
            if ischar(closure_identifier)
                closure_mode = lower(strtrim(closure_identifier));
                if strcmp(closure_mode, 'static_mpi_beta')
                    closure_code = uint8(1);
                    return;
                end
                if strcmp(closure_mode, 'plasma_ofi')
                    closure_code = uint8(2);
                    closure_mode = 'plasma_ofi';
                    return;
                end
                error(error_id, ...
                    ['Unsupported %s ''%s''. Use plasma_ofi or static_mpi_beta.'], ...
                    char(source_label), closure_mode);
            end
            if isnumeric(closure_identifier) && isscalar(closure_identifier) && ...
                    isreal(closure_identifier) && isfinite(closure_identifier)
                closure_code = double(closure_identifier);
                if closure_code == 1
                    closure_code = uint8(1);
                    closure_mode = 'static_mpi_beta';
                    return;
                end
                if closure_code == 2
                    closure_code = uint8(2);
                    closure_mode = 'plasma_ofi';
                    return;
                end
                error(error_id, ...
                    ['Unsupported %s code %.17g. Use exact closure code 1 (static_mpi_beta) ', ...
                     'or 2 (plasma_ofi).'], ...
                    char(source_label), double(closure_identifier));
            end
            error(error_id, ...
                '%s must be a char/string closure label or a numeric scalar closure code; got %s.', ...
                char(source_label), class(closure_identifier));
        end

        function [closure_code, keldysh_nla_enabled, closure_mode] = ...
                resolve_effective_closure_state(nla_cfg)
        % Prefer setup-owned numeric closure flags over string labels for live NLA state.

            resolved_closure = nla_support.resolve_closure_record(nla_cfg);
            closure_code = resolved_closure.closure_code;
            keldysh_nla_enabled = resolved_closure.keldysh_nla_enabled;
            closure_mode = resolved_closure.effective_mode;
        end

        function resolved_closure = resolve_closure_record(nla_cfg)
        % Normalize any live NLA config onto the canonical resolved-closure record.

            if nargin < 1 || isempty(nla_cfg) || ~isstruct(nla_cfg)
                nla_cfg = struct();
            end
            if isfield(nla_cfg, 'resolved_closure') && isstruct(nla_cfg.resolved_closure) && ...
                    ~isempty(nla_cfg.resolved_closure)
                closure_source = nla_cfg.resolved_closure;
            else
                closure_source = nla_cfg;
            end
            requested_mode = char(string(struct_utils.opt_struct_field( ...
                closure_source, 'requested_mode', struct_utils.opt_struct_field( ...
                    closure_source, 'closure_mode_requested', 'auto'))));
            if isempty(strtrim(requested_mode))
                requested_mode = 'auto';
            end
            [closure_code, effective_mode] = nla_support.normalize_effective_closure_identifier( ...
                struct_utils.opt_struct_field(closure_source, 'closure_code', ...
                    struct_utils.opt_struct_field(closure_source, 'effective_mode', ...
                        struct_utils.opt_struct_field(closure_source, 'closure_mode', ...
                            'static_mpi_beta'))), ...
                'CerUPP:InvalidNlaClosureMode', 'effective nla closure');
            keldysh_nla_enabled = (closure_code == uint8(2));
            if isfield(closure_source, 'keldysh_nla_enabled') && ...
                    ~isempty(closure_source.keldysh_nla_enabled)
                keldysh_flag = struct_utils.normalize_bool_scalar( ...
                    closure_source.keldysh_nla_enabled, 'nla_cfg.keldysh_nla_enabled', ...
                    'CerUPP:InvalidNlaClosureMode');
                if logical(keldysh_flag) ~= logical(keldysh_nla_enabled)
                    error('CerUPP:InvalidNlaClosureMode', ...
                        'nla_cfg.keldysh_nla_enabled disagrees with the effective NLA closure selection.');
                end
            end
            plasma_ofi_use_remaining_neutral_factor_flag = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, ...
                    'plasma_ofi_use_remaining_neutral_factor_flag', ...
                    ~struct_utils.opt_struct_field( ...
                        closure_source, 'keldysh_use_additive_volumetric_source_flag', false)), ...
                'nla_cfg.plasma_ofi_use_remaining_neutral_factor_flag', ...
                'CerUPP:InvalidNlaClosureMode');
            nla_use_remaining_neutral_factor_flag_requested = ...
                struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, ...
                    'nla_use_remaining_neutral_factor_flag_requested', ...
                    struct_utils.opt_struct_field(closure_source, ...
                        'nla_use_remaining_neutral_factor_flag', ...
                        plasma_ofi_use_remaining_neutral_factor_flag)), ...
                'nla_cfg.nla_use_remaining_neutral_factor_flag_requested', ...
                'CerUPP:InvalidNlaClosureMode');
            nla_use_remaining_neutral_factor_flag_effective = ...
                struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, ...
                    'nla_use_remaining_neutral_factor_flag_effective', ...
                    nla_use_remaining_neutral_factor_flag_requested), ...
                'nla_cfg.nla_use_remaining_neutral_factor_flag_effective', ...
                'CerUPP:InvalidNlaClosureMode');
            plasma_ofi_nla_replenishment_fallback_applied = ...
                struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, ...
                    'plasma_ofi_nla_replenishment_fallback_applied', ...
                    false), ...
                'nla_cfg.plasma_ofi_nla_replenishment_fallback_applied', ...
                'CerUPP:InvalidNlaClosureMode');
            plasma_ofi_nla_weighting_mismatch_requested = ...
                struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, ...
                    'plasma_ofi_nla_weighting_mismatch_requested', ...
                    logical(keldysh_nla_enabled) && ...
                    (logical(nla_use_remaining_neutral_factor_flag_requested) ~= ...
                     logical(plasma_ofi_use_remaining_neutral_factor_flag))), ...
                'nla_cfg.plasma_ofi_nla_weighting_mismatch_requested', ...
                'CerUPP:InvalidNlaClosureMode');
            keldysh_use_additive_volumetric_source_flag = ...
                struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, ...
                    'keldysh_use_additive_volumetric_source_flag', ...
                    ~plasma_ofi_use_remaining_neutral_factor_flag), ...
                'nla_cfg.keldysh_use_additive_volumetric_source_flag', ...
                'CerUPP:InvalidNlaClosureMode');
            explicit_static_override_active = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, ...
                    'explicit_static_override_active', strcmp(requested_mode, 'static_mpi_beta')), ...
                'nla_cfg.explicit_static_override_active', ...
                'CerUPP:InvalidNlaClosureMode');
            uses_neutral_fraction = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, 'uses_neutral_fraction', ...
                    nla_support.uses_neutral_fraction( ...
                        keldysh_nla_enabled, nla_use_remaining_neutral_factor_flag_effective, ...
                        keldysh_use_additive_volumetric_source_flag)), ...
                'nla_cfg.uses_neutral_fraction', 'CerUPP:InvalidNlaClosureMode');
            [rk_order_mode, rk_order] = ...
                nla_support_normalize_resolved_rk_order_local(closure_source);
            ofi_event_energy_check_request = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, ...
                    'nla_check_ofi_event_energy_flag', false), ...
                'nla_cfg.nla_check_ofi_event_energy_flag', ...
                'CerUPP:InvalidOfiLedgerAccountingFlag');
            ofi_event_depletion_request = struct_utils.normalize_bool_scalar( ...
                struct_utils.opt_struct_field(closure_source, ...
                    'nla_use_ofi_event_depletion_flag', false), ...
                'nla_cfg.nla_use_ofi_event_depletion_flag', ...
                'CerUPP:InvalidOfiLedgerAccountingFlag');
            [ofi_depletion_accounting_mode, ofi_depletion_accounting_mode_code, ...
                nla_check_ofi_event_energy_flag, nla_use_ofi_event_depletion_flag] = ...
                nla_support.resolve_ofi_depletion_accounting_mode( ...
                    struct_utils.opt_struct_field( ...
                        closure_source, 'nla_ofi_energy_accounting_mode', ...
                        struct_utils.opt_struct_field( ...
                            closure_source, 'ofi_depletion_accounting_mode', '')), ...
                    ofi_event_energy_check_request, ...
                    ofi_event_depletion_request);
            resolved_closure = struct( ...
                'requested_mode', requested_mode, ...
                'effective_mode', effective_mode, ...
                'closure_code', closure_code, ...
                'nla_ofi_energy_accounting_mode', ofi_depletion_accounting_mode, ...
                'ofi_depletion_accounting_mode', ofi_depletion_accounting_mode, ...
                'ofi_depletion_accounting_mode_code', ...
                    ofi_depletion_accounting_mode_code, ...
                'nla_check_ofi_event_energy_flag', ...
                    logical(nla_check_ofi_event_energy_flag), ...
                'nla_use_ofi_event_depletion_flag', ...
                    logical(nla_use_ofi_event_depletion_flag), ...
                'keldysh_nla_enabled', logical(keldysh_nla_enabled), ...
                'plasma_ofi_use_remaining_neutral_factor_flag', ...
                    logical(plasma_ofi_use_remaining_neutral_factor_flag), ...
                'nla_use_remaining_neutral_factor_flag_requested', ...
                    logical(nla_use_remaining_neutral_factor_flag_requested), ...
                'nla_use_remaining_neutral_factor_flag_effective', ...
                    logical(nla_use_remaining_neutral_factor_flag_effective), ...
                'plasma_ofi_nla_replenishment_fallback_applied', ...
                    logical(plasma_ofi_nla_replenishment_fallback_applied), ...
                'plasma_ofi_nla_weighting_mismatch_requested', ...
                    logical(plasma_ofi_nla_weighting_mismatch_requested), ...
                'uses_neutral_fraction', logical(uses_neutral_fraction), ...
                'explicit_static_override_active', logical(explicit_static_override_active), ...
                'rk_order_mode', rk_order_mode, ...
                'rk_order', double(rk_order));
        end

        function mode_payload = build_mode_payload(nla_cfg)
        % Build the canonical NLA mode descriptor from the current setup-owned NLA config.

            if nargin < 1 || ~isstruct(nla_cfg)
                nla_cfg = struct();
            end

            empty_desc = nla_support.build_static_multiorder_descriptor([], []);
            resolved_closure = nla_support.resolve_closure_record(nla_cfg);
            closure_code = resolved_closure.closure_code;

            k_orders = struct_utils.opt_struct_field(nla_cfg, 'k_orders', zeros(0, 1));
            beta_vals = struct_utils.opt_struct_field(nla_cfg, 'beta_vals', zeros(0, 1));
            if ~isempty(k_orders) || ~isempty(beta_vals)
                [k_active, beta_active] = nla_support.canonicalize_static_term_pairs( ...
                    k_orders, beta_vals, false, ...
                    'Resolved NLA source vectors', ...
                    'CerUPP:InvalidNlaModePayload', ...
                    'CerUPP:InvalidNlaModePayload');
            else
                [k_active, beta_active] = nla_support.canonicalize_static_term_pairs( ...
                    struct_utils.opt_struct_field(nla_cfg, 'k_active', zeros(0, 1)), ...
                    struct_utils.opt_struct_field(nla_cfg, 'beta_active', zeros(0, 1)), true, ...
                    'Resolved NLA active terms', ...
                    'CerUPP:InvalidNlaModePayload', ...
                    'CerUPP:InvalidNlaModePayload');
            end

            rk_order_mode = char(string(resolved_closure.rk_order_mode));
            rk_order_mode = lower(strtrim(rk_order_mode));
            if strcmp(rk_order_mode, 'follow_plasma')
                rk_order_selection_id = uint8(1);
                rk_order = double(resolved_closure.rk_order);
            elseif strcmp(rk_order_mode, 'explicit')
                rk_order_selection_id = uint8(2);
                rk_order = double(resolved_closure.rk_order);
                if ~(isscalar(rk_order) && isreal(rk_order) && isfinite(rk_order) && ismember(rk_order, [1, 2]))
                    error('CerUPP:InvalidNlaRkOrder', ...
                        'nla_cfg.rk_order must be an explicit scalar 1 or 2 when rk_order_mode=''explicit''.');
                end
                rk_order = double(rk_order);
            else
                error('CerUPP:InvalidNlaRkOrder', ...
                    'nla_cfg.rk_order_mode must be ''follow_plasma'' or ''explicit''; got ''%s''.', rk_order_mode);
            end

            if isempty(k_active)
                static_nla_mode_id = uint8(0);
                static_single_k = NaN;
                static_single_beta = NaN;
                static_multiorder_desc = empty_desc;
            elseif numel(k_active) == 1
                static_nla_mode_id = uint8(1);
                static_single_k = double(k_active(1));
                static_single_beta = double(beta_active(1));
                static_multiorder_desc = empty_desc;
            else
                static_nla_mode_id = uint8(2);
                static_single_k = NaN;
                static_single_beta = NaN;
                static_multiorder_desc = nla_support.build_static_multiorder_descriptor(k_active, beta_active);
            end

            mode_payload = struct( ...
                'resolved_closure', resolved_closure, ...
                'ofi_depletion_accounting_mode', ...
                    resolved_closure.ofi_depletion_accounting_mode, ...
                'ofi_depletion_accounting_mode_code', ...
                    resolved_closure.ofi_depletion_accounting_mode_code, ...
                'static_nla_mode_id', static_nla_mode_id, ...
                'k_active', k_active(:), ...
                'beta_active', beta_active(:), ...
                'static_single_k', double(static_single_k), ...
                'static_single_beta', double(static_single_beta), ...
                'static_multiorder_desc', static_multiorder_desc, ...
                'rk_order_selection_id', rk_order_selection_id, ...
                'rk_order', double(rk_order));
        end

        function tf = uses_neutral_fraction( ...
                closure_mode_or_keldysh_flag, remaining_neutral_factor_flag, ...
                keldysh_use_additive_volumetric_source_flag)
        % True when the applied NLA sink carries remaining-neutral weighting.

            if nargin < 1 || isempty(closure_mode_or_keldysh_flag)
                closure_mode_or_keldysh_flag = 'static_mpi_beta';
            end
            if nargin < 2 || isempty(remaining_neutral_factor_flag)
                remaining_neutral_factor_flag = false;
            end
            if nargin < 3 || isempty(keldysh_use_additive_volumetric_source_flag)
                keldysh_use_additive_volumetric_source_flag = false;
            end

            if islogical(closure_mode_or_keldysh_flag) && isscalar(closure_mode_or_keldysh_flag)
                keldysh_nla_enabled = logical(closure_mode_or_keldysh_flag);
            else
                if isstring(closure_mode_or_keldysh_flag) && isscalar(closure_mode_or_keldysh_flag)
                    closure_mode_or_keldysh_flag = char(closure_mode_or_keldysh_flag);
                end
                if ischar(closure_mode_or_keldysh_flag)
                    closure_mode = lower(strtrim(closure_mode_or_keldysh_flag));
                    if strcmp(closure_mode, 'static_mpi_beta')
                        keldysh_nla_enabled = false;
                    elseif strcmp(closure_mode, 'plasma_ofi')
                        keldysh_nla_enabled = true;
                    else
                        error('CerUPP:InvalidNlaClosureMode', ...
                            ['Unsupported nla neutral-fraction closure selector ''%s''. ', ...
                             'Use plasma_ofi or static_mpi_beta.'], ...
                            closure_mode);
                    end
                elseif isnumeric(closure_mode_or_keldysh_flag) && isscalar(closure_mode_or_keldysh_flag) && ...
                        isreal(closure_mode_or_keldysh_flag) && isfinite(closure_mode_or_keldysh_flag)
                    closure_code = double(closure_mode_or_keldysh_flag);
                    if closure_code == 1
                        keldysh_nla_enabled = false;
                    elseif closure_code == 2
                        keldysh_nla_enabled = true;
                    else
                        error('CerUPP:InvalidNlaClosureMode', ...
                            ['Unsupported nla neutral-fraction closure selector code %.17g. ', ...
                             'Use exact closure code 1 (static_mpi_beta) or 2 (plasma_ofi).'], ...
                            double(closure_mode_or_keldysh_flag));
                    end
                else
                    error('CerUPP:InvalidNlaClosureMode', ...
                        ['nla neutral-fraction closure selector must be a logical scalar, ', ...
                         'char/string closure label, or numeric scalar closure code; got %s.'], ...
                        class(closure_mode_or_keldysh_flag));
                end
            end

            tf = logical(remaining_neutral_factor_flag);
        end

