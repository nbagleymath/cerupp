            mode_payload = nla_support.normalize_mode_payload(mode_payload);
        end

        function [i_new, j_core, nla_diag_core, nla_softwarn_state] = apply_matched_kernel( ...
                i0_core, remaining_neutral_core, nla_runtime_cfg, need_j_model_pre, ...
                nla_rk2_flag, tiny_i, dz_like, need_keldysh_diag_maps, ...
                nla_softwarn_state, nla_diag_core)
        % Apply the OFI-based NLA loss law. Dynamic matched OFI and the
        % static multi-order surrogate use Euler/RK2 stepping, while the
        % static single-order surrogate uses the analytic single-K update.

            if nargin < 8 || isempty(need_keldysh_diag_maps)
                need_keldysh_diag_maps = false;
            end
            keldysh_ctx = propagation_support.resolve_keldysh_nla_context_local(nla_runtime_cfg);
            need_keldysh_diagnostic_maps = logical(struct_utils.opt_struct_field( ...
                keldysh_ctx, 'bookkeeping_diag_enabled', true)) && ...
                logical(need_keldysh_diag_maps);
            [use_static_single_matched_ofi_closed_form, static_single_k, ...
                static_single_sigma] = ...
                nla_support.resolve_static_single_matched_ofi_closed_form_local( ...
                    keldysh_ctx);
            if use_static_single_matched_ofi_closed_form
                [i_new, j_core, nla_diag_core, nla_softwarn_state] = ...
                    nla_support.apply_static_single_matched_ofi_closed_form_local( ...
                        i0_core, remaining_neutral_core, keldysh_ctx, ...
                        static_single_k, static_single_sigma, ...
                        need_j_model_pre, dz_like, need_keldysh_diagnostic_maps, ...
                        nla_softwarn_state, nla_diag_core);
                return;
            end
            [loss0, j_core, sigma_k_eff_diag, beta_eff_full_diag, ...
             beta_eff_applied_diag, nla_softwarn_state] = ...
                nla_support.evaluate_keldysh_matched_loss_and_bookkeeping( ...
                    i0_core, remaining_neutral_core, keldysh_ctx, tiny_i, nla_softwarn_state, ...
                    need_j_model_pre, need_keldysh_diagnostic_maps);
            if nla_rk2_flag
                i_half_raw = i0_core - cast(0.5, 'like', i0_core) .* dz_like .* loss0;
                nla_support.assert_rk2_midpoint_positive( ...
                    i0_core, loss0, i_half_raw, dz_like, 'matched OFI');
                i_half = i_half_raw;
                [loss_half, ~, sigma_k_eff_diag, beta_eff_full_diag, ...
                 beta_eff_applied_diag, nla_softwarn_state] = ...
                    nla_support.evaluate_keldysh_matched_loss_and_bookkeeping( ...
                        i_half, remaining_neutral_core, keldysh_ctx, tiny_i, nla_softwarn_state, ...
                        false, need_keldysh_diagnostic_maps);
                i_new_raw = i0_core - dz_like .* loss_half;
                nla_support.assert_current_step_nonnegative( ...
                    i0_core, loss_half, i_new_raw, dz_like, 'matched OFI');
                i_new = i_new_raw;
                if need_keldysh_diagnostic_maps
                    nla_diag_core.i_eval = i_half;
                end
            else
                i_new_raw = i0_core - dz_like .* loss0;
                nla_support.assert_current_step_nonnegative( ...
                    i0_core, loss0, i_new_raw, dz_like, 'matched OFI');
                i_new = i_new_raw;
                if need_keldysh_diagnostic_maps
                    nla_diag_core.i_eval = i0_core;
                end
            end
            if need_keldysh_diagnostic_maps
                nla_diag_core.sigma_k_eff = sigma_k_eff_diag;
                nla_diag_core.beta_eff_full = beta_eff_full_diag;
                nla_diag_core.beta_eff_applied = beta_eff_applied_diag;
            end
        end

        function [i_new, j_core, ledger_diag] = apply_ofi_ledger_kernel( ...
                i0_core, plasma_book, dt_vec, nla_runtime_cfg, dz_like, tiny_i, ...
                need_j_model_pre)
        % Apply OFI event-depletion from the plasma substep event increment.

            [loss_rate, ledger_diag] = nla_support.build_ofi_ledger_loss_rate( ...
                i0_core, plasma_book, dt_vec, nla_runtime_cfg, true);
            delta_i = dz_like .* loss_rate;
            deficit_mask = (delta_i > i0_core) & ...
                ((delta_i - i0_core) > max(100 * eps('double') * max(double(max(i0_core(:))), 1), 0));
            ledger_diag.intensity_deficit_count = nnz(deficit_mask);
            ledger_diag.max_local_intensity_deficit = 0;
            if any(deficit_mask(:))
                deficit_vals = double(delta_i(deficit_mask) - i0_core(deficit_mask));
                ledger_diag.max_local_intensity_deficit = max(deficit_vals);
                bad_idx = find(deficit_mask, 1, 'first');
                error('CerUPP:NLA:OfiLedgerEnergyDeficit', ...
                    ['OFI event-depletion NLA asked for more local optical energy than ', ...
                     'the pre-NLA field contains at linear index %d. Requested dI=%.6e, ', ...
                     'I0=%.6e. Strict OFI event-depletion does not clamp this deficit.'], ...
                    bad_idx, double(delta_i(bad_idx)), double(i0_core(bad_idx)));
            end
            i_new = i0_core - delta_i;
            j_core = [];
            if logical(need_j_model_pre)
                j_core = zeros(size(i0_core), 'like', i0_core);
                den = max(i0_core, tiny_i);
                pos = (i0_core > 0) & isfinite(den);
                j_core(pos) = loss_rate(pos) ./ den(pos);
            end
        end

        function [loss_rate, ledger_diag] = build_ofi_ledger_loss_rate( ...
                i0_core, plasma_book, dt_vec, nla_runtime_cfg, strict_mode)
        % Convert the plasma OFI event-density increment into dI/dz.
        % The event increment already includes source depletion, caps, replay,
        % and clipping applied by the plasma update; avalanche and
        % recombination records stay outside this OFI optical-loss channel.

            if nargin < 5 || isempty(strict_mode)
                strict_mode = false;
            end
            if ~(isstruct(plasma_book) && isfield(plasma_book, 'drho_ofi_accepted') && ...
                    ~isempty(plasma_book.drho_ofi_accepted))
                error('CerUPP:NLA:MissingOfiLedger', ...
                    ['OFI event-energy accounting requires plasma_book.drho_ofi_accepted ', ...
                     'from the plasma substep.']);
            end
            drho_ofi = plasma_book.drho_ofi_accepted;
            ledger_field_name = 'plasma_book.drho_ofi_accepted';
            if ~isequal(size(drho_ofi), size(i0_core))
                error('CerUPP:NLA:OfiLedgerShapeMismatch', ...
                    '%s has size %s but I0_core has size %s.', ...
                    ledger_field_name, mat2str(size(drho_ofi)), mat2str(size(i0_core)));
            end
            [num_core, nt] = size(i0_core);
            dt_vec = double(dt_vec(:));
            if numel(dt_vec) ~= (nt - 1) || any(~isfinite(dt_vec)) || any(dt_vec <= 0)
                error('CerUPP:NLA:InvalidOfiLedgerDtVector', ...
                    'OFI event-energy accounting expected numel(dt_vec)=Nt-1=%d with finite positive entries; got %d.', ...
                    nt - 1, numel(dt_vec));
            end
            valid_core = true(size(drho_ofi));
            if isfield(plasma_book, 'exact_valid_core') && ...
                    isequal(size(plasma_book.exact_valid_core), size(drho_ofi))
                valid_core = logical(plasma_book.exact_valid_core);
            end
            bad_ledger_mask = ~isfinite(drho_ofi) | ~valid_core;
            negative_mask = isfinite(drho_ofi) & (drho_ofi < 0);
            cap_mask = false(size(drho_ofi));
            if isfield(plasma_book, 'ledger_cap_core') && ...
                    isequal(size(plasma_book.ledger_cap_core), size(drho_ofi))
                cap_mask = logical(plasma_book.ledger_cap_core);
            end
            clip_mask = false(size(drho_ofi));
            if isfield(plasma_book, 'ledger_clip_core') && ...
                    isequal(size(plasma_book.ledger_clip_core), size(drho_ofi))
                clip_mask = logical(plasma_book.ledger_clip_core);
            end
            repair_mask = false(size(drho_ofi));
            if isfield(plasma_book, 'ledger_repair_core') && ...
                    isequal(size(plasma_book.ledger_repair_core), size(drho_ofi))
                repair_mask = logical(plasma_book.ledger_repair_core);
            end
            if logical(strict_mode) && (any(bad_ledger_mask(:)) || any(negative_mask(:)))
                bad_idx = find(bad_ledger_mask | negative_mask, 1, 'first');
                error('CerUPP:NLA:InvalidOfiLedgerForAppliedMode', ...
                    ['OFI event-depletion NLA requires a nonnegative OFI event increment. ', ...
                     'The plasma event record is invalid at linear index %d, usually because ', ...
	                     'a density cap, exact-stage repair, or numerical projection made ', ...
	                     'the mechanism split non-exact.'], bad_idx);
            end
            drho_work = real(drho_ofi);
            if logical(strict_mode)
                drho_work(bad_ledger_mask | negative_mask) = cast(NaN, 'like', drho_work);
            else
                drho_work(bad_ledger_mask | negative_mask) = cast(0, 'like', drho_work);
            end
            dt_row = zeros(1, nt, 'like', i0_core);
            dt_row(2:nt) = cast(dt_vec(:).', 'like', i0_core);
            keldysh_ctx = propagation_support.resolve_keldysh_nla_context_local(nla_runtime_cfg);
            udep = cast(double(keldysh_ctx.keldysh_matched_depletion_J), 'like', i0_core);
            loss_rate = zeros(num_core, nt, 'like', i0_core);
            if nt > 1
                loss_rate(:, 2:nt) = udep .* drho_work(:, 2:nt) ./ dt_row(:, 2:nt);
            end
            loss_rate = propagation_support.require_nonnegative_real_array_local( ...
                loss_rate, 'OFI event NLA loss rate');
            ledger_diag = struct( ...
                'ofi_ledger_loss_rate_core', loss_rate, ...
                'ofi_ledger_drho_core', drho_work, ...
                'ofi_ledger_exact_valid_core', valid_core, ...
                'ofi_ledger_invalid_count', nnz(bad_ledger_mask), ...
                'ofi_ledger_negative_count', nnz(negative_mask), ...
                'ofi_ledger_cap_count', nnz(cap_mask), ...
                'ofi_ledger_clip_count', nnz(clip_mask), ...
                'ofi_ledger_repair_count', nnz(repair_mask), ...
                'ofi_ledger_field_name', ledger_field_name, ...
                'ofi_ledger_energy_density_core', ...
                    cast(double(keldysh_ctx.keldysh_matched_depletion_J), 'like', real(i0_core(:, 1))) .* ...
                    sum(drho_work, 2, 'omitnan'), ...
                'ofi_ledger_dt_convention', 'columns 2:Nt use dt_vec(1:Nt-1); column 1 carries no event increment');
        end

        function [use_static_single_matched_ofi_closed_form, static_single_k, ...
                static_single_sigma] = resolve_static_single_matched_ofi_closed_form_local(keldysh_ctx)
        % Detect the single-order static matched-OFI law dI/dz = -C I^K.

            use_static_single_matched_ofi_closed_form = false;
            static_single_k = NaN;
            static_single_sigma = NaN;
            if ~(isstruct(keldysh_ctx) && isscalar(keldysh_ctx))
                return;
            end
            if logical(struct_utils.opt_struct_field(keldysh_ctx, 'enabled', false))
                return;
            end
            k_vec = double(struct_utils.opt_struct_field(keldysh_ctx, 'K_vec', zeros(0, 1)));
            sigma_vec = double(struct_utils.opt_struct_field(keldysh_ctx, 'sigmaK_vec', zeros(0, 1)));
            if numel(k_vec) ~= numel(sigma_vec)
                return;
            end
            active_mask = isfinite(k_vec(:)) & (k_vec(:) > 0) & ...
                isfinite(sigma_vec(:)) & (sigma_vec(:) > 0);
            if nnz(active_mask) ~= 1
                return;
            end
            active_idx = find(active_mask, 1, 'first');
            use_static_single_matched_ofi_closed_form = true;
            static_single_k = double(k_vec(active_idx));
            static_single_sigma = double(sigma_vec(active_idx));
        end

        function applied_density_scale = resolve_matched_ofi_applied_density_scale_local( ...
                remaining_neutral_core, keldysh_ctx, like_sample)
        % Resolve the density weighting owned by the matched-OFI sink.

            if nargin < 3 || isempty(like_sample)
                like_sample = remaining_neutral_core;
            end
            nla_uses_remaining_neutral = logical(struct_utils.opt_struct_field( ...
                keldysh_ctx, 'nla_use_remaining_neutral_factor_flag_effective', ...
                struct_utils.opt_struct_field( ...
                    keldysh_ctx, 'plasma_ofi_use_remaining_neutral_factor_flag', true)));
            use_additive_volumetric_source = ~nla_uses_remaining_neutral;
            applied_density_scale = cast(remaining_neutral_core, 'like', like_sample);
            if use_additive_volumetric_source
                source_density_scale_m3 = double(struct_utils.opt_struct_field( ...
                    keldysh_ctx, 'ofi_source_density_scale_m3', NaN));
                if ~(isscalar(source_density_scale_m3) && isreal(source_density_scale_m3) && ...
                        isfinite(source_density_scale_m3) && (source_density_scale_m3 > 0))
                    error('CerUPP:AdvanceStepNlaInvalidKeldyshSourceDensityScale', ...
                        ['Matched OFI fixed-density-scale depletion requires a finite positive ', ...
                         'keldysh_ctx.ofi_source_density_scale_m3; got %s.'], ...
                        mat2str(source_density_scale_m3));
                end
                applied_density_scale = cast(source_density_scale_m3, 'like', like_sample);
            end
        end

        function arr = reshape_matched_ofi_array_like_local( ...
                arr, like_sample, quantity_label, error_id)
        % Keep matched-OFI runtime arrays aligned with the active intensity shape.

            if nargin < 3 || isempty(quantity_label)
                quantity_label = 'Matched-OFI runtime array';
            end
            if nargin < 4 || isempty(error_id)
                error_id = 'CerUPP:AdvanceStepNlaMatchedArrayShapeMismatch';
            end
            arr = cast(arr, 'like', like_sample);
            if isscalar(arr) || isequal(size(arr), size(like_sample))
                return;
            end
            if numel(arr) == numel(like_sample)
                arr = reshape(arr, size(like_sample));
                return;
            end
            error(error_id, ...
                ['%s must be scalar or match the active intensity shape; got ', ...
                 'size %s for intensity size %s.'], ...
                quantity_label, mat2str(size(arr)), mat2str(size(like_sample)));
        end

        function [i_new, j_core, nla_diag_core, nla_softwarn_state] = ...
                apply_static_single_matched_ofi_closed_form_local( ...
                i0_core, remaining_neutral_core, keldysh_ctx, static_single_k, ...
                static_single_sigma, need_j_model_pre, dz_like, ...
                need_keldysh_diagnostic_maps, nla_softwarn_state, nla_diag_core)
        % Apply the single-order static matched-OFI law dI/dz = -C I^K analytically.

            kk_2 = double(static_single_k);
            sigma_single = double(static_single_sigma);
            if ~(isscalar(kk_2) && isreal(kk_2) && isfinite(kk_2) && (kk_2 >= 1))
                error('CerUPP:AdvanceStepNlaInvalidMatchedStaticSingleK', ...
                    'Matched static single-order OFI requires one finite K >= 1; got %s.', ...
                    mat2str(kk_2));
            end
            if ~(isscalar(sigma_single) && isreal(sigma_single) && isfinite(sigma_single) && ...
                    (sigma_single > 0))
                error('CerUPP:AdvanceStepNlaInvalidMatchedStaticSingleSigma', ...
                    ['Matched static single-order OFI requires one finite positive sigma_K; ', ...
                     'got %s.'], ...
                    mat2str(sigma_single));
            end
            applied_density_scale = nla_support.resolve_matched_ofi_applied_density_scale_local( ...
                remaining_neutral_core, keldysh_ctx, i0_core);
            beta_eff = cast( ...
                double(keldysh_ctx.keldysh_matched_depletion_J) * sigma_single, ...
                'like', i0_core) .* applied_density_scale;
            beta_eff = propagation_support.require_nonnegative_real_array_local( ...
                beta_eff, 'Matched-OFI single-order beta_eff');
            if need_j_model_pre
                i_pow_km1 = i0_core .^ (kk_2 - 1);
                j_core = beta_eff .* i_pow_km1;
                [i_new, nla_softwarn_state] = nla_support.apply_closed_form_intensity_step( ...
                    i0_core, kk_2, beta_eff, dz_like, i_pow_km1, nla_softwarn_state);
            else
                j_core = [];
                [i_new, nla_softwarn_state] = nla_support.apply_closed_form_intensity_step( ...
                    i0_core, kk_2, beta_eff, dz_like, [], nla_softwarn_state);
            end
            if need_keldysh_diagnostic_maps
                rho_nt_keldysh_norm_m3 = double(struct_utils.opt_struct_field( ...
                    keldysh_ctx, 'rho_nt_keldysh_norm_m3', NaN));
                if ~(isscalar(rho_nt_keldysh_norm_m3) && isreal(rho_nt_keldysh_norm_m3) && ...
                        isfinite(rho_nt_keldysh_norm_m3) && (rho_nt_keldysh_norm_m3 > 0))
                    error('CerUPP:AdvanceStepNlaInvalidMatchedStaticSingleRhoNtNorm', ...
                        ['Matched static single-order OFI requires a finite positive ', ...
                         'keldysh_ctx.rho_nt_keldysh_norm_m3; got %s.'], ...
                        mat2str(rho_nt_keldysh_norm_m3));
                end
                sigma_eff = cast(sigma_single, 'like', i0_core) .* ...
                    ones(size(i0_core), 'like', i0_core);
                keldysh_matched_depletion_rho = cast( ...
                    double(keldysh_ctx.keldysh_matched_depletion_J) * ...
                    rho_nt_keldysh_norm_m3, ...
                    'like', i0_core);
                nla_diag_core.i_eval = i0_core;
                nla_diag_core.sigma_k_eff = sigma_eff;
                nla_diag_core.beta_eff_full = ...
                    keldysh_matched_depletion_rho .* sigma_eff;
                nla_diag_core.beta_eff_applied = beta_eff;
            end
        end

        function [i_new, j_core, nla_softwarn_state] = apply_static_single_kernel( ...
                i0_core, nla_loss_weight_core, nla_mode_payload, need_j_model_pre, dz_like, nla_softwarn_state)
        % Apply one fixed beta_K sink with the analytic intensity update.

            kk_2 = double(nla_mode_payload.static_single_k);
            beta_eff = cast(nla_mode_payload.static_single_beta, 'like', nla_loss_weight_core) .* nla_loss_weight_core;
            if kk_2 < 1
                error('CerUPP:AdvanceStepNlaInvalidKOrder', ...
                    'MPA order k must be >= 1; got %g.', kk_2);
            end
            if need_j_model_pre
                i_pow_km1 = i0_core .^ (kk_2 - 1);
                j_core = beta_eff .* i_pow_km1;
                [i_new, nla_softwarn_state] = nla_support.apply_closed_form_intensity_step( ...
                    i0_core, kk_2, beta_eff, dz_like, i_pow_km1, nla_softwarn_state);
            else
                j_core = [];
                [i_new, nla_softwarn_state] = nla_support.apply_closed_form_intensity_step( ...
                    i0_core, kk_2, beta_eff, dz_like, [], nla_softwarn_state);
            end
        end

        function [i_new, j_core] = apply_static_multi_kernel( ...
                i0_core, nla_loss_weight_core, nla_mode_payload, need_j_model_pre, nla_rk2_flag, dz_like)
        % Apply the summed fixed-order beta_K sink with Euler or midpoint stepping.

            static_multiorder_desc = nla_mode_payload.static_multiorder_desc;
            if need_j_model_pre
                [loss0, j_core] = nla_support.evaluate_static_multiorder_loss_and_bookkeeping( ...
                    i0_core, nla_loss_weight_core, static_multiorder_desc);
            else
                loss0 = nla_support.evaluate_static_multiorder_loss_only( ...
                    i0_core, nla_loss_weight_core, static_multiorder_desc);
                j_core = [];
            end
            if ~nla_rk2_flag
                i_new_raw = i0_core - dz_like .* loss0;
                nla_support.assert_current_step_nonnegative( ...
                    i0_core, loss0, i_new_raw, dz_like, 'static multi-order');
                i_new = i_new_raw;
                return;
            end
            i_half_raw = i0_core - cast(0.5, 'like', i0_core) .* dz_like .* loss0;
            nla_support.assert_rk2_midpoint_positive( ...
                i0_core, loss0, i_half_raw, dz_like, 'static multi-order');
            i_half = i_half_raw;
            loss_half = nla_support.evaluate_static_multiorder_loss_only( ...
                i_half, nla_loss_weight_core, static_multiorder_desc);
            i_new_raw = i0_core - dz_like .* loss_half;
            nla_support.assert_current_step_nonnegative( ...
                i0_core, loss_half, i_new_raw, dz_like, 'static multi-order');
            i_new = i_new_raw;
        end

        function [A_S, A_core_out, j_mpa_core, nla_book, nla_softwarn_state] = finalize_applied_update( ...
                A_S, A_full_2_d, A_core, core_idx, i0_core, i_new, rho_core, dz, tiny_i, ...
                j_model_pre_core, need_nla_book, neutral_frac_clamp_mask, nla_softwarn_state, ...
                full_bookkeeping_ledger)
        % Map the current-step intensity update back onto A_S and emit optional accounting diagnostics.

            if nargin < 14 || isempty(full_bookkeeping_ledger)
                full_bookkeeping_ledger = false;
            end
            ratio = i_new ./ max(i0_core, tiny_i);
            ratio_min = min(ratio(:));
            ratio_max = max(ratio(:));
            if ~(isfinite(ratio_min) && isfinite(ratio_max))
                bad_idx = find(~isfinite(ratio), 1, 'first');
                error('CerUPP:AdvanceStepNlaNonFiniteRatio', ...
                    ['Non-finite NLA intensity ratio detected at index %d. ' ...
                     'Refusing silent Inf/NaN->0 clamp in physics path.'], ...
                    bad_idx);
            end
            ratio_gain_tol = 10 * eps('double');
            if isa(ratio, 'single')
                ratio_gain_tol = double(10 * eps('single'));
            end
            ratio_clamp_mask = [];
            if double(ratio_max) > (1 + ratio_gain_tol)
                gain_mask = (ratio > (1 + ratio_gain_tol));
                gain_count = nnz(gain_mask);
                max_ratio_preclamp = max(double(ratio(gain_mask)));
                nla_softwarn_state = propagation_support.record_nla_ratio_gain_softwarn_local( ...
                    nla_softwarn_state, gain_count, max_ratio_preclamp, ratio_gain_tol);
                [nla_softwarn_state, ~] = run_warn_state_utils.emit_bucket_warn_once( ...
                    nla_softwarn_state, 'nla', ...
                    'NLA_RATIO_GAIN_CLAMPED', ...
                    'CerUPP:NLA:RatioGainClamped', ...
                    ['NLA intensity ratio exceeded 1 before loss-only clamp: ' ...
                     'count=%d, max_ratio=%.6e, tol=%.3e. ' ...
                     'Clamping ratio to [0,1]. Check sign/units of beta_K/sigma_K and dz>0.'], ...
                    gain_count, max_ratio_preclamp, ratio_gain_tol);
                ratio_clamp_mask = gain_mask;
            end
            if double(ratio_min) < 0
                neg_mask = (ratio < 0);
                if isempty(ratio_clamp_mask)
                    ratio_clamp_mask = neg_mask;
                else
                    ratio_clamp_mask = ratio_clamp_mask | neg_mask;
                end
            end
            if ~isempty(ratio_clamp_mask)
                ratio = max(ratio, 0);
                ratio = min(ratio, 1);
            end
            if isempty(A_full_2_d)
                [nx, ny, ~] = size(A_S);
                A_full_2_d = reshape(A_S, nx * ny, []);
            else
                [nx, ny, ~] = size(A_S);
            end
            A_core_out = A_core .* sqrt(ratio);
            A_full_2_d(core_idx, :) = A_core_out;
            A_S = reshape(A_full_2_d, nx, ny, []);
            j_mpa_core = j_model_pre_core;
            nla_book = [];
            if ~need_nla_book
                return;
            end
            exact_valid_core = [];
            if ~isempty(ratio_clamp_mask) || any(neutral_frac_clamp_mask(:))
                exact_valid_core = true(size(i0_core));
                if ~isempty(ratio_clamp_mask)
                    exact_valid_core(ratio_clamp_mask) = false;
                end
                if ~isempty(neutral_frac_clamp_mask)
                    exact_valid_core(neutral_frac_clamp_mask) = false;
                end
            end
            dz_real_like = cast(double(real(dz)), 'like', i0_core);
            loss_rate_applied_core = max((i0_core - (i0_core .* ratio)) ./ dz_real_like, 0);
            i_post_core = [];
            j_applied_core = [];
            if full_bookkeeping_ledger
                i_post_core = i0_core .* ratio;
                j_applied_core = zeros(size(i0_core), 'like', i0_core);
                den = max(i0_core, tiny_i);
                pos = (i0_core > 0) & isfinite(den);
                j_applied_core(pos) = loss_rate_applied_core(pos) ./ den(pos);
            end
            nla_book = nla_support.build_bookkeeping( ...
                i0_core, loss_rate_applied_core, exact_valid_core, full_bookkeeping_ledger, ...
                i_post_core, rho_core, j_model_pre_core, dz, tiny_i, j_applied_core);
        end

        function nla_book = build_bookkeeping( ...
                i_pre_core, loss_rate_applied_core, exact_valid_core, full_bookkeeping_ledger, ...
                i_post_core, rho_core_used, j_model_pre_core, dz, tiny_i, j_applied_core)
        % Build the applied-NLA accounting bundle for the current step.

            nla_book = nla_support.build_bookkeeping_private( ...
                i_pre_core, loss_rate_applied_core, exact_valid_core, full_bookkeeping_ledger, ...
                i_post_core, rho_core_used, j_model_pre_core, dz, tiny_i, j_applied_core);
        end

        function [loss_rate, j_eval, sigma_eff, beta_eff_full, ...
                beta_eff_applied, nla_softwarn_state] = ...
                evaluate_keldysh_matched_terms_for_postrun( ...
                    i_eval, remaining_neutral_core, keldysh_ctx, tiny_i, ...
                    nla_softwarn_state, need_j_output, need_bookkeeping)

        % Public matched-Keldysh sigma/beta rebuild wrapper for post-run helpers.
            [loss_rate, j_eval, sigma_eff, beta_eff_full, ...
                beta_eff_applied, nla_softwarn_state] = ...
                nla_support.evaluate_keldysh_matched_terms( ...
                    i_eval, remaining_neutral_core, keldysh_ctx, tiny_i, nla_softwarn_state, ...
                    need_j_output, need_bookkeeping);
        end
    end

    methods (Static, Access = private)
        function mode_payload = normalize_mode_payload(mode_payload)
        % Require the runtime NLA mode-descriptor shape consumed by advance_z_step.

            if nargin < 1 || ~isstruct(mode_payload)
                error('CerUPP:AdvanceStepInvalidNlaModePayload', ...
                    'nla_runtime_cfg.mode_payload must be a struct in the positional interface.');
            end
            if isfield(mode_payload, 'resolved_closure') && isstruct(mode_payload.resolved_closure) && ...
                    ~isempty(mode_payload.resolved_closure)
                resolved_closure = nla_support.resolve_closure_record(mode_payload.resolved_closure);
            else
                resolved_closure = nla_support.resolve_closure_record(mode_payload);
            end
            closure_code = resolved_closure.closure_code;
            valid_closure_codes = [double(uint8(1)), double(uint8(2))];
            if ~(isnumeric(closure_code) && isscalar(closure_code) && isreal(closure_code) && ...
                    isfinite(double(closure_code)) && ...
                    ismember(double(uint8(round(double(closure_code)))), ...
                        valid_closure_codes))
                error('CerUPP:AdvanceStepInvalidNlaModePayload', ...
                    'nla_runtime_cfg.mode_payload.closure_code must be the static or matched closure code.');
            end
            mode_payload.resolved_closure = resolved_closure;
        end

        function [loss_rate, j_eval] = evaluate_static_multiorder_loss_and_bookkeeping( ...
                i_eval, nla_loss_weight_core, static_multiorder_desc)
        % Evaluate static-beta loss/J terms from one validated static-NLA descriptor.

            [loss_rate, j_eval] = nla_support.evaluate_static_multiorder_terms( ...
                i_eval, nla_loss_weight_core, static_multiorder_desc, true);
        end

        function loss_rate = evaluate_static_multiorder_loss_only( ...
                i_eval, nla_loss_weight_core, static_multiorder_desc)
        % Evaluate only the static-beta loss term at one intensity state.

            loss_rate = nla_support.evaluate_static_multiorder_terms( ...
                i_eval, nla_loss_weight_core, static_multiorder_desc, false);
        end

        function [loss_rate, j_eval] = evaluate_static_multiorder_terms( ...
                i_eval, nla_loss_weight_core, static_multiorder_desc, need_j_eval)
        % Evaluate static-beta loss/J terms at one intensity state.

            i_eval = propagation_support.require_nonnegative_real_array_local(i_eval, 'Static-NLA intensity');
            if ~(isstruct(static_multiorder_desc) && isfield(static_multiorder_desc, 'kind_code'))
                error('CerUPP:AdvanceStepNlaInvalidStaticNlaDescriptor', ...
                    'Static multi-order NLA requires a validated descriptor.');
            end
            kind_code = uint8(double(static_multiorder_desc.kind_code));
            loss_sum = zeros(size(i_eval), 'like', i_eval);
            if need_j_eval
                j_sum = zeros(size(i_eval), 'like', i_eval);
            else
                j_sum = [];
            end
            if kind_code == uint8(1)
                loss_coef = double(static_multiorder_desc.loss_coef(:));
                j_coef = double(static_multiorder_desc.j_coef(:));
                if isfield(static_multiorder_desc, 'active_exp') && isfield(static_multiorder_desc, 'active_loss_coef') && ...
                        isfield(static_multiorder_desc, 'active_j_coef')
                    active_exp = double(static_multiorder_desc.active_exp(:));
                    active_loss_coef = double(static_multiorder_desc.active_loss_coef(:));
                    active_j_coef = double(static_multiorder_desc.active_j_coef(:));
                else
                    active_idx = find((loss_coef ~= 0) | (j_coef ~= 0));
                    active_exp = double(active_idx(:) - 1);
                    active_loss_coef = loss_coef(active_idx);
                    active_j_coef = j_coef(active_idx);
                end
                [loss_sum, j_sum] = nla_support.accumulate_static_multiorder_compressed( ...
                    i_eval, active_exp, active_loss_coef, active_j_coef, need_j_eval, loss_sum, j_sum);
            elseif kind_code == uint8(2)
                k_orders = double(static_multiorder_desc.k_orders(:));
                beta_vals = double(static_multiorder_desc.beta_vals(:));
                [loss_sum, j_sum] = nla_support.accumulate_static_multiorder_fallback( ...
                    i_eval, k_orders, beta_vals, need_j_eval, loss_sum, j_sum);
            else
                error('CerUPP:AdvanceStepNlaInvalidStaticNlaDescriptor', ...
                    'Static multi-order NLA descriptor kind_code=%d is unsupported.', double(kind_code));
            end
            loss_rate = nla_loss_weight_core .* loss_sum;
            if need_j_eval
                j_eval = nla_loss_weight_core .* j_sum;
            else
                j_eval = [];
            end
        end

        function [loss_sum, j_sum] = accumulate_static_multiorder_compressed( ...
                i_eval, active_exp, active_loss_coef, active_j_coef, need_j_eval, loss_sum, j_sum)
        % Accumulate static multi-order terms from the compressed active-exponent descriptor.

            i_pow = ones(size(i_eval), 'like', i_eval);
            prev_exp = 0;
            for kk = 1:numel(active_exp)
                exp_now = active_exp(kk);
                gap = exp_now - prev_exp;
                if gap < 0
                    error('CerUPP:AdvanceStepNlaInvalidStaticNlaDescriptor', ...
                        'Static multi-order NLA active exponents must be nondecreasing.');
                end
                if gap == 1
                    i_pow = i_pow .* i_eval;
                elseif gap > 1
                    i_pow = i_pow .* (i_eval .^ gap);
                end
                if active_loss_coef(kk) ~= 0
                    loss_sum = loss_sum + cast(active_loss_coef(kk), 'like', i_eval) .* i_pow;
                end
                if need_j_eval && (active_j_coef(kk) ~= 0)
                    j_sum = j_sum + cast(active_j_coef(kk), 'like', i_eval) .* i_pow;
                end
                prev_exp = exp_now;
            end
        end

        function [loss_sum, j_sum] = accumulate_static_multiorder_fallback( ...
                i_eval, k_orders, beta_vals, need_j_eval, loss_sum, j_sum)
        % Accumulate static multi-order terms from the raw-order fallback descriptor.

            for kk = 1:numel(k_orders)
                kk_2 = double(k_orders(kk));
                beta_k = cast(beta_vals(kk), 'like', i_eval);
                if beta_k == 0
                    continue;
                end
                i_pow_k = i_eval .^ kk_2;
                loss_sum = loss_sum + beta_k .* i_pow_k;
                if need_j_eval
                    i_pow_km1 = i_eval .^ max(kk_2 - 1, 0);
                    j_sum = j_sum + beta_k .* i_pow_km1;
                end
            end
        end

        function [i_out, nla_softwarn_state] = apply_closed_form_intensity_step( ...
                i_in, kk_2, beta_eff, dz, i_pow_km1_in, nla_softwarn_state)
        % One analytic intensity substep for dI/dz = -beta_eff * I^K.

            if nargin < 6 || isempty(nla_softwarn_state) || ~isstruct(nla_softwarn_state)
                nla_softwarn_state = struct();
            end
            order_one_rel_tol = struct_utils.cerupp_numeric_threshold('rel_tol_tight');
            if abs(kk_2 - 1) < order_one_rel_tol
                i_out = i_in .* exp(-beta_eff .* dz);
            else
                if (nargin >= 5) && ~isempty(i_pow_km1_in)
                    i_pow_km1 = i_pow_km1_in;
                else
                    i_pow_km1 = i_in .^ (kk_2 - 1);
                end
                den = 1 + (kk_2 - 1) .* beta_eff .* i_pow_km1 .* dz;
                positive_overflow_to_zero = isinf(den) & (real(den) > 0) & ...
                    isfinite(i_in) & (i_in >= 0) & ...
                    isfinite(beta_eff) & (beta_eff >= 0) & ...
                    isfinite(real(dz)) & (real(dz) >= 0);
                if any(positive_overflow_to_zero(:))
                    overflow_count = nnz(positive_overflow_to_zero);
                    max_i_overflow = max(double(real(i_in(positive_overflow_to_zero))));
                    if isscalar(beta_eff)
                        max_beta_overflow = double(real(beta_eff));
                    else
                        max_beta_overflow = max(double(real(beta_eff(positive_overflow_to_zero))));
                    end
                    if isscalar(dz)
                        dz_warn = double(real(dz));
                    else
                        dz_warn = max(double(real(dz(positive_overflow_to_zero))));
                    end
                    [nla_softwarn_state, ~] = run_warn_state_utils.emit_bucket_warn_once( ...
                        nla_softwarn_state, 'nla', ...
                        'STATIC_SINGLE_BETA_DEN_OVERFLOW_TO_ZERO', ...
                        'CerUPP:NLA:StaticSingleBetaDenOverflowToZero', ...
                        ['Closed-form static beta_K denominator overflowed positive for %d entries. ' ...
                         'Mapping those updates to I_out=0, which is the analytic strong-depletion limit ' ...
                         'for positive beta_K and dz. max_I=%.6e, max_beta_eff=%.6e, dz=%.6e, K=%.6g.'], ...
                        overflow_count, max_i_overflow, max_beta_overflow, dz_warn, double(kk_2));
                end
                bad_den = (den <= 0) | (~isfinite(den) & ~positive_overflow_to_zero);
                if any(bad_den(:))
                    bad_idx = find(bad_den, 1, 'first');
                    if isscalar(dz)
                        dz_bad = double(dz);
                    else
                        dz_bad = double(dz(bad_idx));
                    end
                    error('CerUPP:AdvanceStepClosedFormNlaInvalidDenominator', ...
                        ['Closed-form NLA denominator became nonpositive/nonfinite at linear index %d ' ...
                         '(den=%.6e, I=%.6e, dz=%.6e, K=%.6g). ' ...
                         'Check beta_K sign/units and dz direction/magnitude.'], ...
                        bad_idx, double(real(den(bad_idx))), double(i_in(bad_idx)), dz_bad, double(kk_2));
                end
                i_out = zeros(size(i_in), 'like', i_in);
                regular_mask = ~positive_overflow_to_zero;
                if any(regular_mask(:))
                    i_out(regular_mask) = i_in(regular_mask) ./ ...
                        (den(regular_mask) .^ (1 / (kk_2 - 1)));
                end
            end
        end

        function [loss_rate, j_eval, sigma_eff, beta_eff_full, beta_eff_applied, nla_softwarn_state] = ...
                evaluate_keldysh_matched_loss_and_bookkeeping( ...
                i_eval, remaining_neutral_core, keldysh_ctx, tiny_i, nla_softwarn_state, ...
                need_j_output, need_bookkeeping)
        % Evaluate matched Keldysh applied loss together with diagnostic sigma/beta maps.

            [loss_rate, j_eval, sigma_eff, beta_eff_full, beta_eff_applied, nla_softwarn_state] = ...
                nla_support.evaluate_keldysh_matched_terms( ...
                    i_eval, remaining_neutral_core, keldysh_ctx, tiny_i, nla_softwarn_state, ...
                    need_j_output, need_bookkeeping);
        end

        function [loss_rate, j_eval, sigma_eff, beta_eff_full, beta_eff_applied, nla_softwarn_state] = ...
                evaluate_keldysh_matched_terms( ...
                i_eval, remaining_neutral_core, keldysh_ctx, tiny_i, nla_softwarn_state, ...
                need_j_output, need_bookkeeping)
        % Evaluate matched-OFI applied loss and optionally derive the
        % sigma/beta diagnostic maps from that same active OFI rate law.
        % remaining_neutral_core is already the caller-clamped nonnegative
        % reservoir remainder. The matched branch keeps the same active
        % plasma OFI rate law as the source step: dynamic W_ion(I) when
        % Keldysh is enabled, or the static sum_K sigma_K I^K law
        % otherwise. The only extra NLA-side choice is whether the sink
        % uses remaining-neutral weighting or the fixed cap-aware density
        % scale rho_ofi_scale.

            if nargin < 5 || isempty(nla_softwarn_state) || ~isstruct(nla_softwarn_state)
                nla_softwarn_state = struct();
            end
            if nargin < 6 || isempty(need_j_output)
                need_j_output = true;
            end
            if nargin < 7 || isempty(need_bookkeeping)
                need_bookkeeping = true;
            end
            need_j_output = logical(need_j_output);
            need_bookkeeping = logical(need_bookkeeping);
            i_eval = propagation_support.require_nonnegative_real_array_local(i_eval, 'Matched-OFI NLA intensity');
            static_k_eff = [];
            static_sigma_eff = [];
            dynamic_ofi_rate_active = ...
                isfield(keldysh_ctx, 'W_ion_interp_fn') && ...
                isa(keldysh_ctx.W_ion_interp_fn, 'function_handle');
            k_vec_static = [];
            sigma_vec_static = [];
            if dynamic_ofi_rate_active
                [w_ion, exp_clamp_count, clamp_info] = plasma_keldysh_eval( ...
                    i_eval, keldysh_ctx.W_ion_interp_fn, ...
                    struct_utils.opt_struct_field(keldysh_ctx, 'eval_opts', struct()));
                if exp_clamp_count > 0
                    detail_clamp = plot_support_utils.compact_detail_text(clamp_info, 240);
                    [nla_softwarn_state, ~] = run_warn_state_utils.emit_bucket_warn_once( ...
                        nla_softwarn_state, 'nla', ...
                        'NLA_KELDYSH_EXP_CLAMP', ...
                        'CerUPP:NLA:KeldyshExponentClampSoft', ...
                        ['Matched OFI NLA direct-W evaluation reported a nonzero shared ', ...
                         'exp_clamp_count=%d on the Keldysh interface. Detail: %s'], ...
                        exp_clamp_count, detail_clamp);
                end
            else
                if ~(isstruct(keldysh_ctx) && isfield(keldysh_ctx, 'K_vec') && isfield(keldysh_ctx, 'sigmaK_vec'))
                    error('CerUPP:AdvanceStepNlaMissingMatchedOfiRate', ...
                        ['Matched plasma-OFI NLA requires either a dynamic W_ion_interp_fn ', ...
                         'or static K_vec/sigmaK_vec source terms.']);
                end
                k_vec_static = double(keldysh_ctx.K_vec(:).');
                sigma_vec_static = double(keldysh_ctx.sigmaK_vec(:).');
                if isempty(k_vec_static) || isempty(sigma_vec_static) || ...
                        (numel(k_vec_static) ~= numel(sigma_vec_static))
                    error('CerUPP:AdvanceStepNlaInvalidMatchedStaticOfiTerms', ...
                        ['Matched static plasma-OFI NLA requires nonempty K_vec and sigmaK_vec ', ...
                         'vectors of equal length.']);
                end
                valid_static_mask = isfinite(k_vec_static) & (k_vec_static > 0) & ...
                    isfinite(sigma_vec_static) & (sigma_vec_static > 0);
                if ~all(valid_static_mask)
                    bad_idx = find(~valid_static_mask, 1, 'first');
                    error('CerUPP:AdvanceStepNlaInvalidMatchedStaticOfiPair', ...
                        ['Matched static plasma-OFI NLA encountered an invalid ', ...
                         '(K,sigma_K) pair at index %d (K=%s, sigma_K=%s).'], ...
                         bad_idx, mat2str(k_vec_static(bad_idx)), mat2str(sigma_vec_static(bad_idx)));
                end
                w_ion = zeros(size(i_eval), 'like', i_eval);
                static_pos_mask = (i_eval > 0) & isfinite(i_eval);
                if need_bookkeeping
                    static_k_eff = zeros(size(i_eval), 'like', i_eval);
                    static_sigma_eff = zeros(size(i_eval), 'like', i_eval);
                end
                if any(static_pos_mask(:))
                    i_static_pos = double(i_eval(static_pos_mask));
                    log_i_static = log(i_static_pos);
                    log_realmax = log(realmax('double'));
                    if numel(k_vec_static) == 1
                        log_w_static = log(sigma_vec_static(1)) + ...
                            k_vec_static(1) .* log_i_static;
                        overflow_mask = (log_w_static > log_realmax);
                        if any(overflow_mask(:))
                            bad_pos = find(overflow_mask, 1, 'first');
                            static_indices = find(static_pos_mask);
                            bad_idx = static_indices(bad_pos);
                            error('CerUPP:AdvanceStepNlaMatchedStaticOfiOverflow', ...
                                ['Matched static plasma-OFI W_ion(I) exceeds the safe exp() range ', ...
                                 'at linear index %d (I=%.6e, K=%.6g).'], ...
                                bad_idx, double(i_eval(bad_idx)), k_vec_static(1));
                        end
                        w_ion(static_pos_mask) = cast(exp(log_w_static), 'like', i_eval);
                        if need_bookkeeping
                            static_k_eff(static_pos_mask) = cast(k_vec_static(1), 'like', i_eval);
                            static_sigma_eff(static_pos_mask) = ...
                                cast(sigma_vec_static(1), 'like', i_eval);
                        end
                    else
                        log_sigma_static = log(sigma_vec_static);
                        max_log_static = -inf(size(log_i_static));
                        for kk = 1:numel(k_vec_static)
                            term_log = log_sigma_static(kk) + ...
                                k_vec_static(kk) .* log_i_static;
                            max_log_static = max(max_log_static, term_log);
                        end
                        sum_scaled_static = zeros(size(log_i_static));
                        sum_k_scaled_static = zeros(size(log_i_static));
                        for kk = 1:numel(k_vec_static)
                            term_log = log_sigma_static(kk) + ...
                                k_vec_static(kk) .* log_i_static;
                            term_scaled = exp(term_log - max_log_static);
                            sum_scaled_static = sum_scaled_static + term_scaled;
                            sum_k_scaled_static = sum_k_scaled_static + ...
                                k_vec_static(kk) .* term_scaled;
                        end
                        log_w_static = max_log_static + log(sum_scaled_static);
                        overflow_mask = (log_w_static > log_realmax);
                        if any(overflow_mask(:))
                            bad_pos = find(overflow_mask, 1, 'first');
                            static_indices = find(static_pos_mask);
                            bad_idx = static_indices(bad_pos);
                            error('CerUPP:AdvanceStepNlaMatchedStaticOfiOverflow', ...
                                ['Matched static plasma-OFI W_ion(I) exceeds the safe exp() range ', ...
                                 'at linear index %d (I=%.6e).'], ...
                                bad_idx, double(i_eval(bad_idx)));
                        end
                        w_ion(static_pos_mask) = cast(exp(log_w_static), 'like', i_eval);
                        if need_bookkeeping
                            k_eff_static = sum_k_scaled_static ./ sum_scaled_static;
                            log_sigma_eff_static = log_w_static - ...
                                k_eff_static .* log_i_static;
                            sigma_overflow_mask = (log_sigma_eff_static > log_realmax);
                            if any(sigma_overflow_mask(:))
                                bad_pos = find(sigma_overflow_mask, 1, 'first');
                                static_indices = find(static_pos_mask);
                                bad_idx = static_indices(bad_pos);
                                error('CerUPP:AdvanceStepNlaMatchedStaticSigmaEffOverflow', ...
                                    ['Matched static plasma-OFI sigma_K,eff exceeds the safe exp() range ', ...
                                     'at linear index %d (I=%.6e).'], ...
                                    bad_idx, double(i_eval(bad_idx)));
                            end
                            static_k_eff(static_pos_mask) = cast(k_eff_static, 'like', i_eval);
                            static_sigma_eff(static_pos_mask) = ...
                                cast(exp(log_sigma_eff_static), 'like', i_eval);
                        end
                    end
                end
            end
            w_ion = cast(propagation_support.require_nonnegative_real_array_local( ...
                w_ion, 'Matched-OFI rate law'), 'like', i_eval);
            w_ion = nla_support.reshape_matched_ofi_array_like_local( ...
                w_ion, i_eval, 'Matched-OFI rate law', ...
                'CerUPP:AdvanceStepNlaMatchedRateShapeMismatch');
            keldysh_matched_depletion_scalar = cast( ...
                double(keldysh_ctx.keldysh_matched_depletion_J), 'like', i_eval);
            applied_density_scale = nla_support.resolve_matched_ofi_applied_density_scale_local( ...
                remaining_neutral_core, keldysh_ctx, i_eval);
            applied_density_scale = nla_support.reshape_matched_ofi_array_like_local( ...
                applied_density_scale, i_eval, 'Matched-OFI applied density scale', ...
                'CerUPP:AdvanceStepNlaMatchedDensityScaleShapeMismatch');
            loss_rate = applied_density_scale .* ...
                keldysh_matched_depletion_scalar .* w_ion;
            loss_rate = propagation_support.require_nonnegative_real_array_local( ...
                loss_rate, 'Matched-OFI loss rate');
            if ~(need_bookkeeping || need_j_output)
                j_eval = [];
                sigma_eff = [];
                beta_eff_full = [];
                beta_eff_applied = [];
                return;
            end
            if need_j_output
                j_eval = zeros(size(loss_rate), 'like', loss_rate);
                den = max(i_eval, tiny_i);
                pos_j = (i_eval > 0) & isfinite(den);
                j_eval(pos_j) = loss_rate(pos_j) ./ den(pos_j);
            else
                j_eval = [];
            end
            if ~need_bookkeeping
                sigma_eff = [];
                beta_eff_full = [];
                beta_eff_applied = [];
                return;
            end
            if dynamic_ofi_rate_active
                i_eval_supported = nla_support.clamp_supported_intensity(i_eval, keldysh_ctx, tiny_i);
                k_eff = nla_support.compute_keldysh_keff(i_eval_supported, keldysh_ctx, tiny_i);
                sigma_den = max(i_eval_supported .^ k_eff, tiny_i);
                sigma_eff = zeros(size(i_eval), 'like', i_eval);
                pos_mask = (i_eval > 0) & isfinite(i_eval) & isfinite(w_ion) & isfinite(k_eff);
                sigma_eff(pos_mask) = w_ion(pos_mask) ./ sigma_den(pos_mask);
            else
                k_eff = static_k_eff;
                sigma_eff = static_sigma_eff;
                pos_mask = (i_eval > 0) & isfinite(i_eval) & isfinite(w_ion) & isfinite(k_eff);
            end
            bad_sigma = pos_mask & ~isfinite(sigma_eff);
            if any(bad_sigma(:))
                bad_idx = find(bad_sigma, 1, 'first');
                error('CerUPP:AdvanceStepNlaNonFiniteKeldyshSigmaEff', ...
                    'Matched OFI sigma_K,eff is non-finite at linear index %d.', bad_idx);
            end
            sigma_eff = propagation_support.require_nonnegative_real_array_local( ...
                sigma_eff, 'Matched-OFI sigma_K,eff');
            % beta_eff_full stays on the full-neutral accounting reference,
            % and beta_eff_applied tracks the current matched loss law.
            keldysh_matched_depletion_rho = cast( ...
                double(keldysh_ctx.keldysh_matched_depletion_J) * ...
                double(keldysh_ctx.rho_nt_keldysh_norm_m3), ...
                'like', i_eval);
            beta_eff_full = keldysh_matched_depletion_rho .* sigma_eff;
            beta_eff_applied = ...
                keldysh_matched_depletion_scalar .* ...
                applied_density_scale .* sigma_eff;
            bad_beta = pos_mask & ~isfinite(beta_eff_full);
            if any(bad_beta(:))
                bad_idx = find(bad_beta, 1, 'first');
                error('CerUPP:AdvanceStepNlaNonFiniteKeldyshBetaEff', ...
                    'Matched OFI beta_eff_full is non-finite at linear index %d.', bad_idx);
            end
            beta_eff_full = propagation_support.require_nonnegative_real_array_local( ...
                beta_eff_full, 'Matched-OFI beta_eff_full');
            bad_beta_applied = pos_mask & ~isfinite(beta_eff_applied);
            if any(bad_beta_applied(:))
                bad_idx = find(bad_beta_applied, 1, 'first');
                error('CerUPP:AdvanceStepNlaNonFiniteKeldyshBetaEffApplied', ...
                    'Matched OFI beta_eff_applied is non-finite at linear index %d.', bad_idx);
            end
            beta_eff_applied = propagation_support.require_nonnegative_real_array_local( ...
                beta_eff_applied, 'Matched-OFI beta_eff_applied');
        end

        function k_eff = compute_keldysh_keff(i_query, keldysh_ctx, tiny_i)
        % Scalar diagnostic exponent used when matched dynamic Keldysh back-calculates sigma/beta diagnostic maps.

            if ~(isstruct(keldysh_ctx) && isfield(keldysh_ctx, 'K_eff_single') && ...
                    isfinite(double(keldysh_ctx.K_eff_single)) && ...
                    (double(keldysh_ctx.K_eff_single) > 0))
                error('CerUPP:AdvanceStepNlaInvalidScalarKeldyshKEff', ...
                    ['Matched Keldysh bookkeeping requires one finite positive setup-side ', ...
                     'scalar keldysh_ctx.K_eff_single.']);
            end
            k_eff = cast(double(keldysh_ctx.K_eff_single), 'like', i_query) .* ...
                ones(size(i_query), 'like', i_query);
        end

        function i_supported = clamp_supported_intensity(i_query, keldysh_ctx, tiny_i)
        % Clamp matched-Keldysh accounting intensities to the declared LUT window.

            i_supported = max(i_query, tiny_i);
            if isfield(keldysh_ctx, 'I_min') && isfinite(double(keldysh_ctx.I_min))
                i_supported = max(i_supported, cast(double(keldysh_ctx.I_min), 'like', i_supported));
            end
            if isfield(keldysh_ctx, 'I_max') && isfinite(double(keldysh_ctx.I_max))
                i_supported = min(i_supported, cast(double(keldysh_ctx.I_max), 'like', i_supported));
            end
        end

        function nla_book = build_bookkeeping_private( ...
                i_pre_core, loss_rate_applied_core, exact_valid_core, full_bookkeeping_ledger, ...
                i_post_core, rho_core_used, j_model_pre_core, dz, tiny_i, j_applied_core)
        % Build the applied-NLA accounting bundle for the current step.

            if nargin < 4 || isempty(full_bookkeeping_ledger)
                full_bookkeeping_ledger = false;
            end
            has_explicit_loss = (nargin >= 2) && ~isempty(loss_rate_applied_core);
            has_explicit_j = (nargin >= 10) && ~isempty(j_applied_core);
            if ~has_explicit_loss
                dz_real_like = cast(double(real(dz)), 'like', i_pre_core);
                loss_rate_applied_core = max((i_pre_core - i_post_core) ./ dz_real_like, 0);
            end
            if logical(full_bookkeeping_ledger) && ~has_explicit_j
                j_applied_core = zeros(size(i_pre_core), 'like', i_pre_core);
                den = max(i_pre_core, tiny_i);
                pos = (i_pre_core > 0) & isfinite(den);
                j_applied_core(pos) = loss_rate_applied_core(pos) ./ den(pos);
            end
            nla_book = struct( ...
                'i_pre_core', i_pre_core, ...
                'loss_rate_applied_core', loss_rate_applied_core);
            if ~isempty(exact_valid_core)
                nla_book.exact_valid_core = logical(exact_valid_core);
            end
            if ~logical(full_bookkeeping_ledger)
                return;
            end
            if has_explicit_loss && has_explicit_j
                applied_ledger_origin = 'explicit';
            elseif ~has_explicit_loss && ~has_explicit_j
                applied_ledger_origin = 'reconstructed';
            else
                applied_ledger_origin = 'mixed';
            end
            nla_book.i_post_core = i_post_core;
            nla_book.rho_core_used = rho_core_used;
            nla_book.j_applied_core = j_applied_core;
            nla_book.j_model_pre_core = j_model_pre_core;
            nla_book.applied_ledger_origin = applied_ledger_origin;
        end

        function assert_rk2_midpoint_positive(i0, loss0, i_half_raw, dz, branch_label)
        % Fail fast when the RK2 midpoint leaves the positive-intensity domain.

            overshoot_mask = (i0 > 0) & (loss0 > 0) & isfinite(i_half_raw) & (i_half_raw <= 0);
            if ~any(overshoot_mask(:))
                return;
            end
            bad_idx = find(overshoot_mask, 1, 'first');
            if isscalar(dz)
                dz_bad = double(dz);
            else
                dz_bad = double(dz(bad_idx));
            end
            error('CerUPP:AdvanceStepNlaRk2MidpointOvershoot', ...
                ['%s RK2 NLA midpoint became nonpositive at linear index %d ' ...
                 '(I0=%.6e, loss0=%.6e, dz=%.6e, Ihalf_raw=%.6e). ' ...
                 'Refusing the hidden positivity fallback because it changes the integrator. ' ...
                 'Decrease stepsize or use Euler intentionally via nla_z_rk2_flag=false ' ...
                 '(or leave nla_z_rk2_flag=[] and select an Euler plasma z-update).'], ...
                branch_label, bad_idx, double(i0(bad_idx)), double(loss0(bad_idx)), dz_bad, double(i_half_raw(bad_idx)));
        end

        function assert_current_step_nonnegative(i0, loss_eval, i_new_raw, dz, branch_label)
        % Fail fast when the current Euler/RK2 NLA step would drive I below zero.

            overshoot_mask = (i0 > 0) & (loss_eval > 0) & isfinite(i_new_raw) & (i_new_raw < 0);
            if ~any(overshoot_mask(:))
                return;
            end
            bad_idx = find(overshoot_mask, 1, 'first');
            if isscalar(dz)
                dz_bad = double(dz);
            else
                dz_bad = double(dz(bad_idx));
            end
            error('CerUPP:AdvanceStepNlaCurrentStepOvershoot', ...
                ['%s NLA current-step update became negative at linear index %d ' ...
                 '(I0=%.6e, loss=%.6e, dz=%.6e, Inew_raw=%.6e). ' ...
                 'Refusing the hidden zero clamp because it changes the applied depletion law. ' ...
                 'Decrease stepsize or use a different explicit NLA stepping choice intentionally.'], ...
                branch_label, bad_idx, double(i0(bad_idx)), double(loss_eval(bad_idx)), dz_bad, double(i_new_raw(bad_idx)));
        end
    end
end


function [enabled, keldysh_nla_context] = nla_support_build_keldysh_nla_context_local( ...
        plasma_runtime_cfg, rho_nt_keldysh_norm_m3)
% Build the OFI-based NLA context struct from the prebuilt OFI setup record.
% This repackages either the direct dynamic W_ion(I) handle or the static
% sum_K sigma_K I^K source terms, plus the depletion controls and
% diagnostic-translation data that advance_z_step.m uses on the OFI-
% based NLA path.

    enabled = false;
    keldysh_nla_context = struct('enabled', false);
    if ~isstruct(plasma_runtime_cfg) || ~isfield(plasma_runtime_cfg, 'ofi_setup') || ...
            isempty(plasma_runtime_cfg.ofi_setup) || ~isstruct(plasma_runtime_cfg.ofi_setup)
        return;
    end

    ofi_setup = plasma_runtime_cfg.ofi_setup;
    required_ofi_fields = {'keldysh_ctx', 'keldysh_matched_depletion_J', 'K_eff_single'};
    missing_ofi_fields = required_ofi_fields(~isfield(ofi_setup, required_ofi_fields));
    if ~isempty(missing_ofi_fields)
        error('apply_nla_step:MissingOfiSetupFields', ...
            'Missing required ofi_setup field(s): %s', strjoin(missing_ofi_fields, ', '));
    end

    shared_ctx = ofi_setup.keldysh_ctx;
    if ~isstruct(shared_ctx)
        error('apply_nla_step:InvalidOfiSetupKeldyshCtx', ...
            'plasma_runtime_cfg.ofi_setup.keldysh_ctx must be a struct.');
    end
    if ~isfield(shared_ctx, 'enabled') || ~nla_support_is_scalar_logical_like_local(shared_ctx.enabled)
        error('apply_nla_step:InvalidOfiSetupKeldyshEnabled', ...
            'plasma_runtime_cfg.ofi_setup.keldysh_ctx.enabled must be scalar logical-like.');
    end
    dynamic_ofi_rate_available = logical(shared_ctx.enabled);
    if dynamic_ofi_rate_available
        if ~(isfield(shared_ctx, 'W_ion_interp_fn') && isa(shared_ctx.W_ion_interp_fn, 'function_handle'))
            error('apply_nla_step:KeldyshMissingWInterp', ...
                'ofi_setup.keldysh_ctx.enabled=true requires W_ion_interp_fn.');
        end
    end

    keldysh_nla_context = struct( ...
        'enabled', true, ...
        'bookkeeping_diag_enabled', true, ...
        'bookkeeping_diag_status', 'ready', ...
        'use_scalar_keff_bookkeeping', true, ...
        'K_eff_single', NaN, ...
        'keldysh_matched_depletion_J', NaN, ...
        'hbar_omega_J', NaN, ...
        'rho_nt_m3', NaN, ...
        'rho_nt_keldysh_norm_m3', NaN, ...
        'plasma_ofi_use_remaining_neutral_factor_flag', true, ...
        'nla_use_remaining_neutral_factor_flag_effective', true, ...
        'ofi_source_density_scale_m3', NaN, ...
        'K_vec', [], ...
        'sigmaK_vec', [], ...
        'W_ion_interp_fn', [], ...
        'I_min', NaN, ...
        'I_max', NaN, ...
        'eval_opts', []);
    if ~(isscalar(ofi_setup.keldysh_matched_depletion_J) && isnumeric(ofi_setup.keldysh_matched_depletion_J) && ...
            isreal(ofi_setup.keldysh_matched_depletion_J) && isfinite(ofi_setup.keldysh_matched_depletion_J) && ...
            (ofi_setup.keldysh_matched_depletion_J > 0))
        error('apply_nla_step:OfiSetupMissingMatchedDepletion', ...
            'ofi_setup.keldysh_matched_depletion_J must be finite and > 0 for matched Keldysh applied depletion.');
    end
    keldysh_nla_context.keldysh_matched_depletion_J = double(ofi_setup.keldysh_matched_depletion_J);
    keldysh_nla_context.hbar_omega_J = double(struct_utils.opt_struct_field( ...
        struct_utils.opt_struct_field(plasma_runtime_cfg, 'keldysh_cfg', struct()), ...
        'hbar_omega_J', NaN));
    keldysh_nla_context.rho_nt_m3 = double(struct_utils.opt_struct_field( ...
        plasma_runtime_cfg, 'rho_nt_m3', NaN));
    if ~(isscalar(rho_nt_keldysh_norm_m3) && isnumeric(rho_nt_keldysh_norm_m3) && ...
            isreal(rho_nt_keldysh_norm_m3) && isfinite(rho_nt_keldysh_norm_m3) && ...
            (rho_nt_keldysh_norm_m3 > 0))
        error('apply_nla_step:KeldyshInvalidRhoNtNorm', ...
            ['Matched Keldysh accounting requires a finite positive ', ...
             'rho_nt_keldysh_norm_m3; got %s.'], ...
            mat2str(rho_nt_keldysh_norm_m3));
    end
    keldysh_nla_context.rho_nt_keldysh_norm_m3 = double(rho_nt_keldysh_norm_m3);
    keldysh_nla_context.plasma_ofi_use_remaining_neutral_factor_flag = logical( ...
        struct_utils.opt_struct_field(ofi_setup, 'plasma_ofi_use_remaining_neutral_factor_flag', ...
            struct_utils.opt_struct_field(shared_ctx, 'plasma_ofi_use_remaining_neutral_factor_flag', ...
                ~struct_utils.opt_struct_field(shared_ctx, 'keldysh_use_additive_volumetric_source_flag', false))));
    keldysh_nla_context.nla_use_remaining_neutral_factor_flag_effective = logical( ...
        struct_utils.opt_struct_field(ofi_setup, 'nla_use_remaining_neutral_factor_flag_effective', ...
            struct_utils.opt_struct_field(shared_ctx, 'nla_use_remaining_neutral_factor_flag_effective', ...
                keldysh_nla_context.plasma_ofi_use_remaining_neutral_factor_flag)));
    use_additive_volumetric_source = ...
        ~keldysh_nla_context.nla_use_remaining_neutral_factor_flag_effective;
    keldysh_nla_context.ofi_source_density_scale_m3 = double(struct_utils.opt_struct_field( ...
        ofi_setup, 'ofi_source_density_scale_m3', ...
        struct_utils.opt_struct_field(shared_ctx, 'ofi_source_density_scale_m3', NaN)));
    if logical(use_additive_volumetric_source) && ...
            ~(isscalar(keldysh_nla_context.ofi_source_density_scale_m3) && ...
              isreal(keldysh_nla_context.ofi_source_density_scale_m3) && ...
              isfinite(keldysh_nla_context.ofi_source_density_scale_m3) && ...
              (keldysh_nla_context.ofi_source_density_scale_m3 > 0))
        error('apply_nla_step:InvalidKeldyshSourceDensityScale', ...
            ['Matched Keldysh fixed-density-scale depletion requires a finite positive ', ...
             'ofi_source_density_scale_m3.']);
    end
    if dynamic_ofi_rate_available && isfield(shared_ctx, 'sigmaK_interp_fn') && ~isempty(shared_ctx.sigmaK_interp_fn)
        error('apply_nla_step:KeldyshUnsupportedSigmaInterp', ...
            ['Matched Keldysh runtime uses W_ion_interp_fn directly. ', ...
             'sigmaK_interp_fn belongs only to sigma/beta diagnostic translation ', ...
             'and is not supported here.']);
    end
    if dynamic_ofi_rate_available
        keldysh_nla_context.W_ion_interp_fn = shared_ctx.W_ion_interp_fn;
        keldysh_nla_context.I_min = shared_ctx.I_min;
        keldysh_nla_context.I_max = shared_ctx.I_max;
    end
    if isfield(shared_ctx, 'K_vec') && ~isempty(shared_ctx.K_vec)
        keldysh_nla_context.K_vec = double(shared_ctx.K_vec(:).');
    elseif isfield(ofi_setup, 'k_power') && ~isempty(ofi_setup.k_power)
        keldysh_nla_context.K_vec = double(ofi_setup.k_power(:).');
    end
    if isfield(shared_ctx, 'sigmaK_vec') && ~isempty(shared_ctx.sigmaK_vec)
        keldysh_nla_context.sigmaK_vec = max(double(shared_ctx.sigmaK_vec(:).'), 0);
    elseif isfield(ofi_setup, 'log_sigK') && ~isempty(ofi_setup.log_sigK)
        keldysh_nla_context.sigmaK_vec = exp(double(ofi_setup.log_sigK(:).'));
    end
    keldysh_nla_context.keldysh_zero_rate_below_wm2 = struct_utils.opt_struct_field( ...
        shared_ctx, 'keldysh_zero_rate_below_wm2', keldysh_nla_context.I_min, 'treat_empty_as_missing', true);
    keldysh_nla_context.W_min_clamp_value = struct_utils.opt_struct_field( ...
        shared_ctx, 'W_min_clamp_value', 0, 'treat_empty_as_missing', true);
    keldysh_nla_context.W_max_clamp_value = struct_utils.opt_struct_field( ...
        shared_ctx, 'W_max_clamp_value', 0, 'treat_empty_as_missing', true);

    if ~(isscalar(ofi_setup.K_eff_single) && isnumeric(ofi_setup.K_eff_single) && ...
            isreal(ofi_setup.K_eff_single) && isfinite(ofi_setup.K_eff_single) && ...
            (ofi_setup.K_eff_single > 0))
        error('apply_nla_step:OfiSetupScalarKeffMissing', ...
            'Matched Keldysh bookkeeping requires a finite positive ofi_setup.K_eff_single.');
    end
    keldysh_nla_context.K_eff_single = double(ofi_setup.K_eff_single);

    keldysh_nla_context.eval_opts = struct( ...
        'I_min', keldysh_nla_context.I_min, ...
        'I_max', keldysh_nla_context.I_max, ...
        'I_zero_below', keldysh_nla_context.keldysh_zero_rate_below_wm2, ...
        'K_eff_single', keldysh_nla_context.K_eff_single, ...
        'clamp_w_interp', true, ...
        'W_min_clamp_value', keldysh_nla_context.W_min_clamp_value, ...
        'W_max_clamp_value', keldysh_nla_context.W_max_clamp_value, ...
        'exp_clamp_count_mode', 'nnz');
    enabled = true;
end

function tf = nla_support_is_scalar_logical_like_local(v)
% Accept the small scalar logical-or-logical-like values used by setup.

    tf = isscalar(v) && (islogical(v) || ...
        (isnumeric(v) && isreal(v) && isfinite(v)));
end

function [requested_mode, explicit_static_override_active] = ...
        nla_support_resolve_requested_closure_mode_local(nla_setup_opts)
% Normalize the requested closure selection at the public parse boundary.

    nla_use_ofi_rate_law_flag = struct_utils.normalize_bool_scalar( ...
        struct_utils.opt_struct_field(nla_setup_opts, 'nla_use_ofi_rate_law_flag', false), ...
        'nla_setup_opts.nla_use_ofi_rate_law_flag', ...
        'CerUPP:InvalidNlaClosureMode');
    explicit_static_override_active = ~logical(nla_use_ofi_rate_law_flag);
    if logical(nla_use_ofi_rate_law_flag)
        requested_mode = 'plasma_ofi';
    else
        requested_mode = 'static_mpi_beta';
    end
end

function nla_setup_opts = nla_support_validate_setup_option_fields_local(nla_setup_opts)
% Reject unknown NLA setup-option names at the public parse boundary.

    if nargin < 1 || isempty(nla_setup_opts)
        nla_setup_opts = struct();
        return;
    end
    if ~isstruct(nla_setup_opts) || ~isscalar(nla_setup_opts)
        error('CerUPP:InvalidNlaSetupOpts', ...
            'nla_setup_opts must be a scalar struct.');
    end
    allowed_fields = { ...
        'nla_use_ofi_rate_law_flag', ...
        'nla_use_remaining_neutral_factor_flag', ...
        'nla_ofi_energy_accounting_mode', ...
        'nla_check_ofi_event_energy_flag', ...
        'nla_use_ofi_event_depletion_flag', ...
        'plasma_flag', ...
        'nla_z_rk2_flag', ...
        'keldysh_enabled', ...
        'ofi_branch_active', ...
        'plasma_ofi_use_remaining_neutral_factor_flag', ...
        'keldysh_use_additive_volumetric_source_flag', ...
        'resolved_closure' ...
    };
    unknown_fields = setdiff(fieldnames(nla_setup_opts).', allowed_fields, 'stable');
    if ~isempty(unknown_fields)
        error('CerUPP:UnknownNlaSetupField', ...
            ['Unknown nla_setup_opts field(s): %s. Allowed fields are: %s.'], ...
            strjoin(unknown_fields, ', '), strjoin(allowed_fields, ', '));
    end
end

function [rk_order_mode, rk_order] = nla_support_resolve_rk_order_local(nla_z_rk2_flag_in)
% Normalize the optional NLA outer-z RK2 override into one record field pair.

    rk_order_mode = 'follow_plasma';
    rk_order = NaN;
    if isempty(nla_z_rk2_flag_in)
        return;
    end
    try
        rk2_flag = struct_utils.normalize_bool_scalar( ...
            nla_z_rk2_flag_in, 'nla_setup_opts.nla_z_rk2_flag', 'CerUPP:InvalidNlaRkOrder');
    catch me
        if strcmp(me.identifier, 'CerUPP:InvalidNlaRkOrder')
            if isstring(nla_z_rk2_flag_in) && isscalar(nla_z_rk2_flag_in)
                rk_value_desc = sprintf('''%s''', char(nla_z_rk2_flag_in));
            elseif ischar(nla_z_rk2_flag_in)
                rk_value_desc = sprintf('''%s''', nla_z_rk2_flag_in);
            elseif isnumeric(nla_z_rk2_flag_in) || islogical(nla_z_rk2_flag_in)
                rk_value_desc = mat2str(nla_z_rk2_flag_in);
            else
                rk_value_desc = sprintf('<class %s, size %s>', class(nla_z_rk2_flag_in), mat2str(size(nla_z_rk2_flag_in)));
            end
            error('CerUPP:InvalidNlaRkOrder', ...
                'nla_setup_opts.nla_z_rk2_flag must be [], false, or true; got %s.', rk_value_desc);
        end
        rethrow(me);
    end
    rk_order_mode = 'explicit';
    rk_order = 1 + double(rk2_flag);
end

function [rk_order_mode, rk_order] = nla_support_normalize_resolved_rk_order_local(closure_source)
% Normalize the stored RK-order pair on an already-built NLA config/record.

    rk_order_mode = char(string(struct_utils.opt_struct_field( ...
        closure_source, 'rk_order_mode', 'follow_plasma')));
    rk_order_mode = lower(strtrim(rk_order_mode));
    rk_order = double(struct_utils.opt_struct_field(closure_source, 'rk_order', NaN));
    if strcmp(rk_order_mode, 'follow_plasma')
        return;
    end
    if strcmp(rk_order_mode, 'explicit')
        if ~(isscalar(rk_order) && isreal(rk_order) && isfinite(rk_order) && ismember(rk_order, [1, 2]))
            error('CerUPP:InvalidNlaRkOrder', ...
                'nla_cfg.rk_order must be an explicit scalar 1 or 2 when rk_order_mode=''explicit''.');
        end
        return;
    end
    error('CerUPP:InvalidNlaRkOrder', ...
        'nla_cfg.rk_order_mode must be ''follow_plasma'' or ''explicit''; got ''%s''.', rk_order_mode);
end
