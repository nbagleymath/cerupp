% Fluence-map and phase-map reduction helpers.
% Purpose:
% - Reduce stored fields into fluence-style and phase-style maps used by
%   storage and plotting.

    methods (Static)
        function summary = summarize_fluence_map(x, y, fxy)
        %SUMMARIZE_FLUENCE_MAP Shared fluence-map reductions for centroid, radial first moment, peak, and beam-center sampling.
        % Beam-center policy matches the driver/restart contract:
        % centroid-nearest sample when valid; otherwise the beam-center
        % sample is left unavailable instead of falling back to peak/axis.
        % method_code=1 marks a centroid-nearest beam-center sample.

            x_col = x(:);
            y_col = y(:);
            summary = struct( ...
                'total', NaN, ...
                'rmean_fluence', NaN, ...
                'centroid_x', NaN, ...
                'centroid_y', NaN, ...
                'peak_x', NaN, ...
                'peak_y', NaN, ...
                'ix_peak', NaN, ...
                'iy_peak', NaN, ...
                'ix_beamcenter', NaN, ...
                'iy_beamcenter', NaN, ...
                'x_beamcenter', NaN, ...
                'y_beamcenter', NaN, ...
                'method_code', NaN);
            if isempty(fxy) || isempty(x_col) || isempty(y_col)
                return;
            end
            if ~isnumeric(fxy) || ~ismatrix(fxy)
                error('storage_support:InvalidFluenceMapShape', ...
                    'fxy must be a numeric 2-D fluence map.');
            end
            if size(fxy, 1) ~= numel(x_col) || size(fxy, 2) ~= numel(y_col)
                error('storage_support:InvalidFluenceMapSizeMismatch', ...
                    'fxy size must match numel(x) x numel(y).');
            end
            if ~isreal(fxy)
                error('storage_support:InvalidFluenceMapComplex', ...
                    'fxy must be real-valued before fluence reductions are computed.');
            end
            if any(~isfinite(fxy(:)))
                error('storage_support:InvalidFluenceMapNonfinite', ...
                    'fxy must be finite before fluence reductions are computed.');
            end
            if any(fxy(:) < 0)
                error('storage_support:InvalidFluenceMapNegative', ...
                    'fxy must be nonnegative before fluence reductions are computed.');
            end

            mx = reshape(trapz(y_col, fxy, 2), [], 1);
            s_total = trapz(x_col, mx, 1);
            summary.total = s_total;
            if isfinite(s_total) && (s_total > 0)
                radius_xy = hypot(x_col, reshape(y_col, 1, []));
                rmean_cand = trapz(x_col, trapz(y_col, radius_xy .* fxy, 2), 1) ./ s_total;
                if isfinite(rmean_cand)
                    summary.rmean_fluence = rmean_cand;
                end
                my = reshape(trapz(x_col, fxy, 1), [], 1);
                x_cand = trapz(x_col, x_col .* mx, 1) ./ s_total;
                y_cand = trapz(y_col, y_col .* my, 1) ./ s_total;
                if isfinite(x_cand) && isfinite(y_cand)
                    summary.centroid_x = x_cand;
                    summary.centroid_y = y_cand;
                    [~, summary.ix_beamcenter] = min(abs(x_col - x_cand));
                    [~, summary.iy_beamcenter] = min(abs(y_col - y_cand));
                    summary.x_beamcenter = x_col(summary.ix_beamcenter);
                    summary.y_beamcenter = y_col(summary.iy_beamcenter);
                    summary.method_code = 1;
                end
            end

            peak_val = max(fxy(:));
            if ~(isfinite(s_total) && (s_total > 0) && isfinite(peak_val) && (peak_val > 0))
                return;
            end

            peak_mask = (fxy == peak_val);
            peak_linear_idx = find(peak_mask);
            if isempty(peak_linear_idx)
                return;
            end

            if numel(peak_linear_idx) == 1
                [summary.ix_peak, summary.iy_peak] = ind2sub(size(fxy), peak_linear_idx);
            else
                % Positive plateaus use a center-of-plateau rule instead of
                % MATLAB's first-index argmax tie-break.

                [peak_ix_all, peak_iy_all] = ind2sub(size(fxy), peak_linear_idx);
                peak_x_center = mean(double(x_col(peak_ix_all)));
                peak_y_center = mean(double(y_col(peak_iy_all)));
                [~, summary.ix_peak] = min(abs(x_col - peak_x_center));
                [~, summary.iy_peak] = min(abs(y_col - peak_y_center));
            end
            summary.peak_x = x_col(summary.ix_peak);
            summary.peak_y = y_col(summary.iy_peak);
        end

        function phase_mean = intensity_weighted_phase_mean(A_S, intens_s, t, recenter_to_fund_t)
        %INTENSITY_WEIGHTED_PHASE_MEAN Shared omega_fund-centered phase-map rule.
        % recenter_to_fund_t may be a length-Nt vector or a [1 1 Nt] time-axis phase factor.

            abs_a_s = sqrt(intens_s);
            A_phase = A_S;
            if nargin >= 4 && ~isempty(recenter_to_fund_t)
                if isvector(recenter_to_fund_t)
                    recenter_to_fund_t = reshape(recenter_to_fund_t(:).', 1, 1, []);
                elseif ~(ndims(recenter_to_fund_t) == 3 && ...
                        isequal(size(recenter_to_fund_t, 1), 1) && ...
                        isequal(size(recenter_to_fund_t, 2), 1) && ...
                        isequal(size(recenter_to_fund_t, 3), size(A_S, 3)))
                    error('storage_support:PhaseRecenterVectorSizeMismatch', ...
                        'recenter_to_fund_t must be length-Nt or [1 1 Nt].');
                end
                A_phase = A_S .* cast(recenter_to_fund_t, 'like', A_S);
            end
            phase_floor = 1e-12;
            i_phase_peak = max(intens_s(:), [], 'omitnan');
            if isfinite(i_phase_peak) && (i_phase_peak > 0)
                phase_valid = isfinite(intens_s) & ...
                    (intens_s > (phase_floor * i_phase_peak));
            else
                phase_valid = false(size(intens_s));
            end
            valid_phasor = phase_valid & (abs_a_s > 0);
            num_integrand = abs_a_s .* A_phase;
            num_integrand(~valid_phasor) = 0;
            den_integrand = intens_s;
            den_integrand(~phase_valid) = 0;
            num_phase = trapz(t, num_integrand, 3);
            den_phase = trapz(t, den_integrand, 3);
            phase_mean = NaN(size(den_phase));
            valid_den = isfinite(den_phase) & (den_phase > 0);
            phase_mean(valid_den) = angle(num_phase(valid_den) ./ den_phase(valid_den));
        end
    end
