            end
        end


        function [store_side_vis_xz, store_peak_drho_over_rho_nt_ofi, ...
                store_peak_drho_over_rho_nt_aval, run_warn_state, ...
                last_reduced_store_idx_out] = ...
                resolve_deferred_store_reductions_local( ...
                store_fluence_xy_visible, y, ...
                store_drho_ofi_xz, store_drho_aval_xz, ...
                store_side_vis_xz, ...
                store_peak_drho_over_rho_nt_ofi, ...
                store_peak_drho_over_rho_nt_aval, ...
                rho_nt, store_z, n_store_actual, run_warn_state, ...
                last_reduced_store_idx)
        % Fill the derived side-view and peak-source traces from their
        % stored parent histories, optionally only for newly appended planes.

            if nargin < 10 || isempty(n_store_actual) || ~isfinite(n_store_actual)
                n_store_actual = 0;
            end
            n_store_actual = max(0, floor(double(n_store_actual)));
            if nargin < 12 || isempty(last_reduced_store_idx) || ...
                    ~isfinite(last_reduced_store_idx)
                last_reduced_store_idx = 0;
            end
            last_reduced_store_idx = max(0, floor(double(last_reduced_store_idx)));
            reduction_start_idx = max(1, last_reduced_store_idx + 1);

            if last_reduced_store_idx > 0
                side_parent_ok = isempty(store_fluence_xy_visible) || ...
                    (size(store_fluence_xy_visible, 3) >= last_reduced_store_idx);
                side_output_ok = isempty(store_side_vis_xz) || ...
                    (size(store_side_vis_xz, 2) >= last_reduced_store_idx);
                ofi_parent_ok = isempty(store_drho_ofi_xz) || ...
                    (size(store_drho_ofi_xz, 2) >= last_reduced_store_idx);
                ofi_output_ok = isempty(store_peak_drho_over_rho_nt_ofi) || ...
                    (numel(store_peak_drho_over_rho_nt_ofi) >= last_reduced_store_idx);
                aval_parent_ok = isempty(store_drho_aval_xz) || ...
                    (size(store_drho_aval_xz, 2) >= last_reduced_store_idx);
                aval_output_ok = isempty(store_peak_drho_over_rho_nt_aval) || ...
                    (numel(store_peak_drho_over_rho_nt_aval) >= last_reduced_store_idx);
                if ~(side_parent_ok && side_output_ok && ofi_parent_ok && ...
                        ofi_output_ok && aval_parent_ok && aval_output_ok) || ...
                        (last_reduced_store_idx > n_store_actual)
                    reduction_start_idx = 1;
                end
            end
            if ~isempty(store_side_vis_xz) && ~isempty(store_fluence_xy_visible) && ...
                    (n_store_actual > 0)
                n_side = min([n_store_actual, size(store_side_vis_xz, 2), size(store_fluence_xy_visible, 3)]);
                for iz = reduction_start_idx:n_side
                    fluence_xy = store_fluence_xy_visible(:, :, iz);
                    if isempty(fluence_xy)
                        store_side_vis_xz(:, iz) = NaN;
                        continue;
                    end
                    side_vis_now = squeeze(trapz(y, fluence_xy, 2)); %[J/m]
                    if isvector(side_vis_now)
                        if numel(side_vis_now) == size(store_side_vis_xz, 1)
                            store_side_vis_xz(:, iz) = side_vis_now(:);
                        else
                            run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                                run_warn_state, 'end', ...
                                'visible_sideview_vector_size_mismatch', ...
                                'CerUPP:Diagnostics:VisibleSideviewVectorSizeMismatch', ...
                                ['Skipping one visible side-view plane because the reduced y-integral ' ...
                                 'returned a vector with %d entries but the x grid expects %d.'], ...
                                numel(side_vis_now), size(store_side_vis_xz, 1));
                            store_side_vis_xz(:, iz) = NaN;
                        end
                    else
                        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                            run_warn_state, 'end', ...
                            'visible_sideview_contract_violation', ...
                            'CerUPP:Diagnostics:VisibleSideviewContractViolation', ...
                            ['Skipping one visible side-view plane because the y-integral ' ...
                             'returned a non-vector shape %s instead of the expected x-vector.'], ...
                            mat2str(size(side_vis_now)));
                        store_side_vis_xz(:, iz) = NaN;
                    end
                end
            end

            if isempty(store_peak_drho_over_rho_nt_ofi) && isempty(store_peak_drho_over_rho_nt_aval)
                last_reduced_store_idx_out = n_store_actual;
                return;
            end

            if ~isempty(store_peak_drho_over_rho_nt_ofi) && ~isempty(store_drho_ofi_xz)
                n_ofi = min([n_store_actual, numel(store_peak_drho_over_rho_nt_ofi), size(store_drho_ofi_xz, 2)]);
                for iz = reduction_start_idx:n_ofi
                    z_now = storage_support.conditional_store_z_local(store_z, iz);
                    [store_peak_drho_over_rho_nt_ofi(iz), run_warn_state] = ...
                        storage_support.compute_peak_drho_over_rho_nt_local( ...
                        run_warn_state, 'end', store_drho_ofi_xz(:, iz), 'OFI', ...
                        'drho_ofi_negative_source_trace', ...
                        'CerUPP:NegativeDrhoOfiDiagnostic', ...
                        'invalid_rho_nt_diag_deferred', ...
                        'CerUPP:Diagnostics:InvalidRhoNtDiag', ...
                        rho_nt, iz, z_now);
                end
            end
            if ~isempty(store_peak_drho_over_rho_nt_aval) && ~isempty(store_drho_aval_xz)
                n_aval = min([n_store_actual, numel(store_peak_drho_over_rho_nt_aval), size(store_drho_aval_xz, 2)]);
                for iz = reduction_start_idx:n_aval
                    z_now = storage_support.conditional_store_z_local(store_z, iz);
                    [store_peak_drho_over_rho_nt_aval(iz), run_warn_state] = ...
                        storage_support.compute_peak_drho_over_rho_nt_local( ...
                        run_warn_state, 'end', store_drho_aval_xz(:, iz), 'avalanche', ...
                        'drho_aval_negative_source_trace', ...
                        'CerUPP:NegativeDrhoAvalancheDiagnostic', ...
                        'invalid_rho_nt_diag_deferred', ...
                        'CerUPP:Diagnostics:InvalidRhoNtDiag', ...
                        rho_nt, iz, z_now);
                end
            end
            last_reduced_store_idx_out = n_store_actual;
        end


