                    'prop_farfield_spectrum_nonnegative_clamped', ...
                    'CerUPP:FarFieldSpectrumNonnegativeClamped');
                if cfg.perf_cfg.track_energy_flag
                    e_from_s = trapz(cfg.nu_sorted, s_hz(cfg.idx_nu));
                else
                    e_from_s = NaN;
                end
                if cfg.perf_cfg.track_energy_flag && isfinite(cfg.energy_val) && (cfg.energy_val > 0) && ...
                        isfinite(e_from_s) && (e_from_s > 0)
                    rel_energy_mismatch = abs(e_from_s - cfg.energy_val) / max(cfg.energy_val, cfg.eps_safe);
                    if rel_energy_mismatch > 5e-2
                        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                            run_warn_state, 'propagation', ...
                            sprintf('prop_farfield_spectrum_energy_mismatch_save_%d', cfg.save_idx), ...
                            'CerUPP:FarFieldSpectrumEnergyMismatchSoft', ...
                            ['Stored output-spectrum energy mismatch at save_idx=%d: E_spec=%.6e J, E_near=%.6e J ', ...
                             '(rel err=%.3e).'], ...
                            cfg.save_idx, e_from_s, cfg.energy_val, rel_energy_mismatch);
                    end
                end
                diagnostic_store.store_spectrum(cfg.save_idx, :) = s_hz;
