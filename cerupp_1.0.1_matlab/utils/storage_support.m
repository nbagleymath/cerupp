                        ['Stored total-fluence beam-center y-cut FWHM returned NaN ', ...
                         'at save_idx=%d, z=%.6e m: %s.'], ...
                        double(cfg.save_idx), double(z_now), bw_yt_msg);
                end
                if all(isfinite([bw_xt, bw_yt])) && all([bw_xt, bw_yt] >= 0)
                    diagnostic_store.store_diameter_total(cfg.save_idx, 1) = mean([bw_xt, bw_yt]);
                end

                if ~isempty(band.f_fund_xy) && logical(band.fund_beamcenter_sample_ok)
                    [bw_xf, bw_xf_msg, bw_xf_status] = filament_diagnostics_utils.fwhm_diameter_from_profile( ...
                        cfg.x, band.f_fund_xy(:, band.iy_bc_fund));
                    if bw_xf_status.recoverable
                        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                            run_warn_state, 'propagation', ...
                            sprintf('store_diameter_fund_x_%s', char(string(bw_xf_status.code))), ...
                            'CerUPP:Diagnostics:StoredFwhmReductionFailed', ...
                            ['Stored fundamental-band beam-center x-cut FWHM returned NaN ', ...
                             'at save_idx=%d, z=%.6e m: %s.'], ...
                            double(cfg.save_idx), double(z_now), bw_xf_msg);
                    end
                    [bw_yf, bw_yf_msg, bw_yf_status] = filament_diagnostics_utils.fwhm_diameter_from_profile( ...
                        cfg.y, band.f_fund_xy(band.ix_bc_fund, :).');
                    if bw_yf_status.recoverable
                        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                            run_warn_state, 'propagation', ...
                            sprintf('store_diameter_fund_y_%s', char(string(bw_yf_status.code))), ...
                            'CerUPP:Diagnostics:StoredFwhmReductionFailed', ...
                            ['Stored fundamental-band beam-center y-cut FWHM returned NaN ', ...
                             'at save_idx=%d, z=%.6e m: %s.'], ...
                            double(cfg.save_idx), double(z_now), bw_yf_msg);
