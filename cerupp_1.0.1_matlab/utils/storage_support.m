        function [diagnostic_store, store_workspaces, run_warn_state, store_ofi_aval_diag_failed] = ...
                write_plasma_nla_history_families_local( ...
                cfg, diagnostic_store, store_workspaces, run_warn_state, store_ofi_aval_diag_failed)
        % Write the plasma, applied-loss, and matched-Keldysh store families.

