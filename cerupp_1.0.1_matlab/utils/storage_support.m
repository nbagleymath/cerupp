        function flat_cfg = merge_store_current_plane_group_local(flat_cfg, group_value, group_label)
        % Merge one grouped store-step owner into the helper-local flat cfg.

            if ~(isstruct(group_value) && isscalar(group_value))
                error('CerUPP:InvalidStorePlaneGroupedInput', ...
                    '%s must be a scalar struct.', group_label);
            end
            group_field_names = fieldnames(group_value);
            overlap = intersect(fieldnames(flat_cfg), group_field_names, 'stable');
            if ~isempty(overlap)
                error('CerUPP:DuplicateStorePlaneGroupedInputField', ...
                    '%s reuses existing store-step field(s): %s', ...
                    group_label, strjoin(overlap, ', '));
            end
            for field_idx = 1:numel(group_field_names)
                field_name = group_field_names{field_idx};
                flat_cfg.(field_name) = group_value.(field_name);
            end
        end


        function reason_text = pick_first_output_history_reason_local(varargin)
        % Return the first enabled reason in a cond/reason pair list, else 'disabled'.

            reason_text = 'disabled';
