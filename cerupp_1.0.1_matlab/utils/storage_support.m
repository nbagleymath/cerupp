        function band_weight_xy_stack = build_store_band_weight_stack_local( ...
                a_fft_stored, band_mask_stack_store, spectral_weight_xyomega, fallback_weight_xy)
        % Build one 2-D in-medium weight map per diagnostic band by taking
        % the broadband spectral weight at one representative FFT-order
        % band bin. Wrapped FFT bands use the circular band midpoint rather
        % than the raw middle array index.

            if ndims(band_mask_stack_store) == 3
                band_mask_stack_store = reshape( ...
                    band_mask_stack_store, ...
                    size(band_mask_stack_store, 1), ...
                    size(band_mask_stack_store, 2), ...
                    size(band_mask_stack_store, 3), 1);
            end
            [nx_local, ny_local, ~] = size(a_fft_stored);
            n_bands = size(band_mask_stack_store, 4);
            band_weight_xy_stack = zeros(nx_local, ny_local, n_bands, ...
                'like', fallback_weight_xy);
            if isempty(spectral_weight_xyomega)
                for band_idx = 1:n_bands
                    band_weight_xy_stack(:, :, band_idx) = fallback_weight_xy;
                end
                return;
            end
            if ~isequal(size(spectral_weight_xyomega, 1), 1) && ...
                    ~isequal(size(spectral_weight_xyomega, 1), nx_local)
                error('CerUPP:InvalidSpectralWeightMapSize', ...
                    ['spectral_weight_xyomega must have x-size 1 or %d for band-center ', ...
                     'weight construction; got %s.'], ...
                    nx_local, mat2str(size(spectral_weight_xyomega)));
            end
            if ~isequal(size(spectral_weight_xyomega, 2), 1) && ...
                    ~isequal(size(spectral_weight_xyomega, 2), ny_local)
                error('CerUPP:InvalidSpectralWeightMapSize', ...
                    ['spectral_weight_xyomega must have y-size 1 or %d for band-center ', ...
                     'weight construction; got %s.'], ...
                    ny_local, mat2str(size(spectral_weight_xyomega)));
            end
            if ~isequal(size(spectral_weight_xyomega, 3), size(a_fft_stored, 3))
                error('CerUPP:InvalidSpectralWeightMapSize', ...
                    ['spectral_weight_xyomega must have %d spectral samples for band-center ', ...
                     'weight construction; got %s.'], ...
                    size(a_fft_stored, 3), mat2str(size(spectral_weight_xyomega)));
            end

            for band_idx = 1:n_bands
                if size(band_mask_stack_store, 1) == 1
                    spectral_mask_line = reshape( ...
                        abs(band_mask_stack_store(1, 1, :, band_idx)), [], 1);
                else
                    spectral_mask_line = reshape( ...
                        max(max(abs(band_mask_stack_store(:, :, :, band_idx)), [], 1), [], 2), ...
                        [], 1);
                end
                center_idx = storage_support.select_store_band_weight_bin_local( ...
                    spectral_mask_line);
                if isempty(center_idx)
                    band_weight_xy_stack(:, :, band_idx) = fallback_weight_xy;
                    continue;
                end
                if isequal(size(spectral_weight_xyomega, 1), 1) && ...
                        isequal(size(spectral_weight_xyomega, 2), 1)
                    band_weight_xy_stack(:, :, band_idx) = ...
                        spectral_weight_xyomega(1, 1, center_idx);
                else
                    band_weight_xy_stack(:, :, band_idx) = ...
                        spectral_weight_xyomega(:, :, center_idx);
                end
            end
        end

        function center_idx = select_store_band_weight_bin_local(spectral_mask_line)
        % Choose one representative FFT-order band bin on the circular
        % spectral grid so wrapped bands do not collapse onto a raw-array edge.

            support_idx = find(spectral_mask_line > 0);
            if isempty(support_idx)
                center_idx = [];
                return;
            end
            support_idx = reshape(support_idx, 1, []);
            nt = numel(spectral_mask_line);
            if numel(support_idx) == 1
                center_idx = support_idx;
                return;
            end
            if numel(support_idx) >= nt
                center_idx = 1;
                return;
            end

            cyclic_gaps = [diff(support_idx), support_idx(1) + nt - support_idx(end)];
            [~, max_gap_pos] = max(cyclic_gaps);
            start_pos = mod(max_gap_pos, numel(support_idx)) + 1;
            support_rot = [support_idx(start_pos:end), support_idx(1:start_pos - 1)];
            support_unwrapped = double(support_rot);
            wrap_jumps = [false, diff(support_rot) <= 0];
            support_unwrapped = support_unwrapped + nt .* cumsum(wrap_jumps);
            midpoint = 0.5 * (support_unwrapped(1) + support_unwrapped(end));
            dist_to_mid = abs(support_unwrapped - midpoint);
            candidate_pos = find(dist_to_mid == min(dist_to_mid));
            candidate_idx = mod(support_rot(candidate_pos) - 1, nt) + 1;
            if numel(candidate_idx) > 1
                dist_to_zero_detuning = min(abs(candidate_idx - 1), nt - abs(candidate_idx - 1));
                [~, tie_idx] = min(dist_to_zero_detuning);
                candidate_idx = candidate_idx(tie_idx);
            end
            center_idx = candidate_idx(1);
        end


        function spectral_store = reduce_weighted_spectral_store_outputs_local( ...
                a_fft_stored, spectral_weight_xyomega, spectral_fluence_density_scale, ...
                save_idx, store_spectral_intens, ...
                ix_axis0, iy_axis0, need_line_oa, ...
                beamcenter_sample_ok, ix_bc, iy_bc, need_line_bc, ...
                fund_beamcenter_sample_ok, ix_bc_fund, iy_bc_fund, need_line_bc_fund, ...
                need_max_xy, need_core_spectrum, ...
                delta_x, delta_y, delta_t)
        % Reduce the spectral store products with the broadband in-medium
        % weight Re(n_lin(x,y,omega))/Re(n_sell(omega_fund)).

            nt = size(a_fft_stored, 3);
            like_real = real(a_fft_stored(1));
            weight_xyomega = cast(spectral_weight_xyomega, 'like', like_real);
            weight_is_spectral_only = isequal(size(weight_xyomega), [1, 1, nt]);
            block_size = 64;
            spectral_store = struct( ...
                'line_oa', [], ...
                'line_bc', [], ...
                'line_bc_fund', [], ...
                'max_xy', [], ...
                'store_spectral_intens', store_spectral_intens, ...
                's_hz', []);
            if need_line_oa
                spectral_store.line_oa = nan(1, nt, 'like', like_real);
                if weight_is_spectral_only
                    oa_weight_omega = reshape(cast(weight_xyomega, 'like', like_real), 1, []);
                else
                    oa_weight_omega = reshape( ...
                        cast(weight_xyomega(ix_axis0, iy_axis0, :), 'like', like_real), 1, []);
                end
            end
            if need_line_bc
                spectral_store.line_bc = nan(1, nt, 'like', like_real);
                if beamcenter_sample_ok
                    if weight_is_spectral_only
                        bc_weight_omega = reshape(cast(weight_xyomega, 'like', like_real), 1, []);
                    else
                        bc_weight_omega = reshape( ...
                            cast(weight_xyomega(ix_bc, iy_bc, :), 'like', like_real), 1, []);
                    end
                else
                    bc_weight_omega = nan(1, nt, 'like', like_real);
                end
            end
            if need_line_bc_fund
                spectral_store.line_bc_fund = nan(1, nt, 'like', like_real);
                if fund_beamcenter_sample_ok
                    if weight_is_spectral_only
                        bc_fund_weight_omega = reshape(cast(weight_xyomega, 'like', like_real), 1, []);
                    else
                        bc_fund_weight_omega = reshape( ...
                            cast(weight_xyomega(ix_bc_fund, iy_bc_fund, :), 'like', like_real), 1, []);
                    end
                else
                    bc_fund_weight_omega = nan(1, nt, 'like', like_real);
                end
            end
            if need_max_xy
                spectral_store.max_xy = nan(1, nt, 'like', like_real);
            end
            if need_core_spectrum
                spectral_store.s_hz = nan(1, nt, 'like', like_real);
            end
            need_store_weighted_cube = ~isempty(spectral_store.store_spectral_intens);
            need_weighted_xy_reduce = need_max_xy || need_store_weighted_cube || ...
                (need_core_spectrum && ~weight_is_spectral_only);
            for start_idx = 1:block_size:nt
                idx = start_idx:min(start_idx + block_size - 1, nt);
                a_fft_block = a_fft_stored(:, :, idx);
                if need_line_oa
                    oa_mag2 = real(a_fft_block(ix_axis0, iy_axis0, :) .* ...
                        conj(a_fft_block(ix_axis0, iy_axis0, :)));
                    spectral_store.line_oa(idx) = oa_weight_omega(idx) .* ...
                        reshape(oa_mag2, 1, []);
                end
                if need_line_bc && beamcenter_sample_ok
                    bc_mag2 = real(a_fft_block(ix_bc, iy_bc, :) .* ...
                        conj(a_fft_block(ix_bc, iy_bc, :)));
                    spectral_store.line_bc(idx) = bc_weight_omega(idx) .* ...
                        reshape(bc_mag2, 1, []);
                end
                if need_line_bc_fund && fund_beamcenter_sample_ok
                    bc_fund_mag2 = real(a_fft_block(ix_bc_fund, iy_bc_fund, :) .* ...
                        conj(a_fft_block(ix_bc_fund, iy_bc_fund, :)));
                    spectral_store.line_bc_fund(idx) = ...
                        bc_fund_weight_omega(idx) .* reshape(bc_fund_mag2, 1, []);
                end
                if need_store_weighted_cube
                    mag2_block = real(a_fft_block .* conj(a_fft_block));
                    if weight_is_spectral_only
                        weight_block = cast(reshape(weight_xyomega(1, 1, idx), 1, 1, []), ...
                            'like', like_real);
                    else
                        weight_block = weight_xyomega(:, :, idx);
                    end
                    weighted_block = mag2_block .* weight_block;
                    if need_max_xy
                        spectral_store.max_xy(idx) = reshape(max(max(weighted_block, [], 1), [], 2), 1, []);
                    end
                    spectral_store.store_spectral_intens(:, :, idx, save_idx) = ...
                        spectral_fluence_density_scale .* weighted_block;
                    if need_core_spectrum
                        if weight_is_spectral_only
                            weight_row = reshape(weight_xyomega(1, 1, idx), 1, []);
                            mag2_sum_xy = reshape(sum(sum(mag2_block, 2), 1), 1, []);
                            spectral_store.s_hz(idx) = ...
                                delta_x * delta_y * mag2_sum_xy .* weight_row .* (delta_t^2);
                        else
                            spectral_store.s_hz(idx) = reshape( ...
                                delta_x * delta_y * sum(sum(weighted_block, 2), 1) .* (delta_t^2), 1, []);
                        end
                    end
                elseif need_max_xy || need_core_spectrum
                    for idx_local = 1:numel(idx)
                        a_fft_slice = a_fft_block(:, :, idx_local);
                        mag2_slice = real(a_fft_slice .* conj(a_fft_slice));
                        if weight_is_spectral_only
                            spectral_weight_local = double(real(weight_xyomega(1, 1, idx(idx_local))));
                            if need_max_xy
                                spectral_store.max_xy(idx(idx_local)) = ...
                                    spectral_weight_local * max(mag2_slice(:));
                            end
                            if need_core_spectrum
                                spectral_store.s_hz(idx(idx_local)) = ...
                                    delta_x * delta_y * sum(mag2_slice(:)) * ...
                                    spectral_weight_local * (delta_t^2);
                            end
                        else
                            weighted_slice = mag2_slice .* weight_xyomega(:, :, idx(idx_local));
                            if need_max_xy
                                spectral_store.max_xy(idx(idx_local)) = max(weighted_slice(:));
                            end
                            if need_core_spectrum
                                spectral_store.s_hz(idx(idx_local)) = ...
                                    delta_x * delta_y * sum(weighted_slice(:)) * (delta_t^2);
                            end
                        end
                    end
                end
            end
            if need_core_spectrum
                spectral_store.s_hz = real(spectral_store.s_hz);
            end
        end


        function surrogate_store = reduce_spectral_plot_surrogate_slices_local( ...
                a_fft_stored, spectral_weight_xyomega, spectral_fluence_density_scale, ...
                iy_axis0, omega_window, omega_fund)
        % Build the smallest near-field spectral slices needed by standard plots.

            nt = size(a_fft_stored, 3);
            nx = size(a_fft_stored, 1);
            ny = size(a_fft_stored, 2);
            like_real = real(a_fft_stored(1));
            if ~(isscalar(iy_axis0) && isfinite(iy_axis0) && ...
                    (round(iy_axis0) == iy_axis0) && iy_axis0 >= 1 && iy_axis0 <= ny)
                error('CerUPP:InvalidSpectralSurrogateYIndex', ...
                    'iy_axis0 must be an integer y index in [1,%d]; got %g.', ny, iy_axis0);
            end
            omega_window = omega_window(:);
            if numel(omega_window) ~= nt
                error('CerUPP:SpectralSurrogateOmegaCountMismatch', ...
                    'omega_window must have %d samples for spectral plot surrogates; got %d.', ...
                    nt, numel(omega_window));
            end
            weight_xyomega = cast(spectral_weight_xyomega, 'like', like_real);
            weight_is_spectral_only = isequal(size(weight_xyomega), [1, 1, nt]);

            a_y0 = reshape(a_fft_stored(:, iy_axis0, :), nx, nt);
            mag2_y0 = real(a_y0 .* conj(a_y0));
            if weight_is_spectral_only
                y0_weight = reshape(weight_xyomega(1, 1, :), 1, nt);
                y0_xomega = mag2_y0 .* y0_weight;
            else
                y0_weight = reshape(weight_xyomega(:, iy_axis0, :), nx, nt);
                y0_xomega = mag2_y0 .* y0_weight;
            end

            [~, idx_fund] = min(abs(double(omega_window) - double(omega_fund)));
            a_fund = a_fft_stored(:, :, idx_fund);
            mag2_fund = real(a_fund .* conj(a_fund));
            if weight_is_spectral_only
                fund_weight = weight_xyomega(1, 1, idx_fund);
            else
                fund_weight = weight_xyomega(:, :, idx_fund);
            end
            surrogate_store = struct( ...
                'y0_xomega_final', spectral_fluence_density_scale .* y0_xomega, ...
                'fund_xy', spectral_fluence_density_scale .* (mag2_fund .* fund_weight));
        end


