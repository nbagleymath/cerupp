        function run_warn_state = emit_negative_drho_source_trace_warning_local( ...
                run_warn_state, trace_vals, trace_label, warning_key, warning_id, save_idx, z_now)
        % Warn once when a drho source diagnostic contains finite negative values beyond roundoff tolerance.

            if nargin < 1 || isempty(run_warn_state) || ~isstruct(run_warn_state)
                run_warn_state = struct();
            end
            if nargin < 2 || isempty(trace_vals)
                return;
            end
            finite_vals = double(real(trace_vals(:)));
            finite_vals = finite_vals(isfinite(finite_vals));
            if isempty(finite_vals)
                return;
            end
            max_abs_val = max(abs(finite_vals));
            if ~isfinite(max_abs_val)
                return;
            end
            neg_tol = max(1e-12 * max_abs_val, eps(max(1.0, max_abs_val)));
            min_val = min(finite_vals);
            if min_val < -neg_tol
                run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                    run_warn_state, 'propagation', ...
                    char(string(warning_key)), char(string(warning_id)), ...
                    ['%s drho(x,z) diagnostics contain finite negative source-rate samples ', ...
                     '(min=%.3e, tol=%.3e) at save_idx=%d, z=%.6e m. ', ...
                     'Keeping the signed peak summary instead of clipping to zero.'], ...
                    char(string(trace_label)), double(min_val), double(neg_tol), ...
                    double(save_idx), double(z_now));
            end
        end

        function [peak_ratio, run_warn_state] = compute_peak_drho_over_rho_nt_local( ...
                run_warn_state, warning_phase, trace_vals, trace_label, warning_key, warning_id, ...
                invalid_rho_key, invalid_rho_id, rho_nt, save_idx, z_now)
        % Reduce one stored drho(x,z) trace to its peak-over-rho_nt scalar with the live warning policy.

            peak_ratio = NaN;
            if nargin < 1 || isempty(run_warn_state) || ~isstruct(run_warn_state)
                run_warn_state = struct();
            end
            if isempty(trace_vals)
                return;
            end
            run_warn_state = storage_support.emit_negative_drho_source_trace_warning_local( ...
                run_warn_state, trace_vals, trace_label, warning_key, warning_id, save_idx, z_now);
            if ~(isscalar(rho_nt) && isfinite(rho_nt) && (rho_nt > 0))
                run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                    run_warn_state, char(string(warning_phase)), ...
                    char(string(invalid_rho_key)), char(string(invalid_rho_id)), ...
                    ['rho_nt is invalid (value=%g). Derived %s/rho_nt diagnostics ', ...
                     'remain NaN.'], ...
                    rho_nt, char(string(trace_label)));
                return;
            end
            peak_val = max(trace_vals(:), [], 'omitnan');
            if isfinite(peak_val)
                peak_ratio = peak_val / double(rho_nt);
            end
        end


        function band_mask_stack = merge_store_band_mask_stacks_local(base_mask_stack, extra_mask_stack)
        % Compose the one-off final-store band mask stack without persisting duplicated base masks.

            if isempty(base_mask_stack)
                band_mask_stack = extra_mask_stack;
            elseif isempty(extra_mask_stack)
                band_mask_stack = base_mask_stack;
            else
                band_mask_stack = cat(4, base_mask_stack, extra_mask_stack);
            end
        end


        function [f_nearfield, fluence_summary, ix_bc, iy_bc] = resolve_weighted_fluence_store_state_local( ...
                need_beamcenter_summary, need_total_fluence_store, f_nearfield, ...
                n_ratio_diag_xy, t, weighted_intensity_rows, ...
                x, y, a_s_flat, num_x_pts, num_y_pts)
        % Resolve the shared weighted-fluence state for this stored plane.
        % This owner keeps the row-vs-map choice lazy: branches that only
        % need the beam-center summary avoid materializing the full
        % near-field fluence map, while map-owning branches still receive
        % the same centroid/peak summary from the already-built map.

            ix_bc = NaN;
            iy_bc = NaN;
            summary_from_fluence_map_ready = false;
            fluence_summary = struct( ...
                'ix_beamcenter', NaN, ...
                'iy_beamcenter', NaN, ...
                'x_beamcenter', NaN, ...
                'y_beamcenter', NaN, ...
                'method_code', NaN);
            if ~logical(need_beamcenter_summary)
                return;
            end
            if isempty(f_nearfield)
                if isempty(weighted_intensity_rows) && ~isempty(a_s_flat)
                    weighted_intensity_rows = storage_support.build_weighted_timedomain_rows_local( ...
                        a_s_flat, n_ratio_diag_xy);
                end
                if logical(need_total_fluence_store)
                    if isempty(weighted_intensity_rows)
                        f_nearfield = [];
                    else
                        weighted_fluence_rows = trapz(t, weighted_intensity_rows, 2);
                        f_nearfield = reshape(weighted_fluence_rows, num_x_pts, num_y_pts); %[J/m^2]
                    end
                    if ~isempty(f_nearfield)
                        fluence_summary = storage_support.summarize_fluence_map(x, y, f_nearfield);
                        summary_from_fluence_map_ready = true;
                    end
                else
                    if isempty(weighted_intensity_rows)
                        weighted_fluence_rows = [];
                    else
                        weighted_fluence_rows = trapz(t, weighted_intensity_rows, 2);
                    end
                    if ~isempty(weighted_fluence_rows)
                        fluence_summary = storage_support.summarize_fluence_map( ...
                            x, y, reshape(weighted_fluence_rows, num_x_pts, num_y_pts));
                        ix_bc = fluence_summary.ix_beamcenter;
                        iy_bc = fluence_summary.iy_beamcenter;
                    end
                    return;
                end
            end
            if ~summary_from_fluence_map_ready && ~isempty(f_nearfield)
                fluence_summary = storage_support.summarize_fluence_map(x, y, f_nearfield);
            end
            ix_bc = fluence_summary.ix_beamcenter;
            iy_bc = fluence_summary.iy_beamcenter;
        end

        function weighted_intensity_rows = build_weighted_timedomain_rows_local(a_s_flat, n_ratio_diag_xy)
        % Build weighted [Nx*Ny,Nt] time-domain intensity rows without materializing a weighted [Nx,Ny,Nt] cube.

            if isempty(a_s_flat)
                weighted_intensity_rows = [];
                return;
            end
            weight_rows = cast(n_ratio_diag_xy(:), 'like', real(a_s_flat(1)));
            weighted_intensity_rows = weight_rows .* real(a_s_flat .* conj(a_s_flat));
        end

        function xy_weight_rows = build_xy_trapz_weight_rows_local(x, y, like_val)
        % Build flattened trapezoidal x-y quadrature weights for rowwise power reductions.

            wx = storage_support.build_trapz_vector_weights_local(x);
            wy = storage_support.build_trapz_vector_weights_local(y);
            xy_weight_rows = reshape(wx * wy.', [], 1);
            xy_weight_rows = cast(xy_weight_rows, 'like', like_val);
        end

        function coord_weights = build_trapz_vector_weights_local(coord_vec)
        % Return one-dimensional trapezoidal integration weights for a coordinate vector.

            coord_vec = double(coord_vec(:));
            n_coord = numel(coord_vec);
            coord_weights = zeros(n_coord, 1);
            if n_coord < 2
                return;
            end
            dcoord = diff(coord_vec);
            coord_weights(1) = dcoord(1) / 2;
            coord_weights(end) = dcoord(end) / 2;
            if n_coord > 2
                coord_weights(2:end-1) = 0.5 .* (dcoord(1:end-1) + dcoord(2:end));
            end
        end

        function shared_store = compute_store_shared_reductions_local(cfg)
        % Build the shared stored-plane reductions that several later Section 5C
        % writes reuse: reusable |A_SSF|^2 terms from stored fft_t(A_S),
        % total fluence, beam center,
        % and the visible/fundamental/RGB band summaries.
        % Custom user-implemented diagnostics can be added in cerupp.m; this
        % helper only prepares the built-in shared reductions once from the
        % current-plane arrays and the small set of booleans they need.

            if nargin < 1 || ~isstruct(cfg)
                error('CerUPP:InvalidStoreSharedReductionCfg', ...
                    'compute_store_shared_reductions_local requires a struct cfg.');
            end
            store_plan = struct_utils.req_struct_field( ...
                cfg, 'store_plan', 'cfg.store_plan');
            plane_state = struct_utils.req_struct_field( ...
                cfg, 'plane_state', 'cfg.plane_state');
            grid_state = struct_utils.req_struct_field( ...
                cfg, 'grid_state', 'cfg.grid_state');

            store_plan_families = struct_utils.req_struct_field( ...
                store_plan.diag, 'families', 'cfg.store_plan.diag');
            spectral_family = struct_utils.req_struct_field( ...
                store_plan_families, 'spectra', 'cfg.store_diag_plan.families');
            fluence_family = struct_utils.req_struct_field( ...
                store_plan_families, 'fluence', 'cfg.store_diag_plan.families');
            beamcenter_family = struct_utils.req_struct_field( ...
                store_plan_families, 'beamcenter', 'cfg.store_diag_plan.families');

            need_rgb_final_plots_this_store = logical(store_plan.need_rgb_final_plots_this_store);
            need_band_center_weight_stack = ~isempty(store_plan.band.base_mask_stack) || ...
                (need_rgb_final_plots_this_store && ~isempty(store_plan.band.rgb_extra_mask_stack));
            need_parseval_band_power = logical( ...
                fluence_family.use_parseval_effective && ...
                (fluence_family.need_total_map || ...
                 beamcenter_family.need_summary || ...
                 fluence_family.need_visible_map || ...
                 fluence_family.need_fund_map || ...
                 store_plan.effective_store_spectral_fluence_flag || ...
                 need_rgb_final_plots_this_store));
            need_a_ssf_mag2 = logical( ...
                need_parseval_band_power || ...
                (spectral_family.need_full_cube && store_plan.have_store_spectral_intens_cube));

            a_ssf_mag2 = [];
            if need_a_ssf_mag2
                a_ssf_mag2 = real(plane_state.a_fft_stored .* conj(plane_state.a_fft_stored));   % |A_SSF|^2 (unscaled mixed-space fft_t(A_S))
            end

            spectral_weight_xyomega = [];
            need_weighted_spectral_density_store = logical( ...
                spectral_family.need_reduced_histories || ...
                (spectral_family.need_full_cube && store_plan.have_store_spectral_intens_cube) || ...
                struct_utils.opt_struct_field(spectral_family, 'need_plot_surrogate_slices', false) || ...
                spectral_family.need_core_spectrum || ...
                need_band_center_weight_stack);
            if need_weighted_spectral_density_store
                if isempty(plane_state.a_fft_stored)
                    error('CerUPP:MissingStoredSpectralField', ...
                        ['Stored weighted spectral diagnostics require the current-plane ', ...
                         'A_SSF/fft_t(A_S) view, but a_fft_stored is empty.']);
                end
                fft_size = size(plane_state.a_fft_stored);
                lin_index_3d = grid_state.lin_index_3d;
                if ~isequal(size(lin_index_3d), fft_size) && ...
                        ~isequal(size(lin_index_3d), [1, 1, fft_size(3)])
                    error('CerUPP:InvalidSpectralWeightMapSize', ...
                        ['lin_index_3d must match |A_SSF|^2 or stay spectral-only [1 1 Nw] ', ...
                         'for stored spectral diagnostics. Got lin_index_3d size %s and |A_SSF|^2 size %s.'], ...
                        mat2str(size(lin_index_3d)), mat2str(fft_size));
                end
                spectral_weight_xyomega = real(lin_index_3d) ./ ...
                    cast(real(grid_state.n_sell_fund), 'like', real(plane_state.a_fft_stored(1)));
                propagation_support.assert_valid_diag_weight_map_local( ...
                    spectral_weight_xyomega, 'spectral_weight_xyomega', ...
                    'stored spectral diagnostic weight build');
                spectral_weight_xyomega = cast(spectral_weight_xyomega, 'like', real(plane_state.a_fft_stored(1)));
            end

            weighted_intensity_rows = [];
            if store_plan.diag.need_weighted_timedomain_row_store
                weighted_intensity_rows = storage_support.build_weighted_timedomain_rows_local( ...
                    plane_state.a_s_flat, grid_state.n_ratio_diag_xy);
            end

            f_nearfield = [];
            if fluence_family.need_total_map
                if store_plan.diag.fluence_use_parseval_effective
                    f_nearfield = band_diagnostics_utils.build_weighted_fluence_from_masked_spectrum( ...
                        plane_state.a_fft_stored, grid_state.n_ratio_diag_xy, grid_state.t, grid_state.delta_t, ...
                        grid_state.fluence_use_parseval, [], ...
                        grid_state.time_grid_supports_parseval_fluence, a_ssf_mag2, []); %[J/m^2]
                else
                    if isempty(weighted_intensity_rows)
                        weighted_intensity_rows = storage_support.build_weighted_timedomain_rows_local( ...
                            plane_state.a_s_flat, grid_state.n_ratio_diag_xy);
                    end
                    weighted_fluence_rows = trapz(grid_state.t, weighted_intensity_rows, 2);
                    f_nearfield = reshape(weighted_fluence_rows, ...
                        grid_state.num_x_pts, grid_state.num_y_pts); %[J/m^2]
                end
            end

            [f_nearfield, fluence_summary, ix_bc, iy_bc] = ...
                storage_support.resolve_weighted_fluence_store_state_local( ...
                    beamcenter_family.need_summary, fluence_family.need_total_map, f_nearfield, ...
                    grid_state.n_ratio_diag_xy, grid_state.t, weighted_intensity_rows, ...
                    grid_state.x, grid_state.y, plane_state.a_s_flat, ...
                    grid_state.num_x_pts, grid_state.num_y_pts);

            band_store = storage_support.build_store_band_diagnostics_local( ...
                plane_state.a_fft_stored, store_plan.band, store_plan.diag, ...
                need_rgb_final_plots_this_store, ...
                grid_state.x, grid_state.y, ...
                spectral_weight_xyomega, grid_state.n_ratio_diag_xy, ...
                grid_state.t, ...
                grid_state.delta_t, grid_state.fluence_use_parseval, ...
                grid_state.ix_axis0, grid_state.iy_axis0, ix_bc, iy_bc, ...
                grid_state.time_grid_supports_parseval_fluence, a_ssf_mag2, ...
                grid_state.n, plane_state.diag_like_real);

            beamcenter_sample_ok = isscalar(ix_bc) && isscalar(iy_bc) && ...
                isfinite(ix_bc) && isfinite(iy_bc) && ...
                (ix_bc >= 1) && (ix_bc <= grid_state.num_x_pts) && ...
                (iy_bc >= 1) && (iy_bc <= grid_state.num_y_pts) && ...
                (ix_bc == round(ix_bc)) && (iy_bc == round(iy_bc));

            shared_store = struct( ...
                'a_ssf_mag2', a_ssf_mag2, ...
                'spectral_weight_xyomega', spectral_weight_xyomega, ...
                'weighted_intensity_rows', weighted_intensity_rows, ...
                'f_nearfield', f_nearfield, ...
                'fluence_summary', fluence_summary, ...
                'ix_bc', ix_bc, ...
                'iy_bc', iy_bc, ...
                'beamcenter_sample_ok', beamcenter_sample_ok, ...
                'band_store', band_store);
        end


        function band_store = build_store_band_diagnostics_local( ...
                a_fft_stored, store_band_plan, store_diag_plan, need_rgb_final_plots_this_store, ...
                x, y, spectral_weight_xyomega, n_ratio_diag_xy, t, delta_t, fluence_use_parseval, ...
                ix_axis0, iy_axis0, ix_bc, iy_bc, ...
                time_grid_supports_parseval_fluence, a_ssf_mag2, ...
                n, diag_like_real)
        % Reduce one stored spectral plane into the visible, fundamental, and RGB band products.
        % The caller stores the returned histories; this helper only builds
        % the current-plane reductions and the fundamental-band-owned center
        % sample used by the stored fundamental trace/diameter outputs.

            fundamental_band_support = struct_utils.req_struct_field( ...
                store_band_plan, 'fundamental_band_support', 'store_band_plan');
            fundamental_band_status = char(string(struct_utils.req_struct_field( ...
                fundamental_band_support, 'status', 'store_band_plan.fundamental_band_support')));
            fundamental_band_has_any_support = ~strcmpi(fundamental_band_status, 'none');
            band_store = struct( ...
                'f_nearfield_visible', [], ...
                'timedom_intensity_oa_vis', [], ...
                'timedom_intensity_bc_vis', [], ...
                'timedom_intensity_maxperp_vis', [], ...
                'f_fund_xy', [], ...
                'timedom_intensity_oa_fund', [], ...
                'timedom_intensity_bc_fund', [], ...
                'timedom_intensity_maxperp_fund', [], ...
                'red_fluence', [], ...
                'green_fluence', [], ...
                'blue_fluence', [], ...
                'fpeak_vis', NaN, ...
                'fpeak_fund', NaN, ...
                'ix_bc_vis', NaN, ...
                'iy_bc_vis', NaN, ...
                'x_bc_vis', NaN, ...
                'y_bc_vis', NaN, ...
                'method_code_vis', NaN, ...
                'vis_beamcenter_sample_ok', false, ...
                'ix_bc_fund', NaN, ...
                'iy_bc_fund', NaN, ...
                'x_bc_fund', NaN, ...
                'y_bc_fund', NaN, ...
                'method_code_fund', NaN, ...
                'fund_beamcenter_sample_ok', false);

            if logical(store_diag_plan.need_fund_trace_store) && ~fundamental_band_has_any_support
                band_store.timedom_intensity_oa_fund = nan(1, n, 'like', diag_like_real);
                band_store.timedom_intensity_bc_fund = nan(1, n, 'like', diag_like_real);
                band_store.timedom_intensity_maxperp_fund = nan(1, n, 'like', diag_like_real);
            end

            band_mask_stack_store = store_band_plan.base_mask_stack;
            band_requests_store = store_band_plan.base_requests;
            idx_red_band_store = store_band_plan.base_idx_red_band;
            idx_green_band_store = store_band_plan.base_idx_green_band;
            idx_blue_band_store = store_band_plan.base_idx_blue_band;
            if logical(need_rgb_final_plots_this_store) && ~isempty(store_band_plan.rgb_extra_mask_stack)
                band_mask_stack_store = storage_support.merge_store_band_mask_stacks_local( ...
                    store_band_plan.base_mask_stack, store_band_plan.rgb_extra_mask_stack);
                band_requests_store = [store_band_plan.base_requests, store_band_plan.rgb_extra_requests];
                idx_red_band_store = store_band_plan.final_idx_red_band;
                idx_green_band_store = store_band_plan.final_idx_green_band;
                idx_blue_band_store = store_band_plan.final_idx_blue_band;
            end
            if isempty(band_mask_stack_store)
                return;
            end
            band_weight_xy_stack = storage_support.build_store_band_weight_stack_local( ...
                a_fft_stored, band_mask_stack_store, ...
                spectral_weight_xyomega, n_ratio_diag_xy);

            [band_fluence_xy, band_td_oa, band_td_bc, band_td_maxperp] = ...
                filament_diagnostics_utils.build_multi_band_time_diagnostics( ...
                    a_fft_stored, band_mask_stack_store, ...
                    band_weight_xy_stack, t, delta_t, fluence_use_parseval, ...
                    ix_axis0, iy_axis0, ix_bc, iy_bc, band_requests_store, ...
                    time_grid_supports_parseval_fluence, a_ssf_mag2);

            band_output_specs = struct( ...
                'idx', {store_band_plan.idx_visible_band, store_band_plan.idx_fund_band}, ...
                'need_fluence', {logical(store_diag_plan.need_visible_fluence_store), logical(store_diag_plan.need_fund_fluence_store)}, ...
                'need_trace', {logical(store_diag_plan.need_visible_trace_store), logical(store_diag_plan.need_fund_trace_store)}, ...
                'fluence_field', {'f_nearfield_visible', 'f_fund_xy'}, ...
                'peak_field', {'fpeak_vis', 'fpeak_fund'}, ...
                'trace_fields', {{ ...
                    'timedom_intensity_oa_vis', 'timedom_intensity_bc_vis', 'timedom_intensity_maxperp_vis'}, { ...
                    'timedom_intensity_oa_fund', 'timedom_intensity_bc_fund', 'timedom_intensity_maxperp_fund'}}, ...
                'allow_missing_peak_nan', {false, ~fundamental_band_has_any_support});
            for spec_idx = 1:numel(band_output_specs)
                band_store = storage_support.populate_store_band_outputs_local( ...
                    band_store, band_output_specs(spec_idx), ...
                    band_fluence_xy, band_td_oa, band_td_bc, band_td_maxperp);
            end

            if logical(store_diag_plan.need_visible_trace_store)
                band_store.timedom_intensity_bc_vis = nan(1, n, 'like', diag_like_real);
            end
            if logical(store_diag_plan.need_fund_trace_store)
                band_store.timedom_intensity_bc_fund = nan(1, n, 'like', diag_like_real);
            end
            if store_band_plan.idx_visible_band > 0
                vis_surface = band_fluence_xy(:, :, store_band_plan.idx_visible_band);
                vis_beamcenter = storage_support.build_band_beamcenter_snapshot_local( ...
                    x, y, vis_surface, numel(x), numel(y));
                band_store.ix_bc_vis = vis_beamcenter.ix;
                band_store.iy_bc_vis = vis_beamcenter.iy;
                band_store.x_bc_vis = vis_beamcenter.x;
                band_store.y_bc_vis = vis_beamcenter.y;
