                        'prop_farfield_spectrum_nonfinite', ...
                        'CerUPP:FarFieldSpectrumNonFiniteSoft', ...
                        ['S_Hz has %d/%d non-finite samples at save_idx=%d; preserving NaN/Inf ', ...
