                        ~isempty(cfg.plasma_book_step.field_energy_drop_solver_timeint_core)
                    sum_plasma_field_loss_core = cfg.plasma_book_step.field_energy_drop_solver_timeint_core;
                elseif isstruct(cfg.plasma_book_step) && ...
                        isfield(cfg.plasma_book_step, 'field_energy_drop_solver_core') && ...
                        ~isempty(cfg.plasma_book_step.field_energy_drop_solver_core)
                    sum_plasma_field_loss_core = trapz(cfg.t, cfg.plasma_book_step.field_energy_drop_solver_core, 2);
                end
                if ~isempty(sum_plasma_field_loss_core)
                    [sum_plasma_field_loss, store_workspaces.diag_xy_scatter_ws] = propagation_support.scatter_core_vec_to_xy( ...
                        sum_plasma_field_loss_core, cfg.core_idx, cfg.num_x_pts, cfg.num_y_pts, ...
                        sum_plasma_field_loss_core, store_workspaces.diag_xy_scatter_ws);
                    sum_plasma_field_loss = cfg.n_ratio_diag_xy .* sum_plasma_field_loss;
                    diagnostic_store.store_plasma_field_d_e_dz(cfg.save_idx) = trapz( ...
                        cfg.x, trapz(cfg.y, sum_plasma_field_loss, 2), 1);
                end

                if cfg.output_dev_cfg.enable_drho_xz_diagnostics
                    [drho_ofi_xz, drho_aval_xz] = storage_support.build_drho_xz_plane_local( ...
                        cfg.plasma_book_step, cfg.drho_xz_diag_helper, cfg.num_x_pts, cfg.diag_like_real);
                end
            end

            if cfg.nl_absorption_flag
                if ~(isstruct(cfg.nla_book_step) && isfield(cfg.nla_book_step, 'loss_rate_applied_core') && ...
                        ~isempty(cfg.nla_book_step.loss_rate_applied_core))
                    error('CerUPP:DriverMissingNlaAppliedLedger', ...
                        ['Local NLA accounting requires nla_book_step.loss_rate_applied_core. ' ...
                         'The active step returned no applied NLA ledger.']);
                end
                loss_rate_applied_core = cfg.nla_book_step.loss_rate_applied_core;
                if isfield(cfg.nla_book_step, 'exact_valid_core') && ...
                        isequal(size(cfg.nla_book_step.exact_valid_core), size(loss_rate_applied_core))
                    exact_valid_core = logical(cfg.nla_book_step.exact_valid_core);
                    loss_rate_applied_core(~exact_valid_core) = NaN;
                else
                    exact_valid_core = [];
                end
                sum_nla_loss_core = trapz(cfg.t, loss_rate_applied_core, 2);
                if ~(isstruct(cfg.nla_book_step) && isfield(cfg.nla_book_step, 'i_pre_core') && ...
                        ~isempty(cfg.nla_book_step.i_pre_core))
                    error('CerUPP:DriverMissingPreNlaLedgerIntensity', ...
                        ['Local NLA accounting requires nla_book_step.i_pre_core. ' ...
                         'The active step returned no pre-NLA ledger intensity.']);
                end
                intens_pre_nla_core = cfg.nla_book_step.i_pre_core;
                j_mpa_core = propagation_support.extract_live_nla_diag_core_rows_local( ...
                    cfg.j_mpa, cfg.core_idx, cfg.n, 'j_mpa');
                if ~isempty(exact_valid_core) && isequal(size(j_mpa_core), size(exact_valid_core))
                    j_mpa_core(~exact_valid_core) = NaN;
                end
                sum_j_mpa_core = trapz(cfg.t, real(j_mpa_core) .* intens_pre_nla_core, 2);

                mpa_rhs_mag_core = propagation_support.extract_live_nla_diag_core_rows_local( ...
                    cfg.mpa_rhs_mag_step, cfg.core_idx, cfg.n, 'mpa_rhs_mag_step');
                if ~isempty(exact_valid_core) && isequal(size(mpa_rhs_mag_core), size(exact_valid_core))
                    mpa_rhs_mag_core(~exact_valid_core) = NaN;
                end
                sum_j_mpa_rhs_core = trapz(cfg.t, mpa_rhs_mag_core, 2);

                nla_store_core_rows = [sum_nla_loss_core, sum_j_mpa_core, sum_j_mpa_rhs_core];
                [nla_store_xy, store_workspaces.nla_store_xy_scatter_ws] = propagation_support.scatter_core_rows_to_full( ...
                    nla_store_core_rows, cfg.core_idx, cfg.num_x_pts, cfg.num_y_pts, 3, ...
                    nla_store_core_rows, store_workspaces.nla_store_xy_scatter_ws);
                sum_nla_loss = cfg.n_ratio_diag_xy .* nla_store_xy(:, :, 1);
                sum_j_mpa = cfg.n_ratio_diag_xy .* nla_store_xy(:, :, 2);
                sum_j_mpa_rhs_mag = nla_store_xy(:, :, 3);

                diagnostic_store.store_nla_loss_applied(:, :, cfg.save_idx) = sum_nla_loss;
                diagnostic_store.store_j_mpa(:, :, cfg.save_idx) = sum_j_mpa;
                diagnostic_store.store_j_mpa_rhs_mag(:, :, cfg.save_idx) = sum_j_mpa_rhs_mag;
                diagnostic_store.store_mpa_d_e_dz(cfg.save_idx) = trapz(cfg.x, trapz(cfg.y, sum_nla_loss, 2), 1);
                if isfield(cfg.nla_book_step, 'ofi_ledger_energy_density_core') && ...
                        isfield(cfg.nla_book_step, 'nla_applied_energy_density_core') && ...
                        ~isempty(cfg.nla_book_step.ofi_ledger_energy_density_core) && ...
                        ~isempty(cfg.nla_book_step.nla_applied_energy_density_core)
                    ledger_scalar_core_rows = [ ...
                        cfg.nla_book_step.nla_applied_energy_density_core(:), ...
                        cfg.nla_book_step.ofi_ledger_energy_density_core(:), ...
                        cfg.nla_book_step.nla_applied_energy_density_core(:) - ...
                            cfg.nla_book_step.ofi_ledger_energy_density_core(:)];
                    [ledger_scalar_xy, store_workspaces.nla_store_xy_scatter_ws] = ...
                        propagation_support.scatter_core_rows_to_full( ...
                        ledger_scalar_core_rows, cfg.core_idx, cfg.num_x_pts, cfg.num_y_pts, 3, ...
                        ledger_scalar_core_rows, store_workspaces.nla_store_xy_scatter_ws);
                    applied_d_e_dz = trapz(cfg.x, trapz(cfg.y, ledger_scalar_xy(:, :, 1), 2), 1);
                    ledger_d_e_dz = trapz(cfg.x, trapz(cfg.y, ledger_scalar_xy(:, :, 2), 2), 1);
                    mismatch_d_e_dz = trapz(cfg.x, trapz(cfg.y, ledger_scalar_xy(:, :, 3), 2), 1);
                    diagnostic_store.store_ofi_event_nla_d_e_dz(cfg.save_idx) = applied_d_e_dz;
                    diagnostic_store.store_ofi_event_d_e_dz(cfg.save_idx) = ledger_d_e_dz;
                    diagnostic_store.store_ofi_event_mismatch_d_e_dz(cfg.save_idx) = mismatch_d_e_dz;
                    ledger_floor = max(realmin(class(ledger_d_e_dz)), eps(class(ledger_d_e_dz)));
                    diagnostic_store.store_ofi_event_relative_mismatch(cfg.save_idx) = ...
                        mismatch_d_e_dz ./ max(abs(ledger_d_e_dz), ledger_floor);
                    diagnostic_store.store_ofi_event_invalid_count(cfg.save_idx) = ...
                        double(struct_utils.opt_struct_field( ...
                            cfg.nla_book_step, 'ofi_ledger_invalid_count', NaN));
                    diagnostic_store.store_ofi_event_negative_count(cfg.save_idx) = ...
                        double(struct_utils.opt_struct_field( ...
                            cfg.nla_book_step, 'ofi_ledger_negative_count', NaN));
                    diagnostic_store.store_ofi_event_cap_count(cfg.save_idx) = ...
                        double(struct_utils.opt_struct_field( ...
                            cfg.nla_book_step, 'ofi_ledger_cap_count', NaN));
                    diagnostic_store.store_ofi_event_clip_count(cfg.save_idx) = ...
                        double(struct_utils.opt_struct_field( ...
                            cfg.nla_book_step, 'ofi_ledger_clip_count', NaN));
                    diagnostic_store.store_ofi_event_repair_count(cfg.save_idx) = ...
                        double(struct_utils.opt_struct_field( ...
                            cfg.nla_book_step, 'ofi_ledger_repair_count', NaN));
                    diagnostic_store.store_ofi_event_intensity_deficit_count(cfg.save_idx) = ...
                        double(struct_utils.opt_struct_field( ...
                            cfg.nla_book_step, 'intensity_deficit_count', NaN));
                    diagnostic_store.store_ofi_event_max_local_deficit(cfg.save_idx) = ...
                        double(struct_utils.opt_struct_field( ...
                            cfg.nla_book_step, 'max_local_intensity_deficit', NaN));
                end
            end

            if cfg.perf_cfg.track_energy_flag && ~isempty(diagnostic_store.store_energy_tracked)
                diagnostic_store.store_energy_tracked(cfg.save_idx) = cfg.energy_val;
                if cfg.save_idx > 1
                    prev_store_energy = diagnostic_store.store_energy_tracked(cfg.save_idx - 1);
                    prev_store_z = storage_support.conditional_store_z_local( ...
                        struct_utils.opt_struct_field(cfg, 'store_z', diagnostic_store.store_z), ...
                        cfg.save_idx - 1);
                    curr_store_z = double(cfg.z_store_value);
                    dz_store_span = curr_store_z - prev_store_z;
                    delta_e_track = prev_store_energy - cfg.energy_val;
                    delta_e_nla = NaN;
                    if ~isempty(diagnostic_store.store_mpa_d_e_dz) && ...
                            cfg.save_idx <= numel(diagnostic_store.store_mpa_d_e_dz)
                        delta_e_nla = diagnostic_store.store_mpa_d_e_dz(cfg.save_idx) .* dz_store_span;
                    end
                    delta_e_plasma_solver = NaN;
                    if ~isempty(diagnostic_store.store_plasma_field_d_e_dz) && ...
                            cfg.save_idx <= numel(diagnostic_store.store_plasma_field_d_e_dz)
                        delta_e_plasma_solver = ...
                            diagnostic_store.store_plasma_field_d_e_dz(cfg.save_idx) .* dz_store_span;
                    end
                    delta_e_track_minus_nla = delta_e_track - delta_e_nla;
                    [run_warn_state, ~] = run_warn_state_utils.emit_info_with_phase( ...
                        run_warn_state, 'propagation', ...
                        sprintf('stored_span_energy_ledger_%d', cfg.save_idx), ...
                        ['Stored span energy ledger at save_idx=%d over (z_prev=%.6e m, ', ...
                         'z_curr=%.6e m, dz=%.6e m): DeltaE_track=%.6e J, ', ...
                         'DeltaE_NLA_diag=%.6e J, DeltaE_plasma_solver=%.6e J ', ...
                         '(separate diagnostic, different metric), DeltaE_track_minus_NLA=%.6e J.'], ...
                        cfg.save_idx, prev_store_z, curr_store_z, dz_store_span, ...
                        delta_e_track, delta_e_nla, delta_e_plasma_solver, ...
                        delta_e_track_minus_nla);
                end
            end

            if cfg.plasma_flag
                if ismatrix(cfg.rho)
                    max_rho_core = max(cfg.rho, [], 2);
                    rho_int_core = trapz(cfg.t, cfg.rho, 2);
                    rho_late_core = cfg.rho(:, end);
                    rho_diag_core_rows = [max_rho_core, rho_int_core, rho_late_core];
                    [rho_diag_full, store_workspaces.rho_diag_xy_scatter_ws] = propagation_support.scatter_core_rows_to_full( ...
                        rho_diag_core_rows, cfg.core_idx, cfg.num_x_pts, cfg.num_y_pts, 3, ...
                        rho_diag_core_rows, store_workspaces.rho_diag_xy_scatter_ws);
                    max_rho = rho_diag_full(:, :, 1);
                    rho_int = rho_diag_full(:, :, 2);
                    rho_late = rho_diag_full(:, :, 3);
                else
                    max_rho = max(cfg.rho, [], 3);
                    rho_int = trapz(cfg.t, cfg.rho, 3);
                    rho_late = cfg.rho(:, :, end);
                end
                diagnostic_store.store_max_rho(:, :, cfg.save_idx) = max_rho;
                diagnostic_store.store_rho_int(:, :, cfg.save_idx) = rho_int;
                diagnostic_store.store_rho_late(:, :, cfg.save_idx) = rho_late;
                diagnostic_store.store_max_rho_maxperp(cfg.save_idx) = ...
                    squeeze(max(max(max_rho, [], 1), [], 2));
                diagnostic_store.store_rho_int_maxperp(cfg.save_idx) = ...
                    squeeze(max(max(rho_int, [], 1), [], 2));

                have_ofi_aval_diag_storage = ...
                    ~isempty(diagnostic_store.store_peak_drho_over_rho_nt_ofi) || ...
                    ~isempty(diagnostic_store.store_peak_drho_over_rho_nt_aval) || ...
                    ~isempty(diagnostic_store.store_drho_ofi_xz) || ...
                    ~isempty(diagnostic_store.store_drho_aval_xz);
                if have_ofi_aval_diag_storage
                    try
                        z_now = storage_support.conditional_store_z_local( ...
                            struct_utils.opt_struct_field(cfg, 'store_z', diagnostic_store.store_z), ...
                            cfg.save_idx);
                        rho_nt_diag = struct_utils.opt_struct_field(cfg, 'rho_nt', NaN);
                        if ~isempty(diagnostic_store.store_peak_drho_over_rho_nt_ofi) && ...
                                cfg.save_idx >= 1 && ...
                                cfg.save_idx <= numel(diagnostic_store.store_peak_drho_over_rho_nt_ofi)
                            diagnostic_store.store_peak_drho_over_rho_nt_ofi(cfg.save_idx) = NaN;
                        end
                        if ~isempty(diagnostic_store.store_peak_drho_over_rho_nt_aval) && ...
                                cfg.save_idx >= 1 && ...
                                cfg.save_idx <= numel(diagnostic_store.store_peak_drho_over_rho_nt_aval)
                            diagnostic_store.store_peak_drho_over_rho_nt_aval(cfg.save_idx) = NaN;
                        end
                        if ~isempty(drho_ofi_xz)
                            diagnostic_store.store_drho_ofi_xz(:, cfg.save_idx) = ...
                                propagation_support.require_live_drho_xz_vector_local( ...
                                drho_ofi_xz, cfg.num_x_pts, 'drho_ofi_xz');
                            if ~isempty(diagnostic_store.store_peak_drho_over_rho_nt_ofi) && ...
                                    cfg.save_idx >= 1 && ...
                                    cfg.save_idx <= numel(diagnostic_store.store_peak_drho_over_rho_nt_ofi)
                                [diagnostic_store.store_peak_drho_over_rho_nt_ofi(cfg.save_idx), run_warn_state] = ...
                                    storage_support.compute_peak_drho_over_rho_nt_local( ...
                                    run_warn_state, 'propagation', diagnostic_store.store_drho_ofi_xz(:, cfg.save_idx), ...
                                    'OFI', 'drho_ofi_negative_source_trace', ...
                                    'CerUPP:NegativeDrhoOfiDiagnostic', ...
                                    'invalid_rho_nt_diag_store_ofi', ...
                                    'CerUPP:Diagnostics:InvalidRhoNtDiag', ...
                                    rho_nt_diag, cfg.save_idx, z_now);
                            end
                        end
                        if ~isempty(drho_aval_xz)
                            diagnostic_store.store_drho_aval_xz(:, cfg.save_idx) = ...
                                propagation_support.require_live_drho_xz_vector_local( ...
                                drho_aval_xz, cfg.num_x_pts, 'drho_aval_xz');
                            if ~isempty(diagnostic_store.store_peak_drho_over_rho_nt_aval) && ...
                                    cfg.save_idx >= 1 && ...
                                    cfg.save_idx <= numel(diagnostic_store.store_peak_drho_over_rho_nt_aval)
                                [diagnostic_store.store_peak_drho_over_rho_nt_aval(cfg.save_idx), run_warn_state] = ...
                                    storage_support.compute_peak_drho_over_rho_nt_local( ...
                                    run_warn_state, 'propagation', diagnostic_store.store_drho_aval_xz(:, cfg.save_idx), ...
                                    'avalanche', 'drho_aval_negative_source_trace', ...
                                    'CerUPP:NegativeDrhoAvalancheDiagnostic', ...
                                    'invalid_rho_nt_diag_store_aval', ...
                                    'CerUPP:Diagnostics:InvalidRhoNtDiag', ...
                                    rho_nt_diag, cfg.save_idx, z_now);
                            end
                        end
                    catch me_ofi
                        [diagnostic_store.store_drho_ofi_xz, diagnostic_store.store_drho_aval_xz, ...
                            diagnostic_store.store_peak_drho_over_rho_nt_ofi, ...
                            diagnostic_store.store_peak_drho_over_rho_nt_aval] = ...
                            storage_support.clear_ofi_aval_diag_plane_local( ...
                            diagnostic_store.store_drho_ofi_xz, diagnostic_store.store_drho_aval_xz, ...
                            diagnostic_store.store_peak_drho_over_rho_nt_ofi, ...
                            diagnostic_store.store_peak_drho_over_rho_nt_aval, cfg.save_idx);
                        if ~isempty(store_ofi_aval_diag_failed)
                            store_ofi_aval_diag_failed(cfg.save_idx) = true;
                        end
                        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                            run_warn_state, 'propagation', ...
                            'ofi_avalanche_storage_failed', ...
                            'CerUPP:OFIAvalancheStorageFailed', ...
                            'OFI/avalanche storage failed at save_idx=%d: %s', ...
                            cfg.save_idx, me_ofi.message);
                    end
                end
            end

            if cfg.keldysh_effective_nla_available_flag
                if ~isempty(cfg.sigmaK_eff_keldysh_step)
                    sigma_pair = plasma_setup_support.unpack_keldysh_effective_diag_summary_local( ...
                        cfg.sigmaK_eff_keldysh_step, 'sigmaK_eff_keldysh_step');
                    diagnostic_store.store_sigma_k_eff_keldysh_oa(cfg.save_idx) = sigma_pair(1);
                    diagnostic_store.store_sigma_k_eff_keldysh_maxperp(cfg.save_idx) = sigma_pair(2);
                end
                if ~isempty(cfg.beta_eff_full_keldysh_step)
                    beta_pair = plasma_setup_support.unpack_keldysh_effective_diag_summary_local( ...
                        cfg.beta_eff_full_keldysh_step, 'beta_eff_full_keldysh_step');
                    diagnostic_store.store_beta_eff_full_keldysh_oa(cfg.save_idx) = beta_pair(1);
                    diagnostic_store.store_beta_eff_full_keldysh_maxperp(cfg.save_idx) = beta_pair(2);
                end
                if ~isempty(cfg.beta_eff_applied_keldysh_step)
                    beta_applied_pair = plasma_setup_support.unpack_keldysh_effective_diag_summary_local( ...
                        cfg.beta_eff_applied_keldysh_step, 'beta_eff_applied_keldysh_step');
                    diagnostic_store.store_beta_eff_applied_keldysh_oa(cfg.save_idx) = beta_applied_pair(1);
                    diagnostic_store.store_beta_eff_applied_keldysh_maxperp(cfg.save_idx) = beta_applied_pair(2);
                end
                if cfg.need_keldysh_effective_nla_raw_history_flag && ...
                        ~isempty(cfg.keldysh_diag_i_core_step) && ...
                        ~isempty(diagnostic_store.store_keldysh_diag_i_core)
                    stored_keldysh_core_idx = struct_utils.opt_struct_field( ...
                        diagnostic_store, 'store_keldysh_diag_core_idx', cfg.core_idx(:));
                    stored_keldysh_core_idx = stored_keldysh_core_idx(:);
                    current_core_idx = cfg.core_idx(:);
                    [current_rows_found, current_rows_in_store] = ismember( ...
                        current_core_idx, stored_keldysh_core_idx);
                    if ~all(current_rows_found)
                        error('CerUPP:StoredKeldyshDiagCoreIndexMismatch', ...
                            ['The current core_idx rows are not all present in the stored ', ...
                             'raw Keldysh core-history axis at save_idx=%d.'], ...
                            cfg.save_idx);
                    end
                    if ~ismatrix(cfg.keldysh_diag_i_core_step) || ...
                            any(size(cfg.keldysh_diag_i_core_step) ~= [numel(current_core_idx), cfg.n])
                        error('CerUPP:InvalidStoredKeldyshDiagIntensityCoreShape', ...
                            ['keldysh_diag_i_core_step must have size %s for the current core_idx rows; ', ...
                             'got %s.'], ...
                            mat2str([numel(current_core_idx), cfg.n]), ...
                            mat2str(size(cfg.keldysh_diag_i_core_step)));
                    end
                    if size(diagnostic_store.store_keldysh_diag_i_core, 1) ~= numel(stored_keldysh_core_idx) || ...
                            size(diagnostic_store.store_keldysh_diag_i_core, 2) ~= cfg.n
                        error('CerUPP:StoredKeldyshDiagIntensityStoreShape', ...
                            ['store_keldysh_diag_i_core must have size [%d %d Ns] for the stored ', ...
                             'union core-index axis; got %s.'], ...
                            numel(stored_keldysh_core_idx), cfg.n, ...
                            mat2str(size(diagnostic_store.store_keldysh_diag_i_core)));
                    end
                    diagnostic_store.store_keldysh_diag_i_core(current_rows_in_store, :, cfg.save_idx) = ...
                        cfg.keldysh_diag_i_core_step;
                end
                if cfg.need_keldysh_effective_nla_raw_history_flag && ...
                        ~isempty(cfg.keldysh_diag_rho_core_step) && ...
                        ~isempty(diagnostic_store.store_keldysh_diag_rho_core)
                    stored_keldysh_core_idx = struct_utils.opt_struct_field( ...
                        diagnostic_store, 'store_keldysh_diag_core_idx', cfg.core_idx(:));
                    stored_keldysh_core_idx = stored_keldysh_core_idx(:);
                    current_core_idx = cfg.core_idx(:);
                    [current_rows_found, current_rows_in_store] = ismember( ...
                        current_core_idx, stored_keldysh_core_idx);
                    if ~all(current_rows_found)
                        error('CerUPP:StoredKeldyshDiagCoreIndexMismatch', ...
                            ['The current core_idx rows are not all present in the stored ', ...
                             'raw Keldysh core-history axis at save_idx=%d.'], ...
                            cfg.save_idx);
                    end
                    if ~ismatrix(cfg.keldysh_diag_rho_core_step) || ...
                            any(size(cfg.keldysh_diag_rho_core_step) ~= [numel(current_core_idx), cfg.n])
                        error('CerUPP:InvalidStoredKeldyshDiagRhoCoreShape', ...
                            ['keldysh_diag_rho_core_step must have size %s for the current core_idx rows; ', ...
                             'got %s.'], ...
                            mat2str([numel(current_core_idx), cfg.n]), ...
                            mat2str(size(cfg.keldysh_diag_rho_core_step)));
                    end
                    if size(diagnostic_store.store_keldysh_diag_rho_core, 1) ~= numel(stored_keldysh_core_idx) || ...
                            size(diagnostic_store.store_keldysh_diag_rho_core, 2) ~= cfg.n
                        error('CerUPP:StoredKeldyshDiagRhoStoreShape', ...
                            ['store_keldysh_diag_rho_core must have size [%d %d Ns] for the stored ', ...
                             'union core-index axis; got %s.'], ...
                            numel(stored_keldysh_core_idx), cfg.n, ...
                            mat2str(size(diagnostic_store.store_keldysh_diag_rho_core)));
                    end
                    diagnostic_store.store_keldysh_diag_rho_core(current_rows_in_store, :, cfg.save_idx) = ...
                        cfg.keldysh_diag_rho_core_step;
                end
            end
        end


        function plane_views = resolve_store_current_plane_field_views_local(cfg)
        % Normalize the current stored-plane field views once before the
        % family writers consume them.

            if isfield(cfg, 'diag_like_real') && ~isempty(cfg.diag_like_real)
                diag_like_real = real(cfg.diag_like_real(1));
            elseif ~isempty(cfg.A_S)
                diag_like_real = real(cfg.A_S(1));
            else
                diag_like_real = 0;
            end

            a_s_full = cfg.A_S;
            if ndims(a_s_full) == 3
                if size(a_s_full, 1) ~= cfg.num_x_pts || ...
                        size(a_s_full, 2) ~= cfg.num_y_pts || ...
                        size(a_s_full, 3) ~= cfg.n
                    error('CerUPP:StoreFieldShapeMismatch', ...
                        ['3-D A_S must have size [%d %d %d] for one stored plane; ', ...
                         'got %s.'], ...
                        cfg.num_x_pts, cfg.num_y_pts, cfg.n, mat2str(size(a_s_full)));
                end
                a_s_flat = reshape(a_s_full, cfg.num_x_pts * cfg.num_y_pts, cfg.n);
            elseif ismatrix(a_s_full)
                if size(a_s_full, 1) ~= (cfg.num_x_pts * cfg.num_y_pts) || ...
                        size(a_s_full, 2) ~= cfg.n
                    error('CerUPP:StoreFieldFlatShapeMismatch', ...
                        ['2-D flattened A_S must have size [%d %d] for one stored plane; ', ...
                         'got %s.'], ...
                        cfg.num_x_pts * cfg.num_y_pts, cfg.n, mat2str(size(a_s_full)));
                end
                a_s_flat = a_s_full;
                a_s_full = reshape(a_s_flat, cfg.num_x_pts, cfg.num_y_pts, cfg.n);
            else
                error('CerUPP:StoreFieldInvalidShape', ...
                    'A_S must be either one 3-D [Nx Ny Nt] plane or one 2-D flattened [Nx*Ny Nt] stack.');
            end

            need_intens_s = cfg.store_diag_plan.need_intens_s_store || ...
                cfg.phase_diagnostic_flag;
            intens_s = [];
            if need_intens_s
                intens_s_precomputed = struct_utils.opt_struct_field(cfg, 'intens_s_precomputed', []);
                if isnumeric(intens_s_precomputed) && isreal(intens_s_precomputed) && ...
                        isequal(size(intens_s_precomputed), size(a_s_full)) && ...
                        strcmp(class(intens_s_precomputed), class(diag_like_real))
                    intens_s = intens_s_precomputed;
                else
                    intens_s = real(a_s_full .* conj(a_s_full)); %[W/m^2], propagated solver intensity |A_S|^2
                end
            end

            a_fft_stored = [];
            if cfg.store_diag_plan.need_fft_band_products
                if ~isempty(cfg.A_SSF)
                    a_fft_stored = cfg.A_SSF;
                else
                    a_fft_stored = fft(a_s_full, [], 3);
                end
            end

            plane_views = struct( ...
                'diag_like_real', diag_like_real, ...
                'a_s_full', a_s_full, ...
                'a_s_flat', a_s_flat, ...
                'intens_s', intens_s, ...
                'a_fft_stored', a_fft_stored, ...
                'need_rgb_final_plots_this_store', logical( ...
                    cfg.store_diag_plan.need_rgb_final_plots && ...
                    (cfg.curr_z_step == cfg.num_zsteps)));
        end

        function [k0n2_oa, k0n2_bc, k0n2_maxperp_kerr] = ...
                build_b_integral_k0n2_samples_local(cfg, shared)
        % Sample the current stored-plane Kerr scale at the same points used by the B-integral traces.

            diag_like_real = real(cfg.diag_like_real(1));
            zero_scale = cast(0, 'like', diag_like_real);
            nan_scale = cast(NaN, 'like', diag_like_real);
            k0n2_oa = zero_scale;
            k0n2_bc = nan_scale;
            k0n2_maxperp_kerr = zero_scale;

            kerr_enabled = struct_utils.opt_struct_field(cfg, 'kerr_enabled_cached', []);
            kerr_n2_xy = struct_utils.opt_struct_field(cfg, 'kerr_n2_xy_cached', []);
            if isempty(kerr_enabled) || isempty(kerr_n2_xy)
                kerr_payload = propagation_support.build_kerr_step_payload_local( ...
                    cfg.nl_index_3d, cfg.omega_window, cfg.omega_fund, ...
                    cfg.n2_kerr_disable_tol, [], true, ...
                    cfg.num_x_pts, cfg.num_y_pts, cfg.core_idx);
                kerr_enabled = kerr_payload.kerr_enabled;
                kerr_n2_xy = kerr_payload.kerr_n2_xy;
            end
            if ~logical(kerr_enabled)
                if logical(shared.beamcenter_sample_ok)
                    k0n2_bc = zero_scale;
                end
                return;
            end

            kerr_n2_xy = real(kerr_n2_xy);
            kerr_n2_flat = reshape(kerr_n2_xy, cfg.num_x_pts * cfg.num_y_pts, 1);
            k0_scale = double(real(cfg.k0_vac));
            k0n2_oa = cast(k0_scale * double(kerr_n2_xy(cfg.ix_axis0, cfg.iy_axis0)), ...
                'like', diag_like_real);
            if logical(shared.beamcenter_sample_ok)
                k0n2_bc = cast(k0_scale * double(kerr_n2_xy(shared.ix_bc, shared.iy_bc)), ...
                    'like', diag_like_real);
            end
            if ~isempty(cfg.core_idx)
                kerr_core_max = max(double(kerr_n2_flat(cfg.core_idx)), [], 'omitnan');
                if isfinite(kerr_core_max)
                    k0n2_maxperp_kerr = cast(k0_scale * kerr_core_max, ...
                        'like', diag_like_real);
                end
            end
        end


