classdef storage_support
% Stored-plane reductions and output-side accounting helpers.
% Used by cerupp.m during Section 5C and by postprocessing rebuild helpers.

    methods (Static)
        function csv_name_out = append_run_id_to_csv_name_local(csv_name_in, run_id)
        % Append a stable run identifier to CSV filenames to prevent cross-run mixing.

            if nargin < 1 || isempty(csv_name_in)
                csv_name_in = 'unnamed.csv';
            end
            if nargin < 2 || isempty(run_id)
                run_id = 'default';
            end

            if isstring(csv_name_in) && isscalar(csv_name_in)
                csv_name_in = char(csv_name_in);
            end
            if isstring(run_id) && isscalar(run_id)
                run_id = char(run_id);
            end
            csv_name_in = strtrim(csv_name_in);
            run_id = strtrim(run_id);
            run_id = regexprep(run_id, '[^A-Za-z0-9_-]', '_');
            if isempty(run_id)
                run_id = 'default';
            end

            [name_dir, name_base, name_ext] = fileparts(csv_name_in);
            if isempty(name_ext)
                name_ext = '.csv';
            end
            already_tagged = ~isempty(regexp(name_base, ['_run_' regexptranslate('escape', run_id) '$'], 'once'));
            if already_tagged
                csv_name_out = fullfile(name_dir, [name_base name_ext]);
            else
                csv_name_out = fullfile(name_dir, sprintf('%s_run_%s%s', name_base, run_id, name_ext));
            end
        end


        function [store_drho_ofi_xz, store_drho_aval_xz, ...
                store_peak_drho_over_rho_nt_ofi, ...
                store_peak_drho_over_rho_nt_aval] = clear_ofi_aval_diag_plane_local( ...
                store_drho_ofi_xz, store_drho_aval_xz, ...
                store_peak_drho_over_rho_nt_ofi, ...
                store_peak_drho_over_rho_nt_aval, save_idx)
        % Clear one stored OFI/avalanche diagnostic plane after a storage failure.

            if ~isempty(store_drho_ofi_xz) && (save_idx >= 1) && (save_idx <= size(store_drho_ofi_xz, 2))
                store_drho_ofi_xz(:,save_idx) = NaN;
            end
            if ~isempty(store_drho_aval_xz) && (save_idx >= 1) && (save_idx <= size(store_drho_aval_xz, 2))
                store_drho_aval_xz(:,save_idx) = NaN;
            end
            if ~isempty(store_peak_drho_over_rho_nt_ofi) && ...
                    (save_idx >= 1) && (save_idx <= numel(store_peak_drho_over_rho_nt_ofi))
                store_peak_drho_over_rho_nt_ofi(save_idx) = NaN;
            end
            if ~isempty(store_peak_drho_over_rho_nt_aval) && ...
                    (save_idx >= 1) && (save_idx <= numel(store_peak_drho_over_rho_nt_aval))
                store_peak_drho_over_rho_nt_aval(save_idx) = NaN;
            end
        end


        function z_now = conditional_store_z_local(store_z, idx)
        % Read one stored z sample when available; otherwise return NaN for warning text.

            z_now = NaN;
            if isempty(store_z)
                return;
            end
            if idx >= 1 && idx <= numel(store_z)
                z_now = double(store_z(idx));
            end
        end

