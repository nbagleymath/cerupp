            fluence_summary = shared.fluence_summary;
            if cfg.store_diag_plan.need_beamcenter_store
                diagnostic_store.store_beamcenter_ix(cfg.save_idx) = shared.ix_bc;
                diagnostic_store.store_beamcenter_iy(cfg.save_idx) = shared.iy_bc;
                diagnostic_store.store_beamcenter_x(cfg.save_idx) = fluence_summary.x_beamcenter;
                diagnostic_store.store_beamcenter_y(cfg.save_idx) = fluence_summary.y_beamcenter;
                diagnostic_store.store_beamcenter_method_code(cfg.save_idx) = fluence_summary.method_code;
                if ~isempty(diagnostic_store.store_beamcenter_ix_vis)
                    diagnostic_store.store_beamcenter_ix_vis(cfg.save_idx) = band.ix_bc_vis;
                    diagnostic_store.store_beamcenter_iy_vis(cfg.save_idx) = band.iy_bc_vis;
                    diagnostic_store.store_beamcenter_x_vis(cfg.save_idx) = band.x_bc_vis;
                    diagnostic_store.store_beamcenter_y_vis(cfg.save_idx) = band.y_bc_vis;
