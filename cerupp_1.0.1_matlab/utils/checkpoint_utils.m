        function diag_field_contract = reassembly_diag_field_contract()
        % Canonical restart-rebuilt versus unrecoverable diagnostic-field provenance.

            specs = checkpoint_utils.diag_field_specs();
            rebuild_mask = ~cellfun(@isempty, {specs.restart_rebuild_note});
            rebuilt_specs = specs(rebuild_mask);
            restart_rebuilt_fields = {rebuilt_specs.name}.';
            restart_rebuilt_notes = struct();
            for ii = 1:numel(restart_rebuilt_fields)
                restart_rebuilt_notes.(restart_rebuilt_fields{ii}) = ...
                    rebuilt_specs(ii).restart_rebuild_note;
            end
            diag_field_contract = struct( ...
                'restart_rebuilt_fields', {restart_rebuilt_fields}, ...
                'restart_rebuilt_notes', restart_rebuilt_notes, ...
                'not_restart_recoverable_fields', {{}}, ...
                'not_restart_recoverable_notes', struct());
        end
    end

    methods (Static, Hidden)
        function write_struct_payload_file(save_target, payload_struct, mat_version_flag, verify_saved_payload_flag)
        % WRITE_STRUCT_PAYLOAD_FILE Atomically save a struct payload to a MAT-file.
        % Payload fields become top-level MAT variables via save(...,'-struct',...).
        % verify_saved_payload_flag and mat_version_flag are explicit at this
        % boundary; the shared checkpoint save-policy wrappers pass
        % caller-selected verification and MAT-version policy into this
        % helper rather than relying on implicit defaults.

            if nargin < 3 || isempty(mat_version_flag)
                error('checkpoint_utils:MissingMatVersionFlag', ...
                    'write_struct_payload_file requires an explicit mat_version_flag.');
            end
            if nargin < 4 || isempty(verify_saved_payload_flag)
                error('checkpoint_utils:MissingVerifySavedPayloadFlag', ...
                    'write_struct_payload_file requires an explicit verify_saved_payload_flag.');
            end
            if isstring(mat_version_flag) && isscalar(mat_version_flag)
                mat_version_flag = char(mat_version_flag);
            end
            if ~ischar(mat_version_flag) || isempty(strtrim(mat_version_flag))
                error('checkpoint_utils:InvalidMatVersionFlag', ...
                    'mat_version_flag must be a nonempty char or scalar string.');
            end
            verify_saved_payload_flag = checkpoint_utils.normalize_checkpoint_bool_scalar_local( ...
                verify_saved_payload_flag, 'verify_saved_payload_flag', ...
                'checkpoint_utils:InvalidVerifySavedPayloadFlag');
            if ~isstruct(payload_struct)
                error('checkpoint_utils:InvalidPayloadStruct', ...
                    'payload_struct must be a struct.');
            end
            payload_fields = fieldnames(payload_struct);
            if isempty(payload_fields)
                error('checkpoint_utils:EmptyPayloadStruct', ...
                    'payload_struct must contain at least one field.');
            end
            verify_fn = [];
            if verify_saved_payload_flag
                verify_fn = @(temp_target) checkpoint_utils.validate_saved_payload_local(temp_target, payload_fields);
            end
            checkpoint_utils.write_atomic_output_file( ...
                save_target, '.tmp', ...
                @(temp_target) checkpoint_utils.write_struct_payload_temp_local( ...
                    temp_target, payload_struct, mat_version_flag), ...
                verify_fn, 'checkpoint_utils:AtomicReplaceFailed', ...
                'checkpoint_utils:InvalidAtomicWriteFn', ...
                'checkpoint_utils:InvalidAtomicVerifyFn', ...
                'checkpoint_utils:DirCreateFailed');
        end
    end

