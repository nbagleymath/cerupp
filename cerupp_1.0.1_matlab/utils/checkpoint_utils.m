                warn_key = artifact_spec.first_failure_warn_key;
                warn_id = artifact_spec.first_failure_warn_id;
                warn_fmt = artifact_spec.first_failure_warn_fmt;
            end
            run_warn_state = output_io_warn_utils.emit_output_io_warn_once( ...
