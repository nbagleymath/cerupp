        function specs = diag_specs_for_rebuild_families(rebuild_families)
        % DIAG_SPECS_FOR_REBUILD_FAMILIES Select schema rows for one restart-rebuild family set.
        % common fields such as store_z are always included.

            specs = checkpoint_utils.diag_field_specs();
            if nargin < 1 || isempty(rebuild_families)
                rebuild_families = {'common'};
            end
            if ischar(rebuild_families)
                rebuild_families = {rebuild_families};
            elseif isstring(rebuild_families)
                rebuild_families = cellstr(rebuild_families(:));
            else
                rebuild_families = rebuild_families(:);
            end
            rebuild_families = cellfun(@(name) lower(strtrim(char(string(name)))), ...
                rebuild_families, 'UniformOutput', false);
            rebuild_families = unique([{'common'}; rebuild_families(:)], 'stable');
            specs = specs(ismember({specs.rebuild_family}.', rebuild_families));
        end

