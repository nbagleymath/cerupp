        function [run_warn_state, save_ok, retried_to_v73, failure_error_id, failure_error_message] = execute_mat_save_policy_with_v7_retry_local(cfg, run_warn_state)
        % EXECUTE_MAT_SAVE_POLICY_WITH_V7_RETRY_LOCAL Retry the standard MAT format once with the large-file format.

            [cfg, run_warn_state] = checkpoint_utils.normalize_policy_inputs_local(cfg, run_warn_state);
            retried_to_v73 = false;
            failure_error_id = '';
            failure_error_message = '';
            phase_tag = checkpoint_utils.policy_char_field_local(cfg, 'phase_tag', run_warn_state_utils.phase_end());
            selected_version = char(string(struct_utils.opt_struct_field(cfg, 'mat_version_flag_override', '')));
            if isempty(selected_version)
                bytes_estimate = struct_utils.opt_struct_field(cfg, 'bytes_estimate', NaN);
                selected_version = checkpoint_utils.select_mat_save_version(double(bytes_estimate));
            end
            if ~strcmp(selected_version, '-v7')
                cfg.mat_version_flag_override = selected_version;
                [run_warn_state, save_ok, failure_error_id, failure_error_message] = ...
                    checkpoint_utils.execute_mat_save_policy(cfg, run_warn_state);
                return;
            end

            io_path = char(string(struct_utils.opt_struct_field(cfg, 'io_path', '')));
            retry_warn_key = checkpoint_utils.policy_char_field_local(cfg, 'retry_warn_key', 'mat_v7_retry');
            retry_warn_id = checkpoint_utils.policy_char_field_local(cfg, 'retry_warn_id', 'CerUPP:Checkpoint:MatSaveV7Retry');
            retry_warn_fmt = checkpoint_utils.policy_char_field_local(cfg, ...
                'retry_warn_fmt', 'MAT save failed with the standard MAT save format; retrying with the large-file MAT save format for %s: %s');

            cfg_v7 = cfg;
            cfg_v7.mat_version_flag_override = '-v7';
            cfg_v7.on_failure = 'throw';
            try
                [run_warn_state, ~] = checkpoint_utils.execute_mat_save_policy(cfg_v7, run_warn_state);
                save_ok = true;
                failure_error_id = '';
                failure_error_message = '';
                return;
            catch me_v7
                run_warn_state = output_io_warn_utils.emit_output_io_warn_once( ...
                    run_warn_state, phase_tag, retry_warn_key, retry_warn_id, ...
                    retry_warn_fmt, io_path, me_v7.message);
            end

            cfg_v73 = cfg;
            cfg_v73.mat_version_flag_override = '-v7.3';
            retried_to_v73 = true;
            [run_warn_state, save_ok, failure_error_id, failure_error_message] = ...
                checkpoint_utils.execute_mat_save_policy(cfg_v73, run_warn_state);
        end

