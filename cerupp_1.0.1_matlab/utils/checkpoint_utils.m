            error_id_txt = char(string(error_id_in));
            if isempty(strtrim(error_id_txt))
                error_id_txt = char(string(default_error_id));
            end
            error_msg_txt = char(string(error_message_in));
            if isempty(strtrim(error_msg_txt))
                error_msg_txt = '(no message)';
            end
            error_msg_txt = strrep(error_msg_txt, sprintf('\n'), ' ');
        end
    end

