        end

        function [checkpoint_policy_state, run_warn_state] = ...
                write_intermediate_checkpoint(cfg, run_warn_state)
        % WRITE_INTERMEDIATE_CHECKPOINT Write one restart checkpoint and optional fullsave payload.
        %   [CHECKPOINT_POLICY_STATE, RUN_WARN_STATE] = ...
        %       WRITE_INTERMEDIATE_CHECKPOINT(CFG, RUN_WARN_STATE)
        %   Writes the restart checkpoint under checkdir, optionally writes
        %   the intermediate fullsave artifact, and returns the updated
        %   canonical checkpoint_policy_state carrier.
        %   Required cfg fields: curr_z_step, checkdir, restart_state,
        %   checkpoint_policy_state.
        %   fullsave_payload is required only when checkpoint_full_save_flag=true
        %   and the current failure latch still allows intermediate fullsave
        %   attempts (that is, disable_fullsave_only has not already latched on).
        %   Shared filename, companion-file, verification, and MAT-version retry
        %   behavior is handled by the helpers below.

            [cfg, run_warn_state, checkpoint_policy_state, curr_z_step, ...
                checkdir, restart_state, failure_phase_tag, verify_policy] = ...
                checkpoint_utils.normalize_intermediate_checkpoint_cfg_local(cfg, run_warn_state);
            if ~checkpoint_policy_state.restart_enabled && ...
                    ~checkpoint_policy_state.fullsave_enabled
                return;
            end
            checkpoint_failure_state = checkpoint_policy_state.failure_state;
            restart_artifact_policy = checkpoint_utils.mat_artifact_policy_spec_local('intermediate_restart');
            fullsave_artifact_policy = checkpoint_utils.mat_artifact_policy_spec_local('intermediate_fullsave');
            if checkpoint_policy_state.restart_enabled
                [checkpoint_failure_state, run_warn_state] = ...
                    checkpoint_utils.write_intermediate_restart_artifact_local( ...
                        cfg, checkpoint_failure_state, run_warn_state, ...
                        restart_artifact_policy, failure_phase_tag, curr_z_step, ...
                        checkdir, restart_state, verify_policy.intermediate_restart);
            end
            if checkpoint_policy_state.fullsave_enabled
                [checkpoint_failure_state, run_warn_state] = ...
                    checkpoint_utils.write_intermediate_fullsave_artifact_local( ...
                        cfg, checkpoint_failure_state, run_warn_state, ...
                        fullsave_artifact_policy, failure_phase_tag, curr_z_step, ...
                        checkdir, verify_policy.intermediate_full);
            end
            checkpoint_policy_state.failure_state = checkpoint_failure_state;
            checkpoint_policy_state.restart_enabled = ...
                logical(checkpoint_policy_state.restart_enabled) && ...
                ~logical(checkpoint_failure_state.disable_restart_only);
            checkpoint_policy_state.fullsave_enabled = ...
                logical(checkpoint_policy_state.fullsave_enabled) && ...
                ~logical(checkpoint_failure_state.disable_fullsave_only);
        end

        function checkpoint_policy_state = initialize_intermediate_checkpoint_policy_state(do_intermediate_saves)
        % INITIALIZE_INTERMEDIATE_CHECKPOINT_POLICY_STATE Build the driver-visible intermediate-checkpoint latch owner once.

            if nargin < 1 || isempty(do_intermediate_saves)
                do_intermediate_saves = true;
            end
            do_intermediate_saves = checkpoint_utils.normalize_checkpoint_bool_scalar_local( ...
                do_intermediate_saves, 'do_intermediate_saves', ...
                'checkpoint_utils:InvalidDoIntermediateSaves');
            checkpoint_policy_state = struct( ...
                'restart_enabled', logical(do_intermediate_saves), ...
                'fullsave_enabled', logical(do_intermediate_saves), ...
                'snapshot_enabled', logical(do_intermediate_saves), ...
                'failure_state', checkpoint_utils.ensure_failure_state_struct(struct()), ...
                'fullsave_last_store_idx', 0, ...
                'fullsave_last_reduced_store_idx', 0);
        end
    end

