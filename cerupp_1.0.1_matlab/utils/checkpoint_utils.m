    methods (Static)
        function version_flag = select_mat_save_version(bytes_estimate)

        % SELECT_MAT_SAVE_VERSION Shared MAT-version selection policy.
        % Uses -v7 below the 1.8e9-byte soft size threshold when the byte
        % estimate is finite and positive; otherwise falls back to -v7.3.
            v7_bytes_soft_limit = 1.8e9;
            if isfinite(bytes_estimate) && (bytes_estimate > 0) && (bytes_estimate < v7_bytes_soft_limit)
                version_flag = '-v7';
            else
                version_flag = '-v7.3';
            end
        end
    end

    methods (Static, Hidden)
        function [run_warn_state, save_ok, failure_error_id, failure_error_message] = execute_mat_save_policy(cfg, run_warn_state)
        % EXECUTE_MAT_SAVE_POLICY Shared MAT-file save orchestration with explicit failure policy.
        % Required cfg fields:
        %   save_fn : function handle save_fn(mat_version_flag).
        % Stable optional cfg fields:
        %   io_path : required when on_failure='warn_continue'.
        %   bytes_estimate : size hint for select_mat_save_version().
        %   phase_tag, failure_tag : warning/output-IO routing tags.
        %   warn_key, warn_id, warn_fmt : warning-routing overrides.
        %   mat_version_flag_override : bypass bytes_estimate-based version selection.
        %   on_failure : 'warn_continue' (default) or 'throw'.
        % Returns [run_warn_state, save_ok]. In warn_continue mode, save
        % exceptions are caught, routed through run_warn_state/output_io
        % accounting, and reported via save_ok=false instead of rethrowing.

            [cfg, run_warn_state] = checkpoint_utils.normalize_policy_inputs_local(cfg, run_warn_state);
            save_fn = struct_utils.req_struct_field(cfg, 'save_fn', 'checkpoint_utils.execute_mat_save_policy');
            bytes_estimate = struct_utils.opt_struct_field(cfg, 'bytes_estimate', NaN);
            io_path = struct_utils.opt_struct_field(cfg, 'io_path', '');
            phase_tag = checkpoint_utils.policy_char_field_local(cfg, 'phase_tag', run_warn_state_utils.phase_end());
            failure_tag = checkpoint_utils.policy_char_field_local(cfg, 'failure_tag', 'output_io');
            warn_key = checkpoint_utils.policy_char_field_local(cfg, 'warn_key', 'mat_save_failed');
            warn_id = checkpoint_utils.policy_char_field_local(cfg, 'warn_id', 'CerUPP:Checkpoint:MatSaveFailed');
            warn_fmt = checkpoint_utils.policy_char_field_local(cfg, 'warn_fmt', 'MAT save failed (%s): %s');
            on_failure = checkpoint_utils.policy_char_field_local(cfg, 'on_failure', 'warn_continue');
            mat_version_flag_override = checkpoint_utils.policy_char_field_local(cfg, 'mat_version_flag_override', '');
            if ~isa(save_fn, 'function_handle')
                error('checkpoint_utils:InvalidSaveFn', ...
                    'cfg.save_fn must be a function handle accepting one MAT version flag.');
            end
            save_ok = false;
            failure_error_id = '';
            failure_error_message = '';
            if isempty(mat_version_flag_override)
                mat_version_flag = checkpoint_utils.select_mat_save_version(double(bytes_estimate));
            else
                mat_version_flag = mat_version_flag_override;
            end
            switch on_failure
                case 'throw'
                    save_fn(mat_version_flag);
                    save_ok = true;
                case 'warn_continue'
                    if isempty(io_path)
                        error('checkpoint_utils:MissingSaveIoPath', ...
                            'cfg.io_path is required when on_failure=''warn_continue''.');
                    end
                    try
                        save_fn(mat_version_flag);
                        save_ok = true;
                    catch me_save
                        failure_error_id = me_save.identifier;
                        failure_error_message = me_save.message;
                        run_warn_state = output_io_warn_utils.emit_output_io_warn_once( ...
                            run_warn_state, phase_tag, warn_key, warn_id, warn_fmt, io_path, me_save.message);
                        run_warn_state = output_io_warn_utils.record_output_io_failure( ...
                            run_warn_state, failure_tag, io_path, me_save, phase_tag);
                    end
                otherwise
                    error('checkpoint_utils:InvalidSaveFailurePolicy', ...
                        'cfg.on_failure must be ''throw'' or ''warn_continue''; got %s.', on_failure);
            end
        end
    end

