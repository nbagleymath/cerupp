        function [checkpoint_failure_state, run_warn_state, retried_to_v73] = ...
                execute_intermediate_artifact_branch_local( ...
                    checkpoint_failure_state, run_warn_state, artifact_spec, ...
                    failure_phase_tag, curr_z_step, io_path, save_cfg)
        % Run one intermediate restart/fullsave branch through the shared save/failure machinery.

            retried_to_v73 = false;
            checkpoint_failure_state = ...
                checkpoint_utils.record_intermediate_artifact_attempt_local( ...
                checkpoint_failure_state, artifact_spec);
            try
                [run_warn_state, ~, retried_to_v73] = checkpoint_utils.execute_mat_artifact_save_local( ...
                    save_cfg, run_warn_state);
                checkpoint_failure_state = checkpoint_utils.record_intermediate_artifact_success_local( ...
                    checkpoint_failure_state, artifact_spec);
            catch me_artifact
                checkpoint_failure_state = checkpoint_utils.record_intermediate_artifact_failure_local( ...
                    checkpoint_failure_state, curr_z_step, me_artifact, artifact_spec);
                disable_latched = false;
                if isfield(artifact_spec, 'disable_flag_field') && ...
                        ~isempty(artifact_spec.disable_flag_field)
                    disable_latched = logical(checkpoint_failure_state.(artifact_spec.disable_flag_field));
                end
                consecutive_failure_count = 0;
                if isfield(artifact_spec, 'consecutive_failure_field') && ...
                        ~isempty(artifact_spec.consecutive_failure_field)
                    consecutive_failure_count = checkpoint_failure_state.(artifact_spec.consecutive_failure_field);
                end
                if (consecutive_failure_count == 1) || disable_latched
                    run_warn_state = checkpoint_utils.emit_intermediate_artifact_degradation_warn_local( ...
                        run_warn_state, failure_phase_tag, artifact_spec, ...
                        curr_z_step, checkpoint_failure_state.(artifact_spec.error_id_field), ...
                        checkpoint_failure_state.(artifact_spec.error_message_field), ...
                        disable_latched);
                end
                run_warn_state = output_io_warn_utils.record_output_io_failure( ...
                    run_warn_state, artifact_spec.failure_tag, io_path, me_artifact, failure_phase_tag);
            end
        end

        function [error_id, error_message] = describe_failure_local(me_in, default_error_id, fallback_message)
            error_id = default_error_id;
            error_message = '(no message)';
            if isa(me_in, 'MException')
                if ~isempty(me_in.identifier)
                    error_id = me_in.identifier;
                end
                if ~isempty(me_in.message)
                    error_message = me_in.message;
                end
            elseif isstruct(me_in)
                if isfield(me_in, 'identifier') && ~isempty(me_in.identifier)
                    error_id = me_in.identifier;
                end
                if isfield(me_in, 'message') && ~isempty(me_in.message)
                    error_message = me_in.message;
                end
            else
                error_message = fallback_message;
            end
        end

