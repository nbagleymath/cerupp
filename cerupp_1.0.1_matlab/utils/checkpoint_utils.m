        function payload_struct = merge_passthrough_payload_fields_local( ...
                payload_struct, cfg, reserved_field_names, owner_label)
            if nargin < 4 || isempty(owner_label)
                owner_label = 'Saved artifact payload';
            end
            if nargin < 3 || isempty(reserved_field_names)
                reserved_field_names = {};
            end
            reserved_field_names = cellstr(string(reserved_field_names(:)));
            cfg_field_names = fieldnames(cfg);
            passthrough_field_names = setdiff(cfg_field_names, reserved_field_names, 'stable');
            for ii = 1:numel(passthrough_field_names)
                field_name = passthrough_field_names{ii};
                if ~isvarname(field_name)
                    error('checkpoint_utils:InvalidPassthroughPayloadFieldName', ...
                        '%s extra field "%s" is not a valid MATLAB variable name.', ...
                        owner_label, field_name);
                end
                if isfield(payload_struct, field_name)
                    error('checkpoint_utils:DuplicatePassthroughPayloadField', ...
                        '%s extra field "%s" collides with an existing saved field.', ...
                        owner_label, field_name);
                end
                payload_struct.(field_name) = cfg.(field_name);
            end
        end

