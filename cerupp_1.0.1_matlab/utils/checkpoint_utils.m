            end
            fid = fopen(temp_target, 'w');
            if fid == -1
                error(open_error_id, open_error_fmt, temp_target);
            end
            cleanup_fid = onCleanup(@() fclose(fid));
            fprintf(fid, '%s\n', text_payload);
        end

        function verify_exact_text_temp_file_local(temp_target, expected_text, verify_error_id)
            if nargin < 3 || isempty(verify_error_id)
                verify_error_id = 'checkpoint_utils:TextTempVerifyFailed';
            end
            file_text = fileread(temp_target);
            file_text = checkpoint_utils.normalize_text_payload_for_compare_local(file_text);
            if ~strcmp(file_text, expected_text)
                error(verify_error_id, ...
                    'Temporary text file verification failed for %s.', temp_target);
            end
        end

        function write_text_payload_file_local( ...
                target_file, text_payload, temp_suffix, ...
                open_error_id, open_error_fmt, verify_error_id, move_error_id)
            expected_text = checkpoint_utils.normalize_text_payload_for_compare_local(text_payload);
            checkpoint_utils.write_atomic_temp_file_local( ...
                target_file, temp_suffix, ...
                @(temp_target) checkpoint_utils.write_text_temp_file_local( ...
                    temp_target, text_payload, open_error_id, open_error_fmt), ...
                @(temp_target) checkpoint_utils.verify_exact_text_temp_file_local( ...
                    temp_target, expected_text, verify_error_id), ...
                move_error_id);
        end

        function text_out = normalize_text_payload_for_compare_local(text_in)
            if isstring(text_in) && isscalar(text_in)
                text_in = char(text_in);
            end
            if ~ischar(text_in)
                error('checkpoint_utils:InvalidTextPayload', ...
                    'Expected char or scalar string text payload; got %s.', class(text_in));
            end
            text_out = regexprep(text_in, '\r?\n$', '');
        end

        function [run_warn_state, io_ok] = execute_text_io_policy_local(cfg, run_warn_state)
            if ~(isstruct(cfg) && isscalar(cfg))
                error('checkpoint_utils:InvalidTextIoCfg', ...
                    'cfg must be a scalar struct for checkpoint_utils.execute_text_io_policy_local.');
            end
            if nargin < 2 || isempty(run_warn_state)
                run_warn_state = struct();
            elseif ~(isstruct(run_warn_state) && isscalar(run_warn_state))
                error('checkpoint_utils:InvalidTextIoWarnState', ...
                    'run_warn_state must be a scalar struct or [].');
            end
            io_path = struct_utils.req_struct_field(cfg, 'io_path', 'checkpoint_utils.execute_text_io_policy_local');
            io_fn = struct_utils.req_struct_field(cfg, 'io_fn', 'checkpoint_utils.execute_text_io_policy_local');
            phase_tag = char(string(struct_utils.opt_struct_field(cfg, 'phase_tag', run_warn_state_utils.phase_end())));
            warn_key = char(string(struct_utils.opt_struct_field(cfg, 'warn_key', 'text_io_failed')));
            warn_id = char(string(struct_utils.opt_struct_field(cfg, 'warn_id', 'CerUPP:RunStatus:TextIoFailed')));
            failure_tag = char(string(struct_utils.opt_struct_field(cfg, 'failure_tag', 'text_io')));
            warn_fmt = char(string(struct_utils.opt_struct_field(cfg, 'warn_fmt', 'Text I/O failed (%s): %s')));
            if ~isa(io_fn, 'function_handle')
                error('checkpoint_utils:InvalidTextIoFn', ...
                    'cfg.io_fn must be a function handle for text I/O policy execution.');
            end
            io_ok = false;
            try
                io_fn();
                io_ok = true;
            catch me_io
                run_warn_state = output_io_warn_utils.emit_output_io_warn_once( ...
                    run_warn_state, phase_tag, warn_key, warn_id, warn_fmt, io_path, me_io.message);
                run_warn_state = output_io_warn_utils.record_output_io_failure( ...
                    run_warn_state, failure_tag, io_path, me_io, phase_tag);
            end
        end

        function write_atomic_temp_file_local(target_file, temp_tag, write_temp_fn, verify_temp_fn, move_error_id, varargin)
            if nargin < 2 || isempty(temp_tag)
                temp_tag = '.tmp';
            end
            if nargin < 4
                verify_temp_fn = [];
            end
            if nargin < 5 || isempty(move_error_id)
                move_error_id = 'checkpoint_utils:AtomicReplaceFailed';
            end
            invalid_write_error_id = 'checkpoint_utils:InvalidAtomicWriteFn';
            invalid_verify_error_id = 'checkpoint_utils:InvalidAtomicVerifyFn';
            dir_create_error_id = 'checkpoint_utils:DirCreateFailed';
            if numel(varargin) >= 1 && ~isempty(varargin{1})
                invalid_write_error_id = char(string(varargin{1}));
            end
            if numel(varargin) >= 2 && ~isempty(varargin{2})
                invalid_verify_error_id = char(string(varargin{2}));
            end
            if numel(varargin) >= 3 && ~isempty(varargin{3})
                dir_create_error_id = char(string(varargin{3}));
            end
            if ~isa(write_temp_fn, 'function_handle')
                error(invalid_write_error_id, ...
                    'write_temp_fn must be a function handle.');
            end
            if ~isempty(verify_temp_fn) && ~isa(verify_temp_fn, 'function_handle')
                error(invalid_verify_error_id, ...
                    'verify_temp_fn must be [] or a function handle.');
            end
            [target_dir, ~, ~] = fileparts(target_file);
            if isempty(target_dir)
                target_dir = '.';
            end
            for attempt_idx = 1:2
                checkpoint_utils.ensure_target_dir_ready_local(target_dir, dir_create_error_id);
                [temp_target, ~] = checkpoint_utils.make_temp_target_local(target_file, temp_tag);
                try
                    write_temp_fn(temp_target);
                    if isa(verify_temp_fn, 'function_handle')
                        verify_temp_fn(temp_target);
                    end
                    [ok_move, move_msg, move_msgid] = movefile(temp_target, target_file, 'f');
                    if ~ok_move
                        error(move_error_id, ...
                            'movefile failed for %s -> %s (%s): %s', ...
                            temp_target, target_file, move_msgid, move_msg);
                    end
                    return;
                catch me_write
                    if exist(temp_target, 'file') == 2
                        try
                            delete(temp_target);
                        catch
                        end
                    end
                    if (attempt_idx == 1) && ...
                            checkpoint_utils.should_retry_atomic_write_after_dir_failure_local(target_dir)
                        continue;
                    end
                    rethrow(me_write);
                end
            end
        end

        function [temp_target, target_dir] = make_temp_target_local(target_file, temp_tag)
            if nargin < 2 || isempty(temp_tag)
                temp_tag = '.tmp';
            end
            [target_dir, base_name, ext] = fileparts(target_file);
            if isempty(target_dir)
                target_dir = '.';
            end
            [~, unique_stem, ~] = fileparts(tempname(target_dir));
            temp_target = fullfile(target_dir, sprintf('.%s%s_%s%s', ...
                base_name, temp_tag, unique_stem, ext));
        end

        function tf = should_retry_atomic_write_after_dir_failure_local(target_dir)
            if nargin < 1 || isempty(target_dir)
                target_dir = '.';
            end
            tf = (exist(target_dir, 'dir') ~= 7);
        end
    end
