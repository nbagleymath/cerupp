        function checkpoint_vars = normalize_checkpoint_varlist(checkpoint_vars_in)
        % NORMALIZE_CHECKPOINT_VARLIST Canonicalize checkpoint payload variable names.
        % CHECKPOINT_VARS = NORMALIZE_CHECKPOINT_VARLIST(CHECKPOINT_VARS_IN)
        % accepts a char/string scalar, string array, or cell array of
        % variable-name entries. The return value is a column cell array of
        % trimmed unique MATLAB identifiers in stable input order.
        % Invalid, empty, or duplicate names fail eagerly with an error.

            if isempty(checkpoint_vars_in)
                error('checkpoint_utils:EmptyCheckpointVarlist', ...
                    'checkpoint_vars must contain at least one variable name.');
            end
            if ischar(checkpoint_vars_in) || (isstring(checkpoint_vars_in) && isscalar(checkpoint_vars_in))
                checkpoint_vars = {checkpoint_utils.normalize_checkpoint_var_entry_local( ...
                    checkpoint_vars_in, 1)};
            else
                if isstring(checkpoint_vars_in)
                    checkpoint_vars_in = cellstr(checkpoint_vars_in(:).');
                end
                if ~iscell(checkpoint_vars_in)
                    checkpoint_vars_in = {checkpoint_vars_in};
                end

                checkpoint_vars = cell(numel(checkpoint_vars_in), 1);
                for ii = 1:numel(checkpoint_vars_in)
                    checkpoint_vars{ii} = checkpoint_utils.normalize_checkpoint_var_entry_local( ...
                        checkpoint_vars_in{ii}, ii);
                end
            end
            checkpoint_vars = checkpoint_vars(:);
            [checkpoint_vars_unique, unique_idx] = unique(checkpoint_vars, 'stable');
            if numel(unique_idx) ~= numel(checkpoint_vars)
                dupes = checkpoint_vars(setdiff(1:numel(checkpoint_vars), unique_idx));
                error('checkpoint_utils:DuplicateCheckpointVarNames', ...
                    'checkpoint_vars contains duplicate names: %s', strjoin(unique(dupes, 'stable'), ', '));
            end
            checkpoint_vars = checkpoint_vars_unique(:);
        end
    end

