        function policy = default_run_output_startup_policy()
        % Delegate the startup collision/archive policy to run_output_utils.

            policy = run_output_utils.default_run_output_startup_policy();
        end

        function reject_restart_diag_reassembly_state_field_collisions(base_state, diag_reassembly_state, checkpoint_name)
        %REJECT_RESTART_DIAG_REASSEMBLY_STATE_FIELD_COLLISIONS Reject diag-reassembly payloads that overwrite continuation state fields.

            if ~(isstruct(base_state) && isscalar(base_state))
                error('checkpoint_utils:InvalidRestartDiagReassemblyBaseState', ...
                    'base_state must be a scalar struct when checking diag-reassembly field collisions.');
            end
            if ~(isstruct(diag_reassembly_state) && isscalar(diag_reassembly_state))
                error('checkpoint_utils:InvalidRestartDiagReassemblyStatePayload', ...
                    'diag_reassembly_state must be a scalar struct when checking field collisions.');
            end
            if nargin < 3 || isempty(checkpoint_name)
                checkpoint_name = '';
            end
            checkpoint_name = char(string(checkpoint_name));
            overlap = intersect(fieldnames(base_state), fieldnames(diag_reassembly_state));
            if isempty(overlap)
                return;
            end
            if isempty(checkpoint_name)
                error('checkpoint_utils:RestartDiagReassemblyStateFieldCollision', ...
                    ['restart_diag_reassembly_state fields collide with restart_state.state: %s. ', ...
                     'Use distinct field names for reassembly-only state.'], ...
                    strjoin(overlap, ', '));
            end
            error('checkpoint_utils:RestartDiagReassemblyStateFieldCollision', ...
                ['Restart checkpoint %s has diag_reassembly_state fields that collide with ', ...
                 'restart_state.state: %s. Use distinct field names for reassembly-only state.'], ...
                checkpoint_name, strjoin(overlap, ', '));
        end

