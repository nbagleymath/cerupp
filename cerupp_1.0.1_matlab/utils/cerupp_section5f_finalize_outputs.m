function varargout = cerupp_section5f_finalize_outputs(varargin)
% Driver-only Section 5F helper for cerupp.m.
% In the usual no-input mode this helper reads the current cerupp.m
% workspace, finalizes the post-propagation output state, and assigns the
% resulting Section 5F variables back into the driver workspace.

    if nargin == 0
        caller_field_names = caller_field_names_local();
        cfg = struct();
        for ii = 1:numel(caller_field_names)
            field_name = caller_field_names{ii};
            try
                cfg.(field_name) = evalin('caller', field_name);
            catch err
                if strcmp(err.identifier, 'MATLAB:UndefinedFunction') || ...
                        strcmp(err.identifier, 'MATLAB:UndefinedVariable')
                    error('CerUPP:MissingSection5FCallerField', ...
                        ['cerupp_section5f_finalize_outputs expected caller variable ''%s'' ', ...
                         'to exist before the Section 5F helper call.'], ...
                        field_name);
                end
                rethrow(err);
            end
        end
        section5f_state = build_section5f_state_local(cfg);
        output_field_names = fieldnames(section5f_state);
        for ii = 1:numel(output_field_names)
            field_name = output_field_names{ii};
            assignin('caller', field_name, section5f_state.(field_name));
        end
        if nargout > 0
            varargout{1} = section5f_state;
        end
        return;
    end

    if (nargin ~= 1) || ~isstruct(varargin{1}) || ~isscalar(varargin{1})
        error('CerUPP:InvalidSection5FCfg', ...
            'cerupp_section5f_finalize_outputs accepts either no inputs or one scalar cfg struct.');
    end

    section5f_state = build_section5f_state_local(varargin{1});
    if nargout > 1
        error('CerUPP:InvalidSection5FOutputCount', ...
            'cerupp_section5f_finalize_outputs returns at most one output struct.');
    end
    if nargout == 1
        varargout{1} = section5f_state;
    end
end

