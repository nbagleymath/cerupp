function [grid_state, A_S, A_SSF, A_F, run_warn_state] = ...
        build_launch_state_local(grid_state, launch_state_inputs, run_warn_state)
    x = struct_utils.req_struct_field( ...
        grid_state, 'x', 'cerupp_section3d_setup.grid_state');
    y = struct_utils.req_struct_field( ...
        grid_state, 'y', 'cerupp_section3d_setup.grid_state');
    t = struct_utils.req_struct_field( ...
        grid_state, 't', 'cerupp_section3d_setup.grid_state');
    kperp = struct_utils.req_struct_field( ...
        grid_state, 'kperp', 'cerupp_section3d_setup.grid_state');
    lambda_window = struct_utils.req_struct_field( ...
        grid_state, 'lambda_window', 'cerupp_section3d_setup.grid_state');
    omega_window = struct_utils.req_struct_field( ...
        grid_state, 'omega_window', 'cerupp_section3d_setup.grid_state');

    [A_xy, fwhm_fund, mask, mask_f, mask_f_w, mask_f_runtime, ...
        mask_f_w_runtime, mask_f_xy, c, n_sell, kcut, k_min_med, ...
        mask_loss_warn_frac] = ...
        struct_utils.unpack_struct_fields(launch_state_inputs, ...
        {'A_xy', 'fwhm_fund', 'mask', 'mask_f', 'mask_f_w', ...
         'mask_f_runtime', 'mask_f_w_runtime', 'mask_f_xy', 'c', ...
         'n_sell', 'kcut', 'k_min_med', ...
         'mask_loss_warn_frac'}, ...
        'cerupp_section3d_setup.launch_state_inputs');

    fprintf(['Beamwidth reference (input setting only; no precomputed z=0 plot point) ', ...
             'FWHM_fund=%.3f um\n'], ...
        fwhm_fund * 1e6);

    A_S = A_xy;
    A_SSF = fft(A_S, [], 3);
    A_F = fft2(A_SSF);

    mask_loss_diagnostic = propagation_support.estimate_linear_mask_energy_loss_once( ...
        A_F, mask_f, mask_f_w);
    if isfinite(mask_loss_diagnostic.applied_step_loss_frac)
        fprintf(['Setup smooth-mask geometry check (one-time): the built smooth spectral mask would remove ~= ', ...
                 '%.3f%% of the launch-spectrum energy.\n'], ...
            100 * mask_loss_diagnostic.applied_step_loss_frac);
        if mask_loss_diagnostic.applied_step_loss_frac > mask_loss_warn_frac
            run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                run_warn_state, 'setup', ...
                'setup_mask_loss_soft_warn', ...
                'CerUPP:Setup:MaskLossSoftWarn', ...
                ['One-time setup geometry estimate: the built smooth spectral mask would remove %.2f%% of ', ...
                 'the launch-spectrum energy, exceeding the configured mask_loss_warn_frac threshold ', ...
                 '(%.2f%%).'], ...
                100 * mask_loss_diagnostic.applied_step_loss_frac, ...
                100 * mask_loss_warn_frac);
        end
    else
        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
            run_warn_state, 'setup', ...
            'setup_mask_loss_diag_skipped', ...
            'CerUPP:MaskLossSetupDiagnosticSkipped', ...
            'Mask-loss setup diagnostic skipped (non-finite or zero baseline spectral energy).');
    end

    dt_vec_runtime = diff(t(:));
    if isa(A_S, 'single')
        dt_vec = single(dt_vec_runtime);
    else
        dt_vec = double(dt_vec_runtime);
    end

    [~, ix_axis0] = min(abs(x));
    [~, iy_axis0] = min(abs(y));
    x_axis0 = x(ix_axis0);
    y_axis0 = y(iy_axis0);
    k_band_med = double(n_sell(:)) .* double(omega_window(:)) / double(c);
    % Reuse the exact step-1 launch-entry helper so the printed launch
    % summary cannot drift from the propagated launch field.
    A_F_launch_report = propagation_support.apply_runtime_launch_mask_local( ...
        A_F, mask_f_runtime, mask_f_w_runtime, mask);

    run_warn_state = mask_and_offaxis_setup_and_check_validity.mask_setup_launch_weighted_angle_report( ...
        A_F_launch_report, mask_f_runtime, mask_f_w_runtime, ...
        kperp, k_band_med, kcut, k_min_med, ...
        run_warn_state);

    grid_state.dt_vec = dt_vec;
    grid_state.ix_axis0 = ix_axis0;
    grid_state.iy_axis0 = iy_axis0;
    grid_state.x_axis0 = x_axis0;
    grid_state.y_axis0 = y_axis0;
end

