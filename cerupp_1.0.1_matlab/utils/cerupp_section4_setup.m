function [time_grid_supports_parseval_fluence, fundamental_band_support, ...
          mask_visible_band_3d, mask_fundamental_band_3d, ...
          mask_red_band_3d, mask_green_band_3d, mask_blue_band_3d, ...
          run_warn_state] = build_band_store_plan_inputs_local( ...
            band_diagnostic_inputs, run_warn_state)
    [time_grid_supports_parseval_fluence, diagnostic_band_cfg, lambda_nm, ...
        lambda_fund, omega_window, mask_f_w, c, n, delta_t] = ...
        struct_utils.unpack_struct_fields(band_diagnostic_inputs, ...
        {'time_grid_supports_parseval_fluence', 'diagnostic_band_cfg', ...
         'lambda_nm', 'lambda_fund', 'omega_window', 'mask_f_w', ...
         'c', 'n', 'delta_t'}, ...
        'cerupp_section3d_setup.band_diagnostic_inputs');

    lambda_m_to_nm_scale = 1e9;
    lambda_fund_nm = lambda_fund * lambda_m_to_nm_scale;
    active_omega_support_mask = reshape(double(mask_f_w), 1, []) > 0;
    mask_visible_band = active_omega_support_mask & ...
        (lambda_nm >= diagnostic_band_cfg.lambda_visible_band_min) & ...
        (lambda_nm <= diagnostic_band_cfg.lambda_visible_band_max);
    mask_fundamental_band = active_omega_support_mask & ...
        (abs(lambda_nm - lambda_fund_nm) <= ...
        diagnostic_band_cfg.lambda_fundamental_band_half_width);
    mask_blue_band = active_omega_support_mask & ...
        (lambda_nm >= diagnostic_band_cfg.lambda_blue_band_min) & ...
        (lambda_nm <= diagnostic_band_cfg.lambda_blue_band_max);
    mask_green_band = active_omega_support_mask & ...
        (lambda_nm >= diagnostic_band_cfg.lambda_green_band_min) & ...
        (lambda_nm <= diagnostic_band_cfg.lambda_green_band_max);
    mask_red_band = active_omega_support_mask & ...
        (lambda_nm >= diagnostic_band_cfg.lambda_red_band_min) & ...
        (lambda_nm <= diagnostic_band_cfg.lambda_red_band_max);

    mask_visible_band_3d = reshape(mask_visible_band, 1, 1, []);
    mask_fundamental_band_3d = reshape(mask_fundamental_band, 1, 1, []);
    mask_red_band_3d = reshape(mask_red_band, 1, 1, []);
    mask_green_band_3d = reshape(mask_green_band, 1, 1, []);
    mask_blue_band_3d = reshape(mask_blue_band, 1, 1, []);

    fundamental_band_requested_lambda_min_nm = ...
        lambda_fund_nm - diagnostic_band_cfg.lambda_fundamental_band_half_width;
    fundamental_band_requested_lambda_max_nm = ...
        lambda_fund_nm + diagnostic_band_cfg.lambda_fundamental_band_half_width;
    if fundamental_band_requested_lambda_min_nm <= 0
        error('CerUPP:InvalidFundamentalBandLambdaRange', ...
            ['Fundamental-band diagnostic window must stay above 0 nm. ', ...
             'Requested interval was [%.3f, %.3f] nm.'], ...
            fundamental_band_requested_lambda_min_nm, ...
            fundamental_band_requested_lambda_max_nm);
    end

    fundamental_band_requested_omega_min = ...
        2*pi*c / (fundamental_band_requested_lambda_max_nm / lambda_m_to_nm_scale);
    fundamental_band_requested_omega_max = ...
        2*pi*c / (fundamental_band_requested_lambda_min_nm / lambda_m_to_nm_scale);
    fundamental_band_sampled_omega = sort(omega_window(mask_fundamental_band));
    fundamental_band_sampled_lambda_nm = lambda_nm(mask_fundamental_band);
    fundamental_band_sampled_num_bins = numel(fundamental_band_sampled_omega);
    fundamental_band_omega_cell_width = 2*pi / (n * delta_t);
    fundamental_band_omega_cell_coverage_fraction = 0;
    fundamental_band_sampled_omega_min = NaN;
    fundamental_band_sampled_omega_max = NaN;
    if fundamental_band_sampled_num_bins > 0
        fundamental_band_cell_omega_min = ...
            fundamental_band_sampled_omega - 0.5 * fundamental_band_omega_cell_width;
        fundamental_band_cell_omega_max = ...
            fundamental_band_sampled_omega + 0.5 * fundamental_band_omega_cell_width;
        fundamental_band_overlap_omega_min = max( ...
            fundamental_band_cell_omega_min, fundamental_band_requested_omega_min);
        fundamental_band_overlap_omega_max = min( ...
            fundamental_band_cell_omega_max, fundamental_band_requested_omega_max);
        fundamental_band_overlap_width = max( ...
            0, fundamental_band_overlap_omega_max - fundamental_band_overlap_omega_min);
        fundamental_band_requested_omega_width = ...
            fundamental_band_requested_omega_max - fundamental_band_requested_omega_min;
        if fundamental_band_requested_omega_width > 0
            fundamental_band_omega_cell_coverage_fraction = min( ...
                1, sum(fundamental_band_overlap_width) / fundamental_band_requested_omega_width);
        end
        fundamental_band_overlap_has_support = (fundamental_band_overlap_width > 0);
        if any(fundamental_band_overlap_has_support)
            fundamental_band_sampled_omega_min = min( ...
                fundamental_band_overlap_omega_min(fundamental_band_overlap_has_support));
            fundamental_band_sampled_omega_max = max( ...
                fundamental_band_overlap_omega_max(fundamental_band_overlap_has_support));
        end
    end

    fundamental_band_sampled_lambda_min_nm = NaN;
    fundamental_band_sampled_lambda_max_nm = NaN;
    if isfinite(fundamental_band_sampled_omega_min) && ...
            isfinite(fundamental_band_sampled_omega_max)
        fundamental_band_sampled_lambda_min_nm = ...
            2*pi*c / fundamental_band_sampled_omega_max * lambda_m_to_nm_scale;
        fundamental_band_sampled_lambda_max_nm = ...
            2*pi*c / fundamental_band_sampled_omega_min * lambda_m_to_nm_scale;
    elseif fundamental_band_sampled_num_bins > 0
        fundamental_band_sampled_lambda_min_nm = min(fundamental_band_sampled_lambda_nm);
        fundamental_band_sampled_lambda_max_nm = max(fundamental_band_sampled_lambda_nm);
    end

    fundamental_band_support_status = 'none';
    if (fundamental_band_sampled_num_bins > 0) && ...
            (fundamental_band_omega_cell_coverage_fraction > 0)
        if fundamental_band_omega_cell_coverage_fraction >= (1 - 1e-12)
            fundamental_band_support_status = 'full';
        else
            fundamental_band_support_status = 'partial';
        end
    end

    fundamental_band_support = struct( ...
        'requested_lambda_min_nm', fundamental_band_requested_lambda_min_nm, ...
        'requested_lambda_max_nm', fundamental_band_requested_lambda_max_nm, ...
        'requested_omega_min', fundamental_band_requested_omega_min, ...
        'requested_omega_max', fundamental_band_requested_omega_max, ...
        'sampled_lambda_min_nm', fundamental_band_sampled_lambda_min_nm, ...
        'sampled_lambda_max_nm', fundamental_band_sampled_lambda_max_nm, ...
        'sampled_omega_min', fundamental_band_sampled_omega_min, ...
        'sampled_omega_max', fundamental_band_sampled_omega_max, ...
        'sampled_num_bins', fundamental_band_sampled_num_bins, ...
        'omega_cell_coverage_fraction', fundamental_band_omega_cell_coverage_fraction, ...
        'status', fundamental_band_support_status, ...
        'has_any_support', ~strcmp(fundamental_band_support_status, 'none'), ...
        'has_full_support', strcmp(fundamental_band_support_status, 'full'));

    if ~fundamental_band_support.has_any_support
        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
            run_warn_state, 'setup', ...
            'fundamental_band_mask_empty', ...
            'CerUPP:FundamentalBandMaskEmpty', ...
            ['Fundamental-band diagnostic mask has no sampled wavelength bins inside ', ...
             'lambda_fund +/- %.1f nm around %.1f nm. Fundamental-band fluence/time-trace ', ...
             'diagnostics will be marked unavailable and related fundamental-band plots skipped.'], ...
            diagnostic_band_cfg.lambda_fundamental_band_half_width, lambda_fund_nm);
    elseif strcmp(fundamental_band_support.status, 'partial')
        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
            run_warn_state, 'setup', ...
            'fundamental_band_mask_partial_support', ...
            'CerUPP:FundamentalBandMaskPartialSupport', ...
            ['Fundamental-band diagnostic mask only partially covers the requested %.1f-%.1f nm band. ', ...
             'Current sampled support is %.1f-%.1f nm across %d bins (%.1f%% omega-cell coverage). ', ...
             'Stored masked-bin reductions remain available, and related fundamental-band plots stay enabled ', ...
             'with this partial sampled support noted in the warning/labels.'], ...
            fundamental_band_requested_lambda_min_nm, ...
            fundamental_band_requested_lambda_max_nm, ...
            fundamental_band_support.sampled_lambda_min_nm, ...
            fundamental_band_support.sampled_lambda_max_nm, ...
            fundamental_band_support.sampled_num_bins, ...
            100 * fundamental_band_support.omega_cell_coverage_fraction);
    end
end

