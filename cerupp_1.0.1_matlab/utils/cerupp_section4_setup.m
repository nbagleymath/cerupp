function section4_state = build_section4_state_local(cfg)
    if ~(isstruct(cfg.diagnostic_band_cfg) && isscalar(cfg.diagnostic_band_cfg))
        error('CerUPP:InvalidSection4DiagnosticBandCfg', ...
            'Section 4 requires one validated diagnostic_band_cfg struct from the earlier Section 3 freeze capture.');
    end
    if ~(isstruct(cfg.frozen_cfg_raw_section3_setup) && isscalar(cfg.frozen_cfg_raw_section3_setup))
        error('CerUPP:InvalidSection4RawSection3Freeze', ...
            'Section 4 requires the earlier frozen_cfg_raw_section3_setup snapshot from the Block-3 capture.');
    end
    live_diagnostic_band_cfg = driver_setup_support.validate_diagnostic_band_cfg( ...
        cfg.diagnostic_band_cfg, 'cerupp_section4_setup live diagnostic_band_cfg');
    frozen_cfg_raw_section3_setup = cfg.frozen_cfg_raw_section3_setup;
    diagnostic_band_cfg = driver_setup_support.validate_diagnostic_band_cfg( ...
        struct_utils.req_struct_field( ...
            frozen_cfg_raw_section3_setup, 'diagnostic_band_cfg', ...
            'cerupp_section4_setup.frozen_cfg_raw_section3_setup'), ...
        'cerupp_section4_setup frozen diagnostic_band_cfg');
    setup_freeze_guard = cfg.setup_freeze_guard;
    visible_runtime_knobs = struct_utils.req_struct_field( ...
        cfg, 'visible_runtime_knobs', 'cerupp_section4_setup cfg');
    cfg.visible_runtime_knobs = visible_runtime_knobs;
    cfg.diagnostic_band_cfg_live = live_diagnostic_band_cfg;

    section3_setup_state = cerupp_section3d_setup( ...
        cfg, diagnostic_band_cfg, setup_freeze_guard, ...
        frozen_cfg_raw_section3_setup);

    grid_state = section3_setup_state.grid_state;
    output_plan = section3_setup_state.output_plan;
    output_dev_cfg = section3_setup_state.output_dev_cfg;
    perf_cfg = section3_setup_state.perf_cfg;
    A_S = section3_setup_state.A_S;
    core_idx = section3_setup_state.core_idx;
    phase_diagnostic_flag = section3_setup_state.phase_diagnostic_flag;
    keldysh_effective_nla_available_flag = ...
        section3_setup_state.keldysh_effective_nla_available_flag;
    need_keldysh_effective_nla_raw_history_flag = ...
        section3_setup_state.need_keldysh_effective_nla_raw_history_flag;
    track_keldysh_effective_nla_diag_flag = ...
        section3_setup_state.track_keldysh_effective_nla_diag_flag;
    [ix_axis0, iy_axis0, x_axis0, y_axis0] = struct_utils.unpack_struct_fields( ...
        grid_state, {'ix_axis0', 'iy_axis0', 'x_axis0', 'y_axis0'}, 'grid_state');
    num_storage_steps = ceil( ...
        cfg.num_zsteps / output_plan.cadence.diagnostic_store_stride_steps);

    section4a_state = storage_support.initialize_section4a_storage_state(struct( ...
        'grid_state', struct( ...
            'x', cfg.x, ...
            'y', cfg.y, ...
            'num_x_pts', cfg.num_x_pts, ...
            'num_y_pts', cfg.num_y_pts, ...
            'core_idx', core_idx, ...
            'n', cfg.n), ...
        'field_state', struct( ...
            'A_S', A_S, ...
            'A_xy', cfg.A_xy), ...
        'output_plan', output_plan, ...
        'setup_state', struct( ...
            'num_storage_steps', num_storage_steps, ...
            'omega_fund', cfg.omega_fund, ...
            'omega_ref', cfg.omega_ref, ...
            't', cfg.t, ...
            'num_zsteps', cfg.num_zsteps, ...
            'z_domain', cfg.z_domain, ...
            'n_ratio_diag_xy', cfg.n_ratio_diag_xy, ...
            't_setup', cfg.t_setup), ...
        'physics_state', struct( ...
            'phase_diagnostic_flag', phase_diagnostic_flag, ...
            'plasma_flag', cfg.plasma_flag, ...
            'nl_absorption_flag', cfg.nl_absorption_flag, ...
            'keldysh_effective_nla_available_flag', ...
                keldysh_effective_nla_available_flag, ...
            'need_keldysh_effective_nla_raw_history_flag', ...
                need_keldysh_effective_nla_raw_history_flag, ...
            'track_keldysh_effective_nla_diag_flag', ...
                track_keldysh_effective_nla_diag_flag, ...
            'keldysh_enabled', cfg.keldysh_enabled, ...
            'ofi_branch_active_for_setup', cfg.ofi_branch_active_for_setup), ...
        'perf_cfg', perf_cfg, ...
        'output_dev_cfg', output_dev_cfg));

    section4_state = section3_setup_state;
    section4_state.diagnostic_band_cfg = diagnostic_band_cfg;
    section4_state.ix_axis0 = ix_axis0;
    section4_state.iy_axis0 = iy_axis0;
    section4_state.x_axis0 = x_axis0;
    section4_state.y_axis0 = y_axis0;
    section4_state.num_storage_steps = num_storage_steps;
    section4_state.section5a_preloop_state = section4a_state;
end

