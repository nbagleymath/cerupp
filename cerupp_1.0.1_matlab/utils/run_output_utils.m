                status_txt = 'skipped';
            elseif ok
                status_txt = 'written';
            else
                status_txt = 'failed';
            end
        end

        function [run_warn_state, pointer_status] = apply_current_run_pointer_local( ...
                run_status_ctx, pointer_cfg, action_mode, run_warn_state)
            pointer_status = 'skipped';
            write_current_pointer = isfield(run_status_ctx, 'write_current_pointer') && ...
                run_status_ctx.write_current_pointer;
            if ~write_current_pointer
                return;
            end
            artifact_path_ctx = run_output_utils.resolve_run_status_artifact_paths_local( ...
                run_status_ctx);
            shared_pointer_cfg = struct( ...
                'run_bucket', artifact_path_ctx.current_pointer_root, ...
                'pointer_name', artifact_path_ctx.current_pointer_name, ...
                'phase_tag', struct_utils.opt_struct_field(pointer_cfg, 'phase_tag', run_warn_state_utils.phase_end()), ...
                'warn_key', struct_utils.opt_struct_field(pointer_cfg, 'warn_key', 'run_id_pointer_write_failed'), ...
                'warn_id', struct_utils.opt_struct_field(pointer_cfg, 'warn_id', 'CerUPP:RunStatus:RunIdPointerWriteFailed'), ...
                'failure_tag', struct_utils.opt_struct_field(pointer_cfg, 'failure_tag', 'current_run_pointer'));
            action_mode = char(string(action_mode));
            switch action_mode
                case 'write'
                    shared_pointer_cfg.run_id = struct_utils.req_struct_field( ...
                        pointer_cfg, 'run_id', 'run_output_utils.apply_current_run_pointer_local');
                    run_warn_state = checkpoint_utils.write_run_id_pointer( ...
                        shared_pointer_cfg, run_warn_state);
                    pointer_status = 'written';
                case 'delete'
                    [run_warn_state, pointer_status] = checkpoint_utils.delete_run_id_pointer( ...
                        shared_pointer_cfg, run_warn_state);
                otherwise
                    error('run_output_utils:InvalidRunStatusPointerAction', ...
                        'Unsupported run-status pointer action "%s".', action_mode);
            end
        end
