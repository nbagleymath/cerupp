classdef run_output_utils
%RUN_OUTPUT_UTILS Startup run-output path and status/pointer lifecycle helpers.
% Purpose:
% - Own run-output collision policy, path resolution, and startup mkdir/status
%   side effects separately from checkpoint/fullsave payload policy.
% - Keep artifact-path ownership and run-status opening close to the output
%   tree startup contract used by driver setup.

    methods (Static)
        function names = artifact_names()
        % Canonical run-status and pointer filenames for the run-output tree.

            names = struct( ...
                'run_status_name', 'run_status.json', ...
                'current_run_pointer_name', 'current_run_id.txt', ...
                'latest_successful_run_pointer_name', 'latest_successful_run_id.txt', ...
                'latest_propagation_complete_run_pointer_name', ...
                    'latest_propagation_complete_run_id.txt', ...
                'latest_fully_packaged_run_pointer_name', ...
                    'latest_fully_packaged_run_id.txt');
        end

        function policy = default_run_output_startup_policy()
        % Visible startup defaults for run-output collision handling.

            policy = struct( ...
                'append_timestamp_to_run_id', false, ...
                'archive_existing_run_output_root', false, ...
                'auto_timestamp_on_run_output_collision', true);
        end

        function [run_output_ctx, run_warn_state] = resolve_run_output_paths(cfg, run_warn_state)
        % Resolve startup artifact paths and emit setup-stage run-output reporting.

            [cfg, run_warn_state] = run_output_utils.normalize_policy_inputs_local(cfg, run_warn_state);
            output_root = struct_utils.opt_struct_field(cfg, 'output_root', '');
            driver_root = struct_utils.opt_struct_field(cfg, 'driver_root', '');
            run_tag = struct_utils.opt_struct_field(cfg, 'run_tag', 'default');
            startup_policy_in = struct_utils.opt_struct_field(cfg, 'output_startup_policy', struct());
            output_root_resolved = run_output_utils.resolve_output_root_local(output_root, driver_root);
            [run_tag, run_warn_state] = run_output_utils.sanitize_run_tag_local(run_tag, run_warn_state);
            startup_policy = run_output_utils.normalize_run_output_startup_policy_local(startup_policy_in);
            [artifact_paths, startup_action, auto_timestamped_run_output_root, run_warn_state] = ...
                run_output_utils.resolve_run_output_artifact_paths_local( ...
                    output_root_resolved, run_tag, startup_policy, run_warn_state);
            [run_warn_state, ~] = run_warn_state_utils.emit_info_with_phase( ...
                run_warn_state, run_warn_state_utils.phase_setup(), 'resolved_run_output_root', ...
                'Resolved run_output_root: %s', artifact_paths.run_output_root);

            run_output_ctx = struct( ...
                'output_root_resolved', output_root_resolved, ...
                'output_startup_policy', startup_policy, ...
                'append_timestamp_to_run_id', logical(startup_policy.append_timestamp_to_run_id), ...
                'archive_existing_run_output_root', logical(startup_policy.archive_existing_run_output_root), ...
                'auto_timestamp_on_run_output_collision', logical(startup_policy.auto_timestamp_on_run_output_collision), ...
                'auto_timestamped_run_output_root', logical(auto_timestamped_run_output_root), ...
                'startup_action', char(string(startup_action)), ...
                'artifact_paths', artifact_paths);
        end

        function [run_status_ctx, run_warn_state] = initialize_run_output_artifacts(cfg, run_warn_state)
        % Perform startup mkdir/status/pointer side effects.

            [cfg, run_warn_state] = run_output_utils.normalize_policy_inputs_local(cfg, run_warn_state);
            run_output_ctx = struct_utils.req_struct_field( ...
                cfg, 'run_output_ctx', 'run_output_utils.initialize_run_output_artifacts');
            output_cfg = struct_utils.opt_struct_field(cfg, 'output_cfg', struct());
            run_status_ctx = struct_utils.opt_struct_field(cfg, 'run_status_ctx', struct());
            restart_compat_version = double(struct_utils.opt_struct_field( ...
                cfg, 'restart_compat_version', NaN));
            release_version = char(string(struct_utils.opt_struct_field( ...
                cfg, 'release_version', '')));
            curr_cerupp_version = char(string(struct_utils.opt_struct_field( ...
                cfg, 'curr_cerupp_version', '')));
            if ~isstruct(output_cfg)
                error('run_output_utils:InvalidOutputCfg', ...
                    'cfg.output_cfg must be a struct or [].');
            end
            if ~isstruct(run_status_ctx)
                run_status_ctx = struct();
            end
            if ~(isstruct(run_output_ctx) && isscalar(run_output_ctx))
                error('run_output_utils:InvalidRunOutputCtx', ...
                    'cfg.run_output_ctx must be a scalar struct.');
            end

            artifact_paths = struct_utils.req_struct_field( ...
                run_output_ctx, 'artifact_paths', ...
                'run_output_utils.initialize_run_output_artifacts');
            startup_action = char(string(struct_utils.req_struct_field( ...
                run_output_ctx, 'startup_action', ...
                'run_output_utils.initialize_run_output_artifacts')));

            run_output_utils.ensure_target_dir_ready_local(artifact_paths.run_bucket);
            [run_warn_state, archive_path] = run_output_utils.materialize_run_output_root_local( ...
                artifact_paths.run_bucket, artifact_paths.run_output_root, artifact_paths.run_id, ...
                startup_action, run_warn_state);
            if strcmp(startup_action, 'archive_existing_run_output_root')
                run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                    run_warn_state, run_warn_state_utils.phase_setup(), ...
                    'setup_run_id_archived_existing_output', ...
                    'CerUPP:RunIdExistsArchived', ...
                    ['run_output_root already existed for run_id="%s". ' ...
                     'Renamed previous run directory to "%s" and created a fresh run directory.'], ...
                    artifact_paths.run_id, archive_path);
            end

            need_plot_output_root = logical(struct_utils.opt_struct_field( ...
                output_cfg, 'save_outputs_as_fig', false)) || ...
                logical(struct_utils.opt_struct_field(output_cfg, 'save_outputs_as_png', false));
            need_csv_output_root = logical(struct_utils.opt_struct_field( ...
                output_cfg, 'export_csv_debug_flag', false));
            need_checkpoint_output_root = logical(struct_utils.opt_struct_field( ...
                output_cfg, 'intermediate_saves', false)) || ...
                logical(struct_utils.opt_struct_field(output_cfg, 'save_final_restart_checkpoint_flag', false)) || ...
                logical(struct_utils.opt_struct_field(output_cfg, 'checkpoint_full_save_flag', false));
            if need_plot_output_root && ~exist(artifact_paths.plots.root, 'dir')
                run_output_utils.ensure_target_dir_ready_local(artifact_paths.plots.root);
            end
            if ~exist(artifact_paths.csv.root, 'dir')
                run_output_utils.ensure_target_dir_ready_local(artifact_paths.csv.root);
            end
            if need_checkpoint_output_root && ~exist(artifact_paths.checkpoints.root, 'dir')
                run_output_utils.ensure_target_dir_ready_local(artifact_paths.checkpoints.root);
            end

            run_status_ctx.artifact_paths = artifact_paths;
            run_status_ctx.enabled = logical(struct_utils.opt_struct_field( ...
                output_cfg, 'write_run_status_flag', false));
            run_status_ctx.write_current_pointer = logical(struct_utils.opt_struct_field( ...
                output_cfg, 'write_current_run_pointer_flag', false));
            if run_status_ctx.enabled || run_status_ctx.write_current_pointer
                run_status_ctx.started_at_utc = checkpoint_utils.current_iso_utc_timestamp();
            end
            [run_warn_state, run_status_ctx] = run_output_utils.open_run_attempt_status( ...
                struct( ...
                    'run_status_ctx', run_status_ctx, ...
                    'restart_compat_version', restart_compat_version, ...
                    'release_version', release_version, ...
                    'curr_cerupp_version', curr_cerupp_version, ...
                    'pointer_phase_tag', run_warn_state_utils.phase_setup(), ...
                    'pointer_warn_key', 'setup_current_run_pointer_write_failed', ...
                    'pointer_warn_id', 'CerUPP:RunStatus:CurrentRunPointerWriteFailed', ...
                    'pointer_failure_tag', 'current_run_pointer', ...
                    'status_phase_tag', run_warn_state_utils.phase_setup(), ...
                    'status_warn_key', 'setup_run_status_write_failed', ...
                    'status_warn_id', 'CerUPP:RunStatus:RunStatusSetupWriteFailed', ...
                    'status_failure_tag', 'run_status_setup_write'), ...
                run_warn_state);
        end

        function [run_warn_state, run_status_ctx] = open_run_attempt_status(cfg, run_warn_state)
        % Publish setup-time launch status and current-run pointer.

            [cfg, run_warn_state] = run_output_utils.normalize_policy_inputs_local(cfg, run_warn_state);
            run_status_ctx = struct_utils.opt_struct_field(cfg, 'run_status_ctx', struct());
            if ~isstruct(run_status_ctx)
                run_status_ctx = struct();
                return;
            end
            [run_id, run_output_root] = run_output_utils.resolve_run_status_identity_local( ...
                run_status_ctx);
            restart_compat_version = double(struct_utils.opt_struct_field( ...
                cfg, 'restart_compat_version', NaN));
            release_version = char(string(struct_utils.opt_struct_field(cfg, 'release_version', '')));
            curr_cerupp_version = char(string(struct_utils.opt_struct_field( ...
                cfg, 'curr_cerupp_version', '')));
            phase_specs = run_output_utils.build_run_status_phase_specs_local('setup');
            [run_warn_state, ~] = run_output_utils.apply_current_run_pointer_local( ...
                run_status_ctx, struct( ...
                    'run_id', run_id, ...
                    'phase_tag', struct_utils.opt_struct_field(cfg, 'pointer_phase_tag', phase_specs.pointer_phase_tag), ...
                    'warn_key', struct_utils.opt_struct_field(cfg, 'pointer_warn_key', phase_specs.pointer_warn_key), ...
                    'warn_id', struct_utils.opt_struct_field(cfg, 'pointer_warn_id', phase_specs.pointer_warn_id), ...
                    'failure_tag', struct_utils.opt_struct_field(cfg, 'pointer_failure_tag', phase_specs.pointer_failure_tag)), ...
                'write', run_warn_state);
            status_payload = checkpoint_utils.build_run_status_payload(struct( ...
                'run_id', run_id, ...
                'run_output_root', run_output_root, ...
                'started_at_utc', struct_utils.opt_struct_field(run_status_ctx, 'started_at_utc', ''), ...
                'state_name', 'launched', ...
                'error_id', '', ...
                'error_message', '', ...
                'restart_compat_version', restart_compat_version, ...
                'release_version', release_version, ...
                'curr_cerupp_version', curr_cerupp_version));
            [run_warn_state, ~] = run_output_utils.publish_run_status_payload_local( ...
                run_status_ctx, status_payload, struct( ...
                    'phase_tag', struct_utils.opt_struct_field(cfg, 'status_phase_tag', phase_specs.status_phase_tag), ...
                    'warn_key', struct_utils.opt_struct_field(cfg, 'status_warn_key', phase_specs.status_warn_key), ...
                    'warn_id', struct_utils.opt_struct_field(cfg, 'status_warn_id', phase_specs.status_warn_id), ...
                    'failure_tag', struct_utils.opt_struct_field(cfg, 'status_failure_tag', phase_specs.status_failure_tag)), ...
                run_warn_state);
        end

        function [run_warn_state, run_status_ctx] = update_run_progress_status(cfg, run_warn_state)
        % Publish a nonterminal running status with propagation progress fields.

            [cfg, run_warn_state] = run_output_utils.normalize_policy_inputs_local(cfg, run_warn_state);
            run_status_ctx = struct_utils.opt_struct_field(cfg, 'run_status_ctx', struct());
            if ~isstruct(run_status_ctx)
                run_status_ctx = struct();
                return;
            end
            if ~(isfield(run_status_ctx, 'enabled') && run_status_ctx.enabled)
                return;
            end

            [run_id, run_output_root] = run_output_utils.resolve_run_status_identity_local( ...
                run_status_ctx);
            status_extra_fields = struct_utils.opt_struct_field(cfg, 'status_extra_fields', struct());
            status_payload = checkpoint_utils.build_run_status_payload(struct( ...
                'run_id', run_id, ...
                'run_output_root', run_output_root, ...
                'started_at_utc', struct_utils.opt_struct_field(run_status_ctx, 'started_at_utc', ''), ...
                'state_name', 'running', ...
                'error_id', '', ...
                'error_message', '', ...
                'restart_compat_version', double(struct_utils.opt_struct_field( ...
                    cfg, 'restart_compat_version', NaN)), ...
                'release_version', char(string(struct_utils.opt_struct_field( ...
                    cfg, 'release_version', ''))), ...
                'curr_cerupp_version', char(string(struct_utils.opt_struct_field( ...
                    cfg, 'curr_cerupp_version', '')))));
            status_payload = run_output_utils.merge_status_extra_fields_local( ...
                status_payload, status_extra_fields);
            [run_warn_state, ~] = run_output_utils.publish_run_status_payload_local( ...
                run_status_ctx, status_payload, struct( ...
                    'phase_tag', struct_utils.opt_struct_field(cfg, 'status_phase_tag', 'propagation'), ...
                    'warn_key', struct_utils.opt_struct_field( ...
                        cfg, 'status_warn_key', 'progress_run_status_write_failed'), ...
                    'warn_id', struct_utils.opt_struct_field( ...
                        cfg, 'status_warn_id', 'CerUPP:RunStatus:ProgressRunStatusWriteFailed'), ...
                    'failure_tag', struct_utils.opt_struct_field( ...
                        cfg, 'status_failure_tag', 'run_status_progress_write')), ...
                run_warn_state);
        end

        function [run_warn_state, run_status_ctx] = finalize_run_attempt_status(cfg, run_warn_state)
        % Publish final status and retire the current-run pointer at run end.

            [cfg, run_warn_state] = run_output_utils.normalize_policy_inputs_local(cfg, run_warn_state);
            run_status_ctx = struct_utils.opt_struct_field(cfg, 'run_status_ctx', struct());
            if ~isstruct(run_status_ctx)
                run_status_ctx = struct();
                return;
            end
            attempt_state = char(string(struct_utils.opt_struct_field(cfg, 'attempt_state', 'failed')));
            error_id = char(string(struct_utils.opt_struct_field(cfg, 'error_id', '')));
            error_message = char(string(struct_utils.opt_struct_field(cfg, 'error_message', '')));
            restart_compat_version = double(struct_utils.opt_struct_field(cfg, 'restart_compat_version', NaN));
            release_version = char(string(struct_utils.opt_struct_field(cfg, 'release_version', '')));
            curr_cerupp_version = char(string(struct_utils.opt_struct_field( ...
                cfg, 'curr_cerupp_version', '')));
            status_extra_fields = struct_utils.opt_struct_field(cfg, 'status_extra_fields', struct());
            [run_id, run_output_root] = run_output_utils.resolve_run_status_identity_local( ...
                run_status_ctx);
            status_payload = checkpoint_utils.build_run_status_payload(struct( ...
                'run_id', run_id, ...
                'run_output_root', run_output_root, ...
                'started_at_utc', struct_utils.opt_struct_field(run_status_ctx, 'started_at_utc', ''), ...
                'state_name', attempt_state, ...
                'error_id', error_id, ...
                'error_message', error_message, ...
                'restart_compat_version', restart_compat_version, ...
                'release_version', release_version, ...
                'curr_cerupp_version', curr_cerupp_version));
            status_payload = run_output_utils.merge_status_extra_fields_local( ...
                status_payload, status_extra_fields);
            status_write_attempted = isfield(run_status_ctx, 'enabled') && run_status_ctx.enabled;
            [run_warn_state, status_write_ok] = run_output_utils.publish_run_status_payload_local( ...
                run_status_ctx, status_payload, struct( ...
                    'phase_tag', struct_utils.opt_struct_field(cfg, 'status_phase_tag', run_warn_state_utils.phase_end()), ...
                    'warn_key', struct_utils.opt_struct_field(cfg, 'status_warn_key', 'run_status_write_failed'), ...
                    'warn_id', struct_utils.opt_struct_field(cfg, 'status_warn_id', 'CerUPP:RunStatus:RunStatusWriteFailed'), ...
                    'failure_tag', struct_utils.opt_struct_field(cfg, 'status_failure_tag', 'run_status_final_write')), ...
                run_warn_state);
            status_write_retry_attempted = false;
            status_write_retry_ok = false;
            if logical(status_write_attempted) && ~logical(status_write_ok)
                status_write_retry_attempted = true;
                [run_warn_state, status_write_retry_ok] = ...
                    run_output_utils.publish_run_status_payload_local( ...
                        run_status_ctx, status_payload, struct( ...
                            'phase_tag', struct_utils.opt_struct_field( ...
                                cfg, 'status_phase_tag', run_warn_state_utils.phase_end()), ...
                            'warn_key', struct_utils.opt_struct_field( ...
                                cfg, 'status_warn_key', 'run_status_write_failed'), ...
                            'warn_id', struct_utils.opt_struct_field( ...
                                cfg, 'status_warn_id', 'CerUPP:RunStatus:RunStatusWriteFailed'), ...
                            'failure_tag', struct_utils.opt_struct_field( ...
                                cfg, 'status_failure_tag', 'run_status_final_write')), ...
                        run_warn_state);
                status_write_ok = logical(status_write_retry_ok);
            end
            current_pointer_status = 'skipped';
            [run_warn_state, current_pointer_status] = ...
                run_output_utils.apply_current_run_pointer_local( ...
                    run_status_ctx, struct( ...
                        'phase_tag', struct_utils.opt_struct_field( ...
                            cfg, 'pointer_phase_tag', run_warn_state_utils.phase_end()), ...
                        'warn_key', struct_utils.opt_struct_field( ...
                            cfg, 'pointer_warn_key', 'current_run_pointer_delete_failed'), ...
                        'warn_id', struct_utils.opt_struct_field( ...
                            cfg, 'pointer_warn_id', ...
                            'CerUPP:RunStatus:CurrentRunPointerDeleteFailed'), ...
                        'failure_tag', struct_utils.opt_struct_field( ...
                            cfg, 'pointer_failure_tag', 'current_run_pointer_delete')), ...
                    'delete', run_warn_state);
            current_pointer_delete_ok = any(strcmp(current_pointer_status, ...
                {'skipped', 'absent', 'deleted'}));
            status_write_post_pointer_attempted = false;
            status_write_post_pointer_ok = true;
            if logical(status_write_attempted) && logical(status_write_ok) && ...
                    any(strcmp(attempt_state, {'success', 'succeeded', 'partial_failed'})) && ...
                    ~current_pointer_delete_ok
                status_write_post_pointer_attempted = true;
                status_extra_fields_pointer_cleanup = status_extra_fields;
                status_extra_fields_pointer_cleanup.attempt_reason = ...
                    'normal_exit_with_current_pointer_cleanup_failure';
                status_payload_pointer_cleanup = checkpoint_utils.build_run_status_payload(struct( ...
                    'run_id', run_id, ...
                    'run_output_root', run_output_root, ...
                    'started_at_utc', struct_utils.opt_struct_field(run_status_ctx, 'started_at_utc', ''), ...
                    'state_name', 'partial_failed', ...
                    'error_id', 'CerUPP:RunStatus:CurrentRunPointerDeleteFailed', ...
                    'error_message', 'Could not retire current_run_id.txt at run end.', ...
                    'restart_compat_version', restart_compat_version, ...
                    'release_version', release_version, ...
                    'curr_cerupp_version', curr_cerupp_version));
                status_payload_pointer_cleanup = ...
                    run_output_utils.merge_status_extra_fields_local( ...
                        status_payload_pointer_cleanup, ...
                        status_extra_fields_pointer_cleanup);
                [run_warn_state, status_write_post_pointer_ok] = ...
                    run_output_utils.publish_run_status_payload_local( ...
                        run_status_ctx, status_payload_pointer_cleanup, struct( ...
                            'phase_tag', struct_utils.opt_struct_field( ...
                                cfg, 'status_phase_tag', run_warn_state_utils.phase_end()), ...
                            'warn_key', struct_utils.opt_struct_field( ...
                                cfg, 'status_warn_key', 'run_status_write_failed'), ...
                            'warn_id', struct_utils.opt_struct_field( ...
                                cfg, 'status_warn_id', 'CerUPP:RunStatus:RunStatusWriteFailed'), ...
                            'failure_tag', struct_utils.opt_struct_field( ...
                                cfg, 'status_failure_tag', 'run_status_final_write')), ...
                        run_warn_state);
                status_write_ok = logical(status_write_ok) && ...
                    logical(status_write_post_pointer_ok);
            end
            run_status_ctx.last_finalize_status = struct( ...
                'status_write_attempted', logical(status_write_attempted), ...
                'status_write_retry_attempted', ...
                    logical(status_write_retry_attempted), ...
                'status_write_retry_ok', ...
                    (~logical(status_write_retry_attempted)) || ...
                    logical(status_write_retry_ok), ...
                'status_write_post_pointer_attempted', ...
                    logical(status_write_post_pointer_attempted), ...
                'status_write_post_pointer_ok', ...
                    logical(status_write_post_pointer_ok), ...
                'status_write_ok', ~logical(status_write_attempted) || ...
                    logical(status_write_ok), ...
                'status_write_status', ...
                    run_output_utils.ternary_status_local( ...
                        logical(status_write_attempted), ...
                        logical(status_write_ok)), ...
                'current_pointer_delete_attempted', ...
                    ~strcmp(current_pointer_status, 'skipped'), ...
                'current_pointer_delete_ok', current_pointer_delete_ok, ...
                'current_pointer_delete_status', char(current_pointer_status));
            if ~logical(status_write_attempted) || logical(status_write_ok)
                if isfield(run_status_ctx, 'enabled')
                    run_status_ctx.enabled = false;
                end
                if isfield(run_status_ctx, 'write_current_pointer')
                    run_status_ctx.write_current_pointer = false;
                end
            end
        end

        function [run_warn_state, run_status_ctx] = ...
                republish_final_run_status_after_pointer_writes(cfg, run_warn_state)
        % Refresh final run_status.json after the late latest-pointer writes.

            [cfg, run_warn_state] = run_output_utils.normalize_policy_inputs_local(cfg, run_warn_state);
            run_status_ctx = struct_utils.opt_struct_field(cfg, 'run_status_ctx', struct());
            if ~isstruct(run_status_ctx)
                run_status_ctx = struct();
                return;
            end

            finalize_status = struct_utils.opt_struct_field( ...
                run_status_ctx, 'last_finalize_status', struct());
            if ~(isstruct(finalize_status) && isscalar(finalize_status))
                finalize_status = struct();
            end

            republish_attempted = false;
            republish_ok = true;
            if logical(struct_utils.opt_struct_field( ...
                    finalize_status, 'status_write_attempted', false)) && ...
                    logical(struct_utils.opt_struct_field( ...
                    finalize_status, 'status_write_ok', true))
                republish_attempted = true;
                [run_id, run_output_root] = run_output_utils.resolve_run_status_identity_local( ...
                    run_status_ctx);
                status_payload = checkpoint_utils.build_run_status_payload(struct( ...
                    'run_id', run_id, ...
                    'run_output_root', run_output_root, ...
                    'started_at_utc', struct_utils.opt_struct_field( ...
                        run_status_ctx, 'started_at_utc', ''), ...
                    'state_name', char(string(struct_utils.opt_struct_field( ...
                        cfg, 'attempt_state', 'failed'))), ...
                    'error_id', char(string(struct_utils.opt_struct_field( ...
                        cfg, 'error_id', ''))), ...
                    'error_message', char(string(struct_utils.opt_struct_field( ...
                        cfg, 'error_message', ''))), ...
                    'restart_compat_version', double(struct_utils.opt_struct_field( ...
                        cfg, 'restart_compat_version', NaN)), ...
                    'release_version', char(string(struct_utils.opt_struct_field( ...
                        cfg, 'release_version', ''))), ...
                    'curr_cerupp_version', char(string(struct_utils.opt_struct_field( ...
                        cfg, 'curr_cerupp_version', '')))));
                status_payload = run_output_utils.merge_status_extra_fields_local( ...
                    status_payload, struct_utils.opt_struct_field( ...
                    cfg, 'status_extra_fields', struct()));
                republish_ctx = run_status_ctx;
                republish_ctx.enabled = true;
                [run_warn_state, republish_ok] = ...
                    run_output_utils.publish_run_status_payload_local( ...
                        republish_ctx, status_payload, struct( ...
                            'phase_tag', struct_utils.opt_struct_field( ...
                                cfg, 'status_phase_tag', ...
                                run_warn_state_utils.phase_end()), ...
                            'warn_key', struct_utils.opt_struct_field( ...
                                cfg, 'status_warn_key', ...
                                'run_status_write_failed'), ...
                            'warn_id', struct_utils.opt_struct_field( ...
                                cfg, 'status_warn_id', ...
                                'CerUPP:RunStatus:RunStatusWriteFailed'), ...
