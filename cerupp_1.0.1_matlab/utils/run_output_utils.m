        function [artifact_paths, startup_action, auto_timestamped_run_output_root, run_warn_state] = ...
                resolve_run_output_artifact_paths_local(output_root_resolved, run_tag, startup_policy, run_warn_state)
            auto_timestamped_run_output_root = false;
            if startup_policy.append_timestamp_to_run_id
                run_id = sprintf('%s_%s', run_tag, datestr(now, 'yyyymmdd_HHMMSS'));
            else
                run_id = run_tag;
            end
            run_id = regexprep(run_id, '[^A-Za-z0-9_-]', '_');
            run_bucket = fullfile(output_root_resolved, ['run_' run_tag]);
            run_output_root = fullfile(run_bucket, run_id);
            startup_action = 'create_new_run_output_root';
            if exist(run_output_root, 'dir')
                if startup_policy.archive_existing_run_output_root
                    startup_action = 'archive_existing_run_output_root';
                elseif startup_policy.auto_timestamp_on_run_output_collision || ...
                        startup_policy.append_timestamp_to_run_id
                    if startup_policy.append_timestamp_to_run_id
                        [run_id, run_output_root] = ...
                            run_output_utils.find_unique_collision_run_root_from_base_local( ...
                            run_bucket, run_id);
                    else
                        [run_id, run_output_root] = ...
                            run_output_utils.find_unique_collision_run_root_local( ...
                            run_bucket, run_tag);
                    end
                    auto_timestamped_run_output_root = true;
                    startup_action = 'auto_timestamp_new_run_output_root';
                    run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                        run_warn_state, run_warn_state_utils.phase_setup(), ...
                        'setup_run_id_auto_timestamped_existing_output', ...
                        'CerUPP:RunOutput:IdExistsAutoTimestamped', ...
                        ['run_output_root already existed for run_tag="%s". ' ...
                         'Created unique run directory "%s" instead of failing startup.'], ...
                        run_tag, run_output_root);
                else
                    error('CerUPP:RunOutputRootExists', ...
                        ['run_output_root="%s" already exists. Refusing automatic archival by default. ', ...
                         'Set append_timestamp_to_run_id=true for unique output trees or ', ...
                         'archive_existing_run_output_root=true to archive the existing tree explicitly.'], ...
                        run_output_root);
                end
            end
            artifact_paths = run_output_utils.build_artifact_paths_local( ...
                run_bucket, run_output_root, run_id);
        end

