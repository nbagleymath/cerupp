                        'pointer_warn_id', 'CerUPP:RunStatus:CurrentRunPointerDeleteFailed', ...
                        'pointer_failure_tag', 'current_run_pointer_delete');
                case 'caught_error'
                    phase_specs = struct( ...
                        'status_phase_tag', 'end', ...
                        'status_warn_key', 'failed_run_status_write_failed', ...
                        'status_warn_id', 'CerUPP:RunStatus:FailedRunStatusWriteFailed', ...
                        'status_failure_tag', 'run_status_failure_write', ...
                        'pointer_phase_tag', 'end', ...
                        'pointer_warn_key', 'failed_current_run_pointer_delete_failed', ...
                        'pointer_warn_id', 'CerUPP:RunStatus:FailedCurrentRunPointerDeleteFailed', ...
                        'pointer_failure_tag', 'current_run_pointer_delete');
                otherwise
                    error('run_output_utils:InvalidFinalizeRunAttemptStatusMode', ...
                        'Unsupported run-status lifecycle mode "%s".', mode_tag);
            end
        end

        function status_payload = merge_status_extra_fields_local(status_payload, status_extra_fields)
            if isempty(status_extra_fields)
                return;
            end
            if ~(isstruct(status_extra_fields) && isscalar(status_extra_fields))
                error('run_output_utils:InvalidRunStatusExtraFields', ...
                    'status_extra_fields must be one scalar struct when provided.');
            end
            extra_field_names = fieldnames(status_extra_fields);
            for field_idx = 1:numel(extra_field_names)
                field_name = extra_field_names{field_idx};
                if ~isvarname(field_name)
                    error('run_output_utils:InvalidRunStatusExtraFieldName', ...
                        'status_extra_fields contains invalid field name "%s".', field_name);
                end
                if isfield(status_payload, field_name)
                    error('run_output_utils:ConflictingRunStatusExtraField', ...
                        ['status_extra_fields.%s conflicts with one built-in run-status ', ...
                         'field. Use a distinct extra field name.'], field_name);
                end
                status_payload.(field_name) = status_extra_fields.(field_name);
            end
        end

        function [run_warn_state, save_ok] = publish_run_status_payload_local( ...
                run_status_ctx, status_payload, status_cfg, run_warn_state)
            save_ok = false;
            if ~(isfield(run_status_ctx, 'enabled') && run_status_ctx.enabled)
                save_ok = true;
                return;
            end
            artifact_path_ctx = run_output_utils.resolve_run_status_artifact_paths_local( ...
                run_status_ctx);
            [run_warn_state, save_ok] = checkpoint_utils.write_run_status_file( ...
                struct( ...
                    'run_bucket', artifact_path_ctx.status_root, ...
                    'status_name', artifact_path_ctx.status_name, ...
                    'status_payload', status_payload, ...
                    'phase_tag', struct_utils.opt_struct_field(status_cfg, 'phase_tag', run_warn_state_utils.phase_end()), ...
                    'warn_key', struct_utils.opt_struct_field(status_cfg, 'warn_key', 'run_status_write_failed'), ...
                    'warn_id', struct_utils.opt_struct_field(status_cfg, 'warn_id', 'CerUPP:RunStatus:RunStatusWriteFailed'), ...
                    'failure_tag', struct_utils.opt_struct_field(status_cfg, 'failure_tag', 'run_status_final_write')), ...
                run_warn_state);
        end

        function status_txt = ternary_status_local(attempted, ok)
