        function [run_id, run_output_root] = find_unique_collision_run_root_local(run_bucket, run_tag)
            collision_stamp = datestr(now, 'yyyymmdd_HHMMSS');
            collision_run_id_base = regexprep( ...
                sprintf('%s_%s', run_tag, collision_stamp), '[^A-Za-z0-9_-]', '_');
            [run_id, run_output_root] = ...
                run_output_utils.find_unique_collision_run_root_from_base_local( ...
                run_bucket, collision_run_id_base);
        end

        function [run_id, run_output_root] = ...
                find_unique_collision_run_root_from_base_local( ...
                run_bucket, collision_run_id_base)
            run_id = collision_run_id_base;
            run_output_root = fullfile(run_bucket, run_id);
            collision_idx = 0;
            while exist(run_output_root, 'dir')
                collision_idx = collision_idx + 1;
                run_id = sprintf('%s_%02d', collision_run_id_base, collision_idx);
                run_output_root = fullfile(run_bucket, run_id);
                if collision_idx > 999
                    error('CerUPP:RunIdTimestampCollision', ...
                        ['Could not resolve a unique run directory from base run_id="%s". ', ...
                         'Tried suffixes up to %d.'], ...
                        collision_run_id_base, collision_idx);
                end
            end
        end

        function [run_warn_state, archive_path] = materialize_run_output_root_local( ...
                run_bucket, run_output_root, run_id, startup_action, run_warn_state)
            archive_path = '';
            if ~exist(run_output_root, 'dir')
                run_output_utils.ensure_target_dir_ready_local(run_output_root);
                return;
            end
            switch char(string(startup_action))
                case 'create_new_run_output_root'
                    error('CerUPP:RunOutputRootMaterializeCollision', ...
                        ['run_output_root="%s" appeared after path resolution but before startup initialization. ', ...
                         'Refusing silent reuse.'], ...
                        run_output_root);
                case 'auto_timestamp_new_run_output_root'
                    archive_path = run_output_utils.build_unique_archive_path_local( ...
                        run_bucket, run_id, run_output_root);
                    [ok_move, move_msg, move_msgid] = movefile( ...
                        run_output_root, archive_path);
                    if ~ok_move
                        error('CerUPP:RunIdArchiveFailed', ...
                            ['Failed to archive colliding timestamped run_output_root="%s" to "%s" before startup initialization. ' ...
                             'movefile error (%s): %s'], ...
                            run_output_root, archive_path, move_msgid, move_msg);
                    end
                    run_output_utils.ensure_target_dir_ready_local(run_output_root);
                case 'archive_existing_run_output_root'
                    archive_path = run_output_utils.build_unique_archive_path_local(run_bucket, run_id, run_output_root);
                    [ok_move, move_msg, move_msgid] = movefile(run_output_root, archive_path);
                    if ~ok_move
                        error('CerUPP:RunIdArchiveFailed', ...
                            ['Failed to archive existing run_output_root="%s" to "%s" before starting new run. ' ...
                             'movefile error (%s): %s'], ...
                            run_output_root, archive_path, move_msgid, move_msg);
                    end
                    run_output_utils.ensure_target_dir_ready_local(run_output_root);
                otherwise
                    error('run_output_utils:UnknownRunOutputStartupAction', ...
                        'Unknown run-output startup_action "%s".', startup_action);
            end
        end

        function archive_path = build_unique_archive_path_local(run_bucket, run_id, run_output_root)
            archive_stamp = datestr(now, 'yyyymmdd_HHMMSS');
            archive_try = fullfile(run_bucket, sprintf('%s_old_pre_%s', run_id, archive_stamp));
            archive_idx = 0;
            while exist(archive_try, 'dir')
                archive_idx = archive_idx + 1;
                archive_try = fullfile(run_bucket, ...
                    sprintf('%s_old_pre_%s_%02d', run_id, archive_stamp, archive_idx));
                if archive_idx > 999
                    error('CerUPP:RunIdArchiveCollision', ...
                        ['Could not resolve a unique archive directory for existing run_output_root="%s". ' ...
                         'Tried timestamped suffixes up to %d.'], run_output_root, archive_idx);
                end
            end
            archive_path = archive_try;
        end

        function ensure_target_dir_ready_local(target_dir)
            if isempty(target_dir)
                target_dir = '.';
            end
            if exist(target_dir, 'dir') ~= 7
                [ok_mkdir, mkdir_msg, mkdir_msgid] = mkdir(target_dir);
                if ~ok_mkdir && (exist(target_dir, 'dir') ~= 7)
                    error('run_output_utils:DirCreateFailed', ...
                        'Could not create directory "%s" (%s): %s', ...
                        target_dir, char(string(mkdir_msgid)), char(string(mkdir_msg)));
                end
            end
        end

        function phase_specs = build_run_status_phase_specs_local(mode_tag)
            if nargin < 1 || isempty(mode_tag)
                mode_tag = 'normal_exit';
            end
            mode_tag = char(string(mode_tag));
            switch mode_tag
                case 'setup'
                    phase_specs = struct( ...
                        'status_phase_tag', run_warn_state_utils.phase_setup(), ...
                        'status_warn_key', 'setup_run_status_write_failed', ...
                        'status_warn_id', 'CerUPP:RunStatus:RunStatusWriteFailed', ...
                        'status_failure_tag', 'run_status_setup_write', ...
                        'pointer_phase_tag', run_warn_state_utils.phase_setup(), ...
                        'pointer_warn_key', 'setup_current_run_pointer_write_failed', ...
                        'pointer_warn_id', 'CerUPP:RunStatus:CurrentRunPointerWriteFailed', ...
                        'pointer_failure_tag', 'current_run_pointer');
                case 'normal_exit'
                    phase_specs = struct( ...
                        'status_phase_tag', 'end', ...
                        'status_warn_key', 'final_run_status_write_failed', ...
                        'status_warn_id', 'CerUPP:RunStatus:FinalRunStatusWriteFailed', ...
