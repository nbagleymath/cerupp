        function core_idx_out = validate_core_geometry_local(core_idx_in, mask_2_d, nx, ny)
        % Boundary-only core-geometry validation for propagation-loop reuse.

            nxy = nx * ny;
            if isempty(core_idx_in)
                error('CerUPP:DriverEmptyCoreIdx', ...
                    'core_idx must be nonempty.');
            end

            if islogical(core_idx_in)
                error('CerUPP:DriverCoreIdxLogicalRejected', ...
                    'core_idx must be a numeric linear-index vector in [1,%d].', nxy);
            elseif isnumeric(core_idx_in)
                core_idx = double(core_idx_in(:));
                if any(~isfinite(core_idx))
                    error('CerUPP:DriverCoreIdxNonFinite', ...
                        'core_idx must contain only finite values.');
                end
                core_idx_round = round(core_idx);
                if any(core_idx_round ~= core_idx)
                    error('CerUPP:DriverCoreIdxNonInteger', ...
                        'core_idx must contain integer linear indices.');
                end
                core_idx = core_idx_round;
                if any(core_idx < 1) || any(core_idx > nxy)
                    error('CerUPP:DriverCoreIdxOutOfRange', ...
                        'core_idx contains values outside valid range [1, %d].', nxy);
                end
                if numel(unique(core_idx)) ~= numel(core_idx)
                    error('CerUPP:DriverCoreIdxDuplicate', ...
                        'core_idx contains duplicate entries; expected a unique active set.');
                end
                core_mask_from_idx = false(nxy, 1);
                core_mask_from_idx(core_idx) = true;
            else
                error('CerUPP:DriverCoreIdxType', ...
                    'core_idx must be numeric linear indices or a logical mask.');
            end

            if isempty(core_idx)
                error('CerUPP:DriverEmptyCoreIdxAfterParse', ...
                    'core_idx selects zero active pixels.');
            end

            if ~isempty(mask_2_d)
                if ~ismatrix(mask_2_d) || (numel(mask_2_d) ~= nxy)
                    error('CerUPP:DriverMask2DSize', ...
                        'mask_2D must be 2D with numel=%d (size [%d %d]).', nxy, nx, ny);
                end
                if islogical(mask_2_d)
                    mask_vec = mask_2_d(:);
                else
                    mask_vals = double(mask_2_d(:));
                    if any(~isfinite(mask_vals))
                        error('CerUPP:DriverMask2DNonFinite', ...
                            'mask_2D must be finite when provided.');
                    end
                    mask_vec = (mask_vals ~= 0);
                end

                if ~isequal(mask_vec, core_mask_from_idx)
                    mismatch_count = nnz(xor(mask_vec, core_mask_from_idx));
                    error('CerUPP:DriverCoreMaskMismatch', ...
                        ['core_idx and mask_2D select different active pixels (%d mismatch of %d). ', ...
                         'Ensure they use the same flattening convention over [nx, ny].'], ...
                        mismatch_count, nxy);
                end
            end

            core_idx_out = core_idx;
        end

