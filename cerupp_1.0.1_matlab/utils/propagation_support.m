        function plasma_book = average_plasma_book_local(book0, book1)
        % Average the sampled plasma accounting ledgers across RK2 propagated stages.

            plasma_book = book0;
            exact_valid_merged = [];
            if isfield(book0, 'exact_valid_core') && isfield(book1, 'exact_valid_core') && ...
                    ~isempty(book0.exact_valid_core) && ~isempty(book1.exact_valid_core) && ...
                    isequal(size(book0.exact_valid_core), size(book1.exact_valid_core))
                exact_valid_merged = logical(book0.exact_valid_core) & logical(book1.exact_valid_core);
                plasma_book.exact_valid_core = exact_valid_merged;
            end
            fields_average = { ...
                'drho_ofi_accepted', 'drho_ofi_applied', ...
                'drho_aval_accepted', 'drho_aval_applied', ...
                'drho_recomb_accepted', 'drho_recomb_applied', ...
                'drho_ofi_rejected_by_cap', 'drho_aval_rejected_by_cap', ...
                'drho_recomb_limited_by_floor', 'drho_numerical_residual'};
            for k = 1:numel(fields_average)
                field_name = fields_average{k};
                if isfield(book0, field_name) && isfield(book1, field_name) && ...
                        ~isempty(book0.(field_name)) && ~isempty(book1.(field_name))
                    averaged_field = 0.5 .* (book0.(field_name) + book1.(field_name));
                    if ~isempty(exact_valid_merged) && isequal(size(averaged_field), size(exact_valid_merged))
                        averaged_field(~exact_valid_merged) = cast(NaN, 'like', averaged_field);
                    end
                    plasma_book.(field_name) = averaged_field;
                end
            end
            fields_or = {'ledger_cap_core', 'ledger_clip_core', 'ledger_repair_core'};
            for k = 1:numel(fields_or)
                field_name = fields_or{k};
                if isfield(book0, field_name) && isfield(book1, field_name) && ...
                        ~isempty(book0.(field_name)) && ~isempty(book1.(field_name)) && ...
                        isequal(size(book0.(field_name)), size(book1.(field_name)))
                    plasma_book.(field_name) = logical(book0.(field_name)) | ...
                        logical(book1.(field_name));
                end
            end
        end

