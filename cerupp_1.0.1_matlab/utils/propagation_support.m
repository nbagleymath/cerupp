        function diagnostic_store = expand_keldysh_core_history_union_local( ...
                diagnostic_store, core_idx_before_rebuild, core_idx)
        % Keep one persistent raw-core history row axis by expanding it to
        % the union of every core_idx seen so far.

            if ~(isstruct(diagnostic_store) && isscalar(diagnostic_store))
                return;
            end
            if ~(isfield(diagnostic_store, 'store_keldysh_diag_i_core') && ...
                    isfield(diagnostic_store, 'store_keldysh_diag_rho_core'))
                return;
            end
            if isempty(diagnostic_store.store_keldysh_diag_i_core) && ...
                    isempty(diagnostic_store.store_keldysh_diag_rho_core)
                if isfield(diagnostic_store, 'store_keldysh_diag_core_idx')
                    diagnostic_store.store_keldysh_diag_core_idx = core_idx(:);
                end
                return;
            end

            stored_core_idx = struct_utils.opt_struct_field( ...
                diagnostic_store, 'store_keldysh_diag_core_idx', core_idx_before_rebuild(:));
            stored_core_idx = stored_core_idx(:);
            union_core_idx = unique([stored_core_idx; core_idx(:)], 'stable');
            if isequal(stored_core_idx, union_core_idx)
                diagnostic_store.store_keldysh_diag_core_idx = union_core_idx;
                return;
            end

            diagnostic_store.store_keldysh_diag_i_core = ...
                propagation_support.expand_keldysh_core_history_array_local( ...
                    diagnostic_store.store_keldysh_diag_i_core, ...
                    stored_core_idx, union_core_idx, ...
                    'store_keldysh_diag_i_core');
