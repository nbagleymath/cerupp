                propagation_support.expand_keldysh_core_history_array_local( ...
                    diagnostic_store.store_keldysh_diag_rho_core, ...
                    stored_core_idx, union_core_idx, ...
                    'store_keldysh_diag_rho_core');
            diagnostic_store.store_keldysh_diag_core_idx = union_core_idx;
        end

        function expanded_history = expand_keldysh_core_history_array_local( ...
                history_cube, stored_core_idx, union_core_idx, field_name)
        % Expand one raw core-history cube onto the stored union row axis.

            if isempty(history_cube)
                expanded_history = history_cube;
                return;
            end
            if size(history_cube, 1) ~= numel(stored_core_idx)
                error('CerUPP:KeldyshCoreHistoryRowCountMismatch', ...
                    ['%s has %d stored rows, but the saved core-index axis has %d rows. ', ...
                     'Refusing to expand a mismatched raw Keldysh history cube.'], ...
                    field_name, size(history_cube, 1), numel(stored_core_idx));
            end
            [stored_rows_found, stored_rows_in_union] = ismember( ...
                stored_core_idx(:), union_core_idx(:));
            if ~all(stored_rows_found)
                error('CerUPP:KeldyshCoreHistoryUnionMappingFailed', ...
                    ['Could not map the saved raw Keldysh core-history rows for %s ', ...
                     'onto the rebuilt union core-index axis.'], ...
                    field_name);
            end
            expanded_history = nan( ...
                numel(union_core_idx), size(history_cube, 2), size(history_cube, 3), ...
                'like', history_cube);
            expanded_history(stored_rows_in_union, :, :) = history_cube;
        end

