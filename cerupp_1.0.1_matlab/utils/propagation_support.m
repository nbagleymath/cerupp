        function drho_xz_diag_helper = build_drho_xz_diag_helper_local( ...
                enable_drho_xz_diagnostics, core_idx, num_x_pts, iy_axis0, dt_vec, nt, like_sample)
        % Precompute the fixed axis-row and dt helpers for optional drho_xz diagnostics.

            if nargin < 7 || isempty(like_sample)
                like_sample = 0;
            end
            drho_xz_diag_helper = struct( ...
                'has_axis_rows', false, ...
                'has_valid_dt', false, ...
                'axis_core_idx', zeros(0, 1), ...
                'axis_x_idx', zeros(0, 1), ...
                'valid_dt_mask', false(1, nt), ...
                'dt_valid_row', zeros(1, 0, 'like', like_sample));
            if ~logical(enable_drho_xz_diagnostics)
                return;
            end
            dt_row = zeros(1, nt, 'like', like_sample);
            dt_row(2:end) = cast(dt_vec(:).', 'like', dt_row);
            valid_dt_mask = isfinite(dt_row) & (dt_row > 0);
            core_idx = double(core_idx(:));
            axis_core_mask = (floor((core_idx - 1) / double(num_x_pts)) + 1) == double(iy_axis0);
            axis_core_idx = find(axis_core_mask);
            axis_x_idx = mod(core_idx(axis_core_mask) - 1, double(num_x_pts)) + 1;
            drho_xz_diag_helper = struct( ...
                'has_axis_rows', ~isempty(axis_core_idx), ...
                'has_valid_dt', any(valid_dt_mask), ...
                'axis_core_idx', axis_core_idx, ...
                'axis_x_idx', axis_x_idx, ...
                'valid_dt_mask', valid_dt_mask, ...
                'dt_valid_row', reshape(dt_row(valid_dt_mask), 1, []));
        end

        function [field_full, field_2_d_workspace] = scatter_core_rows_to_full( ...
                core_rows, core_idx, nx, ny, nt, like_template, field_2_d_workspace)
            if nargin < 7 || isempty(field_2_d_workspace)
                ws = struct('workspace', [], 'core_idx_prev', []);
            elseif isnumeric(field_2_d_workspace)
                ws = struct('workspace', field_2_d_workspace, 'core_idx_prev', []);
            elseif isstruct(field_2_d_workspace) && isfield(field_2_d_workspace, 'workspace') && isfield(field_2_d_workspace, 'core_idx_prev')
                ws = struct('workspace', field_2_d_workspace.workspace, ...
                    'core_idx_prev', field_2_d_workspace.core_idx_prev);
            else
                ws = struct('workspace', [], 'core_idx_prev', []);
            end

            nxy = nx * ny;
            ws_data = ws.workspace;
            core_idx_col = core_idx(:);

            need_new_workspace = isempty(ws_data) ...
                || ~isequal(size(ws_data), [nxy, nt]) ...
                || ((~isreal(ws_data)) ~= (~isreal(like_template)));

            if need_new_workspace
                ws_data = zeros(nxy, nt, 'like', like_template);
                ws.core_idx_prev = core_idx_col;
            else
                need_cast_workspace = ~strcmp(class(ws_data), class(like_template));
                if need_cast_workspace
                    ws_data = cast(ws_data, 'like', like_template);
                end
                if isempty(ws.core_idx_prev)
                    ws_data(:) = 0;
                    ws.core_idx_prev = core_idx_col;
                elseif ~isequal(ws.core_idx_prev, core_idx_col)
                    ws_data(ws.core_idx_prev, :) = 0;
                    ws.core_idx_prev = core_idx_col;
                end
            end

            nc = numel(core_idx_col);
            if ~isequal(size(core_rows), [nc, nt])
                if (nc == 1) && isvector(core_rows) && (numel(core_rows) == nt)
                    core_rows = reshape(core_rows, [1, nt]);
                elseif (nt == 1) && isvector(core_rows) && (numel(core_rows) == nc)
                    core_rows = reshape(core_rows, [nc, 1]);
                else
                    error('struct_utils:scatter_core_rows_to_full:BadCoreRowsShape', ...
                        'core_rows must be size [Nc,Nt]=[%d,%d]; got %s.', ...
                        nc, nt, mat2str(size(core_rows)));
                end
            end
            ws_data(core_idx_col, :) = core_rows;
            field_full = reshape(ws_data, nx, ny, nt);
            ws.workspace = ws_data;
            field_2_d_workspace = ws;
        end

        function [xy, ws] = scatter_core_vec_to_xy( ...
                v_core, core_idx, nx, ny, like_template, ws)
            if nargin < 6 || isempty(ws)
                ws = struct('workspace', [], 'core_idx_prev', []);
            elseif isnumeric(ws)
                ws = struct('workspace', ws, 'core_idx_prev', []);
            elseif ~(isstruct(ws) && isfield(ws, 'workspace') && isfield(ws, 'core_idx_prev'))
                ws = struct('workspace', [], 'core_idx_prev', []);
            else
                ws = struct('workspace', ws.workspace, 'core_idx_prev', ws.core_idx_prev);
            end

            nxy = nx * ny;
            core_idx_col = core_idx(:);
            ws_data = ws.workspace;

            need_new_workspace = isempty(ws_data) ...
                || ~isequal(size(ws_data), [nxy, 1]) ...
                || ((~isreal(ws_data)) ~= (~isreal(like_template)));

            if need_new_workspace
                ws_data = zeros(nxy, 1, 'like', like_template);
                ws.core_idx_prev = core_idx_col;
            else
                need_cast_workspace = ~strcmp(class(ws_data), class(like_template));
                if need_cast_workspace
                    ws_data = cast(ws_data, 'like', like_template);
                end
                if isempty(ws.core_idx_prev)
                    ws_data(:) = 0;
                    ws.core_idx_prev = core_idx_col;
                elseif ~isequal(ws.core_idx_prev, core_idx_col)
                    ws_data(ws.core_idx_prev) = 0;
                    ws.core_idx_prev = core_idx_col;
                end
            end

            nc = numel(core_idx_col);
            if numel(v_core) ~= nc
                error('struct_utils:scatter_core_vec_to_xy:BadVCoreSize', ...
                    'v_core must have Nc=%d elements; got %d.', nc, numel(v_core));
            end
            ws_data(core_idx_col) = v_core(:);
            xy = reshape(ws_data, nx, ny);
            ws.workspace = ws_data;
        end

    end
