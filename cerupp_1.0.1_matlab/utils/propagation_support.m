                max_val = NaN;
            else
                min_val = min(finite_real_vals(:));
                max_val = max(finite_real_vals(:));
            end
            if isreal(bad_val)
                bad_val_str = sprintf('%.6e', double(bad_val));
            else
                bad_val_str = sprintf('%.6e%+.6ei', double(real(bad_val)), double(imag(bad_val)));
            end
            error('CerUPP:InvalidDiagnosticWeightMap', ...
                ['%s must stay finite, real, and > 0 when building weighted diagnostics at %s. ', ...
                 'min=%g, max=%g, first bad linear index=%d, value=%s.'], ...
                map_name, stage_name, double(min_val), double(max_val), bad_idx, bad_val_str);
        end

        function assert_scalar_owner_match_local(lhs_val, rhs_val, lhs_label, rhs_label, err_id, err_fmt)
        % Require two scalar ownership values to agree within a tight numeric tolerance.

            rel_tol = struct_utils.cerupp_numeric_threshold('rel_tol_tight');
            abs_tol = struct_utils.cerupp_numeric_threshold('abs_tol_tiny');
            scale = max([1.0, abs(double(lhs_val)), abs(double(rhs_val))]);
            delta = abs(double(lhs_val) - double(rhs_val));
            tol = double(abs_tol) + double(rel_tol) * scale;
            if delta <= tol
                return;
            end
            error(char(string(err_id)), err_fmt, ...
                char(string(lhs_label)), double(lhs_val), ...
                char(string(rhs_label)), double(rhs_val), ...
                delta, tol);
        end

