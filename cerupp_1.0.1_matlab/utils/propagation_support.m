        function kerr_n2_xy_in = build_kerr_step_payload_local( ...
                nl_index_3d, omega_window, omega_fund, n2_kerr_disable_tol, ...
                qomega_3d, use_nlse_flag, num_x_pts, num_y_pts, core_idx)
        % Build the compact Kerr payload the live steppers actually consume.
        % The Kerr stepper uses one transverse n2(x,y) map plus the
        % separate omega-only qomega(omega) factor, so a 3-D nl_index_3d
        % input is only valid here when it is effectively the same map at
        % every omega slice.

            if (ndims(nl_index_3d) <= 2) || (size(nl_index_3d, 3) <= 1)
                kerr_n2_xy = nl_index_3d(:, :, 1);
            else
                [~, kerr_fund_idx] = min(abs(omega_window(:) - omega_fund));
                kerr_fund_idx = max(1, min(size(nl_index_3d, 3), kerr_fund_idx));
                kerr_n2_xy = nl_index_3d(:, :, kerr_fund_idx);
                max_abs_n2 = max(abs(nl_index_3d(:)));
                tol_abs = max(1e-12 * double(max_abs_n2), 256 * eps(double(max_abs_n2)));
                max_delta = 0;
                for iw = 1:size(nl_index_3d, 3)
                    slice_delta = abs(nl_index_3d(:, :, iw) - kerr_n2_xy);
                    delta_i = max(slice_delta(:));
                    if delta_i > max_delta
                        max_delta = double(delta_i);
                    end
                end
                if max_delta > tol_abs
                    error('CerUPP:UnsupportedFrequencyDependentKerrMap', ...
                        ['nl_index_3d varies with omega (max |dn2|=%.6e m^2/W, tolerance=%.6e m^2/W). ', ...
                         'The live Kerr stepper applies one transverse n2(x,y) map plus the separate ', ...
                         'qomega(omega) factor, so a truly frequency-dependent Kerr map would be silently ', ...
                         'collapsed to the carrier slice. Return a frequency-independent Kerr map or extend ', ...
                         'the stepper before using omega-dependent Kerr support.'], ...
                        max_delta, tol_abs);
                end
            end

            kerr_enabled_current = any( ...
                isfinite(kerr_n2_xy(:)) & ...
                (abs(kerr_n2_xy(:)) > n2_kerr_disable_tol));
            kerr_n2_core = reshape(kerr_n2_xy, num_x_pts * num_y_pts, 1);
            kerr_fee_qomega_payload = [];
            if kerr_enabled_current && ~use_nlse_flag
                kerr_fee_qomega_payload = struct( ...
                    'qomega_w', reshape(qomega_3d, 1, []));
            end
            kerr_n2_xy_in = struct( ...
