classdef propagation_support
% PROPAGATION_SUPPORT Propagation-loop setup, step bookkeeping, and stored-output helpers.
% Keeps the per-step setup and post-step helper routines close to the loop that uses them.

    methods (Static, Hidden)
        %==================================================================
        % I. Per-step policy/runtime setup that cerupp.m reuses each step.
        %==================================================================

        function step_runtime_ctx = build_step_runtime_context_local( ...
                plasma_flag, nl_absorption_flag, diagnostics_flag, strict_stage_finite_scan_flag, ...
                need_store_intens_s, ...
                keldysh_effective_nla_available_flag, ...
                need_keldysh_effective_nla_raw_history_flag, ...
                plasma_runtime_cfg, nla_runtime_cfg, ...
                checkpoint_diag_reassembly_flag, enable_drho_xz_diagnostics, ...
                omega_window, ion_routine_flag, rho_nt_m3, ui, ...
                sigma_vec, sigma_aval_omega_fund, alpha_recombine, core_idx, dt_vec, ...
                plasma_z_rk2_flag, plasma_evolve_t_rk2_flag, ...
                axis_in_core, axis_core_row)
        % Build the one reusable step-runtime owner for the propagation loop.
        % cerupp.m still decides the live store/checkpoint booleans each step; this
        % helper freezes the stable plasma/NLA payloads once while the
        % store/checkpoint-specific wrapper is rebuilt directly from the two
        % per-step booleans.

            plasma_runtime_cfg_base = plasma_runtime_cfg;
            plasma_runtime_cfg_base.plasma_evolve_t_rk2_flag = logical(plasma_evolve_t_rk2_flag);
            nla_runtime_cfg_step_template = nla_runtime_cfg;
            nla_mode_payload = nla_support.require_runtime_mode_payload(nla_runtime_cfg_step_template);
            resolved_nla_closure = struct_utils.req_struct_field( ...
                nla_mode_payload, 'resolved_closure', ...
                'propagation_support.build_step_runtime_context_local.nla_mode_payload');
            ofi_event_accounting_requested = logical(struct_utils.opt_struct_field( ...
                resolved_nla_closure, 'nla_check_ofi_event_energy_flag', false)) || ...
                logical(struct_utils.opt_struct_field( ...
                resolved_nla_closure, 'nla_use_ofi_event_depletion_flag', false));
            nla_uses_neutral_fraction = logical(struct_utils.opt_struct_field( ...
                resolved_nla_closure, 'uses_neutral_fraction', ...
                    struct_utils.opt_struct_field(nla_runtime_cfg_step_template, 'uses_neutral_fraction', false)));
            plasma_call_template = propagation_support.build_realspace_plasma_call_local( ...
                numel(dt_vec) + 1, omega_window, ion_routine_flag, rho_nt_m3, ...
                ui, sigma_vec, sigma_aval_omega_fund, alpha_recombine, ...
                core_idx, dt_vec, plasma_runtime_cfg_base, struct(), [], false);
            nla_rk2_flag = propagation_support.resolve_nla_rk2_flag_local( ...
                nla_mode_payload, plasma_z_rk2_flag);
            submodel_templates = struct( ...
                'plasma', struct( ...
                    'plasma_flag', logical(plasma_flag), ...
                    'runtime_cfg_base', plasma_runtime_cfg_base, ...
                    'call_template', plasma_call_template, ...
                    'core_idx', core_idx, ...
                    'dt_vec', dt_vec, ...
                    'plasma_z_rk2_flag', logical(plasma_z_rk2_flag)), ...
                'nla', struct( ...
                    'nl_absorption_flag', logical(nl_absorption_flag), ...
                    'plasma_flag', logical(plasma_flag), ...
                    'runtime_cfg_base', nla_runtime_cfg_step_template, ...
                    'mode_payload', nla_mode_payload, ...
                    'nla_rk2_flag', logical(nla_rk2_flag), ...
                    'core_idx', core_idx, ...
                    'rho_nt_m3', rho_nt_m3));
            step_runtime_ctx = struct( ...
                'plasma_flag', logical(plasma_flag), ...
                'nl_absorption_flag', logical(nl_absorption_flag), ...
                'nla_uses_neutral_fraction', logical(nla_uses_neutral_fraction), ...
                'diagnostics_flag', logical(diagnostics_flag), ...
                'strict_stage_finite_scan_flag', logical(strict_stage_finite_scan_flag), ...
                'need_store_intens_s', logical(need_store_intens_s), ...
                'keldysh_effective_nla_available_flag', ...
                    logical(keldysh_effective_nla_available_flag), ...
                'need_keldysh_effective_nla_raw_history_flag', ...
                    logical(need_keldysh_effective_nla_raw_history_flag), ...
                'checkpoint_diag_reassembly_flag', logical(checkpoint_diag_reassembly_flag), ...
                'enable_drho_xz_diagnostics', logical(enable_drho_xz_diagnostics), ...
                'ofi_event_accounting_requested', logical(ofi_event_accounting_requested), ...
                'submodel_templates', submodel_templates, ...
                'axis_in_core', logical(axis_in_core), ...
                'axis_core_row', double(axis_core_row));
        end

        function stage_names = runtime_checkpoint_stage_names_local()
        % Canonical sampled advance_z_step timing stage order used everywhere.

            stage_names = {'lin1', 'guiding_total', 'kerr', 'plasma', ...
                'nla', 'linear_tail_plus_absorber', 'total'};
        end

        function timing_stage_struct = zero_runtime_checkpoint_stage_struct_local()
        % Build the zeroed canonical sampled-timing struct.

            stage_names = propagation_support.runtime_checkpoint_stage_names_local();
            timing_stage_struct = struct();
            for stage_idx = 1:numel(stage_names)
                timing_stage_struct.(stage_names{stage_idx}) = 0;
            end
        end

        function timing_stage_struct = scale_runtime_checkpoint_stage_struct_local(timing_stage_struct_in, scale_factor)
        % Scale one canonical sampled-timing struct by a finite real scalar.

            if ~(isscalar(scale_factor) && isnumeric(scale_factor) && isreal(scale_factor) && isfinite(double(scale_factor)))
                error('CerUPP:InvalidRuntimeCheckpointTimingScale', ...
                    'scale_factor must be one finite real scalar.');
            end
            timing_stage_struct = propagation_support.require_runtime_checkpoint_stage_struct_local( ...
                timing_stage_struct_in, 'runtime checkpoint timing scale input');
            stage_names = propagation_support.runtime_checkpoint_stage_names_local();
            for stage_idx = 1:numel(stage_names)
                field_name = stage_names{stage_idx};
                timing_stage_struct.(field_name) = timing_stage_struct.(field_name) * double(scale_factor);
            end
        end

        function timing_stage_struct = add_runtime_checkpoint_stage_struct_local(base_struct, update_struct)
        % Add two canonical sampled-timing structs fieldwise.

            timing_stage_struct = propagation_support.require_runtime_checkpoint_stage_struct_local( ...
                base_struct, 'runtime checkpoint timing base struct');
            update_struct = propagation_support.require_runtime_checkpoint_stage_struct_local( ...
                update_struct, 'runtime checkpoint timing update struct');
            stage_names = propagation_support.runtime_checkpoint_stage_names_local();
            for stage_idx = 1:numel(stage_names)
                field_name = stage_names{stage_idx};
                timing_stage_struct.(field_name) = timing_stage_struct.(field_name) + update_struct.(field_name);
            end
        end

        function timing = build_runtime_checkpoint_summary_from_samples_local(cfg)
        % Rebuild the end-of-run sampled substep timing summary from the accumulated in-run timing samples.

            if nargin < 1 || ~isstruct(cfg)
                error('CerUPP:InvalidRuntimeCheckpointTimingCfg', ...
                    'build_runtime_checkpoint_summary_from_samples_local requires a struct cfg.');
            end

            timing = cfg.timing;
            runtime_checkpoint_sum_report = ...
                propagation_support.resolve_runtime_checkpoint_stage_sum_local(cfg);
            if cfg.enable_advance_step_substep_timing_flag
                timing.runtime_checkpoint_sample_target = min(cfg.sampled_step_timing_target, cfg.num_zsteps);
            else
                timing.runtime_checkpoint_sample_target = 0;
            end
            timing.runtime_checkpoint_sample_count = cfg.sampled_step_timing_count;
            timing.runtime_checkpoint_extrapolated = false;
            timing.runtime_checkpoint_extrapolation_scale = NaN;
            if cfg.enable_advance_step_substep_timing_flag && (cfg.sampled_step_timing_count > 0)
                timing.runtime_checkpoint_extrapolation_scale = ...
                    cfg.num_zsteps / max(cfg.sampled_step_timing_count, 1);
                runtime_checkpoint_sum_report = ...
                    propagation_support.scale_runtime_checkpoint_stage_struct_local( ...
                        runtime_checkpoint_sum_report, ...
                        timing.runtime_checkpoint_extrapolation_scale);
                timing.runtime_checkpoint_extrapolated = ...
                    (cfg.sampled_step_timing_count < cfg.num_zsteps);
            end
            timing.runtime_checkpoint_sum = runtime_checkpoint_sum_report;
            timing.prop_loop_s = toc(cfg.t_prop);
        end

        function sample_step_timing_this_step = should_sample_step_timing_local( ...
                enable_step_timing, sampled_step_timing_count, sampled_step_timing_target)
        % Sample the first requested advance_z_step calls when substep timing is enabled.

            sample_step_timing_this_step = logical(enable_step_timing) && ...
                (double(sampled_step_timing_count) < double(sampled_step_timing_target));
        end

        function [A_F, A_S] = apply_runtime_launch_mask_local( ...
                A_F, mask_f_runtime, mask_f_w_runtime, mask, need_return_a_s)
        % Apply the launch-entry runtime mask used by step 1 and by the
        % Section 4A launch-angle report: binary spectral support cleanup,
        % real-space absorber, then binary cleanup again.

            if nargin < 5
                need_return_a_s = false;
            end

            if ~isempty(mask_f_runtime)
                A_F = A_F .* cast(mask_f_runtime ~= 0, 'like', A_F);
            end
            if ~isempty(mask_f_w_runtime)
                A_F = A_F .* cast(mask_f_w_runtime ~= 0, 'like', A_F);
            end
            a_ssf_launch = ifft2(A_F);
            a_ssf_launch = a_ssf_launch .* cast(mask, 'like', a_ssf_launch);
            A_F = fft2(a_ssf_launch);
            if ~isempty(mask_f_runtime)
                A_F = A_F .* cast(mask_f_runtime ~= 0, 'like', A_F);
            end
            if ~isempty(mask_f_w_runtime)
                A_F = A_F .* cast(mask_f_w_runtime ~= 0, 'like', A_F);
            end
            if need_return_a_s
                A_S = ifft(ifft2(A_F), [], 3);
            else
                A_S = [];
            end
        end

        function timing_stage_sum = resolve_runtime_checkpoint_stage_sum_local(cfg)
        % Accept the named sampled-timing sum as the one live runtime owner.

            if isfield(cfg, 'sampled_step_timing_sum') && ~isempty(cfg.sampled_step_timing_sum)
                timing_stage_sum = propagation_support.require_runtime_checkpoint_stage_struct_local( ...
                    cfg.sampled_step_timing_sum, ...
                    'build_runtime_checkpoint_summary_from_samples_local cfg.sampled_step_timing_sum');
                return;
            end
            timing_stage_sum = propagation_support.zero_runtime_checkpoint_stage_struct_local();
        end

        function timing_stage_struct = require_runtime_checkpoint_stage_struct_local( ...
                timing_stage_struct_in, source_label)
        % Validate one named sampled-timing struct in the canonical stage order.

            if nargin < 2 || isempty(source_label)
                source_label = 'runtime checkpoint timing struct';
            end
            stage_names = propagation_support.runtime_checkpoint_stage_names_local();
            if nargin < 1 || ~isstruct(timing_stage_struct_in) || ~isscalar(timing_stage_struct_in)
                error('CerUPP:InvalidRuntimeCheckpointTimingStruct', ...
                    '%s must be a scalar timing struct.', char(source_label));
            end
            timing_stage_struct = propagation_support.zero_runtime_checkpoint_stage_struct_local();
            for stage_idx = 1:numel(stage_names)
                field_name = stage_names{stage_idx};
                if ~isfield(timing_stage_struct_in, field_name)
                    error('CerUPP:InvalidRuntimeCheckpointTimingStruct', ...
                        '%s is missing required timing field ''%s''.', ...
                        char(source_label), field_name);
                end
                field_value = timing_stage_struct_in.(field_name);
                if ~(isnumeric(field_value) && isscalar(field_value) && isreal(field_value) && isfinite(double(field_value)))
                    error('CerUPP:InvalidRuntimeCheckpointTimingStruct', ...
                        '%s.%s must be one finite real scalar.', ...
                        char(source_label), field_name);
                end
                timing_stage_struct.(field_name) = double(field_value);
            end
        end

        function step_bookkeeping = update_post_step_bookkeeping_local(cfg)
        % Fold step-end warning ledgers, peak trackers, and sampled timing back
        % into the driver-owned run state after one completed propagation step.
        % Users changing the actual propagation physics should still edit the
        % advance_z_step call and the visible state in cerupp.m.

            if nargin < 1 || ~isstruct(cfg)
                error('CerUPP:InvalidPostStepBookkeepingCfg', ...
                    'update_post_step_bookkeeping_local requires a struct cfg.');
            end

            if isfield(cfg, 'post_step_runtime_state')
                step_bookkeeping = struct_utils.req_struct_field( ...
                    cfg, 'post_step_runtime_state', ...
                    'update_post_step_bookkeeping_local cfg');
                if ~(isstruct(step_bookkeeping) && isscalar(step_bookkeeping))
                    error('CerUPP:InvalidPostStepRuntimeState', ...
                        'cfg.post_step_runtime_state must be one scalar struct.');
                end
            else
                carry_field_names = { ...
                    'keldysh_diagnostic_peak_intensity_wm2', ...
                    'plasma_stiffness_diagnostic', ...
                    'rho_peak_over_rho_crit_ref_all_steps', ...
                    'rho_peak_over_rho_crit_ref_z', ...
                    'rho_at_peak_over_rho_crit_ref', ...
                    'rho_crit_ref_at_peak', ...
                    'rho_peak_over_rho_nt_all_steps', ...
                    'rho_peak_over_rho_nt_z', ...
                    'rho_at_peak_over_rho_nt', ...
                    'timing', ...
                    'sampled_step_timing_sum', ...
                    'sampled_step_timing_count'};
                step_bookkeeping = struct();
                for field_idx = 1:numel(carry_field_names)
                    field_name = carry_field_names{field_idx};
                    step_bookkeeping.(field_name) = cfg.(field_name);
                end
            end

            % Reuse the stepper-owned post-step peak instead of rescanning
            % the full field here just to maintain one run-global Keldysh
            % diagnostic exponent selector.
            if isfinite(step_bookkeeping.keldysh_diagnostic_peak_intensity_wm2)
                post_step_peak_intensity = struct_utils.opt_struct_field( ...
                    cfg, 'post_step_peak_intensity', NaN);
                if isfinite(post_step_peak_intensity) && ...
                        (post_step_peak_intensity > step_bookkeeping.keldysh_diagnostic_peak_intensity_wm2)
                    step_bookkeeping.keldysh_diagnostic_peak_intensity_wm2 = ...
                        post_step_peak_intensity;
                end
            end

            % Merge the optional per-step stiffness summary into the
            % run-level maxima that the driver prints later.
            if cfg.perf_cfg.show_plasma_stiffness_diagnostic_flag && ...
                    isstruct(cfg.plasma_stiffness_diagnostic_step)
                if cfg.plasma_stiffness_diagnostic_step.ofi_wdt_max > ...
                        step_bookkeeping.plasma_stiffness_diagnostic.ofi_wdt_max
                    step_bookkeeping.plasma_stiffness_diagnostic.ofi_wdt_max = ...
                        cfg.plasma_stiffness_diagnostic_step.ofi_wdt_max;
                    step_bookkeeping.plasma_stiffness_diagnostic.ofi_w_max = ...
                        cfg.plasma_stiffness_diagnostic_step.ofi_w_max;
                    step_bookkeeping.plasma_stiffness_diagnostic.dt_at_ofi = ...
                        cfg.plasma_stiffness_diagnostic_step.dt_at_ofi;
                end
                if cfg.plasma_stiffness_diagnostic_step.aval_wdt_max > ...
                        step_bookkeeping.plasma_stiffness_diagnostic.aval_wdt_max
                    step_bookkeeping.plasma_stiffness_diagnostic.aval_wdt_max = ...
                        cfg.plasma_stiffness_diagnostic_step.aval_wdt_max;
                    step_bookkeeping.plasma_stiffness_diagnostic.aval_w_max = ...
                        cfg.plasma_stiffness_diagnostic_step.aval_w_max;
                    step_bookkeeping.plasma_stiffness_diagnostic.dt_at_aval = ...
                        cfg.plasma_stiffness_diagnostic_step.dt_at_aval;
                end
                step_bookkeeping.plasma_stiffness_diagnostic.sample_count = ...
                    step_bookkeeping.plasma_stiffness_diagnostic.sample_count + ...
                    cfg.plasma_stiffness_diagnostic_step.sample_count;
            end

            % Update the run-level plasma peak trackers from the step-owned
            % rho peak when available, otherwise fall back to scanning the
            % emitted rho view for this step.
            if cfg.plasma_flag
                rho_step_peak = struct_utils.opt_struct_field(cfg, 'post_step_peak_rho', NaN);
                if ~isfinite(rho_step_peak) && ~isempty(cfg.rho)
                    rho_step_peak = max(real(cfg.rho(:)), [], 'omitnan');
                end
                if isfinite(rho_step_peak)
                    z_post_step = cfg.z_domain(cfg.curr_z_step + 1);
                    rho_crit_scale_step = ...
                        double(real(struct_utils.opt_struct_field(cfg, 'plas_dens_crit', NaN)));
                    if isfinite(rho_crit_scale_step) && (rho_crit_scale_step > 0)
                        frac_crit_step = rho_step_peak / rho_crit_scale_step;
                        if ~isfinite(step_bookkeeping.rho_peak_over_rho_crit_ref_all_steps) || ...
                                (frac_crit_step > step_bookkeeping.rho_peak_over_rho_crit_ref_all_steps)
                            step_bookkeeping.rho_peak_over_rho_crit_ref_all_steps = frac_crit_step;
                            step_bookkeeping.rho_peak_over_rho_crit_ref_z = z_post_step;
                            step_bookkeeping.rho_at_peak_over_rho_crit_ref = rho_step_peak;
                            step_bookkeeping.rho_crit_ref_at_peak = rho_crit_scale_step;
                        end
                    end
                    if isfinite(cfg.rho_nt) && (cfg.rho_nt > 0)
                        frac_nt_step = rho_step_peak / cfg.rho_nt;
                        if ~isfinite(step_bookkeeping.rho_peak_over_rho_nt_all_steps) || ...
                                (frac_nt_step > step_bookkeeping.rho_peak_over_rho_nt_all_steps)
                            step_bookkeeping.rho_peak_over_rho_nt_all_steps = frac_nt_step;
                            step_bookkeeping.rho_peak_over_rho_nt_z = z_post_step;
                            step_bookkeeping.rho_at_peak_over_rho_nt = rho_step_peak;
                        end
                    end
                end
            end

            % Fold one sampled advance_z_step timing record into the
            % running sums used by the final timing report.
            if cfg.perf_cfg.enable_advance_step_substep_timing_flag && ...
                    cfg.step_runtime_meta.timing_enabled
                if step_bookkeeping.sampled_step_timing_count == 0
                    % Keep the first sampled call for the "one representative step" report.

                    step_bookkeeping.timing.runtime_checkpoint_first = cfg.step_runtime_meta.timing;
                end
                step_bookkeeping.sampled_step_timing_sum = ...
                    propagation_support.add_runtime_checkpoint_stage_struct_local( ...
                        step_bookkeeping.sampled_step_timing_sum, ...
                        cfg.step_runtime_meta.timing);
                step_bookkeeping.sampled_step_timing_count = ...
                    step_bookkeeping.sampled_step_timing_count + 1;
            end
        end

        function [mask_f_w, run_warn_state, setup_physics_rewrite_report] = ...
                enforce_medium_sellmeier_window_local( ...
                propagation_medium_name, lambda_window, mask_f_w, run_warn_state, ...
                setup_physics_rewrite_report)
        % Audit the active spectral guard against the nominal Sellmeier range.
        % The live built-in Air/YAG dispersion helpers clamp out-of-range
        % wavelengths to their fit edges; this setup helper only reports
        % when active bins will use that clamped evaluation.

            lambda_vec = reshape(lambda_window, 1, []);
            if isempty(lambda_vec)
                error('CerUPP:DriverEmptyLambdaWindow', ...
                    'lambda_window must be nonempty before medium-range enforcement.');
            end
            if any(~isfinite(lambda_vec)) || any(~isreal(lambda_vec)) || any(lambda_vec <= 0)
                error('CerUPP:DriverInvalidLambdaWindow', ...
                    'lambda_window must contain only finite positive real values.');
            end

            if isempty(mask_f_w)
                mask_shape = [1 1 numel(lambda_vec)];
                mask_is_logical = false;
                mask_f_w_vec = ones(1, numel(lambda_vec));
            else
                mask_shape = size(mask_f_w);
                mask_is_logical = islogical(mask_f_w);
                mask_f_w_vec = reshape(double(mask_f_w), 1, []);
                if numel(mask_f_w_vec) ~= numel(lambda_vec)
                    error('CerUPP:MaskWavelengthSizeMismatch', ...
                        'mask_f_w and lambda_window must have the same number of spectral bins (%d vs %d).', ...
                        numel(mask_f_w_vec), numel(lambda_vec));
                end
            end

            % Work in microns here because the built-in Sellmeier validity
            % ranges are stated in that unit family.
            lambda_um = lambda_vec / 1e-6;
            lambda_min_um = min(lambda_um);
            lambda_max_um = max(lambda_um);
            active_mask_before = mask_f_w_vec > 0.5;
            if strcmpi(propagation_medium_name, 'AIR')
                air_nom_lo_um = 0.23;
                air_nom_hi_um = 1.69;
                invalid_low_live = active_mask_before & (lambda_um < air_nom_lo_um);
                invalid_high_live = active_mask_before & (lambda_um > air_nom_hi_um);
                if any(invalid_low_live)
                    [run_warn_state, setup_physics_rewrite_report] = driver_setup_support.record( ...
                        run_warn_state, setup_physics_rewrite_report, ...
                        'sellmeier_air_low_live_clamp', ...
                        'setup_sellmeier_air_low_live_clamp', ...
                        'CerUPP:Sellmeier:AirLowClamp', ...
                        sprintf('%d live Air bins below Ciddor floor', nnz(invalid_low_live)), ...
                        sprintf('%d live bins lower-edge clamped', nnz(invalid_low_live)), ...
                        ['lambda_window had %d live Air bins below the Ciddor dry-air fit floor %.6g um ', ...
                         '(lowest live %.6g um). Those bins remain active and now evaluate Sellmeier_Air ', ...
                         'with lower-edge clamping instead of hard failure or mask edits.'], ...
                        nnz(invalid_low_live), air_nom_lo_um, min(lambda_um(invalid_low_live)));
                end
                if any(invalid_high_live)
                    [run_warn_state, setup_physics_rewrite_report] = driver_setup_support.record( ...
                        run_warn_state, setup_physics_rewrite_report, ...
                        'sellmeier_air_high_live_clamp', ...
                        'setup_sellmeier_air_high_live_clamp', ...
                        'CerUPP:Sellmeier:AirHighClamp', ...
                        sprintf('%d live Air bins above Ciddor ceiling', nnz(invalid_high_live)), ...
                        sprintf('%d live bins upper-edge clamped', nnz(invalid_high_live)), ...
                        ['lambda_window had %d live Air bins above the Ciddor dry-air fit ceiling %.6g um ', ...
                         '(highest live %.6g um). Those bins remain active and now evaluate Sellmeier_Air ', ...
                         'with upper-edge clamping instead of hard failure or mask edits.'], ...
                        nnz(invalid_high_live), air_nom_hi_um, max(lambda_um(invalid_high_live)));
                end
            else
                yag_nom_lo_um = 0.4;
                yag_nom_hi_um = 5.0;
                invalid_low_live = active_mask_before & (lambda_um < yag_nom_lo_um);
                invalid_high_live = active_mask_before & (lambda_um > yag_nom_hi_um);
                if any(invalid_low_live)
                    [run_warn_state, setup_physics_rewrite_report] = driver_setup_support.record( ...
                        run_warn_state, setup_physics_rewrite_report, ...
                        'sellmeier_yag_low_live_clamp', ...
                        'setup_sellmeier_yag_low_live_clamp', ...
                        'CerUPP:Sellmeier:YAGLowClamp', ...
                        sprintf('%d live bins below Zelmon floor', nnz(invalid_low_live)), ...
                        sprintf('%d live bins lower-edge clamped', nnz(invalid_low_live)), ...
                        ['lambda_window had %d live YAG bins below the Zelmon range floor %.6g um ', ...
                         '(lowest live %.6g um). Those bins remain active and now evaluate Sellmeier_YAG ', ...
                         'with lower-edge clamping instead of soft-masking.'], ...
                        nnz(invalid_low_live), yag_nom_lo_um, min(lambda_um(invalid_low_live)));
                end
                if any(invalid_high_live)
                    [run_warn_state, setup_physics_rewrite_report] = driver_setup_support.record( ...
                        run_warn_state, setup_physics_rewrite_report, ...
                        'sellmeier_yag_high_live_clamp', ...
                        'setup_sellmeier_yag_high_live_clamp', ...
                        'CerUPP:Sellmeier:YAGHighClamp', ...
                        sprintf('%d live bins above Zelmon ceiling', nnz(invalid_high_live)), ...
                        sprintf('%d live bins upper-edge clamped', nnz(invalid_high_live)), ...
                        ['lambda_window had %d live YAG bins above the Zelmon range ceiling %.6g um ', ...
                         '(highest live %.6g um). Those bins remain active and now evaluate Sellmeier_YAG ', ...
                         'with upper-edge clamping instead of soft-masking.'], ...
                        nnz(invalid_high_live), yag_nom_hi_um, max(lambda_um(invalid_high_live)));
                end
            end
            if mask_is_logical
                mask_f_w = reshape(mask_f_w_vec > 0.5, mask_shape);
            else
                mask_f_w = reshape(mask_f_w_vec, mask_shape);
            end
        end

        function mask_loss_diagnostic = estimate_linear_mask_energy_loss_once(A_F, mask_f, mask_f_w)
        % Setup-only diagnostic: estimate how much launch-spectrum energy
        % the built smooth spectral mask would remove if applied once.
        % This reports taper geometry only; runtime propagation uses the
        % derived binary support masks.

            [nx, ny, nw] = size(A_F);
            mask_loss_diagnostic = struct( ...
                'E0', NaN, ...
                'Eapplied', NaN, ...
                'applied_step_loss_frac', NaN, ...
                'Ehalf', NaN, ...
                'Efull', NaN, ...
                'half_step_loss_frac', NaN, ...
                'full_step_loss_frac', NaN);

            if isempty(A_F) || (nw < 1)
                return;
            end

            has_mask_f = ~isempty(mask_f);
            mask_f_is_2d = has_mask_f && ismatrix(mask_f);
            mask_f_is_3d = has_mask_f && (ndims(mask_f) == 3);

            if mask_f_is_2d
                if ~(size(mask_f,1) == nx && size(mask_f,2) == ny)
                    error('CerUPP:DriverMaskFShape', ...
                        'mask_f must be [%d %d] when 2D; got %s.', nx, ny, mat2str(size(mask_f)));
                end
                mask_f2_xy = abs(mask_f).^2;
            elseif mask_f_is_3d
                if ~(size(mask_f,1) == nx && size(mask_f,2) == ny && size(mask_f,3) == nw)
                    error('CerUPP:DriverMaskFShape', ...
                        'mask_f must be [%d %d %d] when 3D; got %s.', nx, ny, nw, mat2str(size(mask_f)));
                end
                mask_f2_xy = [];
            elseif has_mask_f
                error('CerUPP:DriverMaskFShape', ...
                    'mask_f must be empty, 2D, or 3D; got ndims=%d size=%s.', ndims(mask_f), mat2str(size(mask_f)));
            else
                mask_f2_xy = 1;
            end

            if isempty(mask_f_w)
                mask_w2 = ones(1, nw);
            else
                mask_w = reshape(mask_f_w, 1, []);
                if numel(mask_w) ~= nw
                    error('CerUPP:DriverMaskFWShape', ...
                        'maskF_w must have %d frequency elements; got %d.', nw, numel(mask_w));
                end
                mask_w2 = abs(mask_w).^2;
            end

            i = abs(A_F).^2;
            ew = squeeze(sum(sum(i, 1), 2));
            e0 = sum(ew(:));

            if mask_f_is_3d
                mask2 = abs(mask_f).^2;
                ew_applied = squeeze(sum(sum(i .* mask2, 1), 2));
            else
                if isscalar(mask_f2_xy)
                    ew_applied = ew * mask_f2_xy;
                else
                    ew_applied = squeeze(sum(sum(i .* mask_f2_xy, 1), 2));
                end
            end

            eapplied = sum(mask_w2(:) .* ew_applied(:));

            if ~(isfinite(e0) && (e0 > 0))
                return;
            end

            mask_loss_diagnostic.E0 = e0;
            mask_loss_diagnostic.Eapplied = eapplied;
            mask_loss_diagnostic.applied_step_loss_frac = min(max(1 - (eapplied / e0), 0), 1);
            mask_loss_diagnostic.Ehalf = eapplied;
            mask_loss_diagnostic.Efull = eapplied;
            mask_loss_diagnostic.half_step_loss_frac = mask_loss_diagnostic.applied_step_loss_frac;
            mask_loss_diagnostic.full_step_loss_frac = mask_loss_diagnostic.applied_step_loss_frac;
        end


