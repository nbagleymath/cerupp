function tf = propagation_support_has_grouped_input_local(s, group_names)
    tf = isstruct(s) && all(isfield(s, group_names));
end

function flat_inputs = propagation_support_merge_group_fields_local(grouped_inputs, group_names, owner_label)
    flat_inputs = struct();
    for ii = 1:numel(group_names)
        group_name = group_names{ii};
        group_value = struct_utils.req_struct_field(grouped_inputs, group_name, owner_label);
        flat_inputs = propagation_support_merge_one_group_local( ...
            flat_inputs, group_value, [owner_label '.' group_name]);
    end
end

function flat_inputs = propagation_support_merge_one_group_local(flat_inputs, group_value, group_label)
    if ~(isstruct(group_value) && isscalar(group_value))
        error('CerUPP:InvalidPhaseInputGroup', '%s must be a scalar struct.', group_label);
    end
    group_field_names = fieldnames(group_value);
    overlap = intersect(fieldnames(flat_inputs), group_field_names, 'stable');
    if ~isempty(overlap)
        error('CerUPP:DuplicatePhaseInputField', ...
            '%s reuses existing flat input field(s): %s', ...
            group_label, strjoin(overlap, ', '));
    end
    for jj = 1:numel(group_field_names)
        field_name = group_field_names{jj};
        flat_inputs.(field_name) = group_value.(field_name);
    end
end
