        function run_meta = attach_resolved_setup_contract_local( ...
            run_meta, resolved_setup_contract, store_diag_plan)
        % Attach the finalized restart-facing setup summary to run_meta.

            if nargin < 1 || isempty(run_meta) || ~isstruct(run_meta)
                run_meta = struct();
            end
            if nargin < 2 || isempty(resolved_setup_contract) || ~isstruct(resolved_setup_contract)
                resolved_setup_contract = struct();
            end
            if nargin >= 3 && ~isempty(store_diag_plan)
                if ~isfield(resolved_setup_contract, 'diagnostics') || ...
                        ~isstruct(resolved_setup_contract.diagnostics) || isempty(resolved_setup_contract.diagnostics)
                    resolved_setup_contract.diagnostics = struct();
                end
                resolved_setup_contract.diagnostics.store_diag_plan = store_diag_plan;
            end
            run_meta.resolved_setup_contract = resolved_setup_contract;
        end


