                'blue_range_msg', '%s blue-band bounds must satisfy min < max.', ...
                'green_range_msg', '%s green-band bounds must satisfy min < max.', ...
                'red_range_msg', '%s red-band bounds must satisfy min < max.', ...
                'fundamental_range_msg', '%s fundamental-band half-width must be > 0.');
            opts = driver_setup_support.merge_opts_local(defaults, varargin{:});
            if nargin < 2 || isempty(source_name)
                source_name = 'diagnostic_band_cfg';
            end
            if ~isstruct(diagnostic_band_cfg)
                error(opts.notstruct_id, opts.notstruct_msg, source_name);
            end

            required_fields = { ...
                'lambda_visible_band_min', ...
                'lambda_visible_band_max', ...
                'chromatic_onset_bin_width', ...
                'lambda_blue_band_min', ...
                'lambda_blue_band_max', ...
                'lambda_green_band_min', ...
                'lambda_green_band_max', ...
                'lambda_red_band_min', ...
                'lambda_red_band_max', ...
                'lambda_fundamental_band_half_width'};
            missing_fields = required_fields(~isfield(diagnostic_band_cfg, required_fields));
            if ~isempty(missing_fields)
                error(opts.missing_id, opts.missing_msg, ...
                    source_name, strjoin(missing_fields, ', '));
            end
            unknown_fields = setdiff(fieldnames(diagnostic_band_cfg).', required_fields, 'stable');
            if ~isempty(unknown_fields)
                error(opts.unknown_id, opts.unknown_msg, ...
                    source_name, strjoin(unknown_fields, ', '));
            end

            for ii = 1:numel(required_fields)
                field_name = required_fields{ii};
                field_value = diagnostic_band_cfg.(field_name);
                if ~isnumeric(field_value) || ~isscalar(field_value) || ~isreal(field_value) || ~isfinite(field_value)
                    error(opts.value_id, opts.value_msg, ...
                        source_name, field_name, mat2str(field_value));
                end
                diagnostic_band_cfg.(field_name) = double(field_value);
            end

            if ~(diagnostic_band_cfg.lambda_visible_band_min < diagnostic_band_cfg.lambda_visible_band_max)
                error(opts.range_id, opts.visible_range_msg, source_name);
            end
            if ~(diagnostic_band_cfg.chromatic_onset_bin_width > 0)
                error(opts.range_id, opts.chromatic_range_msg, source_name);
            end
            if ~(diagnostic_band_cfg.lambda_blue_band_min < diagnostic_band_cfg.lambda_blue_band_max)
                error(opts.range_id, opts.blue_range_msg, source_name);
            end
            if ~(diagnostic_band_cfg.lambda_green_band_min < diagnostic_band_cfg.lambda_green_band_max)
                error(opts.range_id, opts.green_range_msg, source_name);
            end
            if ~(diagnostic_band_cfg.lambda_red_band_min < diagnostic_band_cfg.lambda_red_band_max)
                error(opts.range_id, opts.red_range_msg, source_name);
            end
            if ~(diagnostic_band_cfg.lambda_fundamental_band_half_width > 0)
                error(opts.range_id, opts.fundamental_range_msg, source_name);
            end
        end
    end

    methods (Static, Access = private)
        function opts = merge_opts_local(defaults, varargin)
        %MERGE_OPTS_LOCAL Merge defaults with struct or name/value overrides.

            opts = defaults;
            if isempty(varargin)
                return;
            end
            unknown = {};

            if (numel(varargin) == 1) && isstruct(varargin{1})
                in = varargin{1};
                fn = fieldnames(in);
                for ii = 1:numel(fn)
                    key = fn{ii};
                    if isfield(opts, key)
                        opts.(key) = in.(key);
                    else
                        unknown{end+1} = key; %#ok<AGROW>
                    end
                end
                if ~isempty(unknown)
                    error('struct_utils:UnknownOptions', ...
                        'Unknown option field(s): %s (allowed: %s)', ...
                        strjoin(unique(unknown, 'stable'), ', '), ...
                        strjoin(fieldnames(defaults), ', '));
                end
                return;
            end

            if mod(numel(varargin), 2) ~= 0
                error('struct_utils:InvalidOptions', ...
                    'Options must be a struct or name/value pairs.');
            end
            for ii = 1:2:numel(varargin)
                key = varargin{ii};
                if isstring(key) && isscalar(key)
                    key = char(key);
                end
                if ~ischar(key)
                    error('struct_utils:InvalidOptionName', ...
                        'Option names must be char or scalar string.');
                end
                if isfield(opts, key)
                    opts.(key) = varargin{ii + 1};
                else
                    unknown{end+1} = key; %#ok<AGROW>
                end
            end
            if ~isempty(unknown)
                error('struct_utils:UnknownOptions', ...
                    'Unknown option field(s): %s (allowed: %s)', ...
                    strjoin(unique(unknown, 'stable'), ', '), ...
                    strjoin(fieldnames(defaults), ', '));
            end
        end
    end
% Owns the compact requested->effective physics-rewrite ledger used during setup.

    methods (Static, Hidden)
        function setup_physics_rewrite_report = init_report()
            setup_physics_rewrite_report = struct( ...
                'items', driver_setup_support.empty_items());
        end

        function setup_physics_rewrite_report = ensure_report(setup_physics_rewrite_report)
            if nargin < 1 || isempty(setup_physics_rewrite_report) || ~isstruct(setup_physics_rewrite_report)
                setup_physics_rewrite_report = driver_setup_support.init_report();
                return;
            end
            if ~isfield(setup_physics_rewrite_report, 'items') || ...
                    ~isstruct(setup_physics_rewrite_report.items)
                setup_physics_rewrite_report.items = driver_setup_support.empty_items();
            end
        end

        function [run_warn_state, setup_physics_rewrite_report] = record( ...
                run_warn_state, setup_physics_rewrite_report, varargin)
            if nargin < 1 || isempty(run_warn_state) || ~isstruct(run_warn_state)
                run_warn_state = struct();
            end
            setup_physics_rewrite_report = driver_setup_support.ensure_report( ...
                setup_physics_rewrite_report);
            rewrite_id = varargin{1};
            warning_key = varargin{2};
            warning_id = varargin{3};
            requested_value = varargin{4};
            effective_value = varargin{5};
            message_fmt = varargin{6};
            message_args = varargin(7:end);
            if isequaln(requested_value, effective_value)
                return;
            end

            item = struct( ...
                'id', char(string(rewrite_id)), ...
                'requested', driver_setup_support.value_repr(requested_value), ...
                'effective', driver_setup_support.value_repr(effective_value), ...
                'message', char(sprintf(message_fmt, message_args{:})), ...
                'warning_id', char(string(warning_id)));
            setup_physics_rewrite_report.items(end+1) = item;
            run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                run_warn_state, driver_setup_support.infer_phase(warning_key), ...
                char(string(warning_key)), char(string(warning_id)), '%s', item.message);
        end

        function print_report(setup_physics_rewrite_report)
            setup_physics_rewrite_report = driver_setup_support.ensure_report( ...
                setup_physics_rewrite_report);
            rewrite_count = numel(setup_physics_rewrite_report.items);
            fprintf('\n=== Setup-Time Physics Rewrite Report ===\n');
            fprintf('rewrites_applied=%d\n', double(rewrite_count));
            if rewrite_count < 1
                fprintf('none\n');
                fprintf('========================================\n\n');
                return;
            end
            for ii = 1:rewrite_count
                item = setup_physics_rewrite_report.items(ii);
                fprintf('- %s: requested=%s -> effective=%s\n', ...
                    item.id, item.requested, item.effective);
                fprintf('  %s\n', item.message);
            end
            fprintf('========================================\n\n');
        end

