                        'signature_kind', 'numeric_sha256', ...
                        'value_class', class(value_in), ...
                        'value_size', double(size(value_in)), ...
                        'is_real', isreal(value_in), ...
                        'hash_sha256', ...
                            driver_setup_support.build_large_numeric_freeze_hash_local( ...
                                value_in));
                end
                return;
            end

            if ischar(value_in) || (isstring(value_in) && isscalar(value_in))
                freeze_value = char(string(value_in));
                return;
            end

            if isstring(value_in)
                freeze_value = cellstr(value_in);
                return;
            end

            if isempty(value_in)
                freeze_value = value_in;
                return;
            end

            freeze_value = struct( ...
                'signature_kind', 'workspace_value_summary', ...
                'value_class', class(value_in), ...
                'value_size', double(size(value_in)));
        end

        function hash_hex = build_large_numeric_freeze_hash_local(value_in)
        % Hash one large numeric/logical array without storing it verbatim
        % in the guard surface.

            md = freeze_hash_utils.sha256_init();
            md = freeze_hash_utils.sha256_update(md, uint8(class(value_in)));
            md = freeze_hash_utils.sha256_update(md, uint8([0, double(isreal(value_in))]));
            md = freeze_hash_utils.sha256_update(md, typecast(uint64(size(value_in)), 'uint8'));
            flat_value = value_in(:);
            chunk_len = 1e5;
            if islogical(flat_value)
                for start_idx = 1:chunk_len:numel(flat_value)
                    stop_idx = min(start_idx + chunk_len - 1, numel(flat_value));
                    md = freeze_hash_utils.sha256_update(md, uint8(flat_value(start_idx:stop_idx)));
                end
            elseif isreal(flat_value)
                md = driver_setup_support.update_digest_from_numeric_parts_local( ...
                    md, flat_value, chunk_len);
            else
                md = driver_setup_support.update_digest_from_numeric_parts_local( ...
                    md, real(flat_value), chunk_len);
                md = freeze_hash_utils.sha256_update(md, uint8('|imag|'));
                md = driver_setup_support.update_digest_from_numeric_parts_local( ...
                    md, imag(flat_value), chunk_len);
            end
            hash_hex = driver_setup_support.digest_to_hex_local(md);
        end

        function hash_hex = build_serialized_freeze_hash_local(value_in)
        % Hash one non-numeric guard value through MATLAB's serialized byte
        % stream so the guard keeps only one compact content signature.

            serialized_bytes = freeze_hash_utils.canonical_serialize_for_hash(value_in);
            md = freeze_hash_utils.sha256_init();
            md = freeze_hash_utils.sha256_update(md, uint8(class(value_in)));
            md = freeze_hash_utils.sha256_update(md, uint8('|serialized|'));
            md = freeze_hash_utils.sha256_update(md, uint8(serialized_bytes(:)));
            hash_hex = driver_setup_support.digest_to_hex_local(md);
        end

        function md = update_digest_from_numeric_parts_local(md, flat_value, chunk_len)
        % Feed one real numeric chunk stream into the active digest.

            for start_idx = 1:chunk_len:numel(flat_value)
                stop_idx = min(start_idx + chunk_len - 1, numel(flat_value));
                md = freeze_hash_utils.sha256_update(md, ...
                    typecast(flat_value(start_idx:stop_idx), 'uint8'));
            end
        end

        function hash_hex = digest_to_hex_local(md)
        % Convert one incremental SHA-256 state into a lowercase hex string.

            hash_hex = freeze_hash_utils.sha256_finalize(md);
        end

        function validated_major_step_custom_args = ...
                validate_major_step_custom_args_local( ...
                raw_major_step_custom_args)
        % Validate the direct driver-owned step custom args.
        % advance_z_step(...) reads this one scalar-struct surface directly
        % and peels any built-in kerr/plasma/nla buckets locally.

            if nargin < 1 || isempty(raw_major_step_custom_args)
                raw_major_step_custom_args = struct();
            end
            if ~(isstruct(raw_major_step_custom_args) && isscalar(raw_major_step_custom_args))
                error('CerUPP:InvalidRawMajorStepCustomArgs', ...
                    'major_step_custom_args must be a scalar struct when building the effective step custom surface.');
            end

            validated_major_step_custom_args = raw_major_step_custom_args;
            current_custom_bucket_names = fieldnames(validated_major_step_custom_args);
            for bucket_idx = 1:numel(current_custom_bucket_names)
                bucket_name = current_custom_bucket_names{bucket_idx};
                bucket_value = validated_major_step_custom_args.(bucket_name);
                if ~(isstruct(bucket_value) && isscalar(bucket_value))
                    error('CerUPP:AdvanceStepInvalidMajorStepCustomArgBucket', ...
                        ['major_step_custom_args.%s must be a scalar struct. ', ...
                         'Direct advance_z_step(...) hook buckets and the built-in ', ...
                         'kerr/plasma/nla buckets all use that same scalar-struct contract.'], ...
                        bucket_name);
                end
            end

        end

        function rebuild_policy = build_rebuild_policy_local(cfg)
        % Build the canonical z-dependent rebuild policy once from the
        % driver's visible rebuild knobs.

            context_name = 'build_rebuild_policy_local cfg';
            if nargin < 1 || ~isstruct(cfg) || ~isscalar(cfg)
                error('CerUPP:InvalidRebuildPolicyCfg', ...
                    '%s must be a scalar struct.', context_name);
            end

            z_dependent_medium_requested = logical(struct_utils.req_struct_field( ...
                cfg, 'z_dependent_medium_flag', context_name));
            allow_z_dependent_keldysh_requested = logical(struct_utils.req_struct_field( ...
                cfg, 'allow_z_dependent_keldysh', context_name));
            keldysh_enabled = logical(struct_utils.req_struct_field( ...
                cfg, 'keldysh_enabled', context_name));
            keldysh_runtime_enabled_effective = logical(struct_utils.opt_struct_field( ...
                cfg, 'dynamic_keldysh_runtime_enabled_effective', keldysh_enabled));

            z_dependent_medium_effective = z_dependent_medium_requested;
            allow_z_dependent_keldysh_effective = ...
                z_dependent_medium_effective && ...
                allow_z_dependent_keldysh_requested;

            rebuild_policy = struct( ...
                'z_dependent_medium_requested', z_dependent_medium_requested, ...
                'z_dependent_medium_effective', z_dependent_medium_effective, ...
                'allow_z_dependent_keldysh_requested', ...
                    allow_z_dependent_keldysh_requested, ...
                'allow_z_dependent_keldysh_effective', ...
                    allow_z_dependent_keldysh_effective, ...
                'allow_keldysh_runtime_reload_effective', ...
                    logical(keldysh_runtime_enabled_effective && ...
                            allow_z_dependent_keldysh_effective));
        end

        function submodel_refresh_cfg = build_medium_rebuild_submodel_refresh_cfg_local(cfg)
        % Build one canonical driver-owned rebuild cfg for the plasma,
        % Keldysh, and NLA refresh path.

            context_name = 'build_medium_rebuild_submodel_refresh_cfg_local cfg';
            if nargin < 1 || ~isstruct(cfg) || ~isscalar(cfg)
                error('CerUPP:InvalidMediumRebuildSubmodelCfgInput', ...
                    '%s must be a scalar struct.', context_name);
            end

            keldysh_material_state_update = struct_utils.opt_struct_field( ...
                cfg, 'keldysh_material_state_update', struct(), ...
                'treat_empty_as_missing', true);
            if ~(isempty(keldysh_material_state_update) || ...
                    (isstruct(keldysh_material_state_update) && ...
                     isscalar(keldysh_material_state_update)))
                error('CerUPP:InvalidRebuildKeldyshMaterialStateUpdate', ...
                    'keldysh_material_state_update must be empty or a scalar struct.');
            end
            if isempty(keldysh_material_state_update)
