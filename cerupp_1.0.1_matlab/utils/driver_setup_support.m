        function sink_mode = resolve_ofi_nla_sink_mode_local(cfg, medium_spec)
        % Resolve the saved OFI-based NLA sink label from the live setup contract.

            nl_absorption_flag = logical(struct_utils.opt_struct_field( ...
                cfg, 'nl_absorption_flag', false));
            nla_use_ofi_rate_law_flag = logical(struct_utils.opt_struct_field( ...
                cfg, 'nla_use_ofi_rate_law_flag', false));
            keldysh_enabled = logical(struct_utils.opt_struct_field( ...
                cfg, 'keldysh_enabled', false));
            k_power_vec = reshape(double(struct_utils.opt_struct_field( ...
                medium_spec, 'k_power_vec', [])), 1, []);
            sigma_k_vec = reshape(double(struct_utils.opt_struct_field( ...
                medium_spec, 'sigma_k_vec', [])), 1, []);
            active_static_mask = isfinite(k_power_vec) & (k_power_vec > 0) & ...
                isfinite(sigma_k_vec) & (sigma_k_vec > 0);
            active_static_terms = nnz(active_static_mask);
            sink_mode = 'disabled';
            if ~nl_absorption_flag
                return;
            end
            if ~nla_use_ofi_rate_law_flag
                sink_mode = 'static_beta_k';
            elseif keldysh_enabled
                sink_mode = 'matched_dynamic_ofi';
            elseif active_static_terms > 1
                sink_mode = 'matched_static_multiorder_orderwise';
            else
                sink_mode = 'matched_static_single_order_udep';
            end
        end

