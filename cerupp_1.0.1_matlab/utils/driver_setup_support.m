        function projected_struct = project_summary_fields_local(source_struct, field_specs)
        % Build a small saved/readback summary from one owner struct using a local field spec.

            if nargin < 1 || isempty(source_struct)
                source_struct = struct();
            end
            if nargin < 2 || isempty(field_specs)
