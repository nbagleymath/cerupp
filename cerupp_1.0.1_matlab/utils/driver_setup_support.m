            end
        end

        function band_mask_stack = cat_store_band_masks_core_local(band_masks)
            if isempty(band_masks)
                band_mask_stack = [];
            else
                band_mask_stack = cat(4, band_masks{:});
                if numel(band_masks) == 1
                    single_mask = band_masks{1};
                    band_mask_stack = reshape(band_mask_stack, ...
                        size(single_mask, 1), size(single_mask, 2), size(single_mask, 3), 1);
                end
            end
        end

        function request = build_store_fluence_only_request_core_local()
            request = struct('fluence', true, 'td_oa', false, 'td_bc', false, 'td_maxperp', false);
        end

        function items = empty_items()
            items = struct( ...
                'id', {}, ...
                'requested', {}, ...
                'effective', {}, ...
                'message', {}, ...
                'warning_id', {});
        end

        function warning_phase = infer_phase(warning_key)
            warning_phase = 'setup';
            warning_key = lower(strtrim(char(string(warning_key))));
            if strncmp(warning_key, 'propagation_', 12)
                warning_phase = 'propagation';
            elseif strncmp(warning_key, 'end_', 4)
                warning_phase = 'end';
            end
        end

        function txt = value_repr(v)
            if isstring(v) && isscalar(v)
                txt = char(v);
            elseif ischar(v)
                txt = v;
            elseif islogical(v) && isscalar(v)
                txt = sprintf('%d', double(v));
            else
                txt = mat2str(v);
            end
        end
    end
end

