        function history_struct = build_output_history_from_specs_local(history_specs)
        % Build the history subtree from {field_name, effective_flag, reason_args} specs.

            history_struct = struct();
            if isempty(history_specs)
                return;
            end
            for spec_idx = 1:size(history_specs, 1)
                field_name = history_specs{spec_idx, 1};
                effective_flag = logical(history_specs{spec_idx, 2});
                reason_args = history_specs{spec_idx, 3};
                if ~iscell(reason_args)
                    reason_args = {reason_args};
                end
                history_struct.(field_name) = driver_setup_support.build_output_history_policy_entry_local( ...
                    effective_flag, driver_setup_support.pick_output_reason_local(reason_args{:}));
            end
        end

        function merged_struct = merge_scalar_structs_local(varargin)
        % Merge scalar structs in caller order; later fields overwrite earlier ones.

            merged_struct = struct();
            for arg_idx = 1:nargin
                piece = varargin{arg_idx};
                if isempty(piece)
                    continue;
                end
                if ~(isstruct(piece) && isscalar(piece))
                    error('CerUPP:InvalidDriverStructMergeInput', ...
                        'merge_scalar_structs_local expects scalar struct inputs.');
                end
                piece_fields = fieldnames(piece);
                for field_idx = 1:numel(piece_fields)
                    field_name = piece_fields{field_idx};
                    merged_struct.(field_name) = piece.(field_name);
                end
            end
        end

