        function raw_medium_setup = build_raw_medium_setup_local(cfg)
        % Build the shared raw medium/default bundle from the current visible knobs.
        % The built-in YAG-versus-Air placeholder family is settled in
        % cerupp.m before the startup handoff so the later raw/frozen
        % setup surfaces carry that same driver-visible selector. When explicit
        % split-threshold/static-surrogate overrides are absent, this helper
        % resolves the built-in defaults directly from the source knobs.

            if nargin < 1 || ~isstruct(cfg) || ~isscalar(cfg)
                error('CerUPP:InvalidRawMediumSetupCfg', ...
                    'build_raw_medium_setup_local requires one scalar cfg struct.');
            end

            n2_kerr_selector_value = double(cfg.n2_kerr);
            if ~isscalar(n2_kerr_selector_value) || ...
                    ~isfinite(n2_kerr_selector_value) || ...
                    ~isreal(n2_kerr_selector_value)
                error('CerUPP:InvalidMediumConfig', ...
                    ['n2_kerr must be a finite real scalar before setup ', ...
                     'selects the built-in medium family.']);
            end
            selected_builtin_medium_family = upper(strtrim(char(string( ...
                struct_utils.req_struct_field( ...
                    cfg, 'selected_builtin_medium_family', ...
                    'build_raw_medium_setup_local')))));
            if ~ismember(selected_builtin_medium_family, {'YAG', 'AIR'})
                error('CerUPP:InvalidMediumConfig', ...
                    ['selected_builtin_medium_family must be ''YAG'' or ''AIR''; ', ...
                     'got ''%s''.'], ...
                    selected_builtin_medium_family);
            end
            abs_n2_kerr_m2_per_w = abs(double(n2_kerr_selector_value));
            if ~isscalar(abs_n2_kerr_m2_per_w) || ...
                    ~isfinite(abs_n2_kerr_m2_per_w) || ...
                    ~isreal(abs_n2_kerr_m2_per_w) || ...
                    (abs_n2_kerr_m2_per_w < 0)
                error('CerUPP:InvalidMediumConfig', ...
                    ['abs(n2_kerr) must be a finite real scalar >= 0 before ', ...
                     'setup builds the raw medium surface.']);
            end
            n2_air_placeholder_threshold = double(struct_utils.req_struct_field( ...
                cfg, 'n2_air_placeholder_threshold', ...
                'build_raw_medium_setup_local'));
            if ~isscalar(n2_air_placeholder_threshold) || ...
                    ~isfinite(n2_air_placeholder_threshold) || ...
                    ~isreal(n2_air_placeholder_threshold) || ...
                    (n2_air_placeholder_threshold < 0)
                error('CerUPP:InvalidMediumConfig', ...
                    ['n2_air_placeholder_threshold must be a finite real ', ...
                     'scalar >= 0 before setup builds the raw medium surface.']);
            end
            ui_value = double(cfg.ui);
            if ~isscalar(ui_value) || ~isfinite(ui_value) || ~isreal(ui_value) || (ui_value <= 0)
                error('CerUPP:InvalidMediumConfig', ...
                    'ui must be a finite real scalar > 0 before setup resolves the built-in medium defaults.');
            end
            lambda_fund_value = double(cfg.lambda_fund);
            if ~isscalar(lambda_fund_value) || ~isfinite(lambda_fund_value) || ...
                    ~isreal(lambda_fund_value) || (lambda_fund_value <= 0)
                error('CerUPP:InvalidMediumConfig', ...
                    'lambda_fund must be a finite real scalar > 0 before setup resolves the built-in static surrogate.');
            end
            keldysh_gap_value = struct_utils.opt_struct_field( ...
                cfg, 'keldysh_gap', ui_value, 'treat_empty_as_missing', true);
            keldysh_matched_depletion_value = struct_utils.opt_struct_field( ...
                cfg, 'keldysh_matched_depletion', ui_value, 'treat_empty_as_missing', true);
            keldysh_electron_effective_mass_over_me = double( ...
                struct_utils.req_struct_field( ...
                    cfg, 'keldysh_electron_effective_mass_over_me', ...
                    'build_raw_medium_setup_local'));
            if ~isscalar(keldysh_electron_effective_mass_over_me) || ...
                    ~isfinite(keldysh_electron_effective_mass_over_me) || ...
                    ~isreal(keldysh_electron_effective_mass_over_me) || ...
                    (keldysh_electron_effective_mass_over_me <= 0)
                error('CerUPP:InvalidMediumConfig', ...
                    ['keldysh_electron_effective_mass_over_me must be one finite ', ...
                     'real scalar > 0 before setup builds the YAG Keldysh medium inputs.']);
            end
            keldysh_hole_effective_mass_over_me = double( ...
                struct_utils.req_struct_field( ...
                    cfg, 'keldysh_hole_effective_mass_over_me', ...
                    'build_raw_medium_setup_local'));
            if ~isscalar(keldysh_hole_effective_mass_over_me) || ...
                    ~isfinite(keldysh_hole_effective_mass_over_me) || ...
                    ~isreal(keldysh_hole_effective_mass_over_me) || ...
                    (keldysh_hole_effective_mass_over_me <= 0)
                error('CerUPP:InvalidMediumConfig', ...
                    ['keldysh_hole_effective_mass_over_me must be one finite ', ...
                     'real scalar > 0 before setup builds the YAG Keldysh medium inputs.']);
            end
            plasma_flag = struct_utils.normalize_bool_scalar( ...
                struct_utils.req_struct_field( ...
                    cfg, 'plasma_flag', 'build_raw_medium_setup_local'), ...
                'plasma_flag', 'CerUPP:InvalidMediumConfig');
            nl_absorption_flag = struct_utils.normalize_bool_scalar( ...
                struct_utils.req_struct_field( ...
                    cfg, 'nl_absorption_flag', 'build_raw_medium_setup_local'), ...
                'nl_absorption_flag', 'CerUPP:InvalidMediumConfig');
            nla_use_ofi_rate_law_flag = struct_utils.normalize_bool_scalar( ...
                struct_utils.req_struct_field( ...
                    cfg, 'nla_use_ofi_rate_law_flag', ...
                    'build_raw_medium_setup_local'), ...
                'nla_use_ofi_rate_law_flag', 'CerUPP:InvalidMediumConfig');
            keldysh_enabled = struct_utils.normalize_bool_scalar( ...
                struct_utils.req_struct_field( ...
                    cfg, 'keldysh_enabled', 'build_raw_medium_setup_local'), ...
                'keldysh_enabled', 'CerUPP:InvalidMediumConfig');
            need_static_mpi_terms = logical(plasma_flag && ~keldysh_enabled) || ...
                logical(nl_absorption_flag && ~nla_use_ofi_rate_law_flag);
            k_power_vec_value = struct_utils.opt_struct_field( ...
                cfg, 'k_power_vec', [], 'treat_empty_as_missing', true);
            sigma_k_vec_value = struct_utils.opt_struct_field( ...
                cfg, 'sigma_k_vec', [], 'treat_empty_as_missing', true);
            if isempty(k_power_vec_value) && (numel(sigma_k_vec_value) == 1)
                omega_fund_value = 2 * pi * 299792458 / lambda_fund_value;
                k_power_vec_value = max(ceil(ui_value / (1.054571817e-34 * omega_fund_value)), 1);
            end
            if need_static_mpi_terms
                if isempty(sigma_k_vec_value)
                    error('CerUPP:InvalidMediumConfig', ...
                        ['Any non-Keldysh static OFI/static beta_K branch requires ', ...
                         'sigma_k_vec to be provided when plasma_flag or ', ...
                         'nl_absorption_flag stays enabled.']);
                end
                if isempty(k_power_vec_value)
                    error('CerUPP:InvalidMediumConfig', ...
                        ['Any non-Keldysh static OFI/static beta_K branch requires ', ...
                         'k_power_vec to be provided with the same length as ', ...
                         'sigma_k_vec, unless sigma_k_vec has exactly one entry.']);
                end
            end
            if numel(k_power_vec_value) ~= numel(sigma_k_vec_value)
                error('CerUPP:InvalidMediumConfig', ...
                    'k_power_vec and sigma_k_vec must have the same number of entries.');
            end
            raw_medium_setup = struct( ...
                'selected_builtin_medium_family', selected_builtin_medium_family, ...
                'n2_air_placeholder_threshold', n2_air_placeholder_threshold, ...
                'lambda_fund', cfg.lambda_fund, ...
                'core_radius', cfg.core_radius, ...
                'n2_kerr', cfg.n2_kerr, ...
                'n2_kerr_disable_tol', cfg.n2_kerr_disable_tol, ...
                'keldysh_lut_i_roi_min', cfg.keldysh_lut_i_roi_min, ...
                'keldysh_electron_effective_mass_over_me', ...
                    keldysh_electron_effective_mass_over_me, ...
                'keldysh_hole_effective_mass_over_me', ...
                    keldysh_hole_effective_mass_over_me, ...
                'ui', ui_value, ...
                'keldysh_gap', keldysh_gap_value, ...
                'keldysh_matched_depletion', keldysh_matched_depletion_value, ...
                'rho_nt', cfg.rho_nt, ...
                'k_power_vec', k_power_vec_value, ...
                'sigma_k_vec', sigma_k_vec_value, ...
                'tau_c', cfg.tau_c, ...
                'alpha_recombine', cfg.alpha_recombine, ...
                'plasma_m_over_me', cfg.plasma_m_over_me, ...
                'air_placeholder_ui', cfg.air_placeholder_ui, ...
                'air_placeholder_rho_nt', cfg.air_placeholder_rho_nt, ...
                'air_placeholder_k_power', cfg.air_placeholder_k_power, ...
                'air_placeholder_sigma_k', cfg.air_placeholder_sigma_k);
        end

