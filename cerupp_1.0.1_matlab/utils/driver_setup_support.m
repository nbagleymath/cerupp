        function freeze_value = build_value_freeze_signature_local(value_in)
        % Normalize one guard-tracked value into the stored compare form
        % without pinning large numeric payloads for the whole run.

            if isstruct(value_in)
                if ~isscalar(value_in)
                    freeze_value = cell(size(value_in));
                    for struct_idx = 1:numel(value_in)
                        freeze_value{struct_idx} = ...
                            driver_setup_support.build_value_freeze_signature_local( ...
                                value_in(struct_idx));
                    end
                    return;
                end
                field_names = fieldnames(value_in);
                freeze_value = struct();
                for field_idx = 1:numel(field_names)
                    field_name = field_names{field_idx};
                    freeze_value.(field_name) = ...
                        driver_setup_support.build_value_freeze_signature_local( ...
                            value_in.(field_name));
                end
                return;
            end

            if iscell(value_in)
                freeze_value = cell(size(value_in));
                for cell_idx = 1:numel(value_in)
                    freeze_value{cell_idx} = ...
                        driver_setup_support.build_value_freeze_signature_local( ...
                            value_in{cell_idx});
                end
                return;
            end

            if isa(value_in, 'function_handle')
                freeze_value = ...
                    driver_setup_support.build_function_handle_freeze_signature_local( ...
                        value_in);
                return;
            end

            if isnumeric(value_in) || islogical(value_in)
                if isempty(value_in) || isscalar(value_in) || (numel(value_in) <= 16)
                    freeze_value = value_in;
                else
                    freeze_value = struct( ...
                        'signature_kind', 'numeric_sha256', ...
                        'value_class', class(value_in), ...
                        'value_size', double(size(value_in)), ...
                        'is_real', isreal(value_in), ...
                        'hash_sha256', ...
                            driver_setup_support.build_large_numeric_freeze_hash_local( ...
                                value_in));
                end
                return;
            end

            if ischar(value_in) || (isstring(value_in) && isscalar(value_in))
                freeze_value = char(string(value_in));
                return;
            end

            if isstring(value_in)
                freeze_value = cellstr(value_in);
                return;
            end

            if isempty(value_in)
                freeze_value = value_in;
                return;
            end

            try
                freeze_value = struct( ...
                    'signature_kind', 'serialized_sha256', ...
                    'value_class', class(value_in), ...
                    'value_size', double(size(value_in)), ...
                    'hash_sha256', ...
                        driver_setup_support.build_serialized_freeze_hash_local( ...
                            value_in));
            catch me_hash
                error('CerUPP:UnsupportedFreezeSignatureValue', ...
                    ['Unsupported guard-signature value class %s. ', ...
                     'Fallback hashing failed with: %s (%s)'], ...
                    class(value_in), me_hash.message, me_hash.identifier);
            end
        end

        function freeze_value = build_function_handle_freeze_signature_local(value_in)
        % Store enough handle metadata for freeze comparison without recursively
        % serializing MATLAB's full function-handle workspace representation.

            handle_info = functions(value_in);
            freeze_value = struct( ...
                'signature_kind', 'function_handle', ...
                'value_class', class(value_in), ...
                'value_size', double(size(value_in)), ...
                'func2str', func2str(value_in));

            if isfield(handle_info, 'function')
                freeze_value.function = char(string(handle_info.function));
            end
            if isfield(handle_info, 'type')
                freeze_value.type = char(string(handle_info.type));
            end
            if isfield(handle_info, 'file')
                freeze_value.file = char(string(handle_info.file));
            end
            if isfield(handle_info, 'workspace')
                freeze_value.workspace = ...
                    driver_setup_support.build_function_workspace_summary_local( ...
                        handle_info.workspace);
            end
        end

        function freeze_value = build_function_workspace_summary_local(value_in)
        % Keep function-handle guard signatures finite even for closures whose
        % MATLAB workspace metadata contains recursive or very large objects.

            freeze_value = struct( ...
                'signature_kind', 'function_handle_workspace_summary', ...
                'value_class', class(value_in), ...
                'value_size', double(size(value_in)));

            if iscell(value_in)
                freeze_value.cell_count = numel(value_in);
                if ~isempty(value_in) && isstruct(value_in{1})
                    freeze_value.first_workspace_fields = ...
                        sort(fieldnames(value_in{1})).';
                end
                return;
            end

            if isstruct(value_in)
                freeze_value.struct_count = numel(value_in);
                if ~isempty(value_in)
                    freeze_value.first_workspace_fields = ...
                        sort(fieldnames(value_in(1))).';
                end
            end
        end

