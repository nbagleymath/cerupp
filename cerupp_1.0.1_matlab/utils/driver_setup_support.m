        function [center_i, run_warn_state] = report_initial_condition_diagnostics_local( ...
                x, y, t, A_xy, n_ratio_diag_xy, p_input_w, p_input_w_beam2, ...
                i_laser_peak, i_laser_peak_beam2, beta_chirp, ...
                oam_charge1, oam_charge_beam2, t_profile, omega_window, c, ...
                lambda_fund, mask_pad_w, mask_f_w, run_warn_state, eps_safe)
        % Print the setup-only IC power/spectrum sanity checks and return the
        % on-axis intensity trace used by the initial diagnostic plots.

            p_target_ic_w = max(double(p_input_w), 0) + max(double(p_input_w_beam2), 0);
            i_diag = n_ratio_diag_xy .* real(A_xy .* conj(A_xy));
            i_raw = real(A_xy .* conj(A_xy));
            p_grid_t = squeeze(trapz(x, trapz(y, i_raw, 2), 1));
            p_grid_t = double(p_grid_t(:));
            p_peak_grid_w = max(p_grid_t);
            [~, i_peak_grid] = max(p_grid_t);
            t_peak_grid_s = t(i_peak_grid);
            fprintf(['IC peak-power (print-only): intended P_peak= %.6e W, ', ...
                     'realized P_peak(grid)= %.6e W at pulse-frame t= %.6e s\n'], ...
                    p_target_ic_w, p_peak_grid_w, t_peak_grid_s);

            try
                A_xy_w = fft(A_xy, [], 3);
                omega_vec = reshape(double(omega_window), 1, []);
                s_w = squeeze(sum(sum(real(A_xy_w .* conj(A_xy_w)), 1), 2));
                s_w = reshape(double(s_w), 1, []);
                if numel(s_w) ~= numel(omega_vec)
                    error('CerUPP:ICSpectralPeakShape', ...
                        'A_xy spectral length (%d) does not match omega_window length (%d).', ...
                        numel(s_w), numel(omega_vec));
                end

                delta_omega_samples = abs(diff(sort(omega_vec(isfinite(omega_vec)))));
                delta_omega_samples = delta_omega_samples(delta_omega_samples > 0);
                if isempty(delta_omega_samples)
                    delta_omega_grid = NaN;
                else
                    delta_omega_grid = median(delta_omega_samples);
                end
                omega_expected = 2*pi*c/lambda_fund;
                omega_pos_mask = isfinite(omega_vec) & (omega_vec > 0);
                omega_peak = NaN;
                if any(omega_pos_mask(:))
                    s_w_pos = s_w;
                    s_w_pos(~omega_pos_mask) = -inf;
                    [~, imax] = max(s_w_pos);
                    omega_peak = omega_vec(imax);
                end
                denom_omega_grid = delta_omega_grid;
                if ~(isfinite(denom_omega_grid) && (denom_omega_grid > 0))
                    denom_omega_grid = eps_safe;
                end
                if isfinite(omega_peak) && (omega_peak > 0)
                    lambda_peak_nm = (2*pi*c/omega_peak)/1e-9;
                    peak_offset_bins = abs(omega_peak - omega_expected) / max(denom_omega_grid, eps_safe);
                    fprintf(['built-field spectral peak = %.1f nm (expected ~%.1f nm; ', ...
                             'offset %.2f FFT bins)\n'], ...
                            lambda_peak_nm, lambda_fund/1e-9, peak_offset_bins);
                    ic_peak_softwarn_bin_tol = 1.5;
                    if peak_offset_bins > ic_peak_softwarn_bin_tol
                        peak_msg = sprintf([ ...
                            'Built launch field spectral peak is %.2f FFT bins from lambda_fund ', ...
                            '(delta_omega=%.6e rad/s, threshold=%.2f bins). This is a soft setup ', ...
                            'diagnostic; inspect custom/imported launch centering if the offset was not intended.'], ...
                            peak_offset_bins, denom_omega_grid, ic_peak_softwarn_bin_tol);
                        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                            run_warn_state, 'setup', ...
                            'setup_ic_spectral_peak_mismatch', ...
                            'CerUPP:ICSpectralPeakMismatch', ...
                            '%s', peak_msg);
                    end
                else
                    fprintf('built-field spectral peak: unavailable (omega_peak=%g; expected ~%.1f nm)\n', ...
                            omega_peak, lambda_fund/1e-9);
                end

                A_t = t_profile(:).';
                A_w_profile = fft(A_t);
                s_w_profile = reshape(real(A_w_profile .* conj(A_w_profile)), 1, []);
                omega_peak_profile = NaN;
                if numel(s_w_profile) == numel(omega_vec) && any(omega_pos_mask(:))
                    s_w_profile_pos = s_w_profile;
                    s_w_profile_pos(~omega_pos_mask) = -inf;
                    [~, imax_profile] = max(s_w_profile_pos);
                    omega_peak_profile = omega_vec(imax_profile);
                end
                if isfinite(omega_peak_profile) && (omega_peak_profile > 0) && ...
                        isfinite(omega_peak) && (omega_peak > 0)
                    profile_offset_bins = abs(omega_peak_profile - omega_peak) / max(denom_omega_grid, eps_safe);
                    if profile_offset_bins > 0.5
                        lambda_peak_profile_nm = (2*pi*c/omega_peak_profile)/1e-9;
                        fprintf(['temporal-profile-only spectral peak = %.1f nm ', ...
                                 '(differs from built-field peak by %.2f FFT bins)\n'], ...
                                lambda_peak_profile_nm, profile_offset_bins);
                    end
                end

                e_spec_total = sum(real(A_xy_w(:) .* conj(A_xy_w(:))));
                e_spec_edge = 0;
                if mask_pad_w > 0
                    mask_f_w_vec = reshape(mask_f_w, [], 1);
                    idx_supp = find(mask_f_w_vec <= 0);
                    if ~isempty(idx_supp)
                        A_xy_w_supp = A_xy_w(:, :, idx_supp);
                        e_spec_edge = sum(real(A_xy_w_supp(:) .* conj(A_xy_w_supp(:))));
                    end
                end
                frac_edge = real(e_spec_edge) / max(real(e_spec_total), eps_safe);
                fprintf('Guard-band masked-bin spectral energy fraction at z=0: %.3e (mask_pad_w=%d)\n', ...
                        frac_edge, mask_pad_w);
                guard_band_edge_frac_tight_thresh = 1e-3;
                if frac_edge > guard_band_edge_frac_tight_thresh
                    guard_msg = sprintf([ ...
                        'Guard-band masked-bin spectral energy fraction exceeds tight threshold: frac=%.3e > %.3e ', ...
                        '(mask_pad_w=%d). Increase spectral bandwidth (t_window/n and/or lambda_ref) or reduce broadening.'], ...
                        frac_edge, guard_band_edge_frac_tight_thresh, mask_pad_w);
                    run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                        run_warn_state, 'setup', ...
                        'setup_guard_band_dependence_exceeded', ...
                        'CerUPP:GuardBandDependence', ...
                        '%s', guard_msg);
                end
            catch me_2
                if mask_pad_w > 0
                    run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                        run_warn_state, 'setup', ...
                        'setup_guard_band_diag_failed_active', ...
                        'CerUPP:GuardBandDiagFailed', ...
                        ['Guard-band diagnostic failed while mask_pad_w=%d (guard bands active). ', ...
                         'Continuing with setup warning. Details: %s'], ...
                        mask_pad_w, me_2.message);
                else
                    run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                        run_warn_state, 'setup', ...
                        'setup_guard_band_diag_failed_soft', ...
                        'CerUPP:GuardBandDiagFailed', ...
                        '%s', me_2.message);
                end
            end

            ic0 = i_diag;
            fprintf('IC debug: mean |A|^2= %.3e, max |A|^2= %.3e\n', ...
                    mean(ic0(:)), max(ic0(:)));
            [~, ix0_dbg] = min(abs(x));
            [~, iy0_dbg] = min(abs(y));
            center_A = squeeze(A_xy(ix0_dbg, iy0_dbg, :));
            center_i = double(n_ratio_diag_xy(ix0_dbg, iy0_dbg)) .* ...
                real(center_A .* conj(center_A));
            fprintf('On-axis sample: max I= %g, mean I= %g\n', max(center_i), mean(center_i));

            no_oam_flag = (double(oam_charge1) == 0) && (double(oam_charge_beam2) == 0);
            no_chirp_flag = (double(beta_chirp) == 0);
            single_beam_flag = ~(isfinite(double(i_laser_peak_beam2)) && ...
                (double(i_laser_peak_beam2) > 0));
            if no_oam_flag && no_chirp_flag && single_beam_flag && ...
                    isfinite(double(i_laser_peak)) && (double(i_laser_peak) > 0)
                realized_peak_i = max(double(i_raw(:)));
                peak_i_rel_err = abs(realized_peak_i - double(i_laser_peak)) / ...
                    max(abs(double(i_laser_peak)), eps_safe);
                if peak_i_rel_err > 1e-2
                    run_warn_state = run_warn_state_utils.emit_softwarn_each_time_with_phase( ...
                        run_warn_state, 'setup', ...
                        'CerUPP:Setup:LaunchPeakIntensityMismatch', ...
                        ['Launch peak intensity differs from i_laser_peak by %.2f%% even though ', ...
                         'beta_chirp=0, oam_charge1=0, oam_charge_beam2=0, and beam 2 is disabled. ', ...
                         'Requested i_laser_peak=%.6e W/m^2, realized peak=%.6e W/m^2.'], ...
                        100 * peak_i_rel_err, double(i_laser_peak), realized_peak_i);
                end
            end
        end


