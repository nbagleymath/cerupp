        function validate_omega_window_fft_order_local(omega_window)
        % Boundary-only omega-grid check for FFT-native ordering (ifftshifted detuning).

            w = omega_window(:).';
            nt = numel(w);
            if nt < 2 || any(~isfinite(w))
                error('CerUPP:DriverFFTOrder', ...
                    'omega_window must be finite with at least two samples.');
            end

            dw = diff(w);
            nonzero_dw = abs(dw(abs(dw) > 0));
            if isempty(nonzero_dw)
                error('CerUPP:DriverFFTOrder', ...
                    'omega_window does not show nonzero FFT-order spacing segments.');
            end
            delta_omega = median(nonzero_dw);
            tol = 1e-10 * max(1, abs(delta_omega));

            idx_ctr = -floor(nt/2):ceil(nt/2)-1;
            idx_fft = ifftshift(idx_ctr);
            omega_ref_est = w(1); % FFT-order convention: index 1 is zero detuning.
            w_expected = omega_ref_est - idx_fft * delta_omega;

            err = max(abs(w - w_expected));
            if err > 50*tol
                error('CerUPP:DriverFFTOrder', ...
                    ['omega_window does not match FFT-native ordering. ', ...
                     'Expected omega_ref - ifftshifted detuning with max abs err %.3e (tol %.3e).'], ...
                    err, 50*tol);
            end
        end

