        function default_value = project_summary_default_local(cast_kind)
            switch char(string(cast_kind))
                case 'char'
                    default_value = '';
                case 'double'
                    default_value = NaN;
                case 'rowdouble'
                    default_value = zeros(1, 0);
                case 'logical'
                    default_value = false;
                otherwise
                    error('CerUPP:UnsupportedSummaryProjectionType', ...
                        'Unsupported summary projection cast "%s".', char(string(cast_kind)));
            end
        end

        function value = project_summary_value_local(raw_value, cast_kind)
            switch char(string(cast_kind))
                case 'char'
                    value = char(string(raw_value));
                case 'double'
                    value = double(raw_value);
                case 'rowdouble'
                    value = reshape(double(raw_value), 1, []);
                case 'logical'
                    value = logical(raw_value);
                otherwise
                    error('CerUPP:UnsupportedSummaryProjectionType', ...
                        'Unsupported summary projection cast "%s".', char(string(cast_kind)));
            end
        end


