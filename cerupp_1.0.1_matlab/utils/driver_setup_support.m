                    freeze_value = cell(size(value_in));
                    for struct_idx = 1:numel(value_in)
                        freeze_value{struct_idx} = ...
                            driver_setup_support.build_function_workspace_freeze_signature_local( ...
                                value_in(struct_idx), depth + 1);
                    end
                    return;
                end
                field_names = sort(fieldnames(value_in));
