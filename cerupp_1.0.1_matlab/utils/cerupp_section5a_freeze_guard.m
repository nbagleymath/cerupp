function varargout = cerupp_section5a_freeze_guard(varargin)
% Driver-only Section 5A helper for cerupp.m.
% In the usual no-input mode this helper reads the current cerupp.m
% workspace, rebuilds the current compare surfaces for every captured
% freeze stage and later built launch/operator/runtime record, and runs
% the full pre-loop freeze guard before propagation starts.

    if nargin == 0
        caller_field_names = caller_field_names_local();
        cfg = struct();
        for ii = 1:numel(caller_field_names)
            field_name = caller_field_names{ii};
            try
                cfg.(field_name) = evalin('caller', field_name);
            catch err
                if strcmp(err.identifier, 'MATLAB:UndefinedFunction') || ...
                        strcmp(err.identifier, 'MATLAB:UndefinedVariable')
                    error('CerUPP:MissingSection5ACallerField', ...
                        ['cerupp_section5a_freeze_guard expected caller variable ''%s'' ', ...
                         'to exist before the Section 5A helper call.'], ...
                        field_name);
                end
                rethrow(err);
            end
        end
        freeze_guard_state = build_freeze_guard_state_local(cfg);
        freeze_guard_state = apply_freeze_guard_local(freeze_guard_state);
        if nargout > 0
            varargout{1} = freeze_guard_state;
        end
        return;
    end

    if (nargin ~= 1) || ~isstruct(varargin{1}) || ~isscalar(varargin{1})
        error('CerUPP:InvalidSection5AFreezeGuardCfg', ...
            'cerupp_section5a_freeze_guard accepts either no inputs or one scalar cfg struct.');
    end

    freeze_guard_state = build_freeze_guard_state_local(varargin{1});
    freeze_guard_state = apply_freeze_guard_local(freeze_guard_state);
    if nargout > 1
        error('CerUPP:InvalidSection5AFreezeGuardOutputCount', ...
            'cerupp_section5a_freeze_guard returns at most one output struct.');
    end
    if nargout == 1
        varargout{1} = freeze_guard_state;
    end
end

