        freeze_guard_state, 'sealed_setup_freeze_surfaces');
    current_surfaces = req_field_local(freeze_guard_state, 'current_surfaces');
    run_warn_state = req_field_local(freeze_guard_state, 'run_warn_state');

    if logical(setup_freeze_guard.enabled)
        user_setup_guard.assert_guard_integrity( ...
            setup_freeze_guard, sealed_setup_freeze_surfaces);
        user_setup_guard.assert_clean( ...
            setup_freeze_guard, current_surfaces);
        freeze_guard_state.run_warn_state = run_warn_state;
        return;
    end

    strict_guard = setup_freeze_guard;
    strict_guard.enabled = true;
    try
        user_setup_guard.assert_guard_integrity( ...
            strict_guard, sealed_setup_freeze_surfaces);
    catch me_guard
        [run_warn_state, handled] = emit_demoted_freeze_guard_warning_local( ...
            run_warn_state, me_guard, 'setup_freeze_guard_integrity_demoted', ...
            'CerUPP:SetupFreezeGuardIntegrityDemotedSoftWarn');
        if ~handled
            rethrow(me_guard);
        end
    end
    try
        user_setup_guard.assert_clean( ...
            strict_guard, current_surfaces);
    catch me_guard
        [run_warn_state, handled] = emit_demoted_freeze_guard_warning_local( ...
            run_warn_state, me_guard, 'setup_freeze_guard_late_edit_demoted', ...
            'CerUPP:SetupFreezeGuardLateEditDemotedSoftWarn');
        if ~handled
            rethrow(me_guard);
        end
    end
    freeze_guard_state.run_warn_state = run_warn_state;
end

function projected_cfg = project_cfg_fields_local(cfg, field_names, context_name)
    projected_cfg = struct();
    for ii = 1:numel(field_names)
        field_name = field_names{ii};
        projected_cfg.(field_name) = struct_utils.req_struct_field( ...
            cfg, field_name, context_name);
    end
end

function value = req_field_local(cfg, field_name)
    value = struct_utils.req_struct_field( ...
        cfg, field_name, 'cerupp_section5a_freeze_guard');
end

function [run_warn_state, handled] = emit_demoted_freeze_guard_warning_local( ...
        run_warn_state, me_guard, warn_key, warn_id)
    handled = false;
    if strcmp(me_guard.identifier, 'CerUPP:LateVisibleSetupEditAfterFreeze')
        handled = true;
        run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
            run_warn_state, 'setup', warn_key, warn_id, ...
            ['enable_setup_freeze_guard_flag=false demoted this freeze-guard hard error to ', ...
             'a soft warning: %s'], ...
            me_guard.message);
    end
end
