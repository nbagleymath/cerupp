        function stage_name = normalize_optional_stage_name_local(stage_name_in)
            stage_name = '';
            if isstring(stage_name_in) && isscalar(stage_name_in)
                stage_name_in = char(stage_name_in);
            end
            if ~(ischar(stage_name_in) && ~isempty(strtrim(stage_name_in)))
                return;
            end
            stage_name = plasma_setup_support.canonical_stage_name(stage_name_in);
        end

        function v = compat_warn_state_value_local(s, field_name, default_value, field_kind)
            if nargin < 4 || isempty(field_kind)
                field_kind = 'num';
            end
            if strcmp(field_kind, 'bool')
                v = struct_utils.normalize_bool_scalar( ...
                    default_value, field_name, 'CerUPP:InvalidWarningStateField');
            else
                v = default_value;
            end
            if ~(isstruct(s) && isscalar(s) && isfield(s, field_name)) || isempty(s.(field_name))
                return;
            end

            raw = s.(field_name);
            switch field_kind
                case 'num'
                    if ~(isnumeric(raw) || islogical(raw))
                        error('CerUPP:InvalidWarningStateField', ...
                            'Field "%s" must be numeric/logical scalar.', field_name);
                    end
                    v = double(raw);
                    allow_nonfinite = isnumeric(default_value) && isscalar(default_value) && ...
                        ~isfinite(double(default_value));
                    if ~isscalar(v) || ~isreal(v) || (~allow_nonfinite && ~isfinite(v))
                        error('CerUPP:InvalidWarningStateField', ...
                            'Field "%s" must be a finite real scalar.', field_name);
                    end
                case 'text'
                    if ischar(raw)
                        v = raw;
                    elseif isstring(raw) && isscalar(raw)
                        v = char(raw);
                    else
                        error('CerUPP:InvalidWarningStateField', ...
                            'Field "%s" must be char or scalar string.', field_name);
                    end
                case 'bool'
                    v = struct_utils.normalize_bool_scalar( ...
                        raw, field_name, 'CerUPP:InvalidWarningStateField');
                otherwise
                    error('CerUPP:InvalidWarningStateAccessorKind', ...
                        'Unsupported warning-state accessor kind "%s".', field_kind);
            end
        end

        function stage_name = summary_stage_name_or_na_local(stage_name_in)
            stage_name = plasma_setup_support.normalize_optional_stage_name_local(stage_name_in);
            if isempty(stage_name)
