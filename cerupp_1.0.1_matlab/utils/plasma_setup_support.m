                keldysh_ctx.plasma_ofi_use_remaining_neutral_factor_flag = logical( ...
                    struct_utils.opt_struct_field( ...
                        ofi_setup, 'plasma_ofi_use_remaining_neutral_factor_flag', true));
            end
            keldysh_ctx.K_eff_single = double(final_keff);
            if isfield(keldysh_ctx, 'use_scalar_keff_bookkeeping')
                keldysh_ctx.use_scalar_keff_bookkeeping = true;
            end
            if isfield(keldysh_ctx, 'bookkeeping_diag_enabled')
                keldysh_ctx.bookkeeping_diag_enabled = true;
            end
            neutral_reservoir_m3 = double(struct_utils.opt_struct_field( ...
                plasma_runtime_cfg, 'neutral_reservoir_m3', NaN));
            if ~(isfinite(neutral_reservoir_m3) && (neutral_reservoir_m3 > 0))
                neutral_reservoir_cap_m3 = struct_utils.opt_struct_field( ...
                    plasma_runtime_cfg, 'neutral_reservoir_cap_m3', ...
                    struct_utils.opt_struct_field(plasma_runtime_cfg, 'rho_stage_cap', Inf));
                neutral_reservoir_m3 = ...
                    plasma_setup_support.resolve_effective_neutral_reservoir_m3_local( ...
                        struct_utils.opt_struct_field(plasma_runtime_cfg, 'rho_nt_m3', NaN), ...
                        neutral_reservoir_cap_m3);
            end
            nla_softwarn_state = struct();
            num_saved = plasma_setup_support.resolve_saved_plane_count_local( ...
                diagnostic_store, size(diagnostic_store.store_keldysh_diag_i_core, 3));
            diagnostic_store = ...
                plasma_setup_support.clear_keldysh_effective_diag_summaries_local( ...
                    diagnostic_store);
            for save_idx = 1:num_saved
                i_core = diagnostic_store.store_keldysh_diag_i_core(:, :, save_idx);
                rho_core = diagnostic_store.store_keldysh_diag_rho_core(:, :, save_idx);
                if isempty(i_core) || ~any(isfinite(i_core(:)) & (i_core(:) >= 0))
                    continue;
                end
                if ~(isfinite(neutral_reservoir_m3) && (neutral_reservoir_m3 > 0))
                    continue;
                end
                if isempty(rho_core) || ~any(isfinite(rho_core(:)))
                    plasma_ofi_uses_remaining_neutral = ...
                        logical(struct_utils.opt_struct_field( ...
                            keldysh_ctx, 'plasma_ofi_use_remaining_neutral_factor_flag', ...
                            ~struct_utils.opt_struct_field( ...
                                keldysh_ctx, ...
                                'keldysh_use_additive_volumetric_source_flag', false)));
                    if ~plasma_ofi_uses_remaining_neutral
                        rho_core = zeros(size(i_core), 'like', i_core);
                    else
                        continue;
                    end
                end
                if isa(i_core, 'single')
                    tiny_i = realmin('single');
                else
                    tiny_i = realmin('double');
                end
                remaining_neutral_core = max( ...
                    cast(double(neutral_reservoir_m3), 'like', i_core) - real(rho_core), 0);
                try
                    [~, ~, sigma_eff, beta_eff_full, beta_eff_applied, nla_softwarn_state] = ...
                        nla_support.evaluate_keldysh_matched_terms_for_postrun( ...
                            real(i_core), remaining_neutral_core, keldysh_ctx, tiny_i, ...
                            nla_softwarn_state, false, true);
                    sigma_pair = ...
                        propagation_support.summarize_keldysh_effective_diag_core_local( ...
                            sigma_eff, true, axis_in_core, axis_core_row);
                    beta_full_pair = ...
                        propagation_support.summarize_keldysh_effective_diag_core_local( ...
                            beta_eff_full, true, axis_in_core, axis_core_row);
                    beta_applied_pair = ...
                        propagation_support.summarize_keldysh_effective_diag_core_local( ...
                            beta_eff_applied, true, axis_in_core, axis_core_row);
                    diagnostic_store.store_sigma_k_eff_keldysh_oa(save_idx) = sigma_pair(1);
                    diagnostic_store.store_sigma_k_eff_keldysh_maxperp(save_idx) = sigma_pair(2);
                    diagnostic_store.store_beta_eff_full_keldysh_oa(save_idx) = beta_full_pair(1);
                    diagnostic_store.store_beta_eff_full_keldysh_maxperp(save_idx) = beta_full_pair(2);
                    diagnostic_store.store_beta_eff_applied_keldysh_oa(save_idx) = beta_applied_pair(1);
                    diagnostic_store.store_beta_eff_applied_keldysh_maxperp(save_idx) = beta_applied_pair(2);
                catch me_rebuild
                    diagnostic_store = ...
                        plasma_setup_support.clear_keldysh_effective_diag_summaries_local( ...
                            diagnostic_store, save_idx);
                    run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                        run_warn_state, 'end', ...
                        'keldysh_postrun_diag_rebuild_failed', ...
                        'CerUPP:KeldyshPostrunDiagnosticRebuildFailed', ...
                        ['Failed to rebuild the matched-Keldysh diagnostic traces from the raw stored core arrays ', ...
                         'at save_idx=%d. Leaving that saved plane unavailable in the final ', ...
                         'matched-Keldysh trace family. Detail: %s'], ...
                        double(save_idx), me_rebuild.message);
                end
            end
        end

