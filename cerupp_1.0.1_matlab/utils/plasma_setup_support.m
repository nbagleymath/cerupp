            end
        end

        function text_out = format_numeric_or_na_local(value_in, format_text)
            if nargin < 2 || isempty(format_text)
                format_text = '%.6g';
            end
            if isscalar(value_in) && isnumeric(value_in) && isreal(value_in) && isfinite(value_in)
                text_out = sprintf(format_text, double(value_in));
            else
                text_out = 'n/a';
            end
        end

