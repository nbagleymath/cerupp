        function value_struct = project_keldysh_runtime_model_view_local(runtime_model, view_name)
        % Materialize one named projection from the canonical Keldysh runtime model.

            projection_specs = plasma_setup_support.keldysh_runtime_projection_specs_local();
            switch lower(char(string(view_name)))
                case 'signature'
                    dst_col = 2;
                    default_col = 3;
                    kind_col = 4;
                case 'cfg_shell'
                    dst_col = 5;
                    default_col = 6;
                    kind_col = 7;
                otherwise
                    error('CerUPP:InvalidKeldyshRuntimeProjectionView', ...
                        'Unsupported Keldysh runtime projection view "%s".', ...
                        char(string(view_name)));
            end
            value_struct = plasma_setup_support.project_keldysh_runtime_model_fields_local( ...
                runtime_model, projection_specs, dst_col, default_col, kind_col);
        end

        function value_struct = project_keldysh_runtime_model_fields_local(runtime_model, field_specs, dst_col, default_col, kind_col)
        % Materialize a subset/literal projection from the canonical Keldysh runtime model.

            value_struct = struct();
            if nargin < 2 || isempty(field_specs)
                return;
            end
            if nargin < 3 || isempty(dst_col)
                dst_col = 1;
            end
            if nargin < 4 || isempty(default_col)
                default_col = 3;
            end
            if nargin < 5 || isempty(kind_col)
                kind_col = 4;
            end
            for spec_idx = 1:size(field_specs, 1)
                src_name = field_specs{spec_idx, 1};
                dst_name = field_specs{spec_idx, dst_col};
                default_value = field_specs{spec_idx, default_col};
                value_kind = lower(char(string(field_specs{spec_idx, kind_col})));
                if isempty(dst_name) || strcmp(value_kind, 'skip')
                    continue;
                end
                if strcmp(value_kind, 'literal')
                    value_struct.(dst_name) = default_value;
                    continue;
                end
                value = struct_utils.opt_struct_field(runtime_model, src_name, default_value);
                switch value_kind
                    case 'logical'
                        value = logical(value);
                    case 'double'
                        value = double(value);
                    case 'char'
                        value = char(string(value));
                    case 'rowdouble'
                        value = double(value(:)).';
                    case 'raw'
                        % Keep the stored value as-is.

                    otherwise
                        error('CerUPP:InvalidKeldyshRuntimeProjectionKind', ...
                            'Unsupported Keldysh runtime projection kind "%s".', value_kind);
                end
                value_struct.(dst_name) = value;
            end
        end

