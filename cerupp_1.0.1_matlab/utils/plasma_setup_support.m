        function keldysh_material_state = resolve_keldysh_material_state_local( ...
                base_material_state, material_state_update, context_label)
        % Build one grouped Keldysh material state from the current
        % driver-owned material scalars plus any optional grouped update.

            if nargin < 1 || isempty(base_material_state) || ...
                    ~(isstruct(base_material_state) && isscalar(base_material_state))
                error('CerUPP:InvalidKeldyshMaterialStateBase', ...
                    'resolve_keldysh_material_state_local requires one scalar base material-state struct.');
            end
            if nargin < 2 || isempty(material_state_update)
                material_state_update = struct();
            end
            if nargin < 3 || isempty(context_label)
                context_label = 'keldysh_material_state';
            end
            if ~(isstruct(material_state_update) && isscalar(material_state_update))
                error('CerUPP:InvalidKeldyshMaterialStateUpdate', ...
                    '%s update must be a scalar struct when supplied.', context_label);
            end

            required_fields = { ...
                'frozen_cfg_rho_nt_m3', ...
                'frozen_cfg_rho_nt_keldysh_norm_m3', ...
                'frozen_cfg_ui', ...
                'frozen_cfg_keldysh_gap_j', ...
                'frozen_cfg_keldysh_matched_depletion_j', ...
                'n_sell_fund', ...
                'frozen_cfg_ofi_k_orders', ...
                'frozen_cfg_sigma_k_vec', ...
                'keldysh_mred_kg'};
            operator_coupled_fields = { ...
                'frozen_cfg_rho_nt_m3', ...
                'frozen_cfg_ui', ...
                'frozen_cfg_keldysh_gap_j', ...
                'n_sell_fund', ...
                'keldysh_mred_kg'};
            update_allowed_fields = setdiff( ...
                required_fields, operator_coupled_fields, 'stable');
            keldysh_material_state = base_material_state;
            update_fields = fieldnames(material_state_update);
            for field_idx = 1:numel(update_fields)
                field_name = update_fields{field_idx};
                if ismember(field_name, operator_coupled_fields)
                    error('CerUPP:UnsupportedOperatorCoupledKeldyshMaterialStateField', ...
                        ['%s update field "%s" changes shared operator/plasma material state that the later rebuild path does not ', ...
                         'fully re-derive from this grouped update surface yet. Keep keldysh_material_state_update limited to these ', ...
                         'downstream OFI/NLA fields until a full re-derive path exists: %s.'], ...
                        context_label, field_name, ...
                        strjoin(update_allowed_fields, ', '));
                end
                if ~ismember(field_name, update_allowed_fields)
                    error('CerUPP:InvalidKeldyshMaterialStateField', ...
                        ['%s update contains unsupported field "%s". ', ...
                         'Only fields from the grouped Keldysh material state may be updated ', ...
                         'through this surface.'], ...
                        context_label, field_name);
                end
                keldysh_material_state.(field_name) = material_state_update.(field_name);
            end
            for field_idx = 1:numel(required_fields)
                field_name = required_fields{field_idx};
                if ~isfield(keldysh_material_state, field_name)
