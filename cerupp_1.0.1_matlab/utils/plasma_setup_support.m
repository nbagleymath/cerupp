        function s = record_exponent_context_array(s, stage_name, expo_raw, i_ref, log_min, log_max)
        % RECORD_EXPONENT_CONTEXT_ARRAY Capture worst-case context when exponent clamps are exercised.

            s = plasma_setup_support.init_state(s);
            if nargin < 3 || isempty(expo_raw)
                return;
            end
            stage_name = plasma_setup_support.canonical_stage_name(stage_name);
            if nargin < 4 || isempty(i_ref)
                i_ref = [];
            end
            if nargin < 5 || isempty(log_min) || ~isfinite(log_min), log_min = -inf; end
            if nargin < 6 || isempty(log_max) || ~isfinite(log_max), log_max = inf; end

            clamp_mask = isfinite(expo_raw) & ((expo_raw < log_min) | (expo_raw > log_max));
            if ~any(clamp_mask(:))
                return;
            end

            raw_clamped = expo_raw(clamp_mask);
            raw_min = double(min(raw_clamped(:)));
            raw_max = double(max(raw_clamped(:)));
            raw_abs_peak = double(max(abs(raw_clamped(:))));
            [s, new_worst] = plasma_setup_support.update_exponent_summary( ...
                s, stage_name, raw_min, raw_max, raw_abs_peak);

            if new_worst && ~isempty(i_ref)
                stage_key = plasma_setup_support.canonical_stage_name(stage_name);
                clamp_idx = find(clamp_mask);
                if ~isempty(clamp_idx)
                    [~, idx_rel_worst] = max(abs(expo_raw(clamp_idx)));
                    idx_worst = clamp_idx(idx_rel_worst);
                    s.global.exponent_soft_clamp.i_at_worst = plasma_setup_support.map_intensity_at_index( ...
                        i_ref, double(idx_worst), size(expo_raw));
                end
                if ~logical(s.global.exponent_soft_clamp.detail_seen_stage.(stage_key))
                    s.global.exponent_soft_clamp.detail_seen_stage.(stage_key) = true;
                end
            end
        end

        function [s, new_worst] = update_exponent_summary(s, stage_name, raw_min, raw_max, raw_abs)
        % UPDATE_EXPONENT_SUMMARY Shared exponent-clamp summary accumulator for raw-array and Keldysh paths.

            s = plasma_setup_support.init_state(s);
            stage_name = plasma_setup_support.canonical_stage_name(stage_name);
            new_worst = false;
            if nargin < 3 || ~isfinite(raw_min)
                raw_min = NaN;
            end
            if nargin < 4 || ~isfinite(raw_max)
                raw_max = NaN;
            end
            if nargin < 5 || ~isfinite(raw_abs)
                raw_abs = NaN;
            end
            exp_rec = s.global.exponent_soft_clamp;
            if isfinite(raw_min)
                exp_rec.raw_min = min(double(exp_rec.raw_min), double(raw_min));
            end
            if isfinite(raw_max)
                exp_rec.raw_max = max(double(exp_rec.raw_max), double(raw_max));
            end
            new_worst = isfinite(raw_abs) && (double(raw_abs) > double(exp_rec.max_abs_raw));
            if new_worst
                exp_rec.max_abs_raw = double(raw_abs);
                exp_rec.worst_stage = plasma_setup_support.canonical_stage_name(stage_name);
            end
            s.global.exponent_soft_clamp = exp_rec;
        end

