classdef plasma_setup_support
% Plasma/Keldysh setup, reporting, and postrun accounting helpers.
% Build setup-side plasma/NLA records from explicit driver inputs and report the resolved plasma model choices.

    methods (Static, Hidden)
        function ofi_setup = build_ofi_setup_static_local(plasma_runtime_cfg, k_power_vec, sigma_k_vec, ofi_branch_active)
        % Build the resolved setup-owned OFI/Keldysh context consumed by plasma and OFI-based NLA.

            if nargin < 4 || isempty(ofi_branch_active)
                ofi_branch_active = true;
            end
            ofi_branch_active = logical(ofi_branch_active);
            [k_power_all, sigma_k_all] = ofi_cache_utils.normalize_mpi_vectors( ...
                k_power_vec, sigma_k_vec);
            kcfg = struct_utils.opt_struct_field(plasma_runtime_cfg, 'keldysh_cfg', struct());
            keldysh_ctx = ofi_cache_utils.build_keldysh_context( ...
                plasma_runtime_cfg, k_power_vec, sigma_k_vec);
            active_ofi = logical(ofi_branch_active) & (sigma_k_all > 0);
            if logical(ofi_branch_active) && isstruct(keldysh_ctx) && isfield(keldysh_ctx, 'enabled') && logical(keldysh_ctx.enabled) && ...
                    isfield(keldysh_ctx, 'idx_dyn') && ~isempty(keldysh_ctx.idx_dyn)
                idx_dyn_raw = double(keldysh_ctx.idx_dyn(:));
                idx_dyn_round = round(idx_dyn_raw);
                idx_tol = 1e-12;
                if any(~isfinite(idx_dyn_raw)) || any(abs(idx_dyn_raw - idx_dyn_round) > idx_tol)
                    error('CerUPP:InvalidKeldyshIdxDyn', ...
                        'keldysh_ctx.idx_dyn must be finite integer indices; got %s.', ...
                        mat2str(idx_dyn_raw(:).'));
                end
                idx_dyn = idx_dyn_round;
                idx_dyn = idx_dyn((idx_dyn >= 1) & (idx_dyn <= numel(active_ofi)));
                if ~isempty(idx_dyn)
                    active_ofi(unique(idx_dyn)) = false;
                end
            end
            k_active = reshape(k_power_all(active_ofi), [1, nnz(active_ofi)]);
            sigma_active = reshape(sigma_k_all(active_ofi), [1, nnz(active_ofi)]);
            hbar_omega_j = struct_utils.opt_struct_field(kcfg, 'hbar_omega_J', NaN);
            ui_j = double(struct_utils.opt_struct_field( ...
                kcfg, 'Ui_J', struct_utils.opt_struct_field(plasma_runtime_cfg, 'Ui_J', NaN)));
            matched_depletion_j = double(struct_utils.opt_struct_field( ...
                kcfg, 'keldysh_matched_depletion_J', ...
                struct_utils.opt_struct_field(plasma_runtime_cfg, 'keldysh_matched_depletion_J', NaN)));
            if ~(isscalar(matched_depletion_j) && isreal(matched_depletion_j) && ...
                    isfinite(matched_depletion_j) && (matched_depletion_j > 0))
                if isscalar(ui_j) && isreal(ui_j) && isfinite(ui_j) && (ui_j > 0)
                    matched_depletion_j = ui_j;
                elseif isscalar(hbar_omega_j) && isreal(hbar_omega_j) && ...
                        isfinite(hbar_omega_j) && (hbar_omega_j > 0) && ...
                        (numel(k_active) == 1) && isfinite(double(k_active(1))) && ...
                        (double(k_active(1)) > 0)
                    matched_depletion_j = double(k_active(1)) .* double(hbar_omega_j);
                end
            end
            % K_display stays setup-side scalar-only for the dynamic
            % W_ion(I) translation. The older runtime-weighted
            % effective-order branch is no longer used.
            use_scalar_keff_flag = true;
            k_eff_single = NaN;
            if isstruct(keldysh_ctx) && isfield(keldysh_ctx, 'K_eff_single') && ...
                    isfinite(keldysh_ctx.K_eff_single) && (keldysh_ctx.K_eff_single > 0)
                k_eff_single = double(keldysh_ctx.K_eff_single);
            elseif isfield(kcfg, 'K_eff_single') && isfinite(kcfg.K_eff_single) && (kcfg.K_eff_single > 0)
                k_eff_single = double(kcfg.K_eff_single);
            elseif (numel(k_active) == 1) && isfinite(double(k_active(1))) && (double(k_active(1)) > 0)
                k_eff_single = double(k_active(1));
            end
            plasma_ofi_use_remaining_neutral_factor_flag = logical(struct_utils.opt_struct_field( ...
                kcfg, 'plasma_ofi_use_remaining_neutral_factor_flag', ...
                ~struct_utils.opt_struct_field(kcfg, 'keldysh_use_additive_volumetric_source_flag', false)));
            source_density_scale_m3 = NaN;
            rho_nt_norm_val = double(struct_utils.opt_struct_field(kcfg, 'rho_nt_keldysh_norm_m3', NaN));
            neutral_reservoir_val = double(struct_utils.opt_struct_field( ...
                plasma_runtime_cfg, 'neutral_reservoir_m3', NaN));
            if isfinite(rho_nt_norm_val) && (rho_nt_norm_val > 0)
                source_density_scale_m3 = rho_nt_norm_val;
                if isfinite(neutral_reservoir_val) && (neutral_reservoir_val > 0)
                    source_density_scale_m3 = min(source_density_scale_m3, neutral_reservoir_val);
                end
            elseif isfinite(neutral_reservoir_val) && (neutral_reservoir_val > 0)
                source_density_scale_m3 = neutral_reservoir_val;
            end
            keldysh_ctx.K_vec = double(k_active);
            keldysh_ctx.sigmaK_vec = double(sigma_active);
            keldysh_ctx.plasma_ofi_use_remaining_neutral_factor_flag = ...
                logical(plasma_ofi_use_remaining_neutral_factor_flag);
            keldysh_ctx.ofi_source_density_scale_m3 = double(source_density_scale_m3);
            keldysh_ctx.keldysh_matched_depletion_J = double(matched_depletion_j);
            keldysh_ctx.Ui_J = double(ui_j);
            report_meta = plasma_setup_support.build_ofi_report_meta_local(kcfg, keldysh_ctx);
            ofi_setup = struct( ...
                'keldysh_ctx', keldysh_ctx, ...
                'hbar_omega_J', double(hbar_omega_j), ...
                'Ui_J', double(ui_j), ...
                'keldysh_matched_depletion_J', double(matched_depletion_j), ...
                'plasma_ofi_use_remaining_neutral_factor_flag', logical(plasma_ofi_use_remaining_neutral_factor_flag), ...
                'ofi_source_density_scale_m3', double(source_density_scale_m3), ...
                'use_scalar_keff_flag', logical(use_scalar_keff_flag), ...
                'K_eff_single', double(k_eff_single), ...
                'report_meta', report_meta, ...
                'k_power', k_active, ...
                'log_sigK', reshape(log(sigma_active), [1, nnz(active_ofi)]));
        end

        function keldysh_setup_cfg = build_keldysh_setup_cfg_local( ...
                keldysh_setup_seed, phase_tag, frozen_cfg_rho_nt_m3, ...
                frozen_cfg_rho_nt_keldysh_norm_m3, plot_session, ...
                keldysh_runtime_enabled)
        % Build the setup-side Keldysh config shell from one shared seed.
        % This packages the selected Keldysh inputs for runtime setup and
        % any setup-time diagnostic plotting. The setup-time plot/save
        % policy comes from the earlier plot_session passed in by cerupp.m.

            if nargin < 1 || isempty(keldysh_setup_seed) || ~isstruct(keldysh_setup_seed)
                keldysh_setup_seed = struct();
            end
            if nargin < 2 || isempty(phase_tag)
                phase_tag = 'setup';
            end
            if nargin < 3 || isempty(frozen_cfg_rho_nt_m3)
                frozen_cfg_rho_nt_m3 = NaN;
            end
            if nargin < 4 || isempty(frozen_cfg_rho_nt_keldysh_norm_m3)
                frozen_cfg_rho_nt_keldysh_norm_m3 = frozen_cfg_rho_nt_m3;
            end
            if nargin < 5 || isempty(plot_session)
                plot_session = struct();
            end
            if nargin < 6 || isempty(keldysh_runtime_enabled)
                keldysh_runtime_enabled = struct_utils.opt_struct_field( ...
                    keldysh_setup_seed, 'keldysh_enabled', false);
            end
            keldysh_setup_cfg = keldysh_setup_seed;
            keldysh_material_state_base = struct( ...
                'frozen_cfg_rho_nt_m3', struct_utils.opt_struct_field( ...
                    keldysh_setup_seed, 'frozen_cfg_rho_nt_m3', frozen_cfg_rho_nt_m3), ...
                'frozen_cfg_rho_nt_keldysh_norm_m3', struct_utils.opt_struct_field( ...
                    keldysh_setup_seed, 'frozen_cfg_rho_nt_keldysh_norm_m3', ...
                    frozen_cfg_rho_nt_keldysh_norm_m3), ...
                'frozen_cfg_ui', struct_utils.opt_struct_field( ...
                    keldysh_setup_seed, 'frozen_cfg_ui', NaN), ...
                'frozen_cfg_keldysh_gap_j', struct_utils.opt_struct_field( ...
                    keldysh_setup_seed, 'frozen_cfg_keldysh_gap_j', NaN), ...
                'frozen_cfg_keldysh_matched_depletion_j', ...
                    struct_utils.opt_struct_field( ...
                        keldysh_setup_seed, ...
                        'frozen_cfg_keldysh_matched_depletion_j', NaN), ...
                'n_sell_fund', struct_utils.opt_struct_field( ...
                    keldysh_setup_seed, 'n_sell_fund', NaN), ...
                'frozen_cfg_ofi_k_orders', struct_utils.opt_struct_field( ...
                    keldysh_setup_seed, 'frozen_cfg_ofi_k_orders', []), ...
                'frozen_cfg_sigma_k_vec', struct_utils.opt_struct_field( ...
                    keldysh_setup_seed, 'frozen_cfg_sigma_k_vec', []), ...
                'keldysh_mred_kg', struct_utils.opt_struct_field( ...
                    keldysh_setup_seed, 'keldysh_mred_kg', NaN));
            keldysh_material_state_seed = struct_utils.opt_struct_field( ...
                keldysh_setup_seed, 'keldysh_material_state', struct(), ...
                'treat_empty_as_missing', true);
            if isempty(keldysh_material_state_seed)
                keldysh_material_state = ...
                    plasma_setup_support.resolve_keldysh_material_state_local( ...
                        keldysh_material_state_base, struct(), ...
                        'build_keldysh_setup_cfg_local');
            else
                % cerupp.m and the rebuild refresh path can pass a fully
                % resolved grouped material record here. Revalidate that
                % full state directly instead of reinterpreting it as a
                % restricted update surface.
                keldysh_material_state = ...
                    plasma_setup_support.resolve_keldysh_material_state_local( ...
                        keldysh_material_state_seed, struct(), ...
                        'build_keldysh_setup_cfg_local keldysh_material_state');
            end
            keldysh_setup_cfg.keldysh_material_state = keldysh_material_state;
            keldysh_setup_cfg.frozen_cfg_ui = keldysh_material_state.frozen_cfg_ui;
            keldysh_setup_cfg.frozen_cfg_keldysh_gap_j = ...
                keldysh_material_state.frozen_cfg_keldysh_gap_j;
            keldysh_setup_cfg.frozen_cfg_keldysh_matched_depletion_j = ...
                keldysh_material_state.frozen_cfg_keldysh_matched_depletion_j;
            keldysh_setup_cfg.n_sell_fund = keldysh_material_state.n_sell_fund;
            keldysh_setup_cfg.frozen_cfg_ofi_k_orders = ...
                keldysh_material_state.frozen_cfg_ofi_k_orders;
            keldysh_setup_cfg.frozen_cfg_sigma_k_vec = ...
                keldysh_material_state.frozen_cfg_sigma_k_vec;
            keldysh_setup_cfg.keldysh_mred_kg = keldysh_material_state.keldysh_mred_kg;
            keldysh_setup_cfg.phase_tag = char(string(phase_tag));
            keldysh_setup_cfg.frozen_cfg_rho_nt_m3 = double(frozen_cfg_rho_nt_m3);
            keldysh_setup_cfg.frozen_cfg_rho_nt_keldysh_norm_m3 = ...
                double(frozen_cfg_rho_nt_keldysh_norm_m3);
            keldysh_setup_cfg.plot_policy = plot_session;
            keldysh_setup_cfg.keldysh_runtime_enabled = logical(keldysh_runtime_enabled);
            [keldysh_setup_cfg.keldysh_lut_i_roi_min, ...
             keldysh_setup_cfg.keldysh_zero_rate_below] = ...
                plasma_setup_support.normalize_keldysh_lut_controls_local( ...
                    struct_utils.req_struct_field( ...
                        keldysh_setup_cfg, 'keldysh_lut_i_roi_min', ...
                        'build_keldysh_setup_cfg_local keldysh_setup_cfg'), ...
                    struct_utils.req_struct_field( ...
                        keldysh_setup_cfg, 'keldysh_zero_rate_below', ...
                        'build_keldysh_setup_cfg_local keldysh_setup_cfg'));
            if isfield(keldysh_setup_cfg, 'i_laser_peak')
                keldysh_setup_cfg = rmfield(keldysh_setup_cfg, 'i_laser_peak');
            end
        end

        function [keldysh_lut_i_roi_min, keldysh_zero_rate_below] = ...
                normalize_keldysh_lut_controls_local( ...
                keldysh_lut_i_roi_min, keldysh_zero_rate_below)
        % Resolve the dense-ROI lower bound and zero-rate floor once at the setup boundary.

            if ~(isscalar(keldysh_lut_i_roi_min) && isnumeric(keldysh_lut_i_roi_min) && ...
                    isreal(keldysh_lut_i_roi_min) && isfinite(keldysh_lut_i_roi_min) && ...
                    (double(keldysh_lut_i_roi_min) > 0))
                error('CerUPP:InvalidKeldyshRoiMinIntensity', ...
                    'keldysh_lut_i_roi_min must be one finite real scalar > 0 [W/m^2].');
            end
            keldysh_lut_i_roi_min = double(keldysh_lut_i_roi_min);
            if ~(isscalar(keldysh_zero_rate_below) && isnumeric(keldysh_zero_rate_below) && ...
                    isreal(keldysh_zero_rate_below) && isfinite(keldysh_zero_rate_below) && ...
                    (double(keldysh_zero_rate_below) >= 0))
                error('CerUPP:InvalidKeldyshZeroRateFloor', ...
                    'keldysh_zero_rate_below must be a finite real scalar >= 0 [W/m^2].');
            end
            keldysh_zero_rate_below = double(keldysh_zero_rate_below);
        end

        function [plasma_runtime_cfg, nla_runtime_cfg, submodel_warn_state, ...
                keldysh_setup_seed, run_warn_state, setup_physics_rewrite_report] = ...
                refresh_medium_rebuild_submodel_cfgs_local(cfg)
        % Refresh the medium-dependent plasma/Keldysh/NLA setup after a z rebuild.
        % Reapply the same setup rules to the rebuilt material scalars while keeping caller-owned plot/report policy explicit.

            if nargin < 1 || ~isstruct(cfg) || ~isscalar(cfg)
                error('CerUPP:InvalidMediumRebuildSubmodelCfg', ...
                    'refresh_medium_rebuild_submodel_cfgs_local requires one scalar struct cfg.');
            end

            context_name = 'refresh_medium_rebuild_submodel_cfgs_local cfg';
            plasma_runtime_cfg = struct_utils.req_struct_field( ...
                cfg, 'plasma_runtime_cfg', context_name);
            nla_runtime_cfg = struct_utils.req_struct_field( ...
                cfg, 'nla_runtime_cfg', context_name);
            keldysh_setup_seed = struct_utils.req_struct_field( ...
                cfg, 'keldysh_setup_seed', context_name);
            run_warn_state = struct_utils.req_struct_field( ...
                cfg, 'run_warn_state', context_name);
            setup_physics_rewrite_report = struct_utils.req_struct_field( ...
                cfg, 'setup_physics_rewrite_report', context_name);
            frozen_cfg_rho_nt_m3 = struct_utils.req_struct_field( ...
                cfg, 'frozen_cfg_rho_nt_m3', context_name);
            frozen_cfg_rho_nt_keldysh_norm_m3 = struct_utils.req_struct_field( ...
                cfg, 'frozen_cfg_rho_nt_keldysh_norm_m3', context_name);
            frozen_cfg_ui = struct_utils.req_struct_field( ...
                cfg, 'frozen_cfg_ui', context_name);
            frozen_cfg_keldysh_gap_j = struct_utils.req_struct_field( ...
                cfg, 'frozen_cfg_keldysh_gap_j', context_name);
            frozen_cfg_keldysh_matched_depletion_j = struct_utils.req_struct_field( ...
                cfg, 'frozen_cfg_keldysh_matched_depletion_j', context_name);
            n_sell_fund = struct_utils.req_struct_field( ...
                cfg, 'n_sell_fund', context_name);
            frozen_cfg_sigma_k_vec = struct_utils.req_struct_field( ...
                cfg, 'frozen_cfg_sigma_k_vec', context_name);
            frozen_cfg_ofi_k_orders = struct_utils.req_struct_field( ...
                cfg, 'frozen_cfg_ofi_k_orders', context_name);
            keldysh_mred_kg = struct_utils.req_struct_field( ...
                cfg, 'keldysh_mred_kg', context_name);
            nl_absorption_flag = struct_utils.req_struct_field( ...
                cfg, 'nl_absorption_flag', context_name);
            nla_use_ofi_rate_law_flag = struct_utils.req_struct_field( ...
                cfg, 'nla_use_ofi_rate_law_flag', context_name);
            keldysh_enabled = struct_utils.req_struct_field( ...
                cfg, 'keldysh_enabled', context_name);
            ofi_branch_active = struct_utils.req_struct_field( ...
                cfg, 'ofi_branch_active', context_name);
            plasma_ofi_use_remaining_neutral_factor_flag = ...
                struct_utils.req_struct_field( ...
                    cfg, 'plasma_ofi_use_remaining_neutral_factor_flag', context_name);
            nla_use_remaining_neutral_factor_flag = ...
                struct_utils.req_struct_field( ...
                    cfg, 'nla_use_remaining_neutral_factor_flag', context_name);
            resolved_nla_setup_closure = struct_utils.req_struct_field( ...
                cfg, 'resolved_nla_setup_closure', context_name);
            nla_z_rk2_flag_effective = struct_utils.req_struct_field( ...
                cfg, 'nla_z_rk2_flag_effective', context_name);
            hbar = struct_utils.req_struct_field(cfg, 'hbar', context_name);
            omega_fund = struct_utils.req_struct_field(cfg, 'omega_fund', context_name);
            submodel_warn_state = struct('plasma', struct(), 'nla', struct());
            rebuild_policy = struct_utils.opt_struct_field( ...
                cfg, 'rebuild_policy', struct(), ...
                'treat_empty_as_missing', true);
            if ~(isempty(rebuild_policy) || ...
                    (isstruct(rebuild_policy) && isscalar(rebuild_policy)))
                error('CerUPP:InvalidRebuildPolicyInSubmodelRefresh', ...
                    'rebuild_policy must be empty or a scalar struct.');
            end
            refresh_keldysh_runtime_cfg = logical(struct_utils.opt_struct_field( ...
                rebuild_policy, 'allow_keldysh_runtime_reload_effective', ...
                struct_utils.opt_struct_field( ...
                    cfg, 'refresh_keldysh_runtime_cfg', keldysh_enabled)));
            keldysh_material_state = plasma_setup_support.resolve_keldysh_material_state_local( ...
                struct( ...
                    'frozen_cfg_rho_nt_m3', frozen_cfg_rho_nt_m3, ...
                    'frozen_cfg_rho_nt_keldysh_norm_m3', ...
                        frozen_cfg_rho_nt_keldysh_norm_m3, ...
                    'frozen_cfg_ui', frozen_cfg_ui, ...
                    'frozen_cfg_keldysh_gap_j', frozen_cfg_keldysh_gap_j, ...
                    'frozen_cfg_keldysh_matched_depletion_j', ...
                        frozen_cfg_keldysh_matched_depletion_j, ...
                    'n_sell_fund', n_sell_fund, ...
                    'frozen_cfg_ofi_k_orders', frozen_cfg_ofi_k_orders, ...
                    'frozen_cfg_sigma_k_vec', frozen_cfg_sigma_k_vec, ...
                    'keldysh_mred_kg', keldysh_mred_kg), ...
                struct_utils.opt_struct_field( ...
                    cfg, 'keldysh_material_state_update', struct(), ...
                    'treat_empty_as_missing', true), ...
                'refresh_medium_rebuild_submodel_cfgs_local');
            frozen_cfg_rho_nt_m3 = keldysh_material_state.frozen_cfg_rho_nt_m3;
            frozen_cfg_rho_nt_keldysh_norm_m3 = ...
                keldysh_material_state.frozen_cfg_rho_nt_keldysh_norm_m3;
            frozen_cfg_ui = keldysh_material_state.frozen_cfg_ui;
            frozen_cfg_keldysh_gap_j = keldysh_material_state.frozen_cfg_keldysh_gap_j;
            frozen_cfg_keldysh_matched_depletion_j = ...
                keldysh_material_state.frozen_cfg_keldysh_matched_depletion_j;
            n_sell_fund = keldysh_material_state.n_sell_fund;
            frozen_cfg_ofi_k_orders = keldysh_material_state.frozen_cfg_ofi_k_orders;
            frozen_cfg_sigma_k_vec = keldysh_material_state.frozen_cfg_sigma_k_vec;
            keldysh_mred_kg = keldysh_material_state.keldysh_mred_kg;
            beta_k_vec = frozen_cfg_ofi_k_orders(:) .* hbar .* omega_fund .* ...
                frozen_cfg_rho_nt_m3 .* frozen_cfg_sigma_k_vec(:);
            keldysh_setup_seed.keldysh_material_state = keldysh_material_state;
            keldysh_setup_seed.frozen_cfg_rho_nt_m3 = frozen_cfg_rho_nt_m3;
            keldysh_setup_seed.frozen_cfg_rho_nt_keldysh_norm_m3 = ...
                frozen_cfg_rho_nt_keldysh_norm_m3;
            keldysh_setup_seed.frozen_cfg_ui = frozen_cfg_ui;
            keldysh_setup_seed.frozen_cfg_keldysh_gap_j = frozen_cfg_keldysh_gap_j;
            keldysh_setup_seed.frozen_cfg_keldysh_matched_depletion_j = ...
                frozen_cfg_keldysh_matched_depletion_j;
            keldysh_setup_seed.n_sell_fund = n_sell_fund;
            keldysh_setup_seed.frozen_cfg_ofi_k_orders = frozen_cfg_ofi_k_orders;
            keldysh_setup_seed.frozen_cfg_sigma_k_vec = frozen_cfg_sigma_k_vec;
            keldysh_setup_seed.keldysh_mred_kg = keldysh_mred_kg;

            keldysh_plot_policy = struct_utils.opt_struct_field(cfg, 'keldysh_plot_policy', struct( ...
                'outdir', '', ...
                'visible', false, ...
                'save_outputs_as_fig', false, ...
                'save_outputs_as_png', false));
            if refresh_keldysh_runtime_cfg
                keldysh_setup_cfg = plasma_setup_support.build_keldysh_setup_cfg_local( ...
                    keldysh_setup_seed, 'propagation', frozen_cfg_rho_nt_m3, ...
                    frozen_cfg_rho_nt_keldysh_norm_m3, ...
                    keldysh_plot_policy, logical(keldysh_enabled));
                [plasma_runtime_cfg.keldysh_cfg, run_warn_state] = ...
                    plasma_keldysh_setup.build_runtime_cfg_from_setup( ...
                        keldysh_setup_cfg, run_warn_state);
                [plasma_runtime_cfg.keldysh_cfg, run_warn_state] = ...
                    plasma_setup_support.init_keldysh_warn_state_local( ...
                        plasma_runtime_cfg.keldysh_cfg, run_warn_state);
                [plasma_runtime_cfg.keldysh_cfg, submodel_warn_state.plasma] = ...
                    plasma_setup_support.detach_keldysh_warn_state_local( ...
                        plasma_runtime_cfg.keldysh_cfg);
            else
                % Keep the cached Keldysh runtime cfg when optical rebuilds
                % are active but dynamic Keldysh itself is not being rebuilt.
                if ~(isfield(plasma_runtime_cfg, 'keldysh_cfg') && ...
                        isstruct(plasma_runtime_cfg.keldysh_cfg))
                    if logical(keldysh_enabled)
                        error('CerUPP:MissingCachedKeldyshRuntimeCfg', ...
                            ['refresh_keldysh_runtime_cfg=false requires an existing ', ...
                             'cached plasma_runtime_cfg.keldysh_cfg when keldysh_enabled=true.']);
                    end
                    plasma_runtime_cfg.keldysh_cfg = struct('enabled', false);
                elseif ~isfield(plasma_runtime_cfg.keldysh_cfg, 'enabled')
                    plasma_runtime_cfg.keldysh_cfg.enabled = logical(keldysh_enabled);
