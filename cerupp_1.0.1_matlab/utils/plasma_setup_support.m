        function summaries_present = keldysh_effective_diag_summaries_present_local(diagnostic_store)
        % Check whether the propagation loop already stored the scalar
        % matched-Keldysh summary traces for every saved plane.

            summaries_present = false;
            if ~(isstruct(diagnostic_store) && isscalar(diagnostic_store) && ...
                    isfield(diagnostic_store, 'store_keldysh_diag_i_core'))
                return;
            end
            num_saved = plasma_setup_support.resolve_saved_plane_count_local( ...
                diagnostic_store, size(diagnostic_store.store_keldysh_diag_i_core, 3));
            if num_saved < 1
                summaries_present = true;
                return;
            end
            summary_field_names = { ...
                'store_sigma_k_eff_keldysh_oa', ...
                'store_sigma_k_eff_keldysh_maxperp', ...
                'store_beta_eff_full_keldysh_oa', ...
                'store_beta_eff_full_keldysh_maxperp', ...
                'store_beta_eff_applied_keldysh_oa', ...
                'store_beta_eff_applied_keldysh_maxperp'};
            for field_idx = 1:numel(summary_field_names)
                field_name = summary_field_names{field_idx};
                if ~isfield(diagnostic_store, field_name)
                    return;
                end
                field_values = diagnostic_store.(field_name);
                if numel(field_values) < num_saved
                    return;
                end
                field_values = field_values(1:num_saved);
                if ~all(isfinite(double(field_values(:))))
                    return;
                end
            end
            summaries_present = true;
        end

        function diagnostic_store = clear_keldysh_effective_diag_summaries_local( ...
                diagnostic_store, save_idx)
        % Clear the scalar matched-Keldysh summary traces so final metadata
        % never leaves stale propagation-time values behind after replay
        % gaps or failures.

            if ~(isstruct(diagnostic_store) && isscalar(diagnostic_store))
                return;
            end
            summary_field_names = { ...
                'store_sigma_k_eff_keldysh_oa', ...
                'store_sigma_k_eff_keldysh_maxperp', ...
                'store_beta_eff_full_keldysh_oa', ...
                'store_beta_eff_full_keldysh_maxperp', ...
                'store_beta_eff_applied_keldysh_oa', ...
                'store_beta_eff_applied_keldysh_maxperp'};
            clear_one_plane_only = (nargin >= 2) && ~isempty(save_idx);
            if clear_one_plane_only
                save_idx = double(save_idx);
            end
            for field_idx = 1:numel(summary_field_names)
                field_name = summary_field_names{field_idx};
                if ~isfield(diagnostic_store, field_name) || ...
                        isempty(diagnostic_store.(field_name))
                    continue;
                end
                field_values = diagnostic_store.(field_name);
                if clear_one_plane_only
                    if save_idx <= numel(field_values)
                        field_values(save_idx) = cast(NaN, 'like', field_values);
                    end
                else
                    field_values(:) = cast(NaN, 'like', field_values);
                end
                diagnostic_store.(field_name) = field_values;
            end
        end

        function neutral_reservoir_m3 = resolve_effective_neutral_reservoir_m3_local( ...
                rho_nt_m3, rho_neutral_supply)
        % Resolve the shared neutral reservoir used by remaining-neutral-weighted plasma and NLA accounting.

            rho_nt_scalar = double(real(rho_nt_m3));
            if ~(isscalar(rho_nt_scalar) && isfinite(rho_nt_scalar) && (rho_nt_scalar > 0))
                error('CerUPP:InvalidNeutralReservoirBaseDensity', ...
                    'rho_nt_m3 must be a finite real scalar > 0 when resolving the effective neutral reservoir.');
            end
            rho_stage_cap_effective = rho_nt_scalar;
            if nargin >= 2 && ~isempty(rho_neutral_supply)
                rho_stage_cap_scalar = double(real(rho_neutral_supply));
                if isscalar(rho_stage_cap_scalar) && isreal(rho_stage_cap_scalar) && ...
                        isfinite(rho_stage_cap_scalar) && (rho_stage_cap_scalar > 0)
                    rho_stage_cap_effective = rho_stage_cap_scalar;
                else
                    error('CerUPP:InvalidNeutralReservoirCap', ...
                        ['rho_neutral_supply must be one finite real scalar > 0 ', ...
                         'when resolving the effective neutral reservoir.']);
                end
            end
            neutral_reservoir_m3 = rho_stage_cap_effective;
        end

        function num_saved = resolve_saved_plane_count_local(diagnostic_store, fallback_count)
        % Resolve how many stored planes are actually populated in one diagnostic store.

            if nargin < 2 || isempty(fallback_count) || ~isfinite(double(fallback_count))
                fallback_count = 0;
            end
            num_saved = max(floor(double(fallback_count)), 0);
            if ~(isstruct(diagnostic_store) && isscalar(diagnostic_store))
                return;
            end
            store_z = struct_utils.opt_struct_field(diagnostic_store, 'store_z', []);
            if isempty(store_z)
                return;
            end
            finite_count = nnz(isfinite(double(store_z(:))));
            if finite_count > 0
                num_saved = min(num_saved, finite_count);
            end
        end


