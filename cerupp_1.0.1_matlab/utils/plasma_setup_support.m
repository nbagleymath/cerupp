        function run_warn_state = emit_keldysh_zero_floor_setup_warning_local(kcfg, run_warn_state)
        % Hard-stop when the zero-rate floor suppresses the intended dynamic
        % Keldysh range, and warn once on softer ordering mismatches.

            if nargin < 2 || isempty(run_warn_state)
                run_warn_state = struct();
            end
            if ~isstruct(kcfg)
                return;
            end
            zero_floor = double(struct_utils.opt_struct_field( ...
                kcfg, 'keldysh_zero_rate_below_wm2', NaN));
            lut_global_min = double(struct_utils.opt_struct_field( ...
                kcfg, 'lut_i_global_min_wm2', NaN));
            roi_anchor_min = double(struct_utils.opt_struct_field( ...
                kcfg, 'I_roi_anchor_min', NaN));
            lut_roi_max = double(struct_utils.opt_struct_field( ...
                kcfg, 'lut_i_roi_max_wm2', NaN));
            lookup_max = double(struct_utils.opt_struct_field( ...
                kcfg, 'I_lookup_max', NaN));
            fatal_violations = {};

            if isfinite(zero_floor) && isfinite(roi_anchor_min) && (zero_floor > roi_anchor_min)
                fatal_violations{end+1} = sprintf([ ... %#ok<AGROW>
                    'keldysh_zero_rate_below=%.3e W/m^2 exceeds ', ...
                    'keldysh_lut_i_roi_min_effective=%.3e W/m^2'], ...
                    zero_floor, roi_anchor_min);
            end
            if isfinite(zero_floor) && isfinite(lookup_max) && (zero_floor > lookup_max)
                fatal_violations{end+1} = sprintf([ ... %#ok<AGROW>
                    'keldysh_zero_rate_below=%.3e W/m^2 exceeds I_lookup_max=%.3e W/m^2'], ...
                    zero_floor, lookup_max);
            end
            if ~isempty(fatal_violations)
                error('CerUPP:Keldysh:ZeroRateFloorSuppressesDynamicBranch', ...
                    ['keldysh_zero_rate_below suppresses the dynamic Keldysh OFI / OFI-based NLA law ', ...
                     'over the intended lookup range: %s. Require ', ...
                     'keldysh_zero_rate_below <= keldysh_lut_i_roi_min_effective <= ', ...
                     'keldysh_lut_i_roi_max <= I_lookup_max. Lower keldysh_zero_rate_below or ', ...
                     'move the ROI/lookup bounds upward intentionally before running.'], ...
                    strjoin(fatal_violations, '; '));
            end

            ordering_values = [zero_floor, lut_global_min, roi_anchor_min, lut_roi_max, lookup_max];
            ordering_labels = { ...
                'keldysh_zero_rate_below', 'keldysh_lut_i_global_min', ...
                'keldysh_lut_i_roi_min_effective', 'keldysh_lut_i_roi_max', ...
                'I_lookup_max'};
            violations = {};
            for idx = 1:(numel(ordering_values) - 1)
                lhs = ordering_values(idx);
                rhs = ordering_values(idx + 1);
                if isfinite(lhs) && isfinite(rhs) && (lhs > rhs)
                    violations{end+1} = sprintf('%s=%.3e W/m^2 exceeds %s=%.3e W/m^2', ... %#ok<AGROW>
                        ordering_labels{idx}, lhs, ordering_labels{idx + 1}, rhs);
                end
            end
            if isempty(violations)
                return;
            end
            run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                run_warn_state, 'setup', ...
                'keldysh_zero_floor_ordering_warning', ...
                'CerUPP:Keldysh:ZeroRateFloorOrderingWarning', ...
                ['Keldysh intensity-floor ordering is inconsistent: %s. Expected ', ...
                 'keldysh_zero_rate_below <= keldysh_lut_i_global_min <= ', ...
                 'keldysh_lut_i_roi_min_effective <= keldysh_lut_i_roi_max <= I_lookup_max. ', ...
                 'A too-large zero-rate floor can suppress the dynamic Keldysh OFI / OFI-based NLA branch ', ...
                 'over part or all of the intended intensity range.'], ...
                strjoin(violations, '; '));
        end

        function plasma_book = init_plasma_book(like_template, nc, nt, full_bookkeeping_ledger, emit_mechanism_ledgers)
        %INIT_PLASMA_BOOK Initialize the shared plasma accounting struct schema.
        % Purpose:
        % - Build the plasma accounting struct used by the propagation step.
        % - Keep the live schema in one place so driver and stepper code do not
        %   rebuild these fields ad hoc.
        % Default returned struct can be lean or full:
        % - emit_mechanism_ledgers=false: return an empty struct for callers that
        %   only attach later scalar/energy accounting outside the plasma kernel.
        % - emit_mechanism_ledgers=true : return [nc x nt] accepted OFI and
        %   avalanche ledgers, compatibility drho_*_applied aliases, cap/
        %   rejected/residual diagnostics, and the logical exact_valid_core.
        % Optional full_bookkeeping_ledger=true restores the heavier
        % drho_recomb_applied compatibility ledger. Numeric fields inherit class
        % from like_template (using its first element when a nonscalar template is
        % passed), while exact_valid_core starts true everywhere.
        % exact_valid_core is cleared when the exact-frozen mechanism
        % partition is unavailable for a sampled cell, such as rho-clamped
        % stages or nonfatal exact-ledger replay failures.

            if nargin < 2 || isempty(nc)
                nc = 0;
            end
            if nargin < 3 || isempty(nt)
                nt = 0;
            end
            if nargin < 4 || isempty(full_bookkeeping_ledger)
                full_bookkeeping_ledger = false;
            end
