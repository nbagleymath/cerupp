function tf = postprocess_has_any_ok_family_local(postprocess_state)
    tf = false;
    if ~isstruct(postprocess_state) || ...
            ~logical(struct_utils.opt_struct_field(postprocess_state, 'requested', false))
        return;
    end
    family_ledger = struct_utils.opt_struct_field( ...
        postprocess_state, 'family_ledger', struct());
    if ~isstruct(family_ledger)
        return;
    end
    family_names = fieldnames(family_ledger);
    for idx = 1:numel(family_names)
        family_state = family_ledger.(family_names{idx});
        if isstruct(family_state) && logical(struct_utils.opt_struct_field( ...
                family_state, 'ok', false))
            tf = true;
            return;
        end
    end
end

