function tf = any_restart_due_before_run_end_local( ...
        completed_z_steps, num_zsteps, checkpoint_stride_steps, ...
        save_final_restart_checkpoint_flag)
    checkpoint_stride_steps = normalize_positive_stride_local( ...
        checkpoint_stride_steps, 'checkpoint_stride_steps');
    due_step_count = floor(double(completed_z_steps) / checkpoint_stride_steps);
    if (double(completed_z_steps) == double(num_zsteps)) && ...
            logical(save_final_restart_checkpoint_flag) && ...
            (mod(double(num_zsteps), checkpoint_stride_steps) == 0)
        due_step_count = max(due_step_count - 1, 0);
    end
    tf = (due_step_count > 0);
end

function tf = any_snapshot_due_before_run_end_local( ...
        completed_z_steps, num_zsteps, snapshot_stride_steps)
    snapshot_stride_steps = normalize_positive_stride_local( ...
        snapshot_stride_steps, 'a_s_rho_snapshot_checkpoint_stride_steps');
    tf = (floor(double(completed_z_steps) / snapshot_stride_steps) > 0) || ...
        (double(completed_z_steps) == double(num_zsteps));
end

function tf = any_fullsave_due_before_run_end_local( ...
        completed_z_steps, num_zsteps, diagnostic_store_stride_steps, ...
        checkpoint_stride_steps)
    diagnostic_store_stride_steps = normalize_positive_stride_local( ...
        diagnostic_store_stride_steps, 'diagnostic_store_stride_steps');
    checkpoint_stride_steps = normalize_positive_stride_local( ...
        checkpoint_stride_steps, 'checkpoint_stride_steps');
    if double(completed_z_steps) <= 0
        tf = false;
        return;
    end
    first_store_step = Inf;
    if double(completed_z_steps) == double(num_zsteps)
        first_store_step = min(diagnostic_store_stride_steps, double(num_zsteps));
    elseif double(completed_z_steps) >= diagnostic_store_stride_steps
        first_store_step = diagnostic_store_stride_steps;
    end
    if ~isfinite(first_store_step)
        tf = false;
        return;
    end
    first_due_checkpoint_step = checkpoint_stride_steps * ...
        ceil(first_store_step / checkpoint_stride_steps);
    tf = (first_due_checkpoint_step <= double(completed_z_steps));
end

function stride_value = normalize_positive_stride_local(raw_stride_value, stride_name)
    stride_value = double(raw_stride_value);
    if ~isscalar(stride_value) || ~isfinite(stride_value) || ...
            ~isreal(stride_value) || (stride_value <= 0)
        error('CerUPP:InvalidSection6CStride', ...
            '%s must be a finite real scalar > 0 before Section 6C status collapse.', ...
            stride_name);
    end
end

