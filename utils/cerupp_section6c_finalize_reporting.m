                'Could not write the final run_status.json file.';
        end
    else
        run_status_attempted = true;
        run_status_write_ok = false;
        run_status_skipped_reason = 'run_status_write_failed';
        run_status_error_id = 'CerUPP:RunStatus:RunStatusWriteFailed';
