            completed_with_all_requested_outputs, ...
        'postprop_finalization_success', run_end_state.finalization.ok, ...
        'terminal_store_matches_accepted_state', ...
            terminal_store_contract.matches_accepted_state, ...
        'terminal_store_contract_reason', terminal_store_contract.reason, ...
        'latest_successful_pointer_eligible', ...
            latest_successful_pointer_eligible, ...
        'latest_fully_packaged_pointer_eligible', ...
            latest_fully_packaged_pointer_eligible, ...
        'latest_propagation_complete_pointer_eligible', ...
            latest_propagation_complete_pointer_eligible);
    artifact_status = build_artifact_status_tree_local(run_end_state);

    section6c_state = struct( ...
        'run_end_state', run_end_state, ...
        'warning_ledgers', warning_ledgers, ...
        'run_warn_state', run_warn_state, ...
        'run_status_ctx', run_status_ctx, ...
        'postprocess_phase_ok', postprocess_phase_ok, ...
        'postprocess_success', postprocess_success, ...
        'propagation_completed_requested_distance', ...
            propagation_completed_requested_distance, ...
        'propagation_success', propagation_success, ...
        'physics_success', physics_success, ...
        'latest_successful_pointer_eligible', ...
            latest_successful_pointer_eligible, ...
        'latest_fully_packaged_pointer_eligible', ...
            latest_fully_packaged_pointer_eligible, ...
        'latest_propagation_complete_pointer_eligible', ...
            latest_propagation_complete_pointer_eligible, ...
        'artifact_status', artifact_status, ...
        'status_extra_fields', status_extra_fields, ...
        'final_output_write_success', final_output_write_success, ...
        'intermediate_output_write_success', ...
            intermediate_output_write_success, ...
        'reporting_success', reporting_success, ...
        'completed_with_all_requested_outputs', ...
            completed_with_all_requested_outputs);
end

function postprocess_state = collapse_postprocess_state_local(postprocess_state)
    postprocess_state.attempted = logical(postprocess_state.attempted);
    if ~postprocess_state.requested
        postprocess_state.skipped_reason = 'not_requested';
        postprocess_state.ok = true;
        postprocess_state.result = 'skipped_not_requested';
    elseif ~postprocess_state.phase_ok
        postprocess_state.skipped_reason = ...
            postprocess_state.requested_outputs_skipped_reason;
        postprocess_state.ok = false;
        postprocess_state.result = 'failed';
    elseif ~postprocess_state.requested_outputs_complete
        postprocess_state.skipped_reason = ...
            postprocess_state.requested_outputs_skipped_reason;
        postprocess_state.ok = false;
        postprocess_state.result = 'failed';
    else
        postprocess_state.skipped_reason = '';
        postprocess_state.ok = true;
        postprocess_state.result = 'succeeded';
    end
end

function intermediate_state = build_intermediate_output_state_local( ...
        output_plan, checkpoint_policy_state, checkpoint_failure_state, ...
        completed_z_steps, num_zsteps)
    request_cfg = struct_utils.req_struct_field( ...
        output_plan, 'request', 'cerupp_section6c_finalize_reporting.output_plan');
    cadence_cfg = struct_utils.req_struct_field( ...
        output_plan, 'cadence', 'cerupp_section6c_finalize_reporting.output_plan');
    restart_due_before_run_end = any_restart_due_before_run_end_local( ...
        completed_z_steps, num_zsteps, cadence_cfg.checkpoint_stride_steps, ...
        request_cfg.save_final_restart_checkpoint_flag);
    snapshot_due_before_run_end = any_snapshot_due_before_run_end_local( ...
        completed_z_steps, num_zsteps, ...
        cadence_cfg.a_s_rho_snapshot_checkpoint_stride_steps);
    fullsave_due_before_run_end = any_fullsave_due_before_run_end_local( ...
        completed_z_steps, num_zsteps, ...
        cadence_cfg.diagnostic_store_stride_steps, ...
        cadence_cfg.checkpoint_stride_steps);
    intermediate_state = struct( ...
        'restart', build_stream_status_local(struct( ...
            'requested', logical(request_cfg.intermediate_saves), ...
            'due_before_run_end', restart_due_before_run_end, ...
            'attempt_count', checkpoint_failure_state.restart_attempt_count, ...
            'success_count', checkpoint_failure_state.restart_success_count, ...
            'last_attempt_ok', checkpoint_failure_state.restart_last_attempt_ok, ...
            'stream_enabled', checkpoint_policy_state.restart_enabled, ...
            'disabled_after_repeated_failures', ...
                checkpoint_failure_state.disable_restart_only, ...
            'ever_failed', checkpoint_failure_state.restart_ever_failed, ...
            'current_error_id', checkpoint_failure_state.error_id, ...
            'current_error_message', checkpoint_failure_state.error_message, ...
            'last_failure_error_id', checkpoint_failure_state.error_id, ...
            'last_failure_error_message', checkpoint_failure_state.error_message)), ...
        'snapshot', build_stream_status_local(struct( ...
            'requested', logical(request_cfg.intermediate_saves), ...
            'due_before_run_end', snapshot_due_before_run_end, ...
            'attempt_count', checkpoint_failure_state.snapshot_attempt_count, ...
            'success_count', checkpoint_failure_state.snapshot_success_count, ...
            'last_attempt_ok', checkpoint_failure_state.snapshot_last_attempt_ok, ...
            'stream_enabled', checkpoint_policy_state.snapshot_enabled, ...
            'disabled_after_repeated_failures', ...
                checkpoint_failure_state.disable_snapshot_only, ...
            'ever_failed', checkpoint_failure_state.snapshot_ever_failed, ...
            'current_error_id', checkpoint_failure_state.snapshot_error_id, ...
            'current_error_message', checkpoint_failure_state.snapshot_error_message, ...
            'last_failure_error_id', checkpoint_failure_state.snapshot_error_id, ...
            'last_failure_error_message', ...
                checkpoint_failure_state.snapshot_error_message)), ...
        'fullsave', build_stream_status_local(struct( ...
            'requested', logical( ...
                request_cfg.intermediate_saves && ...
                request_cfg.checkpoint_full_save_flag), ...
            'due_before_run_end', fullsave_due_before_run_end, ...
