function stream_status = build_stream_status_local(cfg)
    attempted = (cfg.attempt_count > 0);
    due_before_run_end = logical(struct_utils.opt_struct_field( ...
        cfg, 'due_before_run_end', attempted));
    last_attempt_ok = logical(cfg.last_attempt_ok);
    current_error_id = '';
    current_error_message = '';
    if attempted && ~last_attempt_ok
        current_error_id = cfg.current_error_id;
        current_error_message = cfg.current_error_message;
    end
    skipped_reason = '';
    if ~cfg.requested
        skipped_reason = 'not_requested';
    elseif ~due_before_run_end
        skipped_reason = 'not_due_before_run_end';
    elseif ~attempted
        skipped_reason = 'not_attempted_before_run_end';
    elseif logical(cfg.disabled_after_repeated_failures)
        skipped_reason = 'disabled_after_repeated_failures';
    end
    stream_status = struct( ...
        'requested', logical(cfg.requested), ...
        'due_before_run_end', due_before_run_end, ...
        'attempted', attempted, ...
        'ok', (~cfg.requested) || (~due_before_run_end) || ...
            (attempted && last_attempt_ok), ...
        'produced_artifact', (cfg.success_count > 0), ...
        'skipped_reason', skipped_reason, ...
        'error_id', current_error_id, ...
        'error_message', current_error_message, ...
        'stream_enabled', logical(cfg.stream_enabled), ...
        'last_attempt_ok', last_attempt_ok, ...
        'ever_failed', logical(cfg.ever_failed), ...
        'disabled_after_repeated_failures', ...
            logical(cfg.disabled_after_repeated_failures), ...
        'last_failure_error_id', cfg.last_failure_error_id, ...
        'last_failure_error_message', cfg.last_failure_error_message);
end

function final_outputs = build_initial_final_output_state_local( ...
        cfg, run_end_state, terminal_store_contract)
    final_restart_requested = logical( ...
        cfg.output_plan.request.save_final_restart_checkpoint_flag);
    final_restart_write_state = struct_utils.req_struct_field( ...
        cfg, 'final_restart_write_state', ...
        'cerupp_section6c_finalize_reporting.final_restart_write_state');
    final_restart_attempted = final_restart_requested && ...
        (cfg.final_restart_attempted_postprop || ...
         struct_utils.req_struct_field( ...
             final_restart_write_state, 'attempted', ...
             'cerupp_section6c_finalize_reporting.final_restart_write_state'));
    final_restart_error_id = '';
    final_restart_error_message = '';
    final_restart_skipped_reason = '';
    if ~final_restart_requested
        final_restart_skipped_reason = 'not_requested';
    elseif ~run_end_state.finalization.ok && ~cfg.final_restart_save_ok
        if ~isempty(cfg.final_restart_fallback_error_id)
            final_restart_skipped_reason = ...
                'final_restart_after_finalization_failure_failed';
            final_restart_error_id = cfg.final_restart_fallback_error_id;
            final_restart_error_message = ...
                cfg.final_restart_fallback_error_message;
        else
            final_restart_skipped_reason = char(string( ...
                run_end_state.finalization.skipped_reason));
            if isempty(final_restart_skipped_reason)
                final_restart_skipped_reason = 'upstream_finalization_failed';
            end
            final_restart_error_id = run_end_state.finalization.error_id;
            final_restart_error_message = ...
                run_end_state.finalization.error_message;
        end
    elseif ~cfg.final_restart_save_ok
        final_restart_skipped_reason = 'final_restart_failed';
        final_restart_error_id = 'CerUPP:FinalRestartOutputFailed';
        final_restart_error_message = ...
            'Final restart checkpoint prepare/write failed earlier in the end-of-run path.';
    end
    if ~final_restart_requested
        final_restart_result = 'skipped_not_requested';
    elseif cfg.final_restart_save_ok
        final_restart_result = 'succeeded';
    elseif ~run_end_state.finalization.ok && ...
            ~strcmp(final_restart_skipped_reason, ...
                'final_restart_after_finalization_failure_failed')
        final_restart_result = 'skipped_upstream_failure';
    else
        final_restart_result = 'failed';
    end
    final_restart_payload_kind = char(string(struct_utils.opt_struct_field( ...
        final_restart_write_state, 'payload_kind', 'none')));
    final_restart_degraded_fallback_used = ...
        final_restart_requested && cfg.final_restart_save_ok && ...
        strcmp(final_restart_payload_kind, 'minimal');

    end_snapshot_requested = logical(cfg.output_plan.request.save_end_snapshot_flag);
    end_snapshot_write_state = struct_utils.opt_struct_field( ...
        cfg, 'end_snapshot_write_state', struct());
    end_snapshot_attempted = logical(struct_utils.opt_struct_field( ...
        end_snapshot_write_state, 'attempted', ...
        end_snapshot_requested && cfg.end_snapshot_attempted_postprop));
    end_snapshot_error_id = char(string(struct_utils.opt_struct_field( ...
        end_snapshot_write_state, 'error_id', '')));
    end_snapshot_error_message = char(string(struct_utils.opt_struct_field( ...
        end_snapshot_write_state, 'error_message', '')));
    end_snapshot_skipped_reason = char(string(struct_utils.opt_struct_field( ...
        end_snapshot_write_state, 'blocked_reason', '')));
    if ~end_snapshot_requested
        end_snapshot_skipped_reason = 'not_requested';
    elseif isempty(end_snapshot_skipped_reason) && ...
            ~logical(struct_utils.opt_struct_field( ...
                end_snapshot_write_state, 'ok', cfg.end_snapshot_save_ok))
        end_snapshot_skipped_reason = 'end_snapshot_failed';
        if isempty(end_snapshot_error_id)
            end_snapshot_error_id = 'CerUPP:EndSnapshotOutputFailed';
        end
        if isempty(end_snapshot_error_message)
            end_snapshot_error_message = ...
                'End snapshot prepare/write failed earlier in the end-of-run path.';
        end
    end
    if ~end_snapshot_requested
        end_snapshot_result = 'skipped_not_requested';
    elseif logical(struct_utils.opt_struct_field( ...
            end_snapshot_write_state, 'ok', cfg.end_snapshot_save_ok))
        end_snapshot_result = 'succeeded';
    elseif ~end_snapshot_attempted && ~isempty(end_snapshot_skipped_reason)
        end_snapshot_result = 'skipped_contract_not_met';
    else
        end_snapshot_result = 'failed';
    end

    final_fullsave_requested = logical( ...
        cfg.output_plan.request.save_final_full_output_flag);
    final_fullsave_attempted = final_fullsave_requested && ...
        run_end_state.finalization.ok && ~isempty(cfg.final_fullsave_build_cfg);
    final_fullsave_skipped_reason = '';
    final_fullsave_error_id = cfg.final_full_save_error_id;
    final_fullsave_error_message = cfg.final_full_save_error_message;
    if ~final_fullsave_requested
        final_fullsave_skipped_reason = 'not_requested';
    elseif ~terminal_store_contract.matches_accepted_state
        final_fullsave_skipped_reason = ...
            resolve_terminal_store_skipped_reason_local(terminal_store_contract);
        final_fullsave_error_id = 'CerUPP:TerminalStoreMismatch';
        final_fullsave_error_message = ...
            ['The packed stored diagnostic bundle no longer matched the ', ...
             'terminal field after a stored-plane ', ...
             'failure, so CerUPP withheld the ordinary final fullsave ', ...
             'diagnostic store.'];
    elseif ~run_end_state.finalization.ok
        final_fullsave_skipped_reason = char(string( ...
            run_end_state.finalization.skipped_reason));
        if isempty(final_fullsave_skipped_reason)
            final_fullsave_skipped_reason = 'upstream_finalization_failed';
        end
    elseif isempty(cfg.final_fullsave_build_cfg)
        final_fullsave_skipped_reason = 'build_cfg_unavailable';
    elseif ~cfg.final_full_save_ok
        final_fullsave_skipped_reason = 'final_fullsave_failed';
    end
    if ~final_fullsave_requested
        final_fullsave_result = 'skipped_not_requested';
    elseif cfg.final_full_save_ok
        final_fullsave_result = 'succeeded';
    elseif ~terminal_store_contract.matches_accepted_state
        final_fullsave_result = 'skipped_contract_not_met';
    elseif ~run_end_state.finalization.ok
        final_fullsave_result = 'skipped_upstream_failure';
    else
        final_fullsave_result = 'failed';
    end

    final_outputs = struct( ...
        'restart', build_artifact_status_record_local( ...
            final_restart_requested, final_restart_attempted, ...
            (~final_restart_requested) || cfg.final_restart_save_ok, ...
            final_restart_skipped_reason, final_restart_error_id, ...
            final_restart_error_message, final_restart_result), ...
        'snapshot', build_artifact_status_record_local( ...
            end_snapshot_requested, end_snapshot_attempted, ...
            (~end_snapshot_requested) || cfg.end_snapshot_save_ok, ...
            end_snapshot_skipped_reason, end_snapshot_error_id, ...
            end_snapshot_error_message, end_snapshot_result), ...
        'fullsave', build_artifact_status_record_local( ...
            final_fullsave_requested, final_fullsave_attempted, ...
            (~final_fullsave_requested) || cfg.final_full_save_ok, ...
            final_fullsave_skipped_reason, final_fullsave_error_id, ...
            final_fullsave_error_message, final_fullsave_result));
    final_outputs.restart.payload_kind = final_restart_payload_kind;
    final_outputs.restart.degraded_fallback_used = ...
        final_restart_degraded_fallback_used;
    final_outputs.restart.complete_package_ok = ...
        final_outputs.restart.ok && ...
        ~final_restart_degraded_fallback_used;
    final_outputs.snapshot.store_z_source = char(string( ...
        struct_utils.opt_struct_field( ...
            end_snapshot_write_state, 'store_z_source', 'none')));
end

function [pointer_status, run_warn_state] = write_pointer_status_local(cfg, run_warn_state)
    attempted = false;
    pointer_ok = true;
    skipped_reason = '';
    error_id = '';
    error_message = '';
    if ~cfg.requested
        skipped_reason = 'not_requested';
    elseif ~cfg.eligible
        skipped_reason = 'contract_not_met';
    else
        attempted = true;
        [run_warn_state, pointer_ok] = checkpoint_utils.write_run_id_pointer( ...
            struct( ...
                'run_bucket', cfg.run_bucket, ...
                'pointer_name', cfg.pointer_name, ...
                'run_id', cfg.run_id, ...
                'phase_tag', 'end', ...
                'warn_key', cfg.warn_key, ...
                'warn_id', cfg.warn_id, ...
                'failure_tag', cfg.failure_tag), ...
            run_warn_state);
        if ~pointer_ok
            skipped_reason = 'pointer_write_failed';
            error_id = cfg.warn_id;
            error_message = cfg.failure_message;
        end
    end
    if ~cfg.requested
        result = 'skipped_not_requested';
    elseif ~cfg.eligible
        result = 'skipped_contract_not_met';
    elseif pointer_ok
        result = 'succeeded';
    else
        result = 'failed';
    end
    pointer_status = build_artifact_status_record_local( ...
        cfg.requested, attempted, ...
        (~cfg.requested) || (cfg.eligible && pointer_ok), skipped_reason, ...
        error_id, error_message, result);
end

function run_status_record = resolve_run_status_record_local( ...
        run_status_requested, run_status_ctx)
    run_status_attempted = false;
    run_status_write_ok = true;
    run_status_skipped_reason = '';
    run_status_error_id = '';
    run_status_error_message = '';
    if ~run_status_requested
        run_status_skipped_reason = 'not_requested';
    elseif isfield(run_status_ctx, 'last_finalize_status') && ...
            isstruct(run_status_ctx.last_finalize_status)
