        run_status_result = 'skipped_not_requested';
    elseif run_status_write_ok
        run_status_result = 'succeeded';
    else
        run_status_result = 'failed';
    end
    run_status_record = build_artifact_status_record_local( ...
        run_status_requested, run_status_attempted, ...
        (~run_status_requested) || run_status_write_ok, ...
        run_status_skipped_reason, run_status_error_id, ...
        run_status_error_message, run_status_result);
end

function current_pointer_record = resolve_current_pointer_record_local( ...
        current_pointer_requested, run_status_ctx)
    if ~logical(current_pointer_requested)
        current_pointer_record = build_artifact_status_record_local( ...
            false, false, true, 'not_requested', '', '', ...
            'skipped_not_requested');
        return;
    end

    current_pointer_attempted = false;
    current_pointer_ok = true;
    current_pointer_skipped_reason = '';
    current_pointer_error_id = '';
    current_pointer_error_message = '';
    current_pointer_result = 'pending_status_finalize';
    if isfield(run_status_ctx, 'last_finalize_status') && ...
            isstruct(run_status_ctx.last_finalize_status)
        finalize_status = run_status_ctx.last_finalize_status;
        current_pointer_attempted = logical(struct_utils.opt_struct_field( ...
            finalize_status, 'current_pointer_delete_attempted', false));
        current_pointer_ok = logical(struct_utils.opt_struct_field( ...
            finalize_status, 'current_pointer_delete_ok', true));
        current_pointer_status = char(string(struct_utils.opt_struct_field( ...
            finalize_status, 'current_pointer_delete_status', 'skipped')));
        switch current_pointer_status
            case {'deleted', 'absent'}
                current_pointer_result = 'succeeded';
            case 'skipped'
                current_pointer_result = 'skipped_not_requested';
                current_pointer_skipped_reason = 'not_requested';
            case 'failed'
                current_pointer_result = 'failed';
                current_pointer_skipped_reason = ...
                    'current_pointer_delete_failed';
                current_pointer_error_id = ...
                    'CerUPP:RunStatus:CurrentRunPointerDeleteFailed';
                current_pointer_error_message = ...
                    'Could not retire current_run_id.txt at run end.';
                current_pointer_ok = false;
            otherwise
                current_pointer_result = current_pointer_status;
                if ~current_pointer_attempted
                    current_pointer_skipped_reason = current_pointer_status;
                end
                current_pointer_ok = false;
        end
    else
        current_pointer_ok = false;
        current_pointer_skipped_reason = ...
            'current_pointer_finalize_status_missing';
        current_pointer_error_id = ...
            'CerUPP:RunStatus:CurrentRunPointerDeleteStatusMissing';
        current_pointer_error_message = ...
            'The final run-status path did not report the current pointer cleanup result.';
        current_pointer_result = 'failed';
    end

    current_pointer_record = build_artifact_status_record_local( ...
        true, current_pointer_attempted, current_pointer_ok, ...
        current_pointer_skipped_reason, current_pointer_error_id, ...
        current_pointer_error_message, current_pointer_result);
end

function [attempt_state, attempt_identifier, attempt_message, attempt_reason] = ...
        build_attempt_status_local(physics_success, ...
        propagation_completed_requested_distance, artifact_status, ...
        terminal_propagated_state, ...
        terminal_store_matches_accepted_state, ...
        postprocess_phase_ok, intermediate_output_write_success_for_status, ...
        final_output_write_success_for_status, ...
        completed_with_all_requested_outputs_for_status)
    attempt_state = 'success';
    attempt_identifier = '';
    attempt_message = '';
    attempt_reason = 'normal_exit';
    if ~physics_success
        attempt_state = 'failed';
        if isstruct(terminal_propagated_state) && ...
                ~logical(struct_utils.opt_struct_field( ...
                terminal_propagated_state, 'ok', false))
            attempt_identifier = 'CerUPP:BadPropagatedTerminalState';
            attempt_message = ...
                'Run reached the end of cerupp.m, but final A_S, A_F, and/or rho failed the terminal propagated-state contract.';
            attempt_reason = 'bad_propagated_state';
        elseif ~propagation_completed_requested_distance
            attempt_identifier = 'CerUPP:RunStoppedBeforeRequestedDistance';
            attempt_message = ...
                'Run stopped before it reached the requested propagation distance.';
            attempt_reason = 'early_propagation_stop';
        else
            attempt_identifier = 'CerUPP:BadPropagatedTerminalState';
            attempt_message = ...
                'Run reached the end of cerupp.m, but final A_S, A_F, and/or rho failed the terminal propagated-state contract.';
            attempt_reason = 'bad_propagated_state';
        end
    elseif ~completed_with_all_requested_outputs_for_status
        attempt_state = 'partial_failed';
        [attempt_identifier, attempt_message] = ...
            resolve_primary_output_failure_local(artifact_status);
        if ~artifact_status.final.finalization.ok
            attempt_reason = 'normal_exit_with_postprop_finalization_failure';
        elseif ~terminal_store_matches_accepted_state
            attempt_reason = 'normal_exit_with_stale_terminal_store_bundle';
        elseif ~logical(struct_utils.opt_struct_field( ...
                artifact_status.final.restart, 'complete_package_ok', true))
            attempt_reason = 'normal_exit_with_degraded_final_restart';
        elseif ~postprocess_phase_ok
            attempt_reason = 'normal_exit_with_section6a_phase_failure';
        elseif ~artifact_status.final.postprocess.ok
            attempt_reason = 'normal_exit_with_section6a_output_failures';
        elseif ~intermediate_output_write_success_for_status
            attempt_reason = ...
                'normal_exit_with_intermediate_output_write_failures';
        elseif ~final_output_write_success_for_status
            attempt_reason = 'normal_exit_with_final_output_write_failures';
        else
            attempt_reason = 'normal_exit_with_output_gaps';
        end
    end
end

function [error_id, error_message] = resolve_primary_output_failure_local(artifact_status)
% Pick one concrete output-side failure id/message for the late status republish.

    error_id = '';
    error_message = '';
    if ~(isstruct(artifact_status) && isfield(artifact_status, 'final') && ...
            isstruct(artifact_status.final))
        return;
    end
    candidate_fields = { ...
        'current_pointer', ...
        'run_status', ...
        'latest_successful_pointer', ...
        'latest_fully_packaged_pointer', ...
        'latest_propagation_complete_pointer', ...
        'restart', ...
        'snapshot', ...
        'fullsave', ...
        'postprocess', ...
        'finalization'};
    for idx = 1:numel(candidate_fields)
        record = struct_utils.opt_struct_field( ...
            artifact_status.final, candidate_fields{idx}, struct());
        if ~(isstruct(record) && isscalar(record) && ...
                ~logical(struct_utils.opt_struct_field(record, 'ok', true)))
            continue;
        end
        error_id = char(string(struct_utils.opt_struct_field( ...
            record, 'error_id', '')));
        error_message = char(string(struct_utils.opt_struct_field( ...
            record, 'error_message', '')));
        if ~isempty(error_id) || ~isempty(error_message)
            return;
        end
    end
end

