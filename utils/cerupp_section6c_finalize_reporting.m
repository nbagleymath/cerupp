function varargout = cerupp_section6c_finalize_reporting(varargin)
% Driver-only Section 6C helper for cerupp.m.
% In the usual no-input mode this helper reads the current cerupp.m
% workspace, collapses the end-of-run output/status records, writes the
% latest-run pointers, and finalizes the run-status record.

    if nargin == 0
        caller_field_names = caller_field_names_local();
        cfg = struct();
        for ii = 1:numel(caller_field_names)
            field_name = caller_field_names{ii};
            try
                cfg.(field_name) = evalin('caller', field_name);
            catch err
                if strcmp(err.identifier, 'MATLAB:UndefinedFunction') || ...
                        strcmp(err.identifier, 'MATLAB:UndefinedVariable')
                    error('CerUPP:MissingSection6CCallerField', ...
                        ['cerupp_section6c_finalize_reporting expected caller variable ''%s'' ', ...
                         'to exist before the Section 6C helper call.'], ...
                        field_name);
                end
                rethrow(err);
            end
        end
        section6c_state = build_section6c_state_local(cfg);
        output_field_names = fieldnames(section6c_state);
        for ii = 1:numel(output_field_names)
            field_name = output_field_names{ii};
            assignin('caller', field_name, section6c_state.(field_name));
        end
        if nargout > 0
            varargout{1} = section6c_state;
        end
        return;
    end

    if (nargin ~= 1) || ~isstruct(varargin{1}) || ~isscalar(varargin{1})
        error('CerUPP:InvalidSection6CCfg', ...
            'cerupp_section6c_finalize_reporting accepts either no inputs or one scalar cfg struct.');
    end

    section6c_state = build_section6c_state_local(varargin{1});
    if nargout > 1
        error('CerUPP:InvalidSection6COutputCount', ...
            'cerupp_section6c_finalize_reporting returns at most one output struct.');
    end
    if nargout == 1
        varargout{1} = section6c_state;
    end
end

function caller_field_names = caller_field_names_local()
    caller_field_names = { ...
        'output_plan', ...
        'checkpoint_policy_state', ...
        'final_restart_attempted_postprop', ...
        'final_restart_write_state', ...
        'final_restart_fallback_error_id', ...
        'final_restart_fallback_error_message', ...
        'final_restart_save_ok', ...
        'end_snapshot_write_state', ...
        'end_snapshot_attempted_postprop', ...
        'end_snapshot_save_ok', ...
        'final_fullsave_build_cfg', ...
        'final_full_save_ok', ...
        'final_full_save_error_id', ...
        'final_full_save_error_message', ...
        'run_end_state', ...
        'run_warn_state', ...
        'warning_ledgers', ...
        'runtime_setup', ...
        'completed_z_steps', ...
        'num_zsteps', ...
        'terminal_output_publication_allowed', ...
        'final_a_s_state_finite', ...
        'final_a_f_state_finite', ...
        'final_rho_state_finite', ...
        'final_rho_state_shape_ok', ...
        'terminal_propagated_state', ...
        'run_status_ctx', ...
        'finalize_run_status_local'};
end

function section6c_state = build_section6c_state_local(cfg)
    run_end_state = struct_utils.req_struct_field( ...
        cfg, 'run_end_state', 'cerupp_section6c_finalize_reporting.run_end_state');
    checkpoint_policy_state = struct_utils.req_struct_field( ...
        cfg, 'checkpoint_policy_state', ...
        'cerupp_section6c_finalize_reporting.checkpoint_policy_state');
    checkpoint_failure_state = struct_utils.req_struct_field( ...
        checkpoint_policy_state, 'failure_state', ...
        'cerupp_section6c_finalize_reporting.checkpoint_policy_state');

    propagation_completed_requested_distance = ...
        (double(cfg.completed_z_steps) == double(cfg.num_zsteps));
    terminal_propagated_state = resolve_terminal_propagated_state_local( ...
        cfg, run_end_state);
    run_end_state.terminal_propagated_state = terminal_propagated_state;
    propagation_success = ...
        terminal_propagated_state.ok && propagation_completed_requested_distance;
    terminal_store_contract = ...
        resolve_terminal_store_contract_local(run_end_state);
    run_end_state.terminal_store_contract = terminal_store_contract;

    run_end_state.intermediate = build_intermediate_output_state_local( ...
        cfg.output_plan, checkpoint_policy_state, checkpoint_failure_state, ...
        cfg.completed_z_steps, cfg.num_zsteps);
    run_end_state.postprocess = collapse_postprocess_state_local( ...
        run_end_state.postprocess);
    run_end_state.final_outputs = build_initial_final_output_state_local( ...
        cfg, run_end_state, terminal_store_contract);

    warning_ledgers = cfg.warning_ledgers;
    warning_ledgers.run = cfg.run_warn_state;
    warning_ledgers = warning_utils.emit_resetting_run_end_warnings( ...
        'CerUPP:DriverRunEnd', warning_ledgers);
    run_warn_state = warning_ledgers.run;

    postprocess_phase_ok = run_end_state.postprocess.phase_ok;
    postprocess_success = run_end_state.postprocess.ok;
    physics_success = propagation_success;
    latest_pointer_writes_requested = logical( ...
        cfg.output_plan.request.write_latest_successful_run_id_flag);
    latest_successful_pointer_eligible = false;
    latest_fully_packaged_pointer_eligible = false;
    latest_propagation_complete_pointer_eligible = false;
    run_end_state.final_outputs.latest_successful_pointer = ...
        build_pending_pointer_status_local( ...
            latest_pointer_writes_requested, 'pending_post_status_contract');
    run_end_state.final_outputs.latest_fully_packaged_pointer = ...
        build_pending_pointer_status_local( ...
            latest_pointer_writes_requested, 'pending_post_status_contract');
    run_end_state.final_outputs.latest_propagation_complete_pointer = ...
        build_pending_pointer_status_local( ...
            latest_pointer_writes_requested, 'pending_post_status_contract');

    runtime_setup = struct_utils.req_struct_field( ...
        cfg, 'runtime_setup', 'cerupp_section6c_finalize_reporting.runtime_setup');
    pointer_paths = struct_utils.req_struct_field( ...
        struct_utils.req_struct_field( ...
            runtime_setup, 'artifact_paths', ...
            'cerupp_section6c_finalize_reporting.runtime_setup'), ...
        'pointers', 'cerupp_section6c_finalize_reporting.runtime_setup');
    run_id = struct_utils.req_struct_field( ...
        runtime_setup, 'run_id', 'cerupp_section6c_finalize_reporting.runtime_setup');

    run_status_requested = logical(cfg.output_plan.request.write_run_status_flag);
    if ~run_status_requested
        run_status_initial_skipped_reason = 'not_requested';
        run_status_initial_result = 'skipped_not_requested';
    else
        run_status_initial_skipped_reason = '';
        run_status_initial_result = 'pending_write';
    end
    run_end_state.final_outputs.run_status = build_artifact_status_record_local( ...
        run_status_requested, false, true, run_status_initial_skipped_reason, ...
        '', '', run_status_initial_result);

    final_output_write_success_for_status = final_outputs_ok_for_status_local( ...
        run_end_state.final_outputs);
    intermediate_output_write_success_for_status = ...
        intermediate_outputs_ok_local(run_end_state.intermediate);
    reporting_success_for_status = run_end_state.finalization.ok && ...
        terminal_store_contract.matches_accepted_state && ...
        run_end_state.postprocess.ok && ...
        intermediate_output_write_success_for_status && ...
        final_output_write_success_for_status;
    completed_with_all_requested_outputs_for_status = ...
        physics_success && reporting_success_for_status;

    artifact_status = build_artifact_status_tree_local(run_end_state);
    status_extra_fields = build_status_extra_fields_local(struct( ...
        'propagation_success', propagation_success, ...
        'propagation_completed_requested_distance', ...
            propagation_completed_requested_distance, ...
        'physics_success', physics_success, ...
        'postprocess_phase_ok', postprocess_phase_ok, ...
        'postprocess_success', postprocess_success, ...
        'run_end_state', run_end_state, ...
        'run_warn_state', run_warn_state, ...
        'terminal_propagated_state', terminal_propagated_state, ...
        'terminal_store_contract', terminal_store_contract, ...
        'intermediate_output_write_success_for_status', ...
            intermediate_output_write_success_for_status, ...
        'final_output_write_success_for_status', ...
            final_output_write_success_for_status, ...
        'reporting_success_for_status', reporting_success_for_status, ...
        'completed_with_all_requested_outputs_for_status', ...
            completed_with_all_requested_outputs_for_status, ...
        'final_restart_save_ok', cfg.final_restart_save_ok, ...
        'end_snapshot_save_ok', cfg.end_snapshot_save_ok, ...
        'final_full_save_ok', cfg.final_full_save_ok, ...
        'final_a_s_state_finite', cfg.final_a_s_state_finite, ...
        'final_a_f_state_finite', cfg.final_a_f_state_finite, ...
        'final_rho_state_finite', cfg.final_rho_state_finite, ...
        'final_rho_state_shape_ok', cfg.final_rho_state_shape_ok));

    run_status_ctx = cfg.run_status_ctx;
    if run_status_ctx.enabled || run_status_ctx.write_current_pointer
        [attempt_state, attempt_identifier, attempt_message, attempt_reason] = ...
            build_attempt_status_local(physics_success, ...
                propagation_completed_requested_distance, artifact_status, ...
                terminal_propagated_state, ...
                terminal_store_contract.matches_accepted_state, ...
                postprocess_phase_ok, ...
                intermediate_output_write_success_for_status, ...
                final_output_write_success_for_status, ...
                completed_with_all_requested_outputs_for_status);
        status_extra_fields.attempt_reason = attempt_reason;
        [run_warn_state, run_status_ctx] = cfg.finalize_run_status_local( ...
            run_warn_state, run_status_ctx, attempt_state, ...
            attempt_identifier, attempt_message, 'normal_exit', ...
            status_extra_fields);
    end

    run_end_state.final_outputs.run_status = resolve_run_status_record_local( ...
        run_status_requested, run_status_ctx);
    run_end_state.final_outputs.current_pointer = ...
        resolve_current_pointer_record_local( ...
            logical(cfg.output_plan.request.write_current_run_pointer_flag), ...
            run_status_ctx);
    final_output_write_success = final_outputs_ok_after_status_local( ...
        run_end_state.final_outputs);
    intermediate_output_write_success = ...
        intermediate_outputs_ok_local(run_end_state.intermediate);
    reporting_success = run_end_state.finalization.ok && ...
        terminal_store_contract.matches_accepted_state && ...
        run_end_state.postprocess.ok && ...
        intermediate_output_write_success && final_output_write_success;
    completed_with_all_requested_outputs = physics_success && ...
        reporting_success;
    latest_successful_pointer_eligible = ...
        propagation_completed_requested_distance && ...
        logical(cfg.final_a_s_state_finite) && ...
        logical(cfg.final_rho_state_finite) && ...
        postprocess_has_any_ok_family_local(run_end_state.postprocess);
    latest_fully_packaged_pointer_eligible = ...
        completed_with_all_requested_outputs;
    latest_propagation_complete_pointer_eligible = ...
        propagation_completed_requested_distance;
    [run_end_state.final_outputs.latest_successful_pointer, run_warn_state] = ...
        write_pointer_status_local(struct( ...
            'requested', latest_pointer_writes_requested, ...
            'eligible', latest_successful_pointer_eligible, ...
            'run_bucket', struct_utils.req_struct_field( ...
                struct_utils.req_struct_field( ...
                    pointer_paths, 'latest_successful', ...
                    'cerupp_section6c_finalize_reporting.pointer_paths'), ...
                'root', 'cerupp_section6c_finalize_reporting.pointer_paths'), ...
            'pointer_name', struct_utils.req_struct_field( ...
                struct_utils.req_struct_field( ...
                    pointer_paths, 'latest_successful', ...
                    'cerupp_section6c_finalize_reporting.pointer_paths'), ...
                'name', 'cerupp_section6c_finalize_reporting.pointer_paths'), ...
            'run_id', run_id, ...
            'warn_key', 'latest_successful_run_pointer_write_failed', ...
            'warn_id', ...
                'CerUPP:RunStatus:LatestSuccessfulRunPointerWriteFailed', ...
            'failure_tag', 'latest_successful_run_pointer', ...
            'failure_message', 'Could not write latest_successful_run_id.txt.'), ...
            run_warn_state);
    [run_end_state.final_outputs.latest_fully_packaged_pointer, ...
        run_warn_state] = write_pointer_status_local(struct( ...
            'requested', latest_pointer_writes_requested, ...
            'eligible', latest_fully_packaged_pointer_eligible, ...
            'run_bucket', struct_utils.req_struct_field( ...
                struct_utils.req_struct_field( ...
                    pointer_paths, 'latest_fully_packaged', ...
                    'cerupp_section6c_finalize_reporting.pointer_paths'), ...
                'root', 'cerupp_section6c_finalize_reporting.pointer_paths'), ...
            'pointer_name', struct_utils.req_struct_field( ...
                struct_utils.req_struct_field( ...
                    pointer_paths, 'latest_fully_packaged', ...
                    'cerupp_section6c_finalize_reporting.pointer_paths'), ...
                'name', 'cerupp_section6c_finalize_reporting.pointer_paths'), ...
            'run_id', run_id, ...
            'warn_key', 'latest_fully_packaged_run_pointer_write_failed', ...
            'warn_id', ...
                'CerUPP:RunStatus:LatestFullyPackagedRunPointerWriteFailed', ...
            'failure_tag', 'latest_fully_packaged_run_pointer', ...
            'failure_message', 'Could not write latest_fully_packaged_run_id.txt.'), ...
            run_warn_state);
    [run_end_state.final_outputs.latest_propagation_complete_pointer, ...
        run_warn_state] = write_pointer_status_local(struct( ...
            'requested', latest_pointer_writes_requested, ...
            'eligible', latest_propagation_complete_pointer_eligible, ...
            'run_bucket', struct_utils.req_struct_field( ...
                struct_utils.req_struct_field( ...
                    pointer_paths, 'latest_propagation_complete', ...
                    'cerupp_section6c_finalize_reporting.pointer_paths'), ...
                'root', 'cerupp_section6c_finalize_reporting.pointer_paths'), ...
            'pointer_name', struct_utils.req_struct_field( ...
                struct_utils.req_struct_field( ...
                    pointer_paths, 'latest_propagation_complete', ...
                    'cerupp_section6c_finalize_reporting.pointer_paths'), ...
                'name', 'cerupp_section6c_finalize_reporting.pointer_paths'), ...
            'run_id', run_id, ...
            'warn_key', 'latest_propagation_complete_run_pointer_write_failed', ...
            'warn_id', ...
                'CerUPP:RunStatus:LatestPropagationCompleteRunPointerWriteFailed', ...
            'failure_tag', 'latest_propagation_complete_run_pointer', ...
            'failure_message', ...
                'Could not write latest_propagation_complete_run_id.txt.'), ...
            run_warn_state);
    final_output_write_success = final_outputs_ok_after_status_local( ...
        run_end_state.final_outputs);
    intermediate_output_write_success = ...
        intermediate_outputs_ok_local(run_end_state.intermediate);
    reporting_success = run_end_state.finalization.ok && ...
        terminal_store_contract.matches_accepted_state && ...
        run_end_state.postprocess.ok && ...
        intermediate_output_write_success && final_output_write_success;
    completed_with_all_requested_outputs = physics_success && ...
        reporting_success;
    [attempt_state, attempt_identifier, attempt_message, attempt_reason] = ...
        build_attempt_status_local(physics_success, ...
            propagation_completed_requested_distance, ...
            build_artifact_status_tree_local(run_end_state), ...
            terminal_propagated_state, ...
            terminal_store_contract.matches_accepted_state, ...
            postprocess_phase_ok, ...
            intermediate_output_write_success, ...
            final_output_write_success, ...
            completed_with_all_requested_outputs);
    status_extra_fields = ...
        extend_status_extra_fields_with_latest_pointer_results_local( ...
            status_extra_fields, run_end_state, ...
            latest_successful_pointer_eligible, ...
            latest_fully_packaged_pointer_eligible, ...
            latest_propagation_complete_pointer_eligible, ...
            final_output_write_success, reporting_success, ...
            completed_with_all_requested_outputs, attempt_reason);
    if latest_pointer_writes_requested && run_status_requested
        [run_warn_state, run_status_ctx] = ...
            run_output_utils.republish_final_run_status_after_pointer_writes( ...
                struct( ...
                    'run_status_ctx', run_status_ctx, ...
                    'attempt_state', attempt_state, ...
                    'error_id', attempt_identifier, ...
                    'error_message', attempt_message, ...
                    'restart_compat_version', runtime_setup.restart_compat_version, ...
                    'release_version', runtime_setup.release_version, ...
                    'curr_cerupp_version', runtime_setup.curr_cerupp_version, ...
                    'status_extra_fields', status_extra_fields, ...
                    'status_phase_tag', run_warn_state_utils.phase_end(), ...
                    'status_warn_key', 'run_status_write_failed', ...
                    'status_warn_id', 'CerUPP:RunStatus:RunStatusWriteFailed', ...
                    'status_failure_tag', 'run_status_final_write'), ...
                run_warn_state);
    end
    run_end_state.final_outputs.run_status = resolve_run_status_record_local( ...
        run_status_requested, run_status_ctx);
    final_output_write_success = final_outputs_ok_after_status_local( ...
        run_end_state.final_outputs);
    intermediate_output_write_success = ...
        intermediate_outputs_ok_local(run_end_state.intermediate);
    reporting_success = run_end_state.finalization.ok && ...
        terminal_store_contract.matches_accepted_state && ...
        run_end_state.postprocess.ok && ...
        intermediate_output_write_success && final_output_write_success;
    completed_with_all_requested_outputs = physics_success && ...
        reporting_success;
    status_extra_fields.status_failure_categories = ...
        build_status_failure_categories_local(struct( ...
        'run_end_state', run_end_state, ...
        'run_warn_state', run_warn_state, ...
