        if logical(struct_utils.opt_struct_field( ...
                run_status_ctx.last_finalize_status, ...
                'status_write_post_latest_pointer_attempted', false)) && ...
                ~logical(struct_utils.opt_struct_field( ...
                run_status_ctx.last_finalize_status, ...
