        'status_pointer_write', 0, ...
        'diagnostic_info', 0);
    if ~(isstruct(run_warn_state) && isfield(run_warn_state, 'output_io') && ...
            isstruct(run_warn_state.output_io) && isfield(run_warn_state.output_io, 'records'))
        return;
    end
    output_io_records = run_warn_state.output_io.records;
    plot_tags = {'png_export', 'fig_export', 'plot_output_dir_create'};
    restart_tags = {'intermediate_checkpoint', 'intermediate_checkpoint_fullsave', ...
        'a_s_rho_snapshot_checkpoint', 'final_restart_checkpoint'};
    final_save_tags = {'final_full_save', 'final_fullsave_build_failed', ...
        'end_snapshot_save'};
    status_pointer_tags = {'run_status_setup_write', 'run_status_final_write', ...
        'run_status_failure_write', 'current_run_pointer', ...
        'current_run_pointer_delete', 'latest_successful_run_pointer', ...
        'latest_fully_packaged_run_pointer', ...
        'latest_propagation_complete_pointer'};
    diagnostic_info_tags = {'nonfinite_diagnostic_log', 'output_io'};
    for rec_idx = 1:numel(output_io_records)
        rec = output_io_records(rec_idx);
        if ~(isstruct(rec) && isfield(rec, 'tag'))
            continue;
        end
        tag_value = char(string(rec.tag));
        rec_count = 1;
        if isfield(rec, 'count') && isnumeric(rec.count) && ...
                isfinite(rec.count)
            rec_count = max(floor(double(rec.count)), 0);
        end
        if any(strcmp(tag_value, diagnostic_info_tags))
            counts.diagnostic_info = counts.diagnostic_info + rec_count;
        elseif any(strcmp(tag_value, plot_tags))
            counts.plot_write = counts.plot_write + rec_count;
        elseif any(strcmp(tag_value, restart_tags))
            counts.restart_save = counts.restart_save + rec_count;
        elseif any(strcmp(tag_value, final_save_tags))
            counts.final_save = counts.final_save + rec_count;
        elseif any(strcmp(tag_value, status_pointer_tags))
            counts.status_pointer_write = counts.status_pointer_write + rec_count;
        end
    end
end

