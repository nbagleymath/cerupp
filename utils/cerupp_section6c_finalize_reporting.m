function terminal_state = resolve_terminal_propagated_state_local(cfg, run_end_state)
    terminal_state = struct_utils.opt_struct_field( ...
        run_end_state, 'terminal_propagated_state', struct());
    if isstruct(terminal_state) && isscalar(terminal_state) && ...
            isfield(terminal_state, 'ok')
        return;
    end
    final_rho_state_shape_ok = logical(struct_utils.opt_struct_field( ...
        cfg, 'final_rho_state_shape_ok', true));
    terminal_ok = logical(cfg.final_a_s_state_finite) && ...
        logical(cfg.final_a_f_state_finite) && ...
        logical(cfg.final_rho_state_finite) && final_rho_state_shape_ok;
    failure_tags = {};
    if ~logical(cfg.final_a_s_state_finite)
        failure_tags{end + 1} = 'final_a_s_missing_or_nonfinite';
    end
    if ~logical(cfg.final_a_f_state_finite)
        failure_tags{end + 1} = 'final_a_f_missing_or_nonfinite';
    end
    if ~logical(cfg.final_rho_state_finite)
        failure_tags{end + 1} = 'final_rho_missing_or_nonfinite';
    end
    if ~final_rho_state_shape_ok
        failure_tags{end + 1} = 'final_rho_shape_mismatch';
    end
    if terminal_ok
        failure_class = 'none';
        severity = 'none';
    else
        failure_class = 'bad_propagated_state';
        severity = 'fatal';
    end
    terminal_state = struct( ...
        'ok', terminal_ok, ...
        'success', terminal_ok, ...
        'failure_class', failure_class, ...
        'severity', severity, ...
        'a_s_ok', logical(cfg.final_a_s_state_finite), ...
        'a_f_ok', logical(cfg.final_a_f_state_finite), ...
        'rho_ok', logical(cfg.final_rho_state_finite) && ...
            final_rho_state_shape_ok, ...
        'rho_finite_ok', logical(cfg.final_rho_state_finite), ...
        'rho_shape_ok', final_rho_state_shape_ok, ...
        'failure_tags', {failure_tags});
end

