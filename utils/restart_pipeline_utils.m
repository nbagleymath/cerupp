        function stream_write_result = build_checkpoint_stream_write_result_local( ...
                failure_state_before, failure_state_after, ...
                enabled_before_write, enabled_after_write, ...
                requested_for_step, stream_name)
        % Build one truthful per-call checkpoint stream write record from
        % the failure-state counters instead of inferring success from a
        % normal return.

            stream_name = char(string(stream_name));
            switch stream_name
                case 'restart'
                    attempt_count_before = failure_state_before.restart_attempt_count;
                    attempt_count_after = failure_state_after.restart_attempt_count;
                    success_count_before = failure_state_before.restart_success_count;
                    success_count_after = failure_state_after.restart_success_count;
                    last_attempt_ok = logical(failure_state_after.restart_last_attempt_ok);
                    error_id = char(string(failure_state_after.error_id));
                    error_message = char(string(failure_state_after.error_message));
                    disabled_after_repeated_failures = logical( ...
                        failure_state_after.disable_restart_only);
                case 'fullsave'
                    attempt_count_before = failure_state_before.fullsave_attempt_count;
                    attempt_count_after = failure_state_after.fullsave_attempt_count;
                    success_count_before = failure_state_before.fullsave_success_count;
                    success_count_after = failure_state_after.fullsave_success_count;
                    last_attempt_ok = logical(failure_state_after.fullsave_last_attempt_ok);
                    error_id = char(string(failure_state_after.fullsave_error_id));
                    error_message = char(string(failure_state_after.fullsave_error_message));
                    disabled_after_repeated_failures = logical( ...
                        failure_state_after.disable_fullsave_only);
                otherwise
                    error('CerUPP:InvalidCheckpointStreamWriteResult', ...
                        'Unsupported checkpoint stream "%s".', stream_name);
            end

            attempted = (double(attempt_count_after) > double(attempt_count_before));
            written = (double(success_count_after) > double(success_count_before));
            skipped_reason = '';
            if ~logical(requested_for_step)
                skipped_reason = 'not_requested_for_step';
            elseif ~logical(enabled_before_write)
                skipped_reason = 'stream_disabled_before_write';
            elseif attempted && ~written && disabled_after_repeated_failures
                skipped_reason = 'disabled_after_repeated_failures';
            elseif attempted && ~written
                skipped_reason = 'write_failed';
            elseif ~attempted
                skipped_reason = 'writer_returned_without_attempt';
            end

            if ~logical(requested_for_step)
                result = 'not_requested_for_step';
            elseif written
                result = 'written';
            elseif attempted
                result = 'failed';
            else
                result = 'skipped';
            end

            stream_write_result = struct( ...
                'requested_for_step', logical(requested_for_step), ...
                'enabled_before_write', logical(enabled_before_write), ...
                'enabled_after_write', logical(enabled_after_write), ...
                'attempted', attempted, ...
                'written', written, ...
                'last_attempt_ok', last_attempt_ok, ...
                'skipped_reason', skipped_reason, ...
                'result', result, ...
                'error_id', error_id, ...
                'error_message', error_message);
        end

