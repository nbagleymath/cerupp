        function flat_inputs = merge_checkpoint_input_group_local(flat_inputs, group_value, group_label)
        % Merge one grouped checkpoint owner into the helper-local flat cfg.

            if ~(isstruct(group_value) && isscalar(group_value))
                error('CerUPP:InvalidCheckpointGroupedInput', ...
                    '%s must be a scalar struct.', group_label);
            end
            group_field_names = fieldnames(group_value);
            overlap = intersect(fieldnames(flat_inputs), group_field_names, 'stable');
            if ~isempty(overlap)
                error('CerUPP:DuplicateCheckpointGroupedInputField', ...
                    '%s reuses existing checkpoint field(s): %s', ...
                    group_label, strjoin(overlap, ', '));
            end
            for field_idx = 1:numel(group_field_names)
                field_name = group_field_names{field_idx};
                flat_inputs.(field_name) = group_value.(field_name);
            end
        end

