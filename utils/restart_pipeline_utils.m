        function store_failure_state = handle_accepted_step_store_failure_local(cfg)
        % Handle a stored-plane failure that happened after the propagation
        % step was already completed. This path may still write one salvage
        % restart, but it only reports success when that restart was
        % actually written.

            context_name = ...
                'restart_pipeline_utils.handle_accepted_step_store_failure_local cfg';
            if nargin < 1 || ~isstruct(cfg) || ~isscalar(cfg)
                error('CerUPP:InvalidAcceptedStepStoreFailureCfg', ...
                    '%s must be one scalar struct.', context_name);
            end

            run_warn_state = struct_utils.req_struct_field( ...
                cfg, 'run_warn_state', context_name);
            diag_state = struct_utils.req_struct_field( ...
                cfg, 'diag_state', context_name);
            checkpoint_policy_state = struct_utils.req_struct_field( ...
                cfg, 'checkpoint_policy_state', context_name);
            me_store_step = struct_utils.req_struct_field( ...
                cfg, 'store_error', context_name);

