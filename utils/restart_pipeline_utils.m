        % Write the optional end_data.mat snapshot before Section 6 so the
        % returned run_warn_state already includes any end-snapshot I/O result.

            end_snapshot_write_state = ...
                restart_pipeline_utils.build_empty_end_snapshot_write_state( ...
                    cfg.output_cfg.save_end_snapshot_flag);
