        function diagnostic_store = build_requested_trimmed_live_diag_store(requested_fields, n_keep, diag_store_in)
        % Build only the requested diagnostic-store fields and trim only those fields.

            diag_store_in = restart_pipeline_utils.normalize_live_diag_store_input_local(diag_store_in);
            requested_fields = checkpoint_utils.normalize_checkpoint_varlist(requested_fields);
            diag_specs = checkpoint_utils.diag_field_specs();
            field_names = {diag_specs.name};
            requested_diag_mask = ismember(field_names, requested_fields);
            if ~any(requested_diag_mask)
                diagnostic_store = struct();
                return;
            end
            if all(requested_diag_mask)
                diagnostic_store = restart_pipeline_utils.trim_diag_storage_from_schema( ...
                    diag_store_in, n_keep);
                return;
            end
            diagnostic_store = struct();
            requested_diag_specs = diag_specs(requested_diag_mask);
            for ii = 1:numel(requested_diag_specs)
                spec = requested_diag_specs(ii);
                field_value = restart_pipeline_utils.require_diag_store_field_local( ...
                    diag_store_in, spec.name);
                field_value = struct_utils.trim_storage_axis( ...
                    field_value, n_keep, spec.trim_axis);
                diagnostic_store.(spec.name) = field_value;
            end
        end

