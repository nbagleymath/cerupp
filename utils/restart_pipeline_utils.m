        function [controlled_stop_salvage, checkpoint_policy_state_out, ...
                diag_state_out, run_warn_state] = ...
                attempt_controlled_stop_salvage_from_caller(me_run, run_warn_state)
        % Probe the driver catch workspace once and, for controlled-stop
        % exits, attempt the minimal salvage restart checkpoint from the
        % newest recoverable in-memory state.

            if nargin < 2 || ~isstruct(run_warn_state)
                run_warn_state = struct();
            end
            checkpoint_policy_state_out = ...
                restart_pipeline_utils.opt_caller_var_local( ...
                    'checkpoint_policy_state', struct());
            diag_state_out = restart_pipeline_utils.opt_caller_var_local( ...
                'diag_state', struct());
            controlled_stop_salvage = struct( ...
                'attempted', false, ...
                'ok', false, ...
                'stop_identifier', char(string(me_run.identifier)), ...
                'reason', '', ...
                'source_step', NaN, ...
                'write_status', 'not_attempted', ...
                'write_skipped_reason', '', ...
                'error_id', '', ...
                'error_message', '');
            if ~(strcmp(me_run.identifier, 'CerUPP:Wallclock:ProjectedTimeout') || ...
                    strcmp(me_run.identifier, 'CerUPP:MemMon:AbortOnThreshold'))
                return;
            end

            grid_state = restart_pipeline_utils.opt_caller_var_local( ...
                'grid_state', struct());
            medium_state = restart_pipeline_utils.opt_caller_var_local( ...
                'medium_state', struct());
            output_state = restart_pipeline_utils.opt_caller_var_local( ...
                'output_state', struct());
            checkpoint_restart_state_base = ...
                restart_pipeline_utils.opt_caller_var_local( ...
                    'checkpoint_restart_state_base', struct());
            output_plan = restart_pipeline_utils.opt_caller_var_local( ...
                'output_plan', struct());
            run_meta = restart_pipeline_utils.opt_caller_var_local( ...
                'run_meta', struct());
            checkpoint_vars_full = restart_pipeline_utils.opt_caller_var_local( ...
                'checkpoint_vars_full', []);
            checkpoint_diag_reassembly_flag = ...
                restart_pipeline_utils.opt_caller_var_local( ...
                    'checkpoint_diag_reassembly_flag', []);
            rebuild_policy = restart_pipeline_utils.opt_caller_var_local( ...
                'rebuild_policy', struct());
            driver_extension_inputs = ...
                restart_pipeline_utils.opt_caller_var_local( ...
                    'driver_extension_inputs', struct());
            custom_checkpoint_restart_fields = ...
                restart_pipeline_utils.opt_caller_var_local( ...
                    'custom_checkpoint_restart_fields', struct());
            perf_cfg = restart_pipeline_utils.opt_caller_var_local( ...
                'perf_cfg', struct());
            energy = restart_pipeline_utils.opt_caller_var_local( ...
                'energy', []);
            num_zsteps = restart_pipeline_utils.opt_caller_var_local( ...
                'num_zsteps', NaN);
            track_keldysh_effective_nla_diag_flag = ...
                restart_pipeline_utils.opt_caller_var_local( ...
                    'track_keldysh_effective_nla_diag_flag', []);

            salvage_curr_z_step = NaN;
            salvage_z_curr = NaN;
            salvage_z_pre_step = NaN;
            salvage_z_post_step = NaN;
            salvage_dz = NaN;
            salvage_save_idx = NaN;
            salvage_accepted_state = struct();
            salvage_step_reassembly_state = struct();
            checkpoint_step_policy = restart_pipeline_utils.opt_caller_var_local( ...
                'checkpoint_step_policy', struct());
            last_memmon_phase_tag = char(string( ...
                restart_pipeline_utils.opt_caller_var_local( ...
                    'last_memmon_phase_tag', '')));

            if strcmp(me_run.identifier, 'CerUPP:MemMon:AbortOnThreshold')
                controlled_stop_salvage.reason = 'memmon_threshold_abort';
                curr_z_step = restart_pipeline_utils.opt_caller_var_local( ...
                    'curr_z_step', NaN);
                if strcmp(last_memmon_phase_tag, 'START_STEP')
                    z_domain = restart_pipeline_utils.opt_caller_var_local( ...
                        'z_domain', []);
                    controlled_stop_salvage.reason = ...
                        'memmon_threshold_abort_start_step';
                    if isfinite(curr_z_step) && isvector(z_domain) && ...
                            (curr_z_step > 1) && (numel(z_domain) >= curr_z_step)
                        salvage_curr_z_step = double(curr_z_step) - 1;
                        salvage_z_pre_step = double(z_domain(salvage_curr_z_step));
                        salvage_z_post_step = double(z_domain(salvage_curr_z_step + 1));
                        salvage_z_curr = salvage_z_pre_step;
                        salvage_dz = salvage_z_post_step - salvage_z_pre_step;
                    end
                else
                    salvage_curr_z_step = curr_z_step;
                    salvage_z_curr = restart_pipeline_utils.opt_caller_var_local( ...
                        'z_curr', NaN);
                    salvage_z_pre_step = restart_pipeline_utils.opt_caller_var_local( ...
                        'z_pre_step', NaN);
                    salvage_z_post_step = restart_pipeline_utils.opt_caller_var_local( ...
                        'z_post_step', NaN);
                    salvage_dz = restart_pipeline_utils.opt_caller_var_local( ...
                        'dz', NaN);
                end
                salvage_save_idx = restart_pipeline_utils.opt_caller_var_local( ...
                    'save_idx', NaN);
                salvage_accepted_state = restart_pipeline_utils.opt_caller_var_local( ...
                    'accepted_state', struct());
                if ~restart_pipeline_utils.scalar_struct_has_fields_local( ...
                        salvage_accepted_state)
                    A_S = restart_pipeline_utils.opt_caller_var_local('A_S', []);
                    A_F = restart_pipeline_utils.opt_caller_var_local('A_F', []);
                    A_SSF = restart_pipeline_utils.opt_caller_var_local('A_SSF', []);
                    rho = restart_pipeline_utils.opt_caller_var_local('rho', []);
                    if ~isempty(A_S) && ~isempty(A_F) && ~isempty(A_SSF)
                        salvage_accepted_state = ...
                            restart_pipeline_utils.build_accepted_state_from_live( ...
                                A_S, A_F, A_SSF, rho);
                    end
                end
                salvage_step_reassembly_state = ...
                    restart_pipeline_utils.opt_caller_var_local( ...
                        'step_reassembly_state', struct());
                if ~restart_pipeline_utils.scalar_struct_has_fields_local( ...
                        salvage_step_reassembly_state)
                    rhs_plasma = restart_pipeline_utils.opt_caller_var_local( ...
                        'rhs_plasma', []);
                    step_diag = restart_pipeline_utils.opt_caller_var_local( ...
                        'step_diag', struct());
                    if ~isempty(rhs_plasma) && isstruct(step_diag) && ...
                            isscalar(step_diag)
                        salvage_step_reassembly_state = ...
                            restart_pipeline_utils.build_step_reassembly_state_from_live( ...
                                rhs_plasma, step_diag);
                    end
                end
            else
                controlled_stop_salvage.reason = 'projected_wallclock_timeout';
                curr_z_step = restart_pipeline_utils.opt_caller_var_local( ...
                    'curr_z_step', NaN);
                z_domain = restart_pipeline_utils.opt_caller_var_local( ...
                    'z_domain', []);
                salvage_save_idx = restart_pipeline_utils.opt_caller_var_local( ...
                    'save_idx', NaN);
                if isfinite(curr_z_step) && isvector(z_domain) && ...
                        (curr_z_step > 1) && (numel(z_domain) >= curr_z_step)
                    salvage_curr_z_step = double(curr_z_step) - 1;
                    salvage_z_pre_step = double(z_domain(salvage_curr_z_step));
                    salvage_z_post_step = double(z_domain(salvage_curr_z_step + 1));
                    salvage_z_curr = salvage_z_pre_step;
                    salvage_dz = salvage_z_post_step - salvage_z_pre_step;
                end
                A_S = restart_pipeline_utils.opt_caller_var_local('A_S', []);
                A_F = restart_pipeline_utils.opt_caller_var_local('A_F', []);
                A_SSF = restart_pipeline_utils.opt_caller_var_local('A_SSF', []);
                rho = restart_pipeline_utils.opt_caller_var_local('rho', []);
                rhs_plasma = restart_pipeline_utils.opt_caller_var_local( ...
                    'rhs_plasma', []);
                step_diag = restart_pipeline_utils.opt_caller_var_local( ...
                    'step_diag', struct());
                if ~isempty(A_S) && ~isempty(A_F) && ~isempty(A_SSF)
                    salvage_accepted_state = ...
                        restart_pipeline_utils.build_accepted_state_from_live( ...
                            A_S, A_F, A_SSF, rho);
                end
                if ~isempty(rhs_plasma) && isstruct(step_diag) && isscalar(step_diag)
                    salvage_step_reassembly_state = ...
                        restart_pipeline_utils.build_step_reassembly_state_from_live( ...
                            rhs_plasma, step_diag);
                end
            end

            salvage_ready = isfinite(salvage_curr_z_step) && isfinite(salvage_z_curr) && ...
                isfinite(salvage_z_pre_step) && isfinite(salvage_z_post_step) && ...
                isfinite(salvage_dz) && isfinite(salvage_save_idx) && ...
                restart_pipeline_utils.scalar_struct_has_fields_local( ...
                    salvage_accepted_state) && ...
                restart_pipeline_utils.scalar_struct_has_fields_local( ...
                    salvage_step_reassembly_state) && ...
                isstruct(grid_state) && isstruct(medium_state) && ...
                isstruct(output_state) && isstruct(diag_state_out) && ...
                isstruct(checkpoint_policy_state_out) && ...
                isstruct(checkpoint_restart_state_base) && ...
                isstruct(output_plan) && isstruct(run_meta) && ...
                isscalar(num_zsteps) && isfinite(num_zsteps) && ...
                isstruct(rebuild_policy) && isstruct(driver_extension_inputs) && ...
                isstruct(custom_checkpoint_restart_fields) && ...
                isstruct(perf_cfg) && ...
                isscalar(track_keldysh_effective_nla_diag_flag) && ...
                (islogical(track_keldysh_effective_nla_diag_flag) || ...
                 (isnumeric(track_keldysh_effective_nla_diag_flag) && ...
                  isreal(track_keldysh_effective_nla_diag_flag) && ...
                  isfinite(track_keldysh_effective_nla_diag_flag)));
            if ~salvage_ready
                return;
            end

            controlled_stop_salvage.attempted = true;
