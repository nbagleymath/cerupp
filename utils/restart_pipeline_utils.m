        function restart_state = build_restart_state_from_runtime(cfg)
        % BUILD_RESTART_STATE_FROM_RUNTIME Assemble one restart_state from the live driver runtime snapshot.

            if nargin < 1 || ~isstruct(cfg)
                error('CerUPP:InvalidRestartRuntimeCfg', ...
                    'build_restart_state_from_runtime requires a struct cfg.');
            end
            restart_ops_payload = restart_pipeline_utils.build_restart_ops_payload_local(cfg);
            restart_payload = restart_pipeline_utils.build_restart_payload_groups_from_runtime_cfg_local(cfg);
            restart_payload.ops = restart_ops_payload;
            restart_state = restart_pipeline_utils.build_restart_state( ...
                restart_payload, cfg.run_meta, ...
                struct_utils.opt_struct_field(cfg, 'driver_extension_inputs', struct()));
        end

        function tf = restart_state_has_required_groups_local(restart_state)
        % Require the scalar restart-state groups that embedded fullsave restart reuse needs.

            required_groups = struct_utils.restart_required_groups();
            tf = isstruct(restart_state) && isscalar(restart_state) && ...
                all(isfield(restart_state, required_groups));
        end

