        function [checkpoint_vars, diag_store_out, extra_payload, payload, payload_bytes_estimate] = ...
                build_checkpoint_payload_bundle(cfg, diag_store_in)
        % Resolve the canonical checkpoint/full-save field list, diagnostic slice/trim,
        % and final selected payload under one restart-pipeline owner.
        % Extra cfg fields whose names are valid MATLAB variable names are
        % appended to the saved file as top-level MAT variables. Keep
        % that escape hatch for saved files only.

            if nargin < 1 || ~isstruct(cfg)
                error('CerUPP:InvalidCheckpointPayloadBundleCfg', ...
                    'build_checkpoint_payload_bundle requires a struct cfg.');
            end
            diag_store_full = restart_pipeline_utils.normalize_live_diag_store_input_local(diag_store_in);
            checkpoint_vars = struct_utils.opt_struct_field(cfg, 'checkpoint_vars', {});
            if isempty(checkpoint_vars)
                include_keldysh_effective_nla_diag_flag = ...
                    restart_pipeline_utils.resolve_include_keldysh_effective_nla_diag_flag_local(cfg);
                checkpoint_vars = restart_pipeline_utils.full_checkpoint_varlist( ...
                    cfg.store_full_spectrum_flag, cfg.track_energy_flag, ...
                    include_keldysh_effective_nla_diag_flag, ...
                    struct_utils.opt_struct_field(cfg, 'include_embedded_restart_state_flag', false));
                if logical(struct_utils.opt_struct_field(cfg, ...
                        'omit_embedded_restart_state_from_varlist', false))
                    checkpoint_vars = setdiff(checkpoint_vars, {'restart_state'}, 'stable');
                end
            end

            slice_idx_first = struct_utils.opt_struct_field(cfg, 'slice_idx_first', []);
            slice_idx_last = struct_utils.opt_struct_field(cfg, 'slice_idx_last', []);
            trim_n_keep = struct_utils.opt_struct_field(cfg, 'trim_n_keep', []);
            if ~isempty(slice_idx_first) || ~isempty(slice_idx_last)
                if isempty(slice_idx_first) || isempty(slice_idx_last)
                    error('CerUPP:InvalidCheckpointPayloadSliceRange', ...
                        'Both slice_idx_first and slice_idx_last are required for sliced checkpoint payloads.');
                end
                diag_store_out = restart_pipeline_utils.build_requested_live_diag_store_slice( ...
                    checkpoint_vars, slice_idx_first, slice_idx_last, diag_store_full);
            elseif ~isempty(trim_n_keep)
                diag_store_out = restart_pipeline_utils.build_requested_trimmed_live_diag_store( ...
                    checkpoint_vars, trim_n_keep, diag_store_full);
            else
                diag_store_out = diag_store_full;
            end
            include_embedded_restart_state_flag = logical(struct_utils.opt_struct_field( ...
                cfg, 'include_embedded_restart_state_flag', false));
            base_extra_field_names = [ ...
                {'n_store_actual'}; ...
                checkpoint_utils.checkpoint_extra_field_names(include_embedded_restart_state_flag); ...
                {'energy'} ...
            ];
            reserved_field_names = { ...
                'checkpoint_vars', ...
                'slice_idx_first', ...
                'slice_idx_last', ...
                'trim_n_keep', ...
                'store_full_spectrum_flag', ...
                'track_energy_flag', ...
                'include_keldysh_effective_nla_diag_flag', ...
                'include_embedded_restart_state_flag', ...
                'omit_embedded_restart_state_from_varlist', ...
                'n_store_actual', ...
                'lambda_window', ...
                'x', ...
                'y', ...
                't', ...
                'kx', ...
                'ky', ...
                'freq_offset', ...
                'i_laser_peak', ...
                'dz', ...
                'n_sell', ...
                't_window', ...
                'n', ...
                'diagnostic_store_stride_steps', ...
                'omega_window', ...
                'run_meta', ...
                'restart_state', ...
                'energy' ...
            };
            passthrough_field_names = restart_pipeline_utils.collect_checkpoint_passthrough_field_names_local( ...
                cfg, reserved_field_names, 'Checkpoint/fullsave payload');
            extra_field_names = [base_extra_field_names(:); passthrough_field_names(:)];
            extra_field_names = setdiff(extra_field_names(:), checkpoint_vars(:), 'stable');
            checkpoint_vars = [checkpoint_vars(:); extra_field_names(:)];

            payload = struct();
            payload_bytes_estimate = 0;
            extra_payload = struct();
            for ii = 1:numel(checkpoint_vars)
                field_name = checkpoint_vars{ii};
                field_in_diag = isfield(diag_store_out, field_name);
                field_in_cfg = ismember(field_name, base_extra_field_names) || ...
                    ismember(field_name, passthrough_field_names);
                if field_in_diag && field_in_cfg
                    error('checkpoint_utils:DuplicatePayloadField', ...
                        'Checkpoint payload field "%s" was provided more than once across payload groups.', ...
                        field_name);
                end
                if field_in_diag
                    field_value = diag_store_out.(field_name);
                elseif field_in_cfg
                    field_value = struct_utils.req_struct_field( ...
                        cfg, field_name, 'build_checkpoint_payload_bundle cfg');
                else
                    error('checkpoint_utils:MissingPayloadFields', ...
                        'Payload source groups are missing required checkpoint field "%s".', ...
                        field_name);
                end
                payload.(field_name) = field_value;
                payload_bytes_estimate = payload_bytes_estimate + ...
                    checkpoint_utils.estimate_value_bytes(field_value);
            end
        end

        function diagnostic_store = trim_diag_storage_from_schema(diagnostic_store, n_keep)
        % Trim all diagnostic storage arrays inside an explicit diagnostic_store struct.

            if nargin < 1 || ~isstruct(diagnostic_store)
                error('CerUPP:InvalidDiagnosticStoreField', ...
                    'diagnostic_store must be a struct.');
            end
            specs = checkpoint_utils.diag_field_specs();
            for ii = 1:numel(specs)
                spec = specs(ii);
                field_name = spec.name;
                if ~isfield(diagnostic_store, field_name)
                    error('CerUPP:MissingDiagnosticStoreField', ...
                        'Diagnostic storage field "%s" is not defined in diagnostic_store.', ...
                        field_name);
                end
                diagnostic_store.(field_name) = struct_utils.trim_storage_axis( ...
                    diagnostic_store.(field_name), n_keep, spec.trim_axis);
            end
        end

