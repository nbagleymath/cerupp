classdef restart_pipeline_utils
% RESTART_PIPELINE_UTILS Restart/checkpoint payload assembly and trim helpers.
% Used by cerupp.m and checkpoint_utils.m on the save side.

    methods (Static)
        function restart_state = build_restart_state(payload, run_meta, driver_extension_inputs)
        % BUILD_RESTART_STATE Versioned restart/checkpoint payload builder.
        % Requires the structured top-level groups progress/state/grid/medium/ops.
        % When run_meta is omitted, the helper falls back to payload.meta.run_meta,
        % hoists schema/release metadata to top-level fields, and removes the
        % nested restart_compat_version copy before storing run_meta under
        % restart_state.meta. Driver-owned extension inputs live under
        % restart_state.meta.driver_extension_inputs.

            if nargin < 1 || ~isstruct(payload)
                error('CerUPP:DriverInvalidRestartPayloadStruct', ...
                    'restart_pipeline_utils.build_restart_state requires a structured restart payload.');
            end
            if nargin < 2
                run_meta = [];
            end
            if nargin < 3
                driver_extension_inputs = [];
            end
            if isempty(run_meta) && isfield(payload, 'meta') && isstruct(payload.meta) && ...
                    isfield(payload.meta, 'run_meta')
                run_meta = payload.meta.run_meta;
            end
            if isempty(driver_extension_inputs) && isfield(payload, 'meta') && ...
                    isstruct(payload.meta) && ...
                    isfield(payload.meta, 'driver_extension_inputs')
                driver_extension_inputs = payload.meta.driver_extension_inputs;
            end
            required_groups = struct_utils.restart_required_groups();
            missing_groups = required_groups(~isfield(payload, required_groups));
            if ~isempty(missing_groups)
                error('CerUPP:DriverInvalidRestartPayloadStruct', ...
                    'Structured restart payload is missing required group(s): %s', ...
                    strjoin(missing_groups, ', '));
            end
            [restart_schema_tag, restart_schema_ver] = checkpoint_utils.restart_schema_info();
            restart_compat_version_local = checkpoint_utils.restart_compat_version();
            release_version_local = checkpoint_utils.cerupp_release_version();

            restart_state = struct( ...
                'restart_compat_version', restart_compat_version_local, ...
                'release_version', char(string(release_version_local)), ...
                'restart_schema', restart_schema_tag, ...
                'restart_schema_version', restart_schema_ver, ...
                'restart_schema_owner', 'CerUPP', ...
                'progress', payload.progress, ...
                'state', payload.state, ...
                'grid', payload.grid, ...
                'medium', payload.medium, ...
                'ops', payload.ops, ...
                'meta', struct( ...
                    'release_version', char(string(release_version_local))));
            if ~isempty(run_meta)
                if isfield(run_meta, 'restart_compat_version')
                    run_meta = rmfield(run_meta, 'restart_compat_version');
                end
                restart_state.meta.run_meta = run_meta;
            end
            if ~isempty(driver_extension_inputs)
                if ~(isstruct(driver_extension_inputs) && isscalar(driver_extension_inputs))
                    error('CerUPP:InvalidRestartDriverExtensionInputs', ...
                        'driver_extension_inputs must be a scalar struct when present.');
                end
                restart_state.meta.driver_extension_inputs = driver_extension_inputs;
            end
        end

