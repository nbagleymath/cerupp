                if store_failure_state.continue_propagation_allowed
                    run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                        run_warn_state, 'propagation', ...
                        'stored_plane_failure_degraded_completion', ...
                        'CerUPP:StoredPlaneFailureDegradedCompletion', ...
                        ['Stored-plane diagnostics/output failed after the current step at step %d/%d. ', ...
                         'CerUPP kept the last committed stored-plane state, kept the newer post-step field in memory, ', ...
                         'and will continue trying later eligible stored-plane writes. ', ...
                         'Stored-plane-derived terminal outputs stay stale only until a later successful store catches back up.'], ...
                        struct_utils.req_struct_field(cfg, 'curr_z_step', context_name), ...
                        struct_utils.req_struct_field(cfg, 'num_zsteps', context_name));
                else
                    run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                        run_warn_state, 'propagation', ...
                        'stored_plane_failure_degraded_completion', ...
                        'CerUPP:StoredPlaneFailureDegradedCompletion', ...
                        ['Stored-plane diagnostics/output failed after the current step at step %d/%d. ', ...
                         'CerUPP kept the last committed stored-plane state and the newer terminal field in memory, ', ...
                         'but no salvage restart was written, so propagation is ending through the final warning/status path ', ...
                         'instead of continuing with a recoverable step record.'], ...
                        struct_utils.req_struct_field(cfg, 'curr_z_step', context_name), ...
                        struct_utils.req_struct_field(cfg, 'num_zsteps', context_name));
                end
            catch me_store_salvage
                run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                    run_warn_state, 'propagation', ...
                    'store_plane_failure_salvage_restart_failed', ...
                    'CerUPP:StorePlaneFailureSalvageRestartFailed', ...
                    ['The stored-plane path failed after the step was ', ...
                     'completed, and the follow-up salvage restart ', ...
                     'checkpoint also failed. Error: %s (%s)'], ...
                    me_store_salvage.message, ...
                    me_store_salvage.identifier);
                error('CerUPP:StoredPlaneDiagnosticsFailed', ...
                    ['Stored-plane diagnostics/output failed after the ', ...
                     'propagation step had already completed. The original ', ...
                     'failure was %s (%s).'], ...
                    me_store_step.message, me_store_step.identifier);
            end

            store_failure_state.run_warn_state = run_warn_state;
            store_failure_state.diag_state = diag_state;
            store_failure_state.checkpoint_policy_state = checkpoint_policy_state;
        end

