                rhs_plasma, step_diag_or_j_mpa, mpa_rhs_mag_step, nla_book_step, plasma_book_step)
        % Pack the companion per-step arrays and accounting used only for
        % restart reassembly, checkpoint companions, and stored diagnostics.

            if nargin == 2 && isstruct(step_diag_or_j_mpa)
                step_diag = step_diag_or_j_mpa;
                j_mpa = struct_utils.req_struct_field( ...
                    step_diag, 'j_mpa', 'build_step_reassembly_state_from_live step_diag');
                mpa_rhs_mag_step = struct_utils.req_struct_field( ...
                    step_diag, 'mpa_rhs_mag', ...
                    'build_step_reassembly_state_from_live step_diag');
                nla_book_step = struct_utils.req_struct_field( ...
                    step_diag, 'nla_book', 'build_step_reassembly_state_from_live step_diag');
                plasma_book_step = struct_utils.req_struct_field( ...
                    step_diag, 'plasma_book', 'build_step_reassembly_state_from_live step_diag');
            elseif nargin == 5
                j_mpa = step_diag_or_j_mpa;
            else
                error('CerUPP:InvalidStepReassemblyStateInputs', ...
                    ['build_step_reassembly_state_from_live requires rhs_plasma plus either ', ...
                     'step_diag or the four explicit reassembly arrays.']);
            end

            step_reassembly_state = struct( ...
                'rhs_plasma', rhs_plasma, ...
                'j_mpa', j_mpa, ...
                'mpa_rhs_mag_step', mpa_rhs_mag_step, ...
                'nla_book_step', nla_book_step, ...
                'plasma_book_step', plasma_book_step);
        end

