                'run_warn_state', run_warn_state, ...
                'diag_state', diag_state, ...
                'checkpoint_policy_state', checkpoint_policy_state, ...
                'terminal_store_matches_accepted_state', false, ...
                'terminal_store_contract_reason', ...
                    'stored_plane_failure_after_step_acceptance', ...
                'continue_propagation_allowed', false);

            run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                run_warn_state, 'propagation', ...
                'store_plane_failed_after_step_acceptance', ...
                'CerUPP:StorePlaneFailedAfterAcceptedStep', ...
                ['A stored-plane diagnostic/output failure happened after ', ...
                 'the current propagation step had already finished. ', ...
                 'Attempting one minimal salvage restart checkpoint before ', ...
                 'deciding whether propagation can continue. Error: %s (%s)'], ...
                me_store_step.message, me_store_step.identifier);

            salvage_checkpoint_step_policy = struct_utils.req_struct_field( ...
                cfg, 'checkpoint_step_policy', context_name);
            salvage_checkpoint_step_policy.attempt_restart = true;
            salvage_checkpoint_step_policy.attempt_fullsave = false;
            salvage_current_step_io_meta = ...
                restart_pipeline_utils.build_current_step_io_meta( ...
                    struct_utils.req_struct_field(cfg, 'curr_z_step', context_name), ...
                    struct_utils.req_struct_field(cfg, 'z_curr', context_name), ...
                    struct_utils.req_struct_field(cfg, 'z_pre_step', context_name), ...
                    struct_utils.req_struct_field(cfg, 'z_post_step', context_name), ...
                    struct_utils.req_struct_field(cfg, 'dz', context_name), ...
                    struct_utils.req_struct_field(cfg, 'save_idx', context_name));
            output_plan = struct_utils.req_struct_field( ...
                cfg, 'output_plan', context_name);
            perf_cfg = struct_utils.req_struct_field( ...
                cfg, 'perf_cfg', context_name);
            rebuild_policy = struct_utils.req_struct_field( ...
                cfg, 'rebuild_policy', context_name);
            salvage_step_phase_runtime_base = ...
                restart_pipeline_utils.build_checkpoint_phase_runtime_state_from_live( ...
                    salvage_current_step_io_meta, ...
                    struct_utils.req_struct_field(cfg, 'num_zsteps', context_name), ...
                    struct_utils.req_struct_field(cfg, 'z_post_step', context_name), ...
                    struct_utils.req_struct_field(cfg, 'run_meta', context_name), ...
                    struct_utils.req_struct_field(cfg, 'checkpoint_vars_full', context_name), ...
                    output_plan.store.need_store_spectral_intens_cube, ...
                    perf_cfg.track_energy_flag, ...
                    floor(double(struct_utils.req_struct_field( ...
                        cfg, 'save_idx', context_name))), ...
                    output_plan.cadence.diagnostic_store_stride_steps, ...
                    struct_utils.req_struct_field(cfg, 'energy', context_name), ...
                    struct_utils.req_struct_field( ...
                        cfg, 'track_keldysh_effective_nla_diag_flag', context_name), ...
                    salvage_checkpoint_step_policy, checkpoint_policy_state, ...
                    struct_utils.req_struct_field( ...
                        cfg, 'checkpoint_diag_reassembly_flag', context_name), ...
                    output_plan.request, ...
                    rebuild_policy.z_dependent_medium_effective, ...
                    struct_utils.req_struct_field( ...
                        cfg, 'driver_extension_inputs', context_name), ...
                    struct_utils.req_struct_field( ...
                        cfg, 'custom_checkpoint_restart_fields', context_name), ...
                    'Section 5D store-failure salvage runtime_state');

            try
                [checkpoint_write_state, run_warn_state] = ...
                    restart_pipeline_utils.write_checkpoint_from_phase_runtime_local( ...
                        struct_utils.req_struct_field(cfg, 'grid_state', context_name), ...
                        struct_utils.req_struct_field(cfg, 'medium_state', context_name), ...
                        struct_utils.req_struct_field(cfg, 'output_state', context_name), ...
                        salvage_step_phase_runtime_base, ...
                        struct_utils.req_struct_field(cfg, 'accepted_state', context_name), ...
                        struct_utils.req_struct_field(cfg, 'step_reassembly_state', context_name), ...
                        diag_state, ...
                        struct_utils.req_struct_field( ...
                            cfg, 'checkpoint_restart_state_base', context_name), ...
                        run_warn_state);
                checkpoint_policy_state = checkpoint_write_state.checkpoint_policy_state;
                diag_state.diagnostic_store = ...
                    checkpoint_write_state.diagnostic_store_updated;
                salvage_restart_write_state = struct_utils.opt_struct_field( ...
                    struct_utils.opt_struct_field( ...
                        checkpoint_write_state, 'write_result', struct()), ...
                    'restart', struct());
                if logical(struct_utils.opt_struct_field( ...
                        salvage_restart_write_state, 'written', false))
                    store_failure_state.continue_propagation_allowed = true;
                    run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                        run_warn_state, 'propagation', ...
                        'store_plane_failure_salvage_restart_written', ...
                        'CerUPP:StorePlaneFailureSalvageRestartWritten', ...
                        ['A minimal salvage restart checkpoint was written ', ...
                         'after the stored-plane failure so the current step ', ...
                         'is still recoverable and propagation can continue.']);
                else
                    run_warn_state = run_warn_state_utils.emit_warn_once_with_phase( ...
                        run_warn_state, 'propagation', ...
                        'store_plane_failure_salvage_restart_unavailable', ...
                        'CerUPP:StorePlaneFailureSalvageRestartUnavailable', ...
                        ['The stored-plane failure happened after the current ', ...
                         'step finished, but no salvage restart was written ', ...
                         'under the current checkpoint policy (%s).'], ...
                        char(string(struct_utils.opt_struct_field( ...
                            salvage_restart_write_state, ...
                            'skipped_reason', 'restart_not_written'))));
