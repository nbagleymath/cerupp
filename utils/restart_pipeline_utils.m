        function merged_struct = merge_custom_checkpoint_restart_fields_local( ...
                target_struct, cfg, owner_label)
            merged_struct = target_struct;
            custom_fields = struct_utils.opt_struct_field( ...
                cfg, 'custom_checkpoint_restart_fields', struct());
            if isempty(custom_fields)
                return;
            end
            if ~(isstruct(custom_fields) && isscalar(custom_fields))
                error('CerUPP:InvalidCustomCheckpointRestartFields', ...
                    '%s requires custom_checkpoint_restart_fields as a scalar struct.', ...
                    owner_label);
            end
            custom_field_names = fieldnames(custom_fields);
            overlap = intersect(fieldnames(merged_struct), custom_field_names, 'stable');
            if ~isempty(overlap)
                error('CerUPP:DuplicateCustomCheckpointRestartField', ...
                    '%s reuses existing saved-artifact field(s): %s', ...
                    owner_label, strjoin(overlap, ', '));
            end
            for ii = 1:numel(custom_field_names)
                field_name = custom_field_names{ii};
                if ~isvarname(field_name)
                    error('CerUPP:InvalidSavedArtifactExtraFieldName', ...
                        '%s extra field "%s" is not a valid MATLAB variable name.', ...
                        owner_label, field_name);
                end
                merged_struct.(field_name) = custom_fields.(field_name);
            end
        end

